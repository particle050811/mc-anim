// 聊天栏和驯服爱心的核对视图（纯数据，段.ts 也读）：一帧一个视图。刻都从驯服那一刻数起。
// 聊天栏：满亮（0、100）、淡出中（185、195）、消失（200）；爱心：刚出生（0、0.25）、升到一半（5、10）、快消失（15）；两样合看。
// 爱心在占位机位下有几颗飘出画面上沿，另加两张退远的（远景）看全 7 颗。
export type 视图 = {
  名: string;
  宽: number;
  高: number;
  聊天刻?: number;
  爱心刻?: number;
  远景?: true;
};

const 宽 = 1280;
const 高 = 720;

export const 视图们: readonly 视图[] = [
  ...[0, 100, 185, 195, 200].map((刻) => ({ 名: `聊天栏 第 ${刻} 刻`, 宽, 高, 聊天刻: 刻 })),
  ...[0, 0.25, 5, 10, 15].map((刻) => ({ 名: `爱心 第 ${刻} 刻`, 宽, 高, 爱心刻: 刻 })),
  { 名: '合看 第 5 刻', 宽, 高, 聊天刻: 5, 爱心刻: 5 },
  ...[5, 15].map((刻) => ({ 名: `爱心 远景 第 ${刻} 刻`, 宽, 高, 爱心刻: 刻, 远景: true as const })),
];

export const 页宽 = Math.max(...视图们.map((v) => v.宽));
export const 页高 = Math.max(...视图们.map((v) => v.高));
