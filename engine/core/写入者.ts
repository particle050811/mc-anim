// 渲染时写模块全局（共用 uniform、共用设置）、卸载时复位的钩子：只有最后写入的那个组件卸载时才复位（用户 11-01 定）。
// 为什么：拼段切到下一截时，旧画布的卸载排在新画布第一次渲染之后（R3F 在外层的 effect 里才卸里层）。不看是谁写的，旧画布就把新画布刚写的值冲掉，
// 切点第一帧没有雾和自发光，换画布的那几个值（只在天色变了才写的云光）还一直错下去；单帧渲染没有旧画布，于是同一帧的像素取决于之前渲过哪些帧。
// 卸载时复位不能去掉：Studio 从暮色的段切到没有这层的段，要回到默认值。
import { useEffect, useState } from 'react';

/** 一组一起写、一起复位的模块全局共用一个槽 */
export type 写入槽 = { 写入者: object | null };
export const 新写入槽 = (): 写入槽 => ({ 写入者: null });

/** 占槽（渲染时调）：之后的写入算这个组件的 */
export const 占槽 = (槽: 写入槽, 我: object) => {
  槽.写入者 = 我;
};
/** 放槽（卸载时调）：最后写入的还是我才复位，别人已经接手就不碰 */
export const 放槽 = (槽: 写入槽, 我: object, 复位: () => void) => {
  if (槽.写入者 !== 我) return;
  槽.写入者 = null;
  复位();
};

/** 在写模块全局的钩子、组件开头调用（每次渲染都占）。复位：同一个槽要始终给同样的复位 */
export const use写入者 = (槽: 写入槽, 复位: () => void) => {
  const [我] = useState(() => ({}));
  占槽(槽, 我);
  useEffect(() => () => 放槽(槽, 我, 复位), [槽, 我]);
};
