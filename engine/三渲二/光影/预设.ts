/** 样式加上场景给的事实：样式里写了的照样式（试看时盖场景用） */
export const 合光影 = (选项: 光影选项, 场: 光影场参数 = {}): 光影选项 => {
  const 时段 = 选项.时段 ?? 场.时段;
  const 太阳 = 选项.太阳 ?? 场.太阳;
  return {
    ...选项,
    ...(时段 ? { 时段 } : {}),
    ...(太阳 ? { 太阳 } : {}),
    ...(选项.光强 === undefined && 场.光强 !== undefined ? { 光强: 场.光强 } : {}),
    ...(选项.云 ? { 云: { 海平面: 场.海平面 ?? 0, ...选项.云 } } : {}),
  };
};

export const 光影预设 = { 暖柔, 鲜艳, 粉彩 } as const;
export type 光影预设名 = keyof typeof 光影预设;

export const 取光影参数 = (p: 光影选项['预设']): 光影参数 => {
  if (typeof p !== 'string') return p;
  const r = 光影预设[p];
  if (!r) throw new Error(`没有光影预设「${p}」，有：${Object.keys(光影预设).join('、')}`);
  return r;
};
