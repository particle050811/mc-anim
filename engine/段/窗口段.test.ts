import { describe, expect, it } from 'vitest';
import { 定义段 } from './段定义.ts';
import { 定义场时间线, 是框架段, 窗口段, 默认段格式 } from './窗口段.ts';
import { 歌网格解析, type 歌时刻 } from './歌网格.ts';

const 线 = 定义场时间线({
  场: '9-试场',
  事件: {
    开门: { 在: { 秒: 1 } },
    进门: { 在: { 接: '开门', 加秒: 0.5 } },
    关门: { 在: { 帧: 72 } },
  },
});

describe('场时间线', () => {
  it('fps、画幅不给就用默认段格式；事件解成场时间线帧', () => {
    expect([线.fps, 线.宽, 线.高]).toEqual([默认段格式.fps, 默认段格式.宽, 默认段格式.高]);
    expect(线.事件.进门.帧).toBe(36);
  });
  it('扩展时刻（歌网格）', () => {
    const 歌线 = 定义场时间线({ 场: '核对', 解析: 歌网格解析({ 首拍: 0, 拍长: 0.5, 每小节拍数: 4 }), 事件: { a: { 在: { 小节: 1 } as 歌时刻 } } });
    expect(歌线.事件.a.帧).toBe(48);
  });
});

describe('窗口段：段.ts 里不写段键、帧数、fps、画幅', () => {
  it('窗口取事件，帧数、场窗口、事件的段内帧都推出来；声音回调拿到段内事件帧', () => {
    const 段 = 窗口段(线, {
      起: '开门',
      止: '关门',
      声音表: { 资产: { '音效/门': { 时长: 0.5, 峰值: 0 } }, 台词: {} },
      声音: ({ 放, 说, 事件 }) => [放('音效/门', 事件.开门), 说('9-甲-你好', 事件.进门 + 0.5)],
    });
    expect(段).toMatchObject({ 场: '9-试场', 帧数: 48, fps: 24, 宽: 1280, 高: 720, 地形: [], 场窗口: { 起帧: 24, 止帧: 72 }, 框架: '窗口段' });
    expect(段.事件帧).toEqual({ 开门: 0, 进门: 12, 关门: 48 });
    expect(段.声音).toEqual([
      { 帧: 0, 资产: '音效/门', 名: '门', 帧数: 12 },
      { 帧: 12.5, 台词: '9-甲-你好' },
    ]);
    expect(是框架段(段)).toBe(true);
    expect(是框架段(定义段({ 场: '核对', 帧数: 1, fps: 24, 宽: 1, 高: 1, 地形: [] }))).toBe(false);
  });
  it('止可以给帧数、也可以直接给时刻；连续、地形、叠层原样带上', () => {
    const 段 = 窗口段(线, { 起: '进门', 止: { 帧数: 10 }, 连续: true, 地形: ['甲'], 叠层: [{ 名: '字', 入口: '叠层字.tsx' }] });
    expect(段).toMatchObject({ 帧数: 10, 场窗口: { 起帧: 36, 止帧: 46 }, 连续: true, 地形: ['甲'] });
    expect(窗口段(线, { 起: { 秒: 0 }, 止: { 接: '开门', 加帧: 2 } }).帧数).toBe(26);
  });
  it('事件不存在、窗口空或反、超出时长、cue 越过段尾都报错', () => {
    expect(() => 窗口段(线, { 起: '没有' as '开门', 止: '关门' })).toThrow(/没有事件「没有」/);
    expect(() => 窗口段(线, { 起: '关门', 止: '开门', 名: '试' })).toThrow(/试的窗口 \[72, 24\) 是空的或反了/);
    const 短线 = 定义场时间线({ 场: '9-试场', 时长: 2, 事件: { a: { 在: { 秒: 0 } }, b: { 在: { 秒: 3 } } } });
    expect(() => 窗口段(短线, { 起: 'a', 止: 'b' })).toThrow(/超出场时间线/);
    expect(() => 窗口段(线, { 起: '开门', 止: '关门', 声音: ({ 说 }) => [说('9-甲-你好', 60)] })).toThrow(/帧要在段内/);
  });
});
