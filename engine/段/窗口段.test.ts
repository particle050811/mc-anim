import { describe, expect, it } from 'vitest';
import { 定义段 } from './段定义.ts';
import { 定义场时间线, 是框架段, 窗口段, 默认段格式 } from './窗口段.ts';
import { 歌网格解析, type 歌时刻 } from './歌网格.ts';

const 线 = 定义场时间线({
  场: '9-试场',
  事件: {
    开门: { 在: { 秒: 1 } },
    进门: { 在: { 接: '开门', 加秒: 0.5 } },
    关门: { 在: { 帧: 180 } },
  },
});

describe('场时间线', () => {
  it('画幅不给就用默认段格式；事件解成场时间线的秒（帧 按 60 帧一秒）', () => {
    expect([线.宽, 线.高]).toEqual([默认段格式.宽, 默认段格式.高]);
    expect(线.事件.进门.秒).toBe(1.5);
    expect(线.事件.关门.秒).toBe(3);
  });
  it('扩展时刻（歌网格）', () => {
    const 歌线 = 定义场时间线({ 场: '核对', 解析: 歌网格解析({ 首拍: 0, 拍长: 0.5, 每小节拍数: 4 }), 事件: { a: { 在: { 小节: 1 } as 歌时刻 } } });
    expect(歌线.事件.a.秒).toBe(2);
  });
});

describe('窗口段：段.ts 里不写段键、段长、画幅', () => {
  it('窗口取事件，段长、场窗口、事件的段内秒都推出来；声音回调拿到段内事件秒', () => {
    const 段 = 窗口段(线, {
      起: '开门',
      止: '关门',
      声音表: { 资产: { '音效/门': { 时长: 0.5, 峰值: 0 } }, 台词: {} },
      声音: ({ 放, 说, 事件 }) => [放('音效/门', 事件.开门), 说('9-甲-你好', 事件.进门 + 0.02)],
    });
    expect(段).toMatchObject({ 场: '9-试场', 秒: 2, 宽: 1280, 高: 720, 地形: [], 场窗口: { 起秒: 1, 止秒: 3 }, 框架: '窗口段' });
    expect(段.事件秒).toEqual({ 开门: 0, 进门: 0.5, 关门: 2 });
    expect(段.声音).toEqual([
      { 秒: 0, 资产: '音效/门', 名: '门', 长秒: 0.5 },
      { 秒: 0.52, 台词: '9-甲-你好' },
    ]);
    expect(是框架段(段)).toBe(true);
    expect(是框架段(定义段({ 场: '核对', 秒: 1, 宽: 1, 高: 1, 地形: [] }))).toBe(false);
    expect(是框架段(定义段({ 场: '核对', 秒: 1, 宽: 1, 高: 1, 地形: [], 声音: [{ 秒: 0, 台词: '甲' }] }))).toBe(true);
  });
  it('止可以给长秒、也可以直接给时刻；窗口对齐到 1/60 秒；连续、地形、叠层原样带上', () => {
    const 段 = 窗口段(线, { 起: '进门', 止: { 长秒: 0.5 }, 连续: true, 地形: ['甲'], 叠层: [{ 名: '字', 入口: '叠层字.tsx' }] });
    expect(段).toMatchObject({ 秒: 0.5, 场窗口: { 起秒: 1.5, 止秒: 2 }, 连续: true, 地形: ['甲'] });
    expect(窗口段(线, { 起: { 秒: 0 }, 止: { 接: '开门', 加帧: 2 } }).秒).toBeCloseTo(62 / 60);
    // 0.4 秒不在 1/60 秒格上的取整到格
    expect(窗口段(线, { 起: { 秒: 0 }, 止: { 秒: 0.404 } }).秒).toBeCloseTo(24 / 60);
  });
  it('事件不存在、窗口空或反、超出时长、cue 越过段尾都报错', () => {
    expect(() => 窗口段(线, { 起: '没有' as '开门', 止: '关门' })).toThrow(/没有事件「没有」/);
    expect(() => 窗口段(线, { 起: '关门', 止: '开门', 名: '试' })).toThrow(/试的窗口 \[3, 1\) 秒是空的或反了/);
    const 短线 = 定义场时间线({ 场: '9-试场', 时长: 2, 事件: { a: { 在: { 秒: 0 } }, b: { 在: { 秒: 3 } } } });
    expect(() => 窗口段(短线, { 起: 'a', 止: 'b' })).toThrow(/超出场时间线/);
    expect(() => 窗口段(线, { 起: '开门', 止: '关门', 声音: ({ 说 }) => [说('9-甲-你好', 2.5)] })).toThrow(/秒要在段内/);
  });
});
