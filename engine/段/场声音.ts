// 场声音：写在场时间线上、跨段放的音效或配乐（上段起、下段接着放，cue 只写一次）。纯模块。
// 定义场时间线({ 声音: [...] }) 把起止解成场时间线的秒；窗口段 按自己的窗口取落在里面的那一截，各段的 cue 首尾相接起来和一口气放完一样
// （同 作品/把回忆拼好给你/声音/跨段音效.ts 的 段里那截，那是老写法的手工版）。
import { 段格, type 资产cue, type 逐格增益 } from './段定义.ts';
import type { 音频数 } from './声音助手.ts';

/** 场声音的放法（时刻用场时间线的事件名或时刻，见 窗口段.ts 的 定义场时间线） */
export type 场声音选项 = {
  资产: string;
  /** 片段名；同一条场时间线里不能重名（窗口段 的 不放场声音 按名挑）。默认取 id 最后一截 */
  名?: string;
  /** 目标采样峰值 dBFS、目标积分响度 LUFS、直接给的增益倍数：三选一，都不给 = 原样（同 声音助手.ts 的 放） */
  峰值?: number;
  响度?: number;
  增益?: number;
  /** 文件从第几秒放起 */
  入点秒?: number;
  速率?: number;
  /** 循环：放完从文件头接着放，要给 止 */
  循环?: true;
  /** 整个声音最后几秒线性淡到 0（落在哪段就由哪段的那截带上） */
  淡出秒?: number;
  档?: string;
};

/** 解出来的场声音：起秒、止秒是场时间线的秒（止秒不给 = 放到文件完） */
export type 解出场声音 = 场声音选项 & { 名: string; 起秒: number; 止秒?: number };

const 六位 = (x: number) => Math.round(x * 1e6) / 1e6;

/** 不量文件就能断定和窗口 [起秒, 止秒) 不沾边（起在窗口后，或给了止秒且止在窗口前）：这种不查声音表，免得每段的表里都记上全场的声音 */
export const 一定不沾 = (声: 解出场声音, 窗: { 起秒: number; 止秒: number }) => 声.起秒 >= 窗.止秒 || (声.止秒 !== undefined && 声.止秒 <= 窗.起秒);

/** 场声音在场时间线上止在第几秒：给了止秒取止秒（不循环的还不超过文件完），没给就放到文件完 */
export const 场声音尾秒 = (声: 解出场声音, 文件: 音频数) => {
  const 入点 = 声.入点秒 ?? 0;
  const 速率 = 声.速率 ?? 1;
  if (声.循环) return 声.止秒!;
  const 剩秒 = 文件.时长 - 入点;
  if (!(剩秒 > 0)) throw new Error(`场声音「${声.名}」：入点秒 ${入点} 已经到了文件尾（${文件.时长} 秒）`);
  const 放完 = 声.起秒 + 剩秒 / 速率;
  return 声.止秒 === undefined ? 放完 : Math.min(声.止秒, 放完);
};

/** 场时间线第 T 秒上文件放到第几秒（不循环的不取模；测试和文档用这个当「一口气放完」的标准答案） */
export const 场声音位置 = (声: 解出场声音, 文件: 音频数, T: number) => {
  const 秒 = (声.入点秒 ?? 0) + (T - 声.起秒) * (声.速率 ?? 1);
  return 声.循环 ? 秒 % 文件.时长 : 秒;
};

const 基础增益 = (声: 解出场声音, 文件: 音频数): number => {
  const 给了 = [声.增益, 声.峰值, 声.响度].filter((x) => x !== undefined).length;
  if (给了 > 1) throw new Error(`场声音「${声.名}」：峰值、响度、增益只能给一个`);
  if (声.峰值 !== undefined) {
    if (文件.峰值 === undefined) throw new Error(`场声音「${声.名}」：${声.资产} 量不出峰值（静音？），直接给 增益`);
    return 六位(10 ** ((声.峰值 - 文件.峰值) / 20));
  }
  if (声.响度 !== undefined) {
    if (文件.响度 === undefined) throw new Error(`场声音「${声.名}」：${声.资产} 没有响度数，按峰值给或直接给 增益`);
    return 六位(10 ** ((声.响度 - 文件.响度) / 20));
  }
  return 声.增益 ?? 1;
};

/**
 * 这个场声音落在窗口 [起秒, 止秒)（场时间线的秒）里的那几条 cue，秒是段内秒；不沾边给 []。
 * 不循环的一截一条：入点秒 = 原入点 + 已经放过的秒 × 速率，任一时刻的文件位置和一口气放完一样。
 * 循环的：Remotion 的 loop 只绕 [入点, 文件尾]，所以从文件中间接上时拆两条：先放到文件尾，再从文件头起循环。
 * 淡出按整个声音的尾算：尾在本截里就用 淡出秒，尾在后面的段里就写逐格增益（每秒 段格 个值）。
 */
export const 场声音那截 = (声: 解出场声音, 窗: { 起秒: number; 止秒: number }, 文件: 音频数): 资产cue[] => {
  const 尾 = 场声音尾秒(声, 文件);
  const a = Math.max(声.起秒, 窗.起秒);
  const b = Math.min(尾, 窗.止秒);
  if (b - a <= 1e-9) return [];
  const g = 基础增益(声, 文件);
  const 速率 = 声.速率 ?? 1;
  const 增益于 = (x: number, y: number): { 增益?: number | 逐格增益; 淡出秒?: number } => {
    const 淡 = 声.淡出秒;
    if (淡 && y > 尾 - 淡) {
      if (Math.abs(y - 尾) < 1e-9 && 尾 - 淡 >= x - 1e-9) return { ...(g !== 1 ? { 增益: g } : {}), 淡出秒: 淡 };
      const n = Math.floor((y - x) * 段格 + 1e-6) + 1;
      return { 增益: { 每秒: 段格, 值: Array.from({ length: n }, (_, i) => 六位(g * Math.max(0, Math.min(1, (尾 - (x + i / 段格)) / 淡)))) } };
    }
    return g !== 1 ? { 增益: g } : {};
  };
  const 一条 = (x: number, y: number, 入点秒: number, 循环: boolean): 资产cue => ({
    秒: x - 窗.起秒,
    资产: 声.资产,
    名: 声.名,
    长秒: y - x,
    ...(声.档 !== undefined ? { 档: 声.档 } : {}),
    ...(入点秒 > 1e-9 ? { 入点秒 } : {}),
    ...(速率 !== 1 ? { 速率 } : {}),
    ...(循环 ? { 循环: true as const } : {}),
    ...增益于(x, y),
  });
  const 位置 = 场声音位置(声, 文件, a);
  if (!声.循环) return [一条(a, b, 位置, false)];
  // 循环：刚好在文件头（或差不到一个采样）就一条到底
  if (位置 < 1e-6 || 文件.时长 - 位置 < 1e-6) return [一条(a, b, 0, true)];
  const m = Math.min(a + (文件.时长 - 位置) / 速率, b);
  return b - m > 1e-9 ? [一条(a, m, 位置, false), 一条(m, b, 0, true)] : [一条(a, m, 位置, false)];
};
