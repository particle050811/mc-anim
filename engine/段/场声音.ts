// 场声音：写在场时间线上、跨段放的音效或配乐（上段起、下段接着放，cue 只写一次）。纯模块。
// 定义场时间线({ 声音: [...] }) 把起止解成场帧；窗口段 按自己的窗口取落在里面的那一截，各段的 cue 首尾相接起来和一口气放完一样
// （同 作品/把回忆拼好给你/声音/跨段音效.ts 的 段里那截，那是老写法的手工版）。
import type { 资产cue } from './段定义.ts';
import type { 音频数 } from './声音助手.ts';

/** 场声音的放法（时刻用场时间线的事件名或时刻，见 窗口段.ts 的 定义场时间线） */
export type 场声音选项 = {
  资产: string;
  /** 剪映片段名；同一条场时间线里不能重名（窗口段 的 不放场声音 按名挑）。默认取 id 最后一截 */
  名?: string;
  /** 目标采样峰值 dBFS、目标积分响度 LUFS、直接给的增益倍数：三选一，都不给 = 原样（同 声音助手.ts 的 放） */
  峰值?: number;
  响度?: number;
  增益?: number;
  /** 文件从第几秒放起 */
  入点秒?: number;
  速率?: number;
  /** 循环：放完从文件头接着放，要给 止 */
  循环?: true;
  /** 整个声音最后几帧线性淡到 0（落在哪段就由哪段的那截带上） */
  淡出?: number;
  档?: string;
};

/** 解出来的场声音：起帧、止帧是场时间线帧（止帧不给 = 放到文件完） */
export type 解出场声音 = 场声音选项 & { 名: string; 起帧: number; 止帧?: number };

const 六位 = (x: number) => Math.round(x * 1e6) / 1e6;

/** 不量文件就能断定和窗口 [起帧, 止帧) 不沾边（起在窗口后，或给了止帧且止在窗口前）：这种不查声音表，免得每段的表里都记上全场的声音 */
export const 一定不沾 = (声: 解出场声音, 窗: { 起帧: number; 止帧: number }) => 声.起帧 >= 窗.止帧 || (声.止帧 !== undefined && 声.止帧 <= 窗.起帧);

/** 场声音在场时间线上占 [起帧, 尾帧)：给了止帧取止帧（不循环的还不超过文件完），没给就放到文件完 */
export const 场声音尾帧 = (声: 解出场声音, 文件: 音频数, fps: number) => {
  const 入点 = 声.入点秒 ?? 0;
  const 速率 = 声.速率 ?? 1;
  if (声.循环) return 声.止帧!;
  const 剩秒 = 文件.时长 - 入点;
  if (!(剩秒 > 0)) throw new Error(`场声音「${声.名}」：入点秒 ${入点} 已经到了文件尾（${文件.时长} 秒）`);
  const 放完 = 声.起帧 + Math.ceil((剩秒 * fps) / 速率 - 1e-6);
  return 声.止帧 === undefined ? 放完 : Math.min(声.止帧, 放完);
};

/** 场帧 F 上文件放到第几秒（不循环的不取模；测试和文档用这个当「一口气放完」的标准答案） */
export const 场声音位置 = (声: 解出场声音, 文件: 音频数, fps: number, F: number) => {
  const 秒 = (声.入点秒 ?? 0) + ((F - 声.起帧) * (声.速率 ?? 1)) / fps;
  return 声.循环 ? 秒 % 文件.时长 : 秒;
};

const 基础增益 = (声: 解出场声音, 文件: 音频数): number => {
  const 给了 = [声.增益, 声.峰值, 声.响度].filter((x) => x !== undefined).length;
  if (给了 > 1) throw new Error(`场声音「${声.名}」：峰值、响度、增益只能给一个`);
  if (声.峰值 !== undefined) {
    if (文件.峰值 === undefined) throw new Error(`场声音「${声.名}」：${声.资产} 量不出峰值（静音？），直接给 增益`);
    return 六位(10 ** ((声.峰值 - 文件.峰值) / 20));
  }
  if (声.响度 !== undefined) {
    if (文件.响度 === undefined) throw new Error(`场声音「${声.名}」：${声.资产} 没有响度数，按峰值给或直接给 增益`);
    return 六位(10 ** ((声.响度 - 文件.响度) / 20));
  }
  return 声.增益 ?? 1;
};

/**
 * 这个场声音落在窗口 [起帧, 止帧)（场帧）里的那几条 cue，帧是段内帧；不沾边给 []。
 * 不循环的一截一条：入点秒 = 原入点 + 已经放过的帧 × 速率 ÷ fps，逐帧位置和一口气放完一样。
 * 循环的：Remotion 的 loop 只绕 [入点, 文件尾]，所以从文件中间接上时拆两条：先放到文件尾，再从文件头起循环。
 *   拆开那一刻取整到帧：后一条比一口气放完早不到 1 帧（速率 ÷ fps 秒以内），之后的每一圈照这个差。
 */
export const 场声音那截 = (声: 解出场声音, 窗: { 起帧: number; 止帧: number }, fps: number, 文件: 音频数): 资产cue[] => {
  const 尾 = 场声音尾帧(声, 文件, fps);
  const a = Math.max(声.起帧, 窗.起帧);
  const b = Math.min(尾, 窗.止帧);
  if (b <= a) return [];
  const g = 基础增益(声, 文件);
  const 速率 = 声.速率 ?? 1;
  // 一截 [x, y)（场帧）的增益：淡出按整个声音的尾算，落进这截就逐帧写
  const 增益于 = (x: number, y: number): { 增益?: number | readonly number[] } => {
    const 淡 = 声.淡出;
    if (淡 && y > 尾 - 淡) return { 增益: Array.from({ length: y - x }, (_, i) => 六位(g * Math.min(1, (尾 - (x + i)) / 淡))) };
    return g !== 1 ? { 增益: g } : {};
  };
  const 一条 = (x: number, y: number, 入点秒: number, 循环: boolean): 资产cue => ({
    帧: x - 窗.起帧,
    资产: 声.资产,
    名: 声.名,
    帧数: y - x,
    ...(声.档 !== undefined ? { 档: 声.档 } : {}),
    ...(入点秒 > 1e-9 ? { 入点秒 } : {}),
    ...(速率 !== 1 ? { 速率 } : {}),
    ...(循环 ? { 循环: true as const } : {}),
    ...增益于(x, y),
  });
  const 位置 = 场声音位置(声, 文件, fps, a);
  if (!声.循环) return [一条(a, b, 位置, false)];
  // 循环：刚好在文件头（或差不到一个采样）就一条到底
  if (位置 < 1e-6 || 文件.时长 - 位置 < 1e-6) return [一条(a, b, 0, true)];
  const 到文件尾 = Math.ceil(((文件.时长 - 位置) * fps) / 速率 - 1e-6);
  const m = Math.min(a + 到文件尾, b);
  return m < b ? [一条(a, m, 位置, false), 一条(m, b, 0, true)] : [一条(a, m, 位置, false)];
};
