import { describe, expect, it } from 'vitest';
import { 排段, 解事件, 解时刻, 时刻帧 } from './时间线.ts';
import { 歌网格解析, type 歌时刻 } from './歌网格.ts';

const 轴 = { fps: 24 };

describe('时间线：事件解成秒和帧', () => {
  it('秒、帧、接（加秒、加帧，可以接在后面才写的事件上）', () => {
    const 表 = {
      a: { 在: { 秒: 1 } },
      b: { 在: { 接: 'c', 加秒: 0.5 } },
      c: { 在: { 帧: 30 } },
      d: { 在: { 接: 'a', 加帧: 3 }, 依据: '示范' },
    };
    const r = 解事件(表, 轴);
    expect(r.a).toEqual({ 秒: 1, 帧: 24, 依据: '' });
    expect(r.b.秒).toBeCloseTo(1.75);
    expect(r.b.帧).toBe(42);
    expect(r.c).toEqual({ 秒: 1.25, 帧: 30, 依据: '' });
    expect(r.d).toMatchObject({ 帧: 27, 依据: '示范' });
  });

  it('接成环、接不存在的事件、帧不是整数都报错', () => {
    expect(() => 解事件({ a: { 在: { 接: 'b' } }, b: { 在: { 接: 'a' } } }, 轴)).toThrow(/接成了环/);
    expect(() => 解事件({ a: { 在: { 接: 'x' } } }, 轴)).toThrow(/不在表里/);
    expect(() => 时刻帧({ 帧: 1.5 }, {}, 轴)).toThrow(/整数/);
  });

  it('扩展时刻没给 解析 就报错，给了按它换秒', () => {
    const t = { 拍: 2 } as unknown as never;
    expect(() => 解时刻(t, {}, 轴)).toThrow(/没给 解析/);
    const 解析 = 歌网格解析({ 首拍: 0.1, 拍长: 0.5, 每小节拍数: 4 }, [{ 序: 1, 前导: 0.9, 起: 1, 止: 2 }]);
    const 歌轴 = { fps: 24, 解析 };
    const 表 = { x: { 在: { 拍: 2 } as 歌时刻 }, y: { 在: { 小节: 1 } as 歌时刻 }, z: { 在: { 句: 1, 点: '开口' } as 歌时刻 } };
    const r = 解事件(表, 歌轴);
    expect([r.x.秒, r.y.秒, r.z.秒]).toEqual([1.1, 2.1, 0.9]);
    expect(() => 解析({ 句: 2, 点: '起' })).toThrow(/没有第 2 句/);
  });
});

describe('排段：一串首尾相接的窗口', () => {
  const 表 = { 起: { 在: { 秒: 1 } }, 中: { 在: { 秒: 2 } }, 尾: { 在: { 秒: 3 } } };
  it('第一段要写起，后面不写起就接上一段；止可以是时刻、帧数或放完', () => {
    const r = 排段(
      {
        名: '串',
        时长: 4,
        段们: [
          { 名: '甲', 起: { 接: '起', 加秒: 0 }, 止: { 接: '中' } },
          { 名: '乙', 止: { 帧数: 10 } },
          { 名: '丙', 止: '放完' },
        ],
      },
      表,
      轴,
    );
    expect(r.map((w) => [w.名, w.起帧, w.止帧])).toEqual([
      ['甲', 24, 48],
      ['乙', 48, 58],
      ['丙', 58, 96],
    ]);
  });
  it('空了、重叠、超出时长、放完没给时长都报错', () => {
    expect(() => 排段({ 名: 's', 段们: [{ 名: 'a', 起: { 秒: 0 }, 止: { 秒: 1 } }, { 名: 'b', 起: { 秒: 1.5 }, 止: { 秒: 2 } }] }, {}, 轴)).toThrow(/中间空了 12 帧/);
    expect(() => 排段({ 名: 's', 段们: [{ 名: 'a', 起: { 秒: 0 }, 止: { 秒: 1 } }, { 名: 'b', 起: { 秒: 0.5 }, 止: { 秒: 2 } }] }, {}, 轴)).toThrow(/重叠了/);
    expect(() => 排段({ 名: 's', 时长: 1, 段们: [{ 名: 'a', 起: { 秒: 0 }, 止: { 秒: 2 } }] }, {}, 轴)).toThrow(/超出时间轴/);
    expect(() => 排段({ 名: 's', 段们: [{ 名: 'a', 起: { 秒: 0 }, 止: '放完' }] }, {}, 轴)).toThrow(/要给 时长/);
    expect(() => 排段({ 名: 's', 段们: [{ 名: 'a', 止: { 秒: 1 } }] }, {}, 轴)).toThrow(/要写 起/);
  });
});
