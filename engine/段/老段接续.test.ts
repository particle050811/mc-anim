import { describe, expect, it } from 'vitest';
import { 定义段 } from './段定义.ts';
import { 接老段 } from './老段接续.ts';
import { 窗口段 } from './窗口段.ts';

const 老 = (帧数: number, o: { 场?: string; 场窗口?: { 起帧: number; 止帧: number }; fps?: number } = {}) =>
  定义段({ 场: o.场 ?? '7-墙头追逐', 帧数, fps: o.fps ?? 24, 宽: 1280, 高: 720, 地形: [], ...(o.场窗口 ? { 场窗口: o.场窗口 } : {}) });

describe('接老段：老场（定义段 写的）摆上场时间线，新段接得上', () => {
  const 线 = 接老段({
    场: '7-墙头追逐',
    老段: [
      { 键: '7-墙头', 段: 老(30) },
      { 键: '7-音波', 段: 老(89) },
      { 键: '7-上塔', 段: 老(28) },
    ],
    事件: { 新起: { 在: { 接: '7-上塔.止' } }, 新止: { 在: { 接: '新起', 加秒: 2 } } },
    声音: [{ 资产: '音效/风', 在: '7-上塔.起', 增益: 0.5 }],
  });

  it('老段按清单顺序首尾相接；fps、画幅取老段的', () => {
    expect(线.事件['7-墙头.起'].帧).toBe(0);
    expect(线.事件['7-音波.起'].帧).toBe(30);
    expect(线.事件['7-上塔.止'].帧).toBe(147);
    expect([线.fps, 线.宽, 线.高]).toEqual([24, 1280, 720]);
  });

  it('新段从老段的止起；场声音从老段里起的，新段只放落进来的那截', () => {
    const 新 = 窗口段(线, { 起: '新起', 止: '新止', 声音表: { 资产: { '音效/风': { 时长: 2 } }, 台词: {} } });
    expect(新.场窗口).toEqual({ 起帧: 147, 止帧: 195 });
    // 风 在 7-上塔 起（场帧 119）放 48 帧：新段里还剩 20 帧，从文件第 28 帧接着放
    expect(新.声音).toEqual([{ 帧: 0, 资产: '音效/风', 名: '风', 帧数: 20, 入点秒: 28 / 24, 增益: 0.5 }]);
  });

  it('有 场窗口 的老段照它的；起帧 可以手给（老时间线里段间跳过一截的）', () => {
    const 带窗 = 接老段({ 场: '2-门口', 老段: [{ 键: '2-烟花', 段: 老(10, { 场: '2-门口', 场窗口: { 起帧: 100, 止帧: 110 } }) }, { 键: '2-空床', 段: 老(5, { 场: '2-门口' }) }] });
    expect([带窗.事件['2-烟花.起'].帧, 带窗.事件['2-空床.起'].帧]).toEqual([100, 110]);
    const 跳 = 接老段({ 场: '7-墙头追逐', 老段: [{ 键: 'a', 段: 老(10) }, { 键: 'b', 段: 老(10), 起帧: 40 }] });
    expect(跳.事件['b.止'].帧).toBe(50);
  });

  it('场、fps 对不上，重复、重名都报错', () => {
    expect(() => 接老段({ 场: '7-墙头追逐', 老段: [{ 键: 'a', 段: 老(10, { 场: '7-收场' }) }] })).toThrow(/是场 7-收场 的段/);
    expect(() => 接老段({ 场: '7-墙头追逐', 老段: [{ 键: 'a', 段: 老(10) }, { 键: 'b', 段: 老(10, { fps: 30 }) }] })).toThrow(/摆不上同一条/);
    expect(() => 接老段({ 场: '7-墙头追逐', 老段: [{ 键: 'a', 段: 老(10) }, { 键: 'a', 段: 老(10) }] })).toThrow(/列了两次/);
    expect(() => 接老段({ 场: '7-墙头追逐', 老段: [{ 键: 'a', 段: 老(10) }], 事件: { 'a.止': { 在: { 秒: 1 } } } as never })).toThrow(/重名/);
    expect(() => 接老段({ 场: '7-墙头追逐', 老段: [] })).toThrow(/至少一个/);
  });
});
