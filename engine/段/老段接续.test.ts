import { describe, expect, it } from 'vitest';
import { 核老段, 接老段 } from './老段接续.ts';
import { 窗口段 } from './窗口段.ts';

describe('接老段：老场（定义段 写的）摆上场时间线，新段接得上', () => {
  const 线 = 接老段({
    场: '7-墙头追逐',
    老段: [
      { 键: '7-墙头', 帧数: 30 },
      { 键: '7-音波', 帧数: 89 },
      { 键: '7-上塔', 帧数: 28 },
    ],
    事件: { 新起: { 在: { 接: '7-上塔.止' } }, 新止: { 在: { 接: '新起', 加秒: 2 } } },
    声音: [{ 资产: '音效/风', 在: '7-上塔.起', 增益: 0.5 }],
  });

  it('老段按清单顺序首尾相接；fps、画幅默认 24、1280×720；带一张老段表', () => {
    expect(线.事件['7-墙头.起'].帧).toBe(0);
    expect(线.事件['7-音波.起'].帧).toBe(30);
    expect(线.事件['7-上塔.止'].帧).toBe(147);
    expect([线.fps, 线.宽, 线.高]).toEqual([24, 1280, 720]);
    expect(线.老段.map((x) => x.起帧)).toEqual([0, 30, 119]);
  });

  it('新段从老段的止起；场声音从老段里起的，新段只放落进来的那截', () => {
    const 新 = 窗口段(线, { 起: '新起', 止: '新止', 声音表: { 资产: { '音效/风': { 时长: 2 } }, 台词: {} } });
    expect(新.场窗口).toEqual({ 起帧: 147, 止帧: 195 });
    // 风 在 7-上塔 起（场帧 119）放 48 帧：新段里还剩 20 帧，从文件第 28 帧接着放
    expect(新.声音).toEqual([{ 帧: 0, 资产: '音效/风', 名: '风', 帧数: 20, 入点秒: 28 / 24, 增益: 0.5 }]);
  });

  it('起帧 可以手给（老时间线里段间跳过一截的、有场窗口的）', () => {
    const 跳 = 接老段({ 场: '7-墙头追逐', 老段: [{ 键: 'a', 帧数: 10 }, { 键: 'b', 帧数: 10, 起帧: 40 }] });
    expect(跳.事件['b.止'].帧).toBe(50);
  });

  it('重复、重名、帧数不对、空表都报错', () => {
    expect(() => 接老段({ 场: '7-墙头追逐', 老段: [{ 键: 'a', 帧数: 10 }, { 键: 'a', 帧数: 10 }] })).toThrow(/列了两次/);
    expect(() => 接老段({ 场: '7-墙头追逐', 老段: [{ 键: 'a', 帧数: 10 }], 事件: { 'a.止': { 在: { 秒: 1 } } } as never })).toThrow(/重名/);
    expect(() => 接老段({ 场: '7-墙头追逐', 老段: [{ 键: 'a', 帧数: 0 }] })).toThrow(/正整数/);
    expect(() => 接老段({ 场: '7-墙头追逐', 老段: [] })).toThrow(/至少一个/);
  });

  it('核老段：抄的帧数、场、fps 和老段的 段.ts 对', () => {
    const 段们: Record<string, { 场: string; 帧数: number; fps: number; 宽: number; 高: number }> = {
      '7-墙头': { 场: '7-墙头追逐', 帧数: 30, fps: 24, 宽: 1280, 高: 720 },
      '7-音波': { 场: '7-墙头追逐', 帧数: 90, fps: 24, 宽: 1280, 高: 720 },
      '7-上塔': { 场: '7-收场', 帧数: 28, fps: 30, 宽: 1280, 高: 720 },
    };
    expect(核老段(线, (k) => 段们[k])).toEqual([
      '老段 7-音波 的帧数：时间线里抄的 89，段.ts 里 90',
      '老段 7-上塔 是场 7-收场 的段，不在 7-墙头追逐',
      '老段 7-上塔 的 fps、画幅（30，1280×720）和场时间线（24，1280×720）不一样',
    ]);
    expect(核老段(线, () => undefined)[0]).toBe('老段 7-墙头 不在清单里');
  });
});
