import { afterEach, describe, expect, it } from 'vitest';
import { dB增益, 做声音助手, 开始收集, 结束收集, 缺声音数, type 声音表 } from './声音助手.ts';

const 表: 声音表 = {
  资产: { '音效/炸': { 时长: 1.5, 峰值: -2, 响度: -20 }, '音效/静': { 时长: 1 } },
  台词: {},
};
const { 放, 说, 接着说 } = 做声音助手({ fps: 24, 帧数: 48, 表, 段名: '测试段' });

afterEach(() => {
  结束收集();
});

describe('放：一条音效 cue 只写一次，时长、峰值取声音表', () => {
  it('一个数 = 目标峰值：增益 = 10^((目标 − 峰值)/20)；默认放到文件完（向上取整），名取 id 最后一节', () => {
    expect(放('音效/炸', 10, -8)).toEqual({ 帧: 10, 资产: '音效/炸', 名: '炸', 帧数: 36, 增益: dB增益(-6) });
    expect(dB增益(-6)).toBe(0.501187);
  });
  it('截到段尾；入点秒、速率算进默认帧数；响度目标；直接给增益', () => {
    expect(放('音效/炸', 30).帧数).toBe(18);
    expect(放('音效/炸', 0, { 入点秒: 0.5 }).帧数).toBe(24);
    expect(放('音效/炸', 0, { 速率: 2 }).帧数).toBe(18);
    expect(放('音效/炸', 0, { 响度: -26 }).增益).toBe(dB增益(-6));
    expect(放('音效/炸', 0, { 增益: 0.3, 淡出: 4, 档: '中 -20', 名: '大炸' })).toMatchObject({ 增益: 0.3, 淡出: 4, 档: '中 -20', 名: '大炸' });
    expect(放('音效/炸', 0, { 循环: true }).帧数).toBe(48);
    expect('增益' in 放('音效/炸', 0)).toBe(false);
  });
  it('表里没有：报错说跑 anim cues；量不出峰值、峰值增益同时给、帧带小数都报错', () => {
    expect(() => 放('音效/没有', 0)).toThrow(缺声音数);
    expect(() => 放('音效/没有', 0)).toThrow(/测试段 的声音表里没有「音效\/没有」.*anim cues/);
    expect(() => 放('音效/静', 0, -10)).toThrow(/量不出峰值/);
    expect(() => 放('音效/炸', 0, { 峰值: -1, 增益: 1 })).toThrow(/只能给一个/);
    expect(() => 放('音效/炸', 0.5)).toThrow(/整数/);
  });
  it('收集模式：要过的 id 都记下来（表里有的也记，免得生成的表来回翻），缺的给一帧的占位，不报错', () => {
    const 要过 = 开始收集();
    expect(放('音效/新', 5, -10)).toEqual({ 帧: 5, 资产: '音效/新', 名: '新', 帧数: 1 });
    放('音效/炸', 0);
    expect([...要过]).toEqual(['音效/新', '音效/炸']);
    结束收集();
    expect(() => 放('音效/新', 5)).toThrow(缺声音数);
  });
});

describe('说、接着说', () => {
  it('台词 cue 不要数（开口、时长在画面那头用）', () => {
    expect(说('6-李樱-出征', 3.5)).toEqual({ 帧: 3.5, 台词: '6-李樱-出征' });
    expect(接着说('6-李樱-出征', 0, { 帧数: 10 })).toEqual({ 帧: 0, 台词: '6-李樱-出征', 接上段: true, 帧数: 10 });
  });
});
