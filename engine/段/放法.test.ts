import { describe, expect, it } from 'vitest';
import type { 声音cue } from './段定义.ts';
import { 段放法 } from './放法.ts';
import type { 声音表 } from './声音助手.ts';

const 表: 声音表 = {
  资产: { '配音/甲': { 时长: 2 }, '音效/门': { 时长: 1 } },
  台词: { 甲: { 配音: '配音/甲', 开口: 0.03, 时长: 2 }, 乙: { 配音: '配音/甲', 开口: 0, 时长: 2, 上段开口帧: -30 } },
};
const 段 = (声音: 声音cue[], 帧数 = 100) => ({ 声音, 帧数, fps: 24 });

describe('段放法：台词（同 台词轨.tsx、台词落点.ts）', () => {
  it('文件头 = 开口帧 − 开口秒 × fps，从文件头那帧（往后取整）放到文件完多 1 帧', () => {
    const [x] = 段放法(段([{ 帧: 10, 台词: '甲' }]), 表, { 台词增益: 1 });
    // 头 = 10 − 0.72 = 9.28 → 起帧 10，跳 0.72 帧
    expect(x).toMatchObject({ 类: '台词清单', 资产: '配音/甲', 名: '甲', 起帧: 10, 速率: 1, 循环: false });
    expect(x!.入点秒).toBeCloseTo(0.72 / 24);
    expect(x!.帧数).toBe(Math.ceil(48 - 0.72) + 1);
    expect(x!.增益(0)).toBe(1);
  });
  it('开口在段头之前：从第 0 帧起、跳过前面那截；截到段尾、同一句的下一截', () => {
    const [x] = 段放法(段([{ 帧: 0.2, 台词: '甲' }], 20), 表, { 台词增益: 0.5 });
    expect(x!.起帧).toBe(0);
    expect(x!.入点秒).toBeCloseTo((0 - (0.2 - 0.72)) / 24);
    expect(x!.帧数).toBe(20);
    expect(x!.增益(3)).toBe(0.5);
    const 两截 = 段放法(段([{ 帧: 5, 台词: '甲' }, { 帧: 30, 台词: '甲', 接上段: true }]), 表, { 台词增益: 1 });
    expect(两截.map((s) => [s.起帧, s.帧数])).toEqual([
      [5, 25],
      [30, Math.ceil(48 - (30 - (5 - 0.72))) + 1],
    ]);
    expect(两截[1]!.入点秒).toBeCloseTo((30 - (5 - 0.72)) / 24);
  });
  it('跨段的接上段按 上段开口帧 推文件头；没有就报错', () => {
    const [x] = 段放法(段([{ 帧: 0, 台词: '乙', 接上段: true }]), 表, { 台词增益: 1 });
    expect([x!.起帧, x!.入点秒, x!.帧数]).toEqual([0, 30 / 24, 48 - 30 + 1]);
    expect(() => 段放法(段([{ 帧: 0, 台词: '甲', 接上段: true }]), 表, { 台词增益: 1 })).toThrow(/接上段/);
    expect(() => 段放法(段([{ 帧: 0, 台词: '丙' }]), 表, { 台词增益: 1 })).toThrow(/anim cues/);
  });
});

describe('段放法：音效、配乐', () => {
  it('cue 原样换成放法；配乐/ 开头的记进配乐清单；增益照 cue增益（淡出）', () => {
    const r = 段放法(
      段([
        { 帧: 3, 资产: '音效/门', 名: '门', 帧数: 24, 速率: 1.5, 档: '中 -20' },
        { 帧: 0, 资产: '配乐/歌', 名: '歌', 帧数: 10, 入点秒: 4, 增益: 0.5, 淡出: 5 },
      ]),
      表,
      { 台词增益: 1 },
    );
    expect(r[0]).toMatchObject({ 类: '音效清单', 起帧: 3, 帧数: 24, 入点秒: 0, 速率: 1.5, 档: '中 -20' });
    expect(r[1]).toMatchObject({ 类: '配乐清单', 入点秒: 4, 循环: false });
    expect([r[1]!.增益(0), r[1]!.增益(8)]).toEqual([0.5, 0.2]);
  });
  it('同一个文件叠着放：后一声加区分标记；不叠的不加', () => {
    const r = 段放法(
      段([
        { 帧: 0, 资产: '音效/门', 名: 'a', 帧数: 10 },
        { 帧: 5, 资产: '音效/门', 名: 'b', 帧数: 10 },
        { 帧: 20, 资产: '音效/门', 名: 'c', 帧数: 10 },
      ]),
      表,
      { 台词增益: 1 },
    );
    expect(r.map((s) => s.区分)).toEqual([undefined, '段声音1', undefined]);
  });
  it('循环又带入点秒：报错', () => {
    expect(() => 段放法(段([{ 帧: 0, 资产: '音效/门', 名: 'a', 帧数: 10, 循环: true, 入点秒: 0.2 }]), 表, { 台词增益: 1 })).toThrow(/循环/);
  });
});
