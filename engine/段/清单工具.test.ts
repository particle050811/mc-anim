import { describe, expect, it } from 'vitest';
import { 清单工具 } from './清单工具.ts';

describe('清单工具：作品 清单.ts 尾部的通用部分', () => {
  const 清单 = [
    { 键: '核对-冒烟', 章: '核对' as const },
    { 键: '6-进入森林', 章: 6, 集: 1 },
    { 键: '6-斩娜迦', 章: 6 },
    { 键: '7-黑暗降临', 章: 7 },
  ];
  const { 段目录, 段名, 编号 } = 清单工具(清单);
  it('段目录、段名、编号', () => {
    expect(段目录('核对-冒烟')).toBe('核对/冒烟');
    expect(段目录('6-斩娜迦')).toBe('段/6-斩娜迦');
    expect(段名(清单[1]!)).toBe('进入森林');
    expect(段名(清单[0]!)).toBe('冒烟');
    expect([编号('6-进入森林'), 编号('6-斩娜迦'), 编号('7-黑暗降临'), 编号('核对-冒烟'), 编号('没有')]).toEqual(['6-01', '6-02', '7-01', null, null]);
  });
});
