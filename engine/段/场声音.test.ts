import { describe, expect, it } from 'vitest';
import { cue增益, type 资产cue } from './段定义.ts';
import { 场声音位置, 场声音尾帧, 场声音那截, type 解出场声音 } from './场声音.ts';
import { 开始收集, 结束收集 } from './声音助手.ts';
import { 定义场时间线, 窗口段 } from './窗口段.ts';

const fps = 24;
const 风: 解出场声音 = { 资产: '音效/风', 名: '风', 起帧: 30, 入点秒: 0.25, 速率: 1.25, 峰值: -12 };
const 风数 = { 时长: 3, 峰值: -6 };

/** 照 <段声音> 的放法（段画面.tsx）：段内第 f 帧落在哪条 cue、放到文件第几秒、增益多少；没有声音给 null */
const 放到 = (cues: readonly 资产cue[], f: number, 时长: number) => {
  const c = cues.find((x) => x.帧 <= f && f < x.帧 + x.帧数);
  if (!c) return null;
  const 秒 = (c.入点秒 ?? 0) + ((f - c.帧) * (c.速率 ?? 1)) / fps;
  return { 秒: c.循环 ? 秒 % 时长 : 秒, 增益: cue增益(c, f - c.帧) };
};

/** 把场帧 [起, 止) 切成几段窗口，逐帧比「各段的那截」和「一口气放完」 */
const 逐帧比 = (声: 解出场声音, 数: { 时长: number; 峰值?: number }, 切点: readonly number[], 容差秒: number) => {
  const 尾 = 场声音尾帧(声, 数, fps);
  const 界 = [0, ...切点, 尾 + 10];
  const 一口气增益 = (F: number) => {
    const g = 声.增益 ?? (声.峰值 !== undefined ? 10 ** ((声.峰值 - 数.峰值!) / 20) : 1);
    return 声.淡出 ? g * Math.min(1, (尾 - F) / 声.淡出) : g;
  };
  let 比了 = 0;
  for (let i = 0; i + 1 < 界.length; i++) {
    const 窗 = { 起帧: 界[i]!, 止帧: 界[i + 1]! };
    const cues = 场声音那截(声, 窗, fps, 数);
    for (let F = 窗.起帧; F < 窗.止帧; F++) {
      const 实 = 放到(cues, F - 窗.起帧, 数.时长);
      if (F < 声.起帧 || F >= 尾) {
        expect(实, `场帧 ${F} 不该有声`).toBeNull();
        continue;
      }
      expect(实, `场帧 ${F} 该有声`).not.toBeNull();
      const 该 = 场声音位置(声, 数, fps, F);
      // 循环的位置按圈比（差一点点绕回文件头的也算对得上）
      const 差 = Math.abs(实!.秒 - 该);
      expect(Math.min(差, 数.时长 - 差), `场帧 ${F}`).toBeLessThanOrEqual(容差秒 + 1e-6);
      expect(实!.增益).toBeCloseTo(一口气增益(F), 5);
      比了++;
    }
  }
  expect(比了).toBe(尾 - 声.起帧);
};

describe('场声音那截：上段起、下段接着放，逐帧和一口气放完一样', () => {
  it('不循环：切点前后各帧位置、增益都一样（带入点秒、变速）', () => {
    expect(场声音尾帧(风, 风数, fps)).toBe(30 + Math.ceil(((3 - 0.25) * 24) / 1.25));
    逐帧比(风, 风数, [40], 0);
    逐帧比(风, 风数, [31, 32, 50, 51], 0);
  });
  it('切在声音开头、末尾那一帧上也对；不沾边的窗口没有 cue', () => {
    const 尾 = 场声音尾帧(风, 风数, fps);
    逐帧比(风, 风数, [30, 尾 - 1, 尾], 0);
    expect(场声音那截(风, { 起帧: 0, 止帧: 30 }, fps, 风数)).toEqual([]);
    expect(场声音那截(风, { 起帧: 尾, 止帧: 尾 + 5 }, fps, 风数)).toEqual([]);
  });
  it('后一段那截的 cue：从段首放，入点秒 = 原入点 + 已放的帧 × 速率 ÷ fps', () => {
    const [c] = 场声音那截(风, { 起帧: 40, 止帧: 60 }, fps, 风数);
    expect(c).toEqual({ 帧: 0, 资产: '音效/风', 名: '风', 帧数: 20, 入点秒: 0.25 + (10 * 1.25) / 24, 速率: 1.25, 增益: expect.any(Number) });
    expect(场声音那截(风, { 起帧: 0, 止帧: 40 }, fps, 风数)[0]).toMatchObject({ 帧: 30, 帧数: 10, 入点秒: 0.25 });
  });
  it('淡出按整个声音的尾算：落在哪段，哪段的那截逐帧带上', () => {
    const 淡 = { ...风, 淡出: 12 };
    const 尾 = 场声音尾帧(淡, 风数, fps);
    逐帧比(淡, 风数, [尾 - 5], 0);
    逐帧比(淡, 风数, [40, 尾 - 20], 0);
    // 没碰到淡出的那截还是一个数
    expect(typeof 场声音那截(淡, { 起帧: 0, 止帧: 40 }, fps, 风数)[0]!.增益).toBe('number');
  });
  it('止帧截短；给了止帧且在窗口前的不沾边', () => {
    const 短 = { ...风, 止帧: 45 };
    逐帧比(短, 风数, [40], 0);
    expect(场声音尾帧(短, 风数, fps)).toBe(45);
  });
  it('循环：从文件中间接上时拆成放到文件尾、再从头循环两条，位置差不到 1 帧', () => {
    const 环: 解出场声音 = { 资产: '音效/雨', 名: '雨', 起帧: 5, 止帧: 200, 循环: true, 增益: 0.5 };
    const 数 = { 时长: 1.01 };
    逐帧比(环, 数, [50, 51, 120], 1 / fps);
    const 后 = 场声音那截(环, { 起帧: 50, 止帧: 120 }, fps, 数);
    expect(后.map((c) => [c.帧, c.帧数, Boolean(c.循环), c.入点秒 ?? 0])).toEqual([
      [0, 4, false, ((50 - 5) / 24) % 1.01],
      [4, 66, true, 0],
    ]);
    // 段首正好在文件头：一条循环到底
    const 整圈 = { ...环, 起帧: 0 };
    expect(场声音那截(整圈, { 起帧: 0, 止帧: 100 }, fps, { 时长: 1 }).map((c) => c.循环)).toEqual([true]);
    expect(场声音那截(整圈, { 起帧: 48, 止帧: 100 }, fps, { 时长: 1 })).toEqual([{ 帧: 0, 资产: '音效/雨', 名: '雨', 帧数: 52, 循环: true, 增益: 0.5 }]);
  });
  it('峰值、响度、增益只能给一个；入点秒到了文件尾报错', () => {
    expect(() => 场声音那截({ ...风, 增益: 2 }, { 起帧: 0, 止帧: 60 }, fps, 风数)).toThrow(/只能给一个/);
    expect(() => 场声音那截({ ...风, 入点秒: 3 }, { 起帧: 0, 止帧: 60 }, fps, 风数)).toThrow(/文件尾/);
  });
});

describe('场时间线的 声音 + 窗口段', () => {
  const 线 = 定义场时间线({
    场: '9-试场',
    事件: { 开场: { 在: { 秒: 0 } }, 起风: { 在: { 秒: 1 } }, 切: { 在: { 秒: 2 } }, 收: { 在: { 秒: 4 } } },
    声音: [
      { 资产: '音效/风', 在: '起风', 峰值: -12 },
      { 资产: '配乐/底', 名: '底乐', 在: '开场', 止: '收', 循环: true, 增益: 0.3, 淡出: 6 },
    ],
  });
  const 表 = { 资产: { '音效/风': { 时长: 3, 峰值: -6 }, '配乐/底': { 时长: 1.5 } }, 台词: {} };

  it('起止解成场帧；每段自动带上自己窗口里的那截，排在段自己的 cue 后面', () => {
    expect(线.声音).toEqual([
      { 资产: '音效/风', 名: '风', 起帧: 24, 峰值: -12 },
      { 资产: '配乐/底', 名: '底乐', 起帧: 0, 止帧: 96, 循环: true, 增益: 0.3, 淡出: 6 },
    ]);
    const 上 = 窗口段(线, { 起: '开场', 止: '切', 声音表: 表, 声音: ({ 放 }) => [放('音效/风', 0, { 名: '先吹一下', 帧数: 2 })] });
    const 下 = 窗口段(线, { 起: '切', 止: '收', 声音表: 表 });
    expect(上.声音!.map((c) => c.台词 === undefined && [c.名, c.帧, c.帧数, c.入点秒 ?? 0])).toEqual([
      ['先吹一下', 0, 2, 0],
      ['风', 24, 24, 0],
      ['底乐', 0, 48, 0],
    ]);
    expect(下.声音!.map((c) => c.台词 === undefined && [c.名, c.帧, c.帧数, c.入点秒 ?? 0])).toEqual([
      ['风', 0, 48, 1],
      ['底乐', 0, 24, 0.5],
      ['底乐', 24, 24, 0],
    ]);
    // 底乐 的淡出落在下段最后 6 帧
    const 末条 = 下.声音!.at(-1)!;
    expect(末条.台词 === undefined && (末条.增益 as number[]).slice(-6)).toEqual([0.3, 0.25, 0.2, 0.15, 0.1, 0.05]);
  });
  it('不放场声音：全不放或按名挑；段没有自己的 cue、也没有场声音时不写 声音', () => {
    expect(窗口段(线, { 起: '切', 止: '收', 声音表: 表, 不放场声音: true }).声音).toBeUndefined();
    expect(窗口段(线, { 起: '切', 止: '收', 声音表: 表, 不放场声音: ['底乐'] }).声音!.map((c) => c.台词 === undefined && c.名)).toEqual(['风']);
  });
  it('收集模式：场声音也记进要过的 id；表里没有就先不出 cue', () => {
    const 要过 = 开始收集();
    try {
      const 段 = 窗口段(线, { 起: '切', 止: '收' });
      expect(段.声音).toBeUndefined();
      expect([...要过].sort()).toEqual(['配乐/底', '音效/风']);
    } finally {
      结束收集();
    }
    expect(() => 窗口段(线, { 起: '切', 止: '收' })).toThrow(/跑 anim cues/);
  });
  it('一定不沾边的（起在窗口后）不查表', () => {
    const 早 = 窗口段(线, { 起: '开场', 止: { 帧数: 10 }, 声音表: { 资产: { '配乐/底': { 时长: 1.5 } }, 台词: {} } });
    expect(早.声音!.map((c) => c.台词 === undefined && c.名)).toEqual(['底乐']);
  });
  it('重名、循环不给止、窗口反了都报错', () => {
    expect(() => 定义场时间线({ 场: '9-试', 事件: { a: { 在: { 秒: 0 } } }, 声音: [{ 资产: '音效/x', 在: 'a' }, { 资产: '音效/x', 在: { 秒: 1 } }] })).toThrow(/重名「x」/);
    expect(() => 定义场时间线({ 场: '9-试', 事件: { a: { 在: { 秒: 0 } } }, 声音: [{ 资产: '音效/x', 在: 'a', 循环: true }] })).toThrow(/要给 止/);
    expect(() => 定义场时间线({ 场: '9-试', 事件: { a: { 在: { 秒: 1 } } }, 声音: [{ 资产: '音效/x', 在: 'a', 止: { 秒: 0 } }] })).toThrow(/空的或反了/);
  });
});
