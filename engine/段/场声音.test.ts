import { describe, expect, it } from 'vitest';
import { cue增益, type 资产cue } from './段定义.ts';
import { 场声音位置, 场声音尾秒, 场声音那截, type 解出场声音 } from './场声音.ts';
import { 开始收集, 结束收集 } from './声音助手.ts';
import { 定义场时间线, 窗口段 } from './窗口段.ts';

const 风: 解出场声音 = { 资产: '音效/风', 名: '风', 起秒: 1.25, 入点秒: 0.25, 速率: 1.25, 峰值: -12 };
const 风数 = { 时长: 3, 峰值: -6 };

/** 照 <段声音> 的放法（段画面.tsx）：段内第 t 秒落在哪条 cue、放到文件第几秒、增益多少；没有声音给 null */
const 放到 = (cues: readonly 资产cue[], t: number, 时长: number) => {
  const c = cues.find((x) => x.秒 <= t + 1e-9 && t < x.秒 + x.长秒 - 1e-9);
  if (!c) return null;
  const 秒 = (c.入点秒 ?? 0) + (t - c.秒) * (c.速率 ?? 1);
  return { 秒: c.循环 ? 秒 % 时长 : 秒, 增益: cue增益(c, t - c.秒) };
};

/** 把场时间线切成几段窗口，每 1/60 秒比「各段的那截」和「一口气放完」 */
const 逐刻比 = (声: 解出场声音, 数: { 时长: number; 峰值?: number }, 切点: readonly number[]) => {
  const 尾 = 场声音尾秒(声, 数);
  const 界 = [0, ...切点, 尾 + 0.5];
  const 一口气增益 = (T: number) => {
    const g = 声.增益 ?? (声.峰值 !== undefined ? 10 ** ((声.峰值 - 数.峰值!) / 20) : 1);
    return 声.淡出秒 ? g * Math.min(1, (尾 - T) / 声.淡出秒) : g;
  };
  let 比了 = 0;
  for (let i = 0; i + 1 < 界.length; i++) {
    const 窗 = { 起秒: 界[i]!, 止秒: 界[i + 1]! };
    const cues = 场声音那截(声, 窗, 数);
    for (let k = Math.ceil(窗.起秒 * 60 - 1e-9); k / 60 < 窗.止秒 - 1e-9; k++) {
      const T = k / 60;
      const 实 = 放到(cues, T - 窗.起秒, 数.时长);
      if (T < 声.起秒 - 1e-9 || T >= 尾 - 1e-9) {
        expect(实, `第 ${T} 秒不该有声`).toBeNull();
        continue;
      }
      expect(实, `第 ${T} 秒该有声`).not.toBeNull();
      const 该 = 场声音位置(声, 数, T);
      const 差 = Math.abs(实!.秒 - 该);
      expect(Math.min(差, 数.时长 - 差), `第 ${T} 秒`).toBeLessThanOrEqual(1e-6);
      expect(实!.增益, `第 ${T} 秒`).toBeCloseTo(一口气增益(T), 5);
      比了++;
    }
  }
  expect(比了).toBeGreaterThan(0);
};

describe('场声音那截：上段起、下段接着放，每一刻和一口气放完一样', () => {
  it('不循环：切点前后位置、增益都一样（带入点秒、变速）', () => {
    expect(场声音尾秒(风, 风数)).toBeCloseTo(1.25 + (3 - 0.25) / 1.25);
    逐刻比(风, 风数, [1.7]);
    逐刻比(风, 风数, [1.3, 1.35, 2.1, 2.15]);
  });
  it('切在声音开头、末尾上也对；不沾边的窗口没有 cue', () => {
    const 尾 = 场声音尾秒(风, 风数);
    逐刻比(风, 风数, [1.25, 尾 - 0.05, 尾]);
    expect(场声音那截(风, { 起秒: 0, 止秒: 1.25 }, 风数)).toEqual([]);
    expect(场声音那截(风, { 起秒: 尾, 止秒: 尾 + 0.2 }, 风数)).toEqual([]);
  });
  it('后一段那截的 cue：从段首放，入点秒 = 原入点 + 已放的秒 × 速率', () => {
    const [c] = 场声音那截(风, { 起秒: 1.75, 止秒: 2.5 }, 风数);
    expect(c).toEqual({ 秒: 0, 资产: '音效/风', 名: '风', 长秒: 0.75, 入点秒: 0.25 + 0.5 * 1.25, 速率: 1.25, 增益: expect.any(Number) });
    expect(场声音那截(风, { 起秒: 0, 止秒: 1.75 }, 风数)[0]).toMatchObject({ 秒: 1.25, 长秒: 0.5, 入点秒: 0.25 });
  });
  it('淡出按整个声音的尾算：尾在本截里用 淡出秒，尾在后面的段里写逐格增益', () => {
    const 淡 = { ...风, 淡出秒: 0.5 };
    const 尾 = 场声音尾秒(淡, 风数);
    逐刻比(淡, 风数, [尾 - 0.2]);
    逐刻比(淡, 风数, [1.7, 尾 - 0.8]);
    expect(typeof 场声音那截(淡, { 起秒: 0, 止秒: 1.7 }, 风数)[0]!.增益).toBe('number');
    expect(场声音那截(淡, { 起秒: 1.7, 止秒: 尾 }, 风数)[0]).toMatchObject({ 淡出秒: 0.5 });
    expect(场声音那截(淡, { 起秒: 1.7, 止秒: 尾 - 0.2 }, 风数)[0]!.增益).toMatchObject({ 每秒: 60 });
  });
  it('止秒截短', () => {
    const 短 = { ...风, 止秒: 1.9 };
    逐刻比(短, 风数, [1.7]);
    expect(场声音尾秒(短, 风数)).toBe(1.9);
  });
  it('循环：从文件中间接上时拆成放到文件尾、再从头循环两条', () => {
    const 环: 解出场声音 = { 资产: '音效/雨', 名: '雨', 起秒: 0.2, 止秒: 8, 循环: true, 增益: 0.5 };
    const 数 = { 时长: 1.01 };
    逐刻比(环, 数, [2, 2.05, 5]);
    const 后 = 场声音那截(环, { 起秒: 2, 止秒: 5 }, 数);
    const 位置 = 1.8 % 1.01;
    const 圆 = (x: number) => Math.round(x * 1e9) / 1e9;
    expect(后.map((c) => [圆(c.秒), 圆(c.长秒), Boolean(c.循环), 圆(c.入点秒 ?? 0)])).toEqual([
      [0, 圆(1.01 - 位置), false, 圆(位置)],
      [圆(1.01 - 位置), 圆(3 - (1.01 - 位置)), true, 0],
    ]);
    // 段首正好在文件头：一条循环到底
    const 整圈 = { ...环, 起秒: 0 };
    expect(场声音那截(整圈, { 起秒: 0, 止秒: 4 }, { 时长: 1 }).map((c) => c.循环)).toEqual([true]);
    expect(场声音那截(整圈, { 起秒: 2, 止秒: 4 }, { 时长: 1 })).toEqual([{ 秒: 0, 资产: '音效/雨', 名: '雨', 长秒: 2, 循环: true, 增益: 0.5 }]);
  });
  it('峰值、响度、增益只能给一个；入点秒到了文件尾报错', () => {
    expect(() => 场声音那截({ ...风, 增益: 2 }, { 起秒: 0, 止秒: 3 }, 风数)).toThrow(/只能给一个/);
    expect(() => 场声音那截({ ...风, 入点秒: 3 }, { 起秒: 0, 止秒: 3 }, 风数)).toThrow(/文件尾/);
  });
});

describe('场时间线的 声音 + 窗口段', () => {
  const 线 = 定义场时间线({
    场: '9-试场',
    事件: { 开场: { 在: { 秒: 0 } }, 起风: { 在: { 秒: 1 } }, 切: { 在: { 秒: 2 } }, 收: { 在: { 秒: 4 } } },
    声音: [
      { 资产: '音效/风', 在: '起风', 峰值: -12 },
      { 资产: '配乐/底', 名: '底乐', 在: '开场', 止: '收', 循环: true, 增益: 0.3, 淡出秒: 0.25 },
    ],
  });
  const 表 = { 资产: { '音效/风': { 时长: 3, 峰值: -6 }, '配乐/底': { 时长: 1.5 } }, 台词: {} };

  it('起止解成场时间线的秒；每段自动带上自己窗口里的那截，排在段自己的 cue 后面', () => {
    expect(线.声音).toEqual([
      { 资产: '音效/风', 名: '风', 起秒: 1, 峰值: -12 },
      { 资产: '配乐/底', 名: '底乐', 起秒: 0, 止秒: 4, 循环: true, 增益: 0.3, 淡出秒: 0.25 },
    ]);
    const 上 = 窗口段(线, { 起: '开场', 止: '切', 声音表: 表, 声音: ({ 放 }) => [放('音效/风', 0, { 名: '先吹一下', 长秒: 0.1 })] });
    const 下 = 窗口段(线, { 起: '切', 止: '收', 声音表: 表 });
    expect(上.声音!.map((c) => c.台词 === undefined && [c.名, c.秒, c.长秒, c.入点秒 ?? 0])).toEqual([
      ['先吹一下', 0, 0.1, 0],
      ['风', 1, 1, 0],
      ['底乐', 0, 2, 0],
    ]);
    expect(下.声音!.map((c) => c.台词 === undefined && [c.名, c.秒, c.长秒, c.入点秒 ?? 0])).toEqual([
      ['风', 0, 2, 1],
      ['底乐', 0, 1, 0.5],
      ['底乐', 1, 1, 0],
    ]);
    // 底乐 的淡出落在下段最后一条里
    expect(下.声音!.at(-1)).toMatchObject({ 增益: 0.3, 淡出秒: 0.25 });
  });
  it('不放场声音：全不放或按名挑；段没有自己的 cue、也没有场声音时不写 声音', () => {
    expect(窗口段(线, { 起: '切', 止: '收', 声音表: 表, 不放场声音: true }).声音).toBeUndefined();
    expect(窗口段(线, { 起: '切', 止: '收', 声音表: 表, 不放场声音: ['底乐'] }).声音!.map((c) => c.台词 === undefined && c.名)).toEqual(['风']);
  });
  it('收集模式：场声音也记进要过的 id；表里没有就先不出 cue', () => {
    const 要过 = 开始收集();
    try {
      const 段 = 窗口段(线, { 起: '切', 止: '收' });
      expect(段.声音).toBeUndefined();
      expect([...要过].sort()).toEqual(['配乐/底', '音效/风']);
    } finally {
      结束收集();
    }
    expect(() => 窗口段(线, { 起: '切', 止: '收' })).toThrow(/跑 anim cues/);
  });
  it('一定不沾边的（起在窗口后）不查表', () => {
    const 早 = 窗口段(线, { 起: '开场', 止: { 长秒: 0.5 }, 声音表: { 资产: { '配乐/底': { 时长: 1.5 } }, 台词: {} } });
    expect(早.声音!.map((c) => c.台词 === undefined && c.名)).toEqual(['底乐']);
  });
  it('重名、循环不给止、窗口反了都报错', () => {
    expect(() => 定义场时间线({ 场: '9-试', 事件: { a: { 在: { 秒: 0 } } }, 声音: [{ 资产: '音效/x', 在: 'a' }, { 资产: '音效/x', 在: { 秒: 1 } }] })).toThrow(/重名「x」/);
    expect(() => 定义场时间线({ 场: '9-试', 事件: { a: { 在: { 秒: 0 } } }, 声音: [{ 资产: '音效/x', 在: 'a', 循环: true }] })).toThrow(/要给 止/);
    expect(() => 定义场时间线({ 场: '9-试', 事件: { a: { 在: { 秒: 1 } } }, 声音: [{ 资产: '音效/x', 在: 'a', 止: { 秒: 0 } }] })).toThrow(/空的或反了/);
  });
});
