import { describe, expect, it } from 'vitest';
import { 叠贴图 } from './贴图合成.ts';

const 图 = (...像素: number[][]) => ({ w: 像素.length, h: 1, px: new Uint8Array(像素.flat()) });

describe('叠贴图', () => {
  it('不透明盖住、透明露底、半透明按 alpha 混', () => {
    const 底 = 图([10, 20, 30, 255], [10, 20, 30, 255], [0, 0, 0, 255], [0, 0, 0, 0]);
    const 上 = 图([200, 0, 0, 255], [0, 0, 0, 0], [255, 255, 255, 51], [90, 90, 90, 255]);
    expect([...叠贴图([底, 上]).px]).toEqual([200, 0, 0, 255, 10, 20, 30, 255, 51, 51, 51, 255, 90, 90, 90, 255]);
  });

  it('一层原样返回，尺寸不一样报错，不改输入', () => {
    const 底 = 图([1, 2, 3, 255]);
    expect(叠贴图([底])).toBe(底);
    expect(() => 叠贴图([底, 图([0, 0, 0, 255], [0, 0, 0, 255])])).toThrow(/尺寸/);
    叠贴图([底, 图([9, 9, 9, 255])]);
    expect([...底.px]).toEqual([1, 2, 3, 255]);
  });
});
