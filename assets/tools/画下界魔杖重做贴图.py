#!/usr/bin/env python3
"""画「亚波伦不放水」重做的下界魔杖的贴图（资产 贴图/物品/下界魔杖重做）：64×32 的 RGBA PNG，8 块 16×16 的料，一个模型像素一个贴图像素。
料的顺序和 作品/亚波伦不放水/物品/下界魔杖重做.tsx 的 料表 对应（第 i 块在 x = i % 4 × 16、y = i // 4 × 16）。
颜色是自己配的（黑石、镶金黑石、岩浆块、绯红菌柄、烈焰棒的样子），没有抄游戏或模组贴图的像素。只用标准库，同样的输入出同样的字节。

用法：python3 assets/tools/画下界魔杖重做贴图.py <输出.png>，再 anim --作品 亚波伦不放水 assets add 贴图/物品/下界魔杖重做 <输出.png> --替换
"""
import struct
import sys
import zlib

格 = 16


def 散(x: int, y: int, 种: int) -> float:
    """0～1 的定值噪声"""
    n = (x * 374761393 + y * 668265263 + 种 * 2147483647) & 0xFFFFFFFF
    n = ((n ^ (n >> 13)) * 1274126177) & 0xFFFFFFFF
    return ((n ^ (n >> 16)) & 0xFFFF) / 0xFFFF


def 挑(色们, 权, r: float):
    总 = sum(权)
    for 色, w in zip(色们, 权):
        r -= w / 总
        if r <= 0:
            return 色
    return 色们[-1]


def 黑(x, y):
    # 黑石：偏冷的紫灰，比纯黑亮一档，压在黑红衣服和暗红背景上还分得出
    return 挑([(30, 27, 38), (38, 35, 48), (48, 44, 60), (62, 57, 78)], [3, 5, 3, 1], 散(x, y, 1))


def 黑亮(x, y):
    # 磨制黑石的棱：框、节、托用，给轮廓一条亮边
    return 挑([(66, 61, 84), (80, 74, 100), (98, 91, 122), (58, 54, 74)], [4, 4, 2, 2], 散(x, y, 2))


def 金(x, y):
    return 挑([(246, 195, 67), (222, 160, 40), (255, 236, 150), (190, 122, 28)], [5, 3, 2, 2], 散(x, y, 3))


def 芯(x, y):
    # 从正中往外：淡黄 → 黄 → 橙 → 深橙（照原版芯的黄橙）。模型里按面居中取，所以亮心总在面的正中
    d = max(abs(x - 7.5), abs(y - 7.5))
    r = 散(x, y, 4)
    if d < 1:
        return (255, 246, 176)
    if d < 2:
        return (255, 226, 96) if r < 0.75 else (255, 246, 176)
    if d < 3:
        return (255, 184, 44) if r < 0.75 else (255, 226, 96)
    return (246, 132, 22) if r < 0.75 else (255, 184, 44)


裂纹 = [
    "...#......#.....",
    "..##.....##.....",
    ".##.....##...#..",
    "##.....##...##..",
    "#....###...##...",
    "....##.#..##....",
    "...##..####.....",
    "####....##......",
    "...##....##...##",
    "....#.....##.##.",
    "....##.....###..",
    ".....##....#....",
    "......###.##....",
    "..##....###.....",
    ".##......#......",
    "##.......#......",
]


def 岩浆(x, y):
    # 岩浆块的样子：暗红褐的壳、亮橙黄的裂
    if 裂纹[y][x] == "#":
        return (255, 214, 84) if 散(x, y, 5) < 0.45 else (255, 150, 32)
    return 挑([(84, 24, 10), (108, 34, 12), (66, 18, 8)], [4, 3, 3], 散(x, y, 6))


def 熔核(x, y):
    # 乙的核：整块发亮的橙，裂是白黄，零星几点暗红（像一颗小岩浆怪）
    if 裂纹[y][x] == "#":
        return (255, 248, 190) if 散(x, y, 7) < 0.5 else (255, 222, 96)
    return 挑([(255, 150, 34), (248, 118, 22), (255, 178, 52), (206, 70, 16)], [5, 3, 2, 1], 散(x, y, 8))


def 绯红(x, y):
    # 绯红菌柄：竖纹（列定深浅，再撒一点噪声）
    列 = 散(x, 0, 9)
    底 = (118, 28, 56) if 列 < 0.4 else (136, 38, 68) if 列 < 0.75 else (96, 20, 46)
    r = 散(x, y, 10)
    if r < 0.12:
        return (160, 54, 84)
    if r > 0.9:
        return (74, 14, 36)
    return 底


def 烈焰(x, y):
    # 烈焰棒：横向亮暗相间的节
    带 = y % 4
    底 = [(255, 226, 92), (255, 196, 50), (244, 150, 22), (196, 104, 10)][带]
    return (255, 244, 170) if 散(x, y, 11) < 0.12 else 底


料们 = [黑, 黑亮, 金, 芯, 岩浆, 熔核, 绯红, 烈焰]


def main() -> None:
    宽, 高 = 格 * 4, 格 * 2
    行们 = []
    for y in range(高):
        行 = bytearray([0])
        for x in range(宽):
            料 = 料们[(y // 格) * 4 + x // 格]
            行 += bytes((*料(x % 格, y % 格), 255))
        行们.append(bytes(行))

    def 块(类: bytes, 数: bytes) -> bytes:
        return struct.pack(">I", len(数)) + 类 + 数 + struct.pack(">I", zlib.crc32(类 + 数) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + 块(b"IHDR", struct.pack(">IIBBBBB", 宽, 高, 8, 6, 0, 0, 0)) + 块(b"IDAT", zlib.compress(b"".join(行们), 9)) + 块(b"IEND", b"")
    with open(sys.argv[1], "wb") as f:
        f.write(png)


if __name__ == "__main__":
    main()
