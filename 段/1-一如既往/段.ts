// 验证片唯一的一段：第一人称固定机位，递蛋糕、驯服、微笑推镜、咔哒定格。帧数、场窗口、原声 cue 的帧和入点、咔哒的帧从 分镜.ts 推，增益从场参数推，段里不写数字。
import { 定义段 } from '@engine/段/段定义.ts';
import { fps, 段内事件帧, 段时钟, 画幅 } from '../../分镜.ts';
import { 原声增益, 原声淡入帧, 咔哒增益, 咔哒声 } from '../../场/1-隐世之境一楼/参数.ts';

const 键 = '1-一如既往';
const 钟 = 段时钟(键);

// 原声：固定增益，开头淡入（第 f 帧乘 (f + 1) / 淡入帧，到满为止）。画面里的 配乐音轨.tsx 照这条 cue 出声
const 原声增益帧 = Array.from({ length: 钟.原声.帧数 }, (_, f) => Math.round(原声增益 * Math.min(1, (f + 1) / 原声淡入帧) * 1e6) / 1e6);

// 咔哒：女仆相机的快门声，比定格那一帧早 起音秒 起放，主音落在定格（闪白）那一帧；放满整个文件。画面里的 音效轨.tsx 照这条 cue 出声
const 咔哒起 = 段内事件帧(键).咔哒定格 - Math.round(咔哒声.起音秒 * fps);
const 咔哒帧数 = Math.min(Math.ceil(咔哒声.时长秒 * fps), 钟.帧数 - 咔哒起);

export default 定义段({
  场: '1-隐世之境一楼',
  帧数: 钟.帧数,
  fps,
  宽: 画幅.宽,
  高: 画幅.高,
  地形: [],
  场窗口: 钟.场窗口,
  声音: [
    { ...钟.原声, 资产: '配乐/把回忆拼好给你-抖音原声', 名: '原声', 增益: 原声增益帧 },
    { 帧: 咔哒起, 资产: '音效/车万女仆/item.camera_use', 名: '咔哒', 帧数: 咔哒帧数, 增益: 咔哒增益 },
  ],
});
