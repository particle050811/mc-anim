const 线性 = (K: readonly (readonly [number, number])[], t: number) => {
  const i = K.findIndex(([kt]) => kt > t);
  if (i <= 0) return K[i === 0 ? 0 : K.length - 1]![1];
  const [t0, v0] = K[i - 1]!;
  const [t1, v1] = K[i]!;
  return v0 + ((v1 - v0) * (t - t0)) / (t1 - t0);
};
