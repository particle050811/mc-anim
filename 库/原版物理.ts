// 原版（1.20.1）实体逐刻运动的正本（10-30 整体优化方案 0.6）：下落、落地时刻、按刻插值。新代码一律从这里 import；
// 旧代码里照 LivingEntity.travel 手写的下落循环（`v = (v − 0.08) × 0.98`）原样不动，登记在 docs/副本表.tsv。纯模块。
//
// 原版每刻（20 刻/秒），生物、玩家（LivingEntity.travel）：先按当前速度挪（Entity.move），再改速度：竖直 v = (v − 重力) × 0.98，水平在空中 × 0.91、在地上 × 0.6 × 0.91。
// 物品、下落方块（ItemEntity.tick、FallingBlockEntity.tick）顺序不同：先加重力（v − 0.04），再挪，再 × 0.98（物品水平也是 × 0.98）。
// 用 下落选项 的 物品下落（重力 0.04、先加重力）；同样的初速，物品第一刻就动，生物第二刻才动。
// 渲染时刻与刻之间按 partialTick 线性插值，所以「第 k.5 刻」的位置是第 k、k+1 刻两个位置的中点。
// 这里的高度都是竖直方向的位移（往上为正），单位格；用在场景坐标里就是 z。

export const 刻每秒 = 20;

/** 原版常数（LivingEntity、ItemEntity、FallingBlockEntity、Player） */
export const 原版运动 = {
  /** 生物、玩家的重力（格/刻²） */
  生物重力: 0.08,
  /** 物品、下落方块的重力 */
  物品重力: 0.04,
  /** 竖直阻力：每刻速度乘这个 */
  竖直阻力: 0.98,
  /** 生物空中水平阻力 */
  空中水平阻力: 0.91,
  /** 物品空中水平阻力（ItemEntity.tick；落地时是方块滑度 × 0.98） */
  物品水平阻力: 0.98,
  /** 地上水平阻力：方块滑度 0.6 × 0.91（冰 0.98、蓝冰 0.989 另算） */
  地面水平阻力: 0.6 * 0.91,
  /** 起跳的竖直初速（跳跃提升每级 +0.1） */
  跳跃初速: 0.42,
  /** 疾跑起跳时朝前多给的水平速度 */
  疾跑跳加速: 0.2,
  /** 站在地上时的竖直速度：每刻都被重力拉一次 (0 − 0.08) × 0.98，再被地面挡住；从边上走下去时就以这个速度开始掉 */
  站着竖直速度: (0 - 0.08) * 0.98,
} as const;

export type 下落选项 = {
  初速?: number;
  重力?: number;
  阻力?: number;
  /** 物品、下落方块：先加重力再挪（默认 false：生物、玩家的先挪再改速度） */
  先加重力?: boolean;
};

/** 物品、下落方块的下落（ItemEntity、FallingBlockEntity）。初速另给：{ ...物品下落, 初速: 0.2 } */
export const 物品下落: 下落选项 = { 重力: 原版运动.物品重力, 先加重力: true };

/** 下落一刻：默认先挪再改速度（生物）；先加重力 时先 v − 重力、再挪、再乘阻力（物品） */
export const 下落一刻 = (高: number, 速: number, 重力: number = 原版运动.生物重力, 阻力: number = 原版运动.竖直阻力, 先加重力 = false) =>
  先加重力 ? { 高: 高 + 速 - 重力, 速: (速 - 重力) * 阻力 } : { 高: 高 + 速, 速: (速 - 重力) * 阻力 };

/**
 * 从 0 起落了 刻数 刻时的高度（≤ 0 时一直往下，不碰地面）；刻数可带小数，刻与刻之间线性插值。刻数 ≤ 0 给 0。
 * 副本：把回忆 2-末地 的 原版下落 返回的是「掉了多少格」，等于这里取负（初速 0）。
 */
export const 下落高度 = (刻数: number, 选项: 下落选项 = {}): number => {
  if (刻数 <= 0) return 0;
  let 高 = 0;
  let 速 = 选项.初速 ?? 0;
  const n = Math.floor(刻数);
  for (let k = 0; k < n; k++) ({ 高, 速 } = 下落一刻(高, 速, 选项.重力, 选项.阻力, 选项.先加重力));
  // 刻间按下一刻的位置插（先加重力 时下一刻挪的是 速 − 重力，不是 速）
  return 高 + (刻数 - n) * (下落一刻(高, 速, 选项.重力, 选项.阻力, 选项.先加重力).高 - 高);
};

/**
 * 从 0 掉到 −落差 的逐刻高度表：第 0 项是 0，往后每刻一项，最后一项正好是 −落差（落地那一刻夹在地面上）。
 * 副本：把回忆 2-第一晚 的 下落（默认初速是 站着竖直速度：从方块边上走下去）。
 */
export const 下落表 = (落差: number, 选项: 下落选项 = {}): number[] => {
  if (!(落差 > 0)) return [0];
  const out = [0];
  let 高 = 0;
  let 速 = 选项.初速 ?? 0;
  for (let k = 0; 高 > -落差; k++) {
    if (k > 100000) throw new Error(`下落表：${落差} 格落不到底（初速 ${选项.初速}）`);
    const 下 = 下落一刻(高, 速, 选项.重力, 选项.阻力, 选项.先加重力);
    高 = Math.max(-落差, 下.高);
    速 = 下.速;
    out.push(高);
  }
  return out;
};

/**
 * 掉 落差 格要几刻（带小数：碰地那一刻按这一刻里走过的比例算）。秒 = 刻 / 20。
 * 副本：应力转动 6-3-2 编排的 fallTime（返回秒）。
 */
export const 落地刻 = (落差: number, 选项: 下落选项 = {}): number => {
  if (!(落差 > 0)) return 0;
  let 高 = 0;
  let 速 = 选项.初速 ?? 0;
  for (let k = 0; k < 100000; k++) {
    const 下 = 下落一刻(高, 速, 选项.重力, 选项.阻力, 选项.先加重力);
    if (下.高 <= -落差) return k + (高 + 落差) / (高 - 下.高);
    高 = 下.高;
    速 = 下.速;
  }
  throw new Error(`落地刻：${落差} 格落不到底（初速 ${选项.初速}）`);
};

/** 逐刻表按刻取值：刻与刻之间线性插值（渲染的 partialTick），出了表两头停在端点 */
export const 按刻取 = (表: readonly number[], 刻: number): number => {
  if (!表.length) throw new Error('按刻取：空表');
  if (刻 <= 0) return 表[0]!;
  const i = Math.floor(刻);
  if (i >= 表.length - 1) return 表[表.length - 1]!;
  return 表[i]! + (表[i + 1]! - 表[i]!) * (刻 - i);
};
