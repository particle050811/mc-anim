export const 亚波伦位 = (t: number): V3 => {
  const s = t - 幕起;
  let 现: V3 = 站.一;
  for (const { 到, 位, 渡 } of 到位) {
    if (s <= 到 - 渡) break;
    const u = 平滑(clamp01((s - (到 - 渡)) / 渡));
    现 = [混(现[0], 位[0], u), 混(现[1], 位[1], u), 混(现[2], 位[2], u)];
    if (u < 1) break;
  }
  return 现;
};
