const 图腾表 = 图腾粒子表(S, 1, { 地面: S[2] });

export default 定义画面(段, 声音, () => {
  const { 秒, 段: 本段 } = use段(段);
  const t = 幕起 + 秒;
  const 她此刻 = 演.在(t);
  const 参 = 轮盘参(t);
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  // 末尾火光糊满画面约 0.5 秒：橙白色盖住场景，界面只留血条
  const 糊 = Math.min(1, Math.max(0, (秒 - (本段.秒 - 0.5)) / 0.15));
  return (
    <台地画布
      机位={机位}
      界面={
        <>
          <战斗界面 宽={画幅.宽} 高={画幅.高} s={2} 血条={{ 血比: 1 }} />
          {糊 > 0 && <div style={{ position: 'absolute', inset: 0, opacity: 糊, background: 'radial-gradient(circle at 50% 50%, #fff6dc 0%, #ffc060 45%, #ff8a28 100%)' }} />}
        </>
      }
    >
      <娘化亚波伦 {...她此刻.属性} 持杖 />
      {参 && <杖尖轮盘 杖={演.杖(t)} {...盘摆} 参={参} 每像素格={每像素格} />}
      <炼狱结界演出 秒={t - 扔} 设定={结界设定} />
      <出手们 表={出手表} 秒={t} 况={况} />
      <图腾粒子 表={图腾表} 秒={t - 图腾秒} />
      <反应史蒂夫 状态={史蒂夫状态在(t)} />
    </台地画布>
  );
});
