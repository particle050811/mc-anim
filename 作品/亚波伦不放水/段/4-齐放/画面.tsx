export default 定义画面(段, 声音, () => {
  const { 秒, 段: 本段 } = use段(段);
  const t = 幕起 + 秒;
  const 她 = 演.在(t);
  const 参 = 轮盘参(t);
  const 她胸 = 加(亚波伦位(t), [0, 0, 1.1]);
  const { 机位, 镜 } = 取镜头(镜头表在(t), 秒, 本段.秒);
  // 4-14b 是史蒂夫视角，镜头就在他头里，不画他
  const 第一人称 = 镜.名 === '4-14b';
  // 4-18 末尾火光糊满画面约 0.5 秒：橙白色盖住场景，界面只留血条
  const 糊 = Math.min(1, Math.max(0, (秒 - (本段.秒 - 0.5)) / 0.15));
  const 只血条 = 秒 >= 本段.秒 - 0.5;
  return (
    <台地画布
      机位={机位}
      界面={
        <>
          <战斗界面
            宽={画幅.宽}
            高={画幅.高}
            s={2}
            血条={{ 血比: 0.985 }}
            计数={只血条 ? undefined : { n: 计数在(t) }}
            名签们={出手名签(签表, t, 况, 机位)}
          />
          {糊 > 0 && <div style={{ position: 'absolute', inset: 0, opacity: 糊, background: 'radial-gradient(circle at 50% 50%, #fff6dc 0%, #ffc060 45%, #ff8a28 100%)' }} />}
        </>
      }
    >
      <娘化亚波伦 {...她.属性} 持杖 />
      {参 && <杖尖轮盘 杖={演.杖(t)} {...盘摆} 参={参} 每像素格={每像素格} />}
      <炼狱结界演出 秒={t - 扔} 设定={结界设定} />
      <出手们 表={出手表} 秒={t} 况={况} />
      {!第一人称 && <反应史蒂夫 状态={史蒂夫状态在(t)} />}
    </台地画布>
  );
});
