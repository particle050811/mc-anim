// 第 2 幕 起飞、张开轮盘的画面：走位和她的演出在 编排.ts，这里摆镜头（分镜第二稿 2-01～2-05，机位是 Agent 摆的）。屏幕字（「假如祂用呢？」和片名）用户 11-10 说没要求加，去掉了。
// 没做：猩红雨、史蒂夫走路的腿（位置是平移的）、声音。仪式结构留在台地上（火还烧着，祭品没了）。
import React from 'react';
import { clamp01, lerp as 混 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { 定义画面, use段 } from '@engine/段/段画面.tsx';
import { 娘化亚波伦 } from '../../角色/娘化亚波伦.tsx';
import { 反应史蒂夫 } from '../../角色/反应史蒂夫.tsx';
import { 亚波伦血条 } from '../../界面/战斗界面.tsx';
import { 杖尖轮盘 } from '../../界面/杖尖轮盘.tsx';
import { 安息仪式演出 } from '../../特效/安息仪式.tsx';
import { 召唤方案们 } from '../../特效/安息仪式时序.ts';
import { 祭坛 } from '../../场/1-台地/布局.ts';
import { 取镜头, 台地画布, 画幅, type 镜头 } from '../../场/1-台地/台地场.tsx';
import 线 from '../../场/1-台地/时间线.ts';
import { 亚波伦位, 史蒂夫位, 史蒂夫眼, 演, 现身后, 盘位, 盘半径, 盘摆, 每像素格, 轮盘参 } from './编排.ts';
import 段 from './段.ts';
import 声音 from './声音地址.生成.ts';

const 加 = (a: readonly number[], b: readonly number[], k = 1): V3 => [a[0]! + b[0]! * k, a[1]! + b[1]! * k, a[2]! + b[2]! * k];
const 平滑 = (u: number) => u * u * (3 - 2 * u);

export default 定义画面(段, 声音, () => {
  const { 秒, 事件, 段: 本段 } = use段(段);
  // 编排的时钟：现身后几秒
  const t = 现身后(线.事件.召唤完.秒) + 秒;
  const 她 = 演.在(t);
  const 她位 = 亚波伦位(t);
  const 她胸 = 加(她位, [0, 0, 1.1]);
  const 史位 = 史蒂夫位(t);
  const 盘 = 盘位(t);
  const 参 = 轮盘参(t);
  const 镜头表: 镜头[] = [
    // 2-01 中景，从动作线东侧拍：他冲上来跳上基座挥剑，她离地
    { 名: '2-01', 起: 0, 机位: (u) => ({ pos: 加(祭坛, [混(9.5, 8.8, u), -6.2, 1.7]), tgt: 加(祭坛, [0, -2.6, 混(2.6, 3.6, u)]), lens: 26 }) },
    // 2-02 跟拍上升
    { 名: '2-02', 起: 2, 机位: () => ({ pos: [祭坛[0] - 7.5, 祭坛[1] - 9.5, 祭坛[2] + 1.2 + (她位[2] - 祭坛[2]) * 0.6], tgt: 她胸, lens: 34 }) },
    // 2-03 斜侧面略仰的全景，固定：她在左上，杖指向右下的史蒂夫，盘斜对着镜头
    { 名: '2-03', 起: 事件.举杖 - 0.2, 机位: () => ({ pos: 加(祭坛, [-2.5, -21, 2.4]), tgt: 加(祭坛, [3.4, -2, 8.8]), lens: 22 }) },
    // 2-04 史蒂夫背后过肩仰拍：盘的正面对着他
    {
      名: '2-04',
      起: 10,
      机位: (u) => {
        const 向 = [史位[0] - 她位[0], 史位[1] - 她位[1]];
        const 长 = Math.hypot(向[0]!, 向[1]!);
        const [dx, dy] = [向[0]! / 长, 向[1]! / 长];
        return { pos: [史位[0] + dx * 混(2.4, 2.0, u) - dy * 0.7, 史位[1] + dy * 混(2.4, 2.0, u) + dx * 0.7, 史位[2] + 1.45], tgt: 加(盘.心, [0, 0, -1.2]), lens: 36 };
      },
    },
    // 2-05 贴着盘面斜掠，停在圆心和后面的杖头上
    {
      名: '2-05',
      起: 12.5,
      机位: (u) => {
        const k = 平滑(u);
        // 离盘的远近跟着盘的大小走
        const r = (盘半径 / 6) * 1.6;
        const 位 = 加(加(加(盘.心, 盘.右, 混(7, 1.4, k) * r), 盘.上, 混(1.8, 0.5, k) * r), 盘.法向, 混(2.2, 3.6, k) * r);
        return { pos: 位, tgt: 加(盘.心, 盘.右, 混(3.2, 0, k) * r), lens: 混(26, 34, k) };
      },
    },
  ];
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  const 落地后 = 秒 >= 1.7;
  // 朝向：冲的时候朝北，之后身子跟着头转（看 偏出 50 度身子自己跟）
  const 朝她 = (Math.atan2(-(她位[0] - 史位[0]), 她位[1] - 史位[1]) * 180) / Math.PI;
  return (
    <台地画布
      机位={机位}
      界面={
        <>
          <亚波伦血条 宽={画幅.宽} s={2} 血比={1} />
        </>
      }
    >
      {/* 仪式做完后留在台地上的结构：方案的 总秒 之后就是静态的结构和火 */}
      <group position={祭坛}>
        <安息仪式演出 秒={线.事件.召唤完.秒 - 线.事件.放环.秒 + 秒} 方案={召唤方案们.短} />
      </group>
      <娘化亚波伦 {...她.属性} 持杖 />
      {参 && <杖尖轮盘 杖={演.杖(t)} {...盘摆} 参={参} 每像素格={每像素格} />}
      <反应史蒂夫
        状态={{
          位置: 史位,
          朝向: 秒 < 1.7 ? 0 : 朝她,
          看: 秒 < 0.75 ? 加(祭坛, [0, 0, 4]) : 加(她位, [0, 0, 1.5]),
          秒,
          右手: '剑',
          // 用户 11-10 定：高端局，史蒂夫不拿盾
          左手: '空',
          挥剑秒: 秒 >= 事件.跳劈 ? 秒 - 事件.跳劈 : undefined,
        }}
      />
    </台地画布>
  );
});
