const 加 = (a: readonly number[], b: readonly number[], k = 1): V3 => [a[0]! + b[0]! * k, a[1]! + b[1]! * k, a[2]! + b[2]! * k];
const 插 = (a: readonly number[], b: readonly number[], k: number): V3 => [混(a[0]!, b[0]!, k), 混(a[1]!, b[1]!, k), 混(a[2]!, b[2]!, k)];
const 本地 = (x: number, y: number, z: number): V3 => 加(祭坛, [x, y, z]);
/** 第 2 幕幕内秒 → 编排的钟（现身后几秒） */
const 幕起 = 现身后(线.事件.召唤完.秒);
const 钟 = (s: number) => 幕起 + s;
const 史胸 = (t: number) => 加(史蒂夫位(t), [0, 0, 1.2]);
const 她胸 = (t: number) => 加(亚波伦位(t), [0, 0, 1.1]);
/** 水平单位向量 a → b */
const 朝 = (a: readonly number[], b: readonly number[]): V3 => {
  const [x, y] = [b[0]! - a[0]!, b[1]! - a[1]!];
  const n = Math.hypot(x, y) || 1;
  return [x / n, y / n, 0];
};
/** 往左转 90 度（水平） */
const 左 = (v: readonly number[]): V3 => [-v[1]!, v[0]!, 0];

/** 镜头从幕内 起 秒开始、到 止 秒，跟拍；摆(编排的钟, 进度) */
const 跟 = (名: string, 起: number, 止: number, 摆: (t: number, k: number) => Cam, 步?: number): 镜头 => ({ 名, 起, 机位: 跟拍(止 - 起, (s, k) => 摆(钟(起 + s), k), 步) });

const 切 = [0, 1.3, 2.45, 3.35, 4.17, 5.4, 6.6, 7.65, 8.9, 10.3, 11.95] as const;
const 镜头表: 镜头[] = [
  // 2-01 贴着他右手边跟着冲：他疾跑、连跳两下上基座，机位跟着他往北、随着跳抬起来，前面是祭坛上的她
  跟('2-01', 切[0], 切[1], (t, k) => {
    const p = 史蒂夫位(t);
    // 高过灵魂火（火顶离地 2 格），不然跳上基座那一下机位撞进东南角的火里
    return { pos: [p[0] + 3.6, p[1] - 0.4, Math.max(混(祭坛[2], p[2], 0.6) + 0.9, 祭坛[2] + 2.5)], tgt: 插(史胸(t), 她胸(t), 混(0.3, 0.45, k)), lens: 24 };
  }),
  // 2-02 祭坛西边、和他们一样高：他跳上台子在空中劈下去，她仰身往后一让、离地；她往东飞走，镜头摇过去跟着
  跟('2-02', 切[1], 切[2], (t, k) => ({ pos: 本地(-5.6, 混(-1.2, -0.4, k), 混(3.0, 3.6, 平滑(k))), tgt: 插(史胸(t), 她胸(t), 0.7), lens: 20 })),
  // 2-03 南边跟着往东追：他跳下台子疾跑起跳、在空中劈第二刀，她横着让出那条线
  跟('2-03', 切[2], 切[3], (t) => {
    const m = 插(史胸(t), 她胸(t), 0.5);
    return { pos: 加(m, [-1.0, -6.6, 1.0]), tgt: m, lens: 24 };
  }),
  // 2-04 贴地跟着她滑：他落地横扫，刀从她头上过去，她贴着地面绕着他滑到他背后；切在她瞬移那一下
  跟('2-04', 切[3], 切[4], (t) => {
    const [史, 她] = [史蒂夫位(t), 亚波伦位(t)];
    const 向 = 朝(史, 她);
    return { pos: 加(加(史, 向, 3.0), 左(向), 4.2).map((v, i) => (i === 2 ? 祭坛[2] + 0.55 : v)) as V3, tgt: 加(插(她, 史, 0.35), [0, 0, 0.8]), lens: 24 };
  }, 0.12),
  // 2-05 甩到他背后：她从烟里出现在他身后，他转身回砍，她后仰着往后滑退；镜头从他左后方跟着她往东南让
  {
    名: '2-05',
    起: 切[4],
    机位: (() => {
      const 跟着 = 跟拍(切[5] - 切[4], (s, k) => {
        const t = 钟(切[4] + s);
        const 史 = 史蒂夫位(t);
        return { pos: 加(史, [混(-1.2, 0.2, k), 混(-4.8, -5.4, k), 1.3]), tgt: 插(史胸(t), 她胸(t), 0.6), lens: 24 };
      });
      // 切进来的头 0.2 秒镜头还朝着她瞬移前的地方，甩过去
      const 烟起 = 瞬移们[0]!.从;
      return (u: number, s: number): Cam => {
        const c = 跟着(u, s);
        const k = 平滑(s / 0.2);
        return k >= 1 ? c : { ...c, tgt: 插(加(烟起, [0, 0, 0.8]), c.tgt, k) };
      };
    })(),
  },
  // 2-06 西边跟着往东南追：他疾跑跳起来劈第六刀，她侧飞让开，机位随着他起跳抬高
  跟('2-06', 切[5], 切[6], (t) => {
    const m = 插(史胸(t), 她胸(t), 0.5);
    return { pos: 加(m, [-5.6, -1.0, 1.4]), tgt: m, lens: 24 };
  }),
  // 2-07 贴地仰拍：他跳起来往上砍，她往上一拔，刀尖擦着她脚底过去；镜头跟着她往上摇
  跟('2-07', 切[6], 切[7], (t, k) => ({ pos: 本地(混(8.4, 8.9, k), 混(-9.4, -9.8, k), 0.45), tgt: 插(史胸(t), 她胸(t), 混(0.45, 0.7, 平滑(k))), lens: 22 })),
  // 2-08 他背后仰拍：她从他头顶斜着拔上去、往西南绕，他仰着头跟着倒退（他整个人在画面下半）
  跟('2-08', 切[7], 切[8], (t) => {
    const 史 = 史蒂夫位(t);
    const 向 = 朝(亚波伦位(t), 史);
    return { pos: 加(加(加(史, 向, 7.0), 左(向), 1.5), [0, 0, 2.0]), tgt: 插(史蒂夫眼(t), 她胸(t), 0.4), lens: 16 };
  }),
  // 2-09 空中在她前面倒着飞：她背对他往祭坛上空飞、迎着镜头过来，她身后下方是追着她跑的他
  跟('2-09', 切[8], 切[9], (t) => {
    const 她 = 亚波伦位(t);
    const 速 = 朝(亚波伦位(t - 0.1), 她);
    return { pos: 加(加(加(她, 左(速), -2.0), 速, 10.0), [0, 0, 2.0]), tgt: 插(她胸(t), 史胸(t), 0.27), lens: 16 };
  }),
  // 2-10 在她面前：她到了祭坛上空，转过身来、杖平伸出去指着他，盘从杖尖一圈圈张开，镜头慢慢往前推
  跟('2-10', 切[9], 切[10], (t, k) => {
    // 在她和他之间那条斜线上（盘正对着他张开，机位在这条线上才看得见盘面），往她右手边偏一点
    const 胸 = 她胸(t);
    const d = 加(史蒂夫眼(t), 胸, -1);
    const n = Math.hypot(...d);
    return { pos: 加(加(胸, d, 混(5.2, 4.2, 平滑(k)) / n), 左(朝(胸, 史蒂夫眼(t))), 1.6), tgt: 插(胸, 盘位(t).心, 0.3), lens: 26 };
  }),
  // 2-11 她背后越过她的肩往下看：盘在杖尖前面张开，盘那边地上的他追过来刹住、往后一缩，站定
  跟('2-11', 切[10], 线.事件.开盘完.秒 - 线.事件.召唤完.秒, (t, k) => {
    const 胸 = 她胸(t);
    const d = 加(史蒂夫眼(t), 胸, -1);
    const n = Math.hypot(...d);
    return { pos: 加(加(加(胸, d, -混(4.6, 5.2, k) / n), 左(朝(胸, 史蒂夫眼(t))), 2.6), [0, 0, 1.2]), tgt: 插(盘位(t).心, 史蒂夫眼(t), 0.5), lens: 26 };
  }),
];

export default 定义画面(段, 声音, () => {
  const { 秒, 段: 本段 } = use段(段);
  const t = 钟(秒);
  const 她 = 演.在(t);
  const 参 = 轮盘参(t);
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  return (
    <台地画布 仪式结构 机位={机位} 界面={<亚波伦血条 宽={画幅.宽} s={2} 血比={1} />}>
      {/* 仪式做完后留在台地上的结构：方案的 总秒 之后就是静态的结构和火 */}
      <group position={祭坛}>
        <安息仪式演出 秒={线.事件.召唤完.秒 - 线.事件.放环.秒 + 秒} 方案={召唤方案们.短} />
      </group>
      <娘化亚波伦 {...她.属性} 持杖 />
      {参 && <杖尖轮盘 杖={演.杖(t)} {...盘摆} 参={参} 每像素格={每像素格} />}
      <瞬移烟 瞬移们={瞬移们} 秒={t} />
      <反应史蒂夫
        状态={{
          ...史蒂夫走.在(t),
          看: 史蒂夫看(t),
          秒,
          右手: 史蒂夫右手(t),
          // 用户 11-10 定：高端局，史蒂夫不拿盾
          左手: '空',
          挥剑秒: 史蒂夫挥剑秒(t),
          蓄力: 史蒂夫蓄力(t),
        }}
      />
    </台地画布>
  );
});
