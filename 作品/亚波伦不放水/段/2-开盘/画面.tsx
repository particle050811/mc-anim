/** 水平单位向量 a → b */
const 朝 = (a: readonly number[], b: readonly number[]): V3 => {
  const [x, y] = [b[0]! - a[0]!, b[1]! - a[1]!];
  const n = Math.hypot(x, y) || 1;
  return [x / n, y / n, 0];
};
/** 往左转 90 度（水平） */
const 左 = (v: readonly number[]): V3 => [-v[1]!, v[0]!, 0];
const 归 = (v: readonly number[]): V3 => {
  const n = Math.hypot(...v) || 1;
  return [v[0]! / n, v[1]! / n, v[2]! / n];
};
/** 从 pos 看 a、b 两点：视线取两个方向的加权平均（w 偏向 a），远近差得多时也能把两人都框住 */
const 两看 = (pos: V3, a: readonly number[], b: readonly number[], w: number): V3 => 加(pos, 加(加([0, 0, 0], 归(加(a, pos, -1)), w), 归(加(b, pos, -1)), 1 - w));

