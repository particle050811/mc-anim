/** 2-11 里他的小动作（幕内秒；不改位置）：抬头看她（切进来时视线比她低一些，0.4 秒抬上去），剑往上提一点握紧、提到幕末（Agent 取的；提到 0.45 时拳头到了脸的高度，挡脸）。
 * 第 4 幕开头他是放下剑的（编排-齐放.ts），切过去的 4-01 只拍她，他不在画面里 */
const 收势 = { 抬头: [12.9, 13.3] as const, 低看: 0.3, 举剑: [13.0, 13.35] as const, 剑高: 0.25 };
const 史蒂夫收势 = (秒: number, t: number) => {
  const 看 = 史蒂夫看(t);
  if (秒 < 收势.抬头[0]) return { 看, 蓄力: 史蒂夫蓄力(t) };
  // 低看：往他眼高那条水平线压一部分
  const 低 = 收势.低看 * (1 - 平滑((秒 - 收势.抬头[0]) / (收势.抬头[1] - 收势.抬头[0])));
  const 眼 = 史蒂夫眼(t);
  const 看低: V3 = [看[0], 看[1], 混(看[2], 眼[2], 低)];
  const 举 = 收势.剑高 * 平滑((秒 - 收势.举剑[0]) / (收势.举剑[1] - 收势.举剑[0]));
  return { 看: 看低, 蓄力: Math.max(史蒂夫蓄力(t), 举) };
};

