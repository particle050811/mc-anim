// 第 2 幕 起飞、张开轮盘的画面：走位和她的演出在 场/1-台地/编排-开盘.ts，这里摆镜头。屏幕字（「假如祂用呢？」和片名）用户 11-10 说没要求加，去掉了。
// 镜头是 Agent 摆的五个一直在走的镜头（用户 11-10 嫌初版运镜僵，重排过；内容还是分镜第二稿 2-01～2-05 那五件事）：机位是过关键点的样条，关键点跟着人在那一刻的位置定，切进来时已经带着速度。
// 没做：猩红雨、声音。仪式结构留在台地上（火还烧着，祭品没了）。
import React from 'react';
import { 机位样条, type Cam, type 样条关键 } from '@engine/core/机位.ts';
import { lerp as 混 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { 定义画面, use段 } from '@engine/段/段画面.tsx';
import { 娘化亚波伦 } from '../../角色/娘化亚波伦.tsx';
import { 反应史蒂夫 } from '../../角色/反应史蒂夫.tsx';
import { 亚波伦血条 } from '../../界面/战斗界面.tsx';
import { 杖尖轮盘 } from '../../界面/杖尖轮盘.tsx';
import { 安息仪式演出 } from '../../特效/安息仪式.tsx';
import { 召唤方案们 } from '../../特效/安息仪式时序.ts';
import { 祭坛 } from '../../场/1-台地/布局.ts';
import { 取镜头, 台地画布, 画幅, type 镜头 } from '../../场/1-台地/台地场.tsx';
import 线 from '../../场/1-台地/时间线.ts';
import { 亚波伦位, 亚波伦头, 史蒂夫位, 史蒂夫眼, 史蒂夫走, 演, 现身后, 盘位, 盘半径, 盘摆, 每像素格, 轮盘参 } from '../../场/1-台地/编排-开盘.ts';
import 段 from './段.ts';
import 声音 from './声音地址.生成.ts';

const 加 = (a: readonly number[], b: readonly number[], k = 1): V3 => [a[0]! + b[0]! * k, a[1]! + b[1]! * k, a[2]! + b[2]! * k];

const 度 = Math.PI / 180;

export default 定义画面(段, 声音, () => {
  const { 秒, 事件, 段: 本段 } = use段(段);
  // 编排的时钟：现身后几秒
  const 幕起 = 现身后(线.事件.召唤完.秒);
  const t = 幕起 + 秒;
  const 她 = 演.在(t);
  const 参 = 轮盘参(t);
  const 本地 = (x: number, y: number, z: number): V3 => 加(祭坛, [x, y, z]);
  const 键 = (时刻: number, pos: V3, tgt: V3, lens: number): 样条关键 => [时刻, { pos, tgt, lens }];
  // 盘张开以后她只剩悬着的起伏，镜头按盘在一个定下来的时刻的位置摆（跟着盘每帧走，她的起伏就被镜头抵掉了）
  const 盘 = 盘位(现身后(线.事件.张盘.秒) + 1);
  const 史定 = 史蒂夫位(幕起 + 6);
  const 史眼定 = 史蒂夫眼(幕起 + 6);
  const 镜头表: 镜头[] = [
    // 2-01 贴地从动作线东侧跟着他往北走：他冲上来、跳上基座在空中挥剑，她离地往上走出画面，他落在基座上往回跳
    {
      名: '2-01',
      起: 0,
      机位: (_u, s) =>
        机位样条(
          [
            键(0, 本地(7.0, -9.2, 1.0), 本地(0, -5.6, 1.6), 26),
            键(1.0, 本地(6.0, -5.6, 1.3), 本地(0, -2.2, 3.0), 24),
            键(1.9, 本地(6.4, -3.2, 1.7), 本地(0, -2.4, 3.7), 23),
          ],
          s,
        ),
    },
    // 2-02 接她往上走：摇臂跟着她盘旋上升，从正南的下方转到东北、升到和她平齐，扫过她的正面；她升到位、杖抬起来
    {
      名: '2-02',
      起: 1.9,
      机位: (_u, s) => {
        const 关键 = [0, 0.9, 1.8, 2.7, 3.5].map((秒点, i, 全): 样条关键 => {
          const k = i / (全.length - 1);
          const 位 = 亚波伦位(幕起 + 1.9 + 秒点);
          const [角, 半径] = [混(-100, 20, k) * 度, 混(6.4, 5.2, k)];
          // 看的点比胸口高半格：她头顶的光环让到血条下面
          return 键(秒点, 加(位, [半径 * Math.cos(角), 半径 * Math.sin(角), 1.1 + 混(-1.6, 0.3, k)]), 加(位, [0, 0, 1.6]), 混(27, 32, k));
        });
        return 机位样条(关键, s);
      },
    },
    // 2-03 在杖指的方向上、盘的正面略偏：三圈一圈一圈张开，镜头一路往后拉，把整个盘和盘后面的她让出来
    {
      名: '2-03',
      起: 5.4,
      机位: (_u, s) => {
        const 点 = (前: number, 右: number, 上: number) => 加(加(加(盘.心, 盘.法向, 前), 盘.右, 右), 盘.上, 上);
        return 机位样条([键(0, 点(2.6, 1.7, 0.6), 点(-0.9, 0, 0.1), 28), 键(1.2, 点(4.6, 1.0, 0.1), 点(-0.4, 0, 0), 26), 键(2.6, 点(5.8, -1.6, -0.8), 点(0, 0, 0), 24)], s);
      },
    },
    // 2-04 从史蒂夫右肩后起，越过他的肩往上摇、往前推：从他的后脑勺一路摇到头顶上对着他的盘和盘后面的她（她在 12 格高，一个画面装不下两个人，用摇的）
    {
      名: '2-04',
      起: 8,
      机位: (_u, s) => {
        const 向 = [史定[0] - 盘.心[0], 史定[1] - 盘.心[1]];
        const 长 = Math.hypot(向[0]!, 向[1]!);
        const [dx, dy] = [向[0]! / 长, 向[1]! / 长];
        // 后 = 在他背后几格，右 = 往他右手边偏几格
        const 点 = (后: number, 右: number, 高: number): V3 => [史定[0] + dx * 后 - dy * 右, 史定[1] + dy * 后 + dx * 右, 史定[2] + 高];
        const 看 = (k: number) => 加(史眼定, [(盘.心[0] - 史眼定[0]) * k, (盘.心[1] - 史眼定[1]) * k, (盘.心[2] - 史眼定[2]) * k]);
        return 机位样条([键(0, 点(4.8, 1.3, 1.4), 看(0.03), 28), 键(1.1, 点(3.3, 1.1, 1.8), 看(0.16), 34), 键(2.2, 点(1.6, 0.9, 2.2), 看(1), 50)], s);
      },
    },
    // 2-05 贴着盘面斜掠进来，一边往外拉开，收在盘的斜正面：圆心、杖头和盘后面的她
    {
      名: '2-05',
      起: 10.2,
      机位: (_u, s) => {
        // 离盘的远近跟着盘的大小走
        const r = (盘半径 / 6) * 1.6;
        const 一格 = (右: number, 上: number, 前: number, 看右: number, lens: number): Cam => ({
          pos: 加(加(加(盘.心, 盘.右, 右 * r), 盘.上, 上 * r), 盘.法向, 前 * r),
          tgt: 加(盘.心, 盘.右, 看右 * r),
          lens,
        });
        return 机位样条(
          [
            [0, 一格(7.4, 1.9, 2.1, 3.4, 26)],
            [0.8, 一格(4.6, 1.2, 4.4, 1.4, 28)],
            [1.8, 一格(3.2, 0.8, 6.5, 0.4, 30)],
          ],
          s,
        );
      },
    },
  ];
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  return (
    <台地画布
      仪式结构
      机位={机位}
      界面={
        <>
          <亚波伦血条 宽={画幅.宽} s={2} 血比={1} />
        </>
      }
    >
      {/* 仪式做完后留在台地上的结构：方案的 总秒 之后就是静态的结构和火 */}
      <group position={祭坛}>
        <安息仪式演出 秒={线.事件.召唤完.秒 - 线.事件.放环.秒 + 秒} 方案={召唤方案们.短} />
      </group>
      <娘化亚波伦 {...她.属性} 持杖 />
      {参 && <杖尖轮盘 杖={演.杖(t)} {...盘摆} 参={参} 每像素格={每像素格} />}
      <反应史蒂夫
        状态={{
          ...史蒂夫走.在(t),
          看: 亚波伦头(t),
          秒,
          右手: '剑',
          // 用户 11-10 定：高端局，史蒂夫不拿盾
          左手: '空',
          挥剑秒: 秒 >= 事件.跳劈 ? 秒 - 事件.跳劈 : undefined,
        }}
      />
    </台地画布>
  );
});
