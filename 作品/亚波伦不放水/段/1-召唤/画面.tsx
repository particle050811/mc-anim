// 第 1 幕 召唤的画面：台地上的安息仪式（特效/安息仪式.tsx，短方案）→ 过渡 → 亚波伦现身、持杖站在祭坛上；史蒂夫在祭坛南边看着、后退、拔剑。
// 镜头是 Agent 摆的三个连续运动的长镜头（用户 11-10 嫌初版运镜僵，重排过；分镜第二稿的 1-01～1-04 是四个基本固定的机位）。和分镜不一样：没有「手落在祭坛上」的特写（史蒂夫站在基座圈外够不着，环直接出现在祭坛上）。
import React from 'react';
import { 机位样条 } from '@engine/core/机位.ts';
import { clamp01 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { 定义画面, use段 } from '@engine/段/段画面.tsx';
import { 娘化亚波伦, 站立 } from '../../角色/娘化亚波伦.tsx';
import { 反应史蒂夫 } from '../../角色/反应史蒂夫.tsx';
import { 亚波伦血条 } from '../../界面/战斗界面.tsx';
import { 安息仪式演出 } from '../../特效/安息仪式.tsx';
import { 召唤方案们, 游戏, 现身位置 } from '../../特效/安息仪式时序.ts';
import { 祭坛 } from '../../场/1-台地/布局.ts';
import { 亚波伦头, 史蒂夫走, 现身后 as 编排钟 } from '../../场/1-台地/编排-开盘.ts';
import 线 from '../../场/1-台地/时间线.ts';
import { 取镜头, 台地画布, 画幅, type 镜头 } from '../../场/1-台地/台地场.tsx';
import 段 from './段.ts';
import 声音 from './声音地址.生成.ts';

const 方案 = 召唤方案们.短;
const 加 = (a: V3, b: readonly number[]): V3 => [a[0] + b[0]!, a[1] + b[1]!, a[2] + b[2]!];

export default 定义画面(段, 声音, () => {
  const { 秒, 事件, 段: 本段 } = use段(段);
  const 仪式秒 = 秒 - 事件.放环;
  const 现身后 = 秒 - 事件.现身;
  // 编排的钟（现身后几秒，现身前是负的）：史蒂夫的走位从第 1 幕开头一路排到第 2 幕（场/1-台地/编排-开盘.ts）
  const t = 编排钟(线.事件.开始.秒 + 秒);
  // 机位都是过关键点的样条（engine/core/机位.ts 的 机位样条）：镜头一直在走、切进来时已经带着速度，不在关键点上停（用户 11-10：前面的运镜太僵，要流畅的电影级运镜）
  const 本地 = (x: number, y: number, z: number): V3 => 加(祭坛, [x, y, z]);
  const 镜头表: 镜头[] = [
    // 1-01 一镜到现身前：从史蒂夫右肩后起，越过他推向祭坛（环落下、碎屑往祭坛收），顺势绕到东侧升起来看完成的光柱、法阵、聚风带，他在画面深处后退拔剑
    {
      名: '1-01',
      起: 0,
      机位: (_u, s) =>
        机位样条(
          [
            [0, { pos: 本地(2.2, -9.8, 2.1), tgt: 本地(0, -1, 2.4), lens: 30 }],
            [2, { pos: 本地(4.6, -7.6, 1.8), tgt: 本地(0, 0, 2.5), lens: 29 }],
            [3.4, { pos: 本地(8.0, -3.6, 2.8), tgt: 本地(0, 0, 3.0), lens: 28 }],
            [4.8, { pos: 本地(8.6, 2.0, 4.4), tgt: 本地(0, -0.3, 2.4), lens: 27 }],
            [6.1, { pos: 本地(6.2, 6.6, 5.2), tgt: 本地(0, -1.0, 2.0), lens: 26 }],
          ],
          s,
        ),
    },
    // 1-02 贴地仰拍，从史蒂夫左后方擦着他往祭坛推：火焰炸开，她出现在祭坛上，他在前景右侧退半步、被镜头越过去
    {
      名: '1-02',
      起: 事件.现身 - 0.4,
      机位: (_u, s) =>
        机位样条(
          [
            [0, { pos: 本地(-3.4, -11.8, 0.7), tgt: 本地(0.3, 0, 3.2), lens: 22 }],
            [2.7, { pos: 本地(-2.6, -7.2, 1.1), tgt: 本地(0.1, 0, 3.6), lens: 24 }],
          ],
          s,
        ),
    },
    // 1-03 从史蒂夫肩后起，越过他的头顶一路推到她的脸；他在镜头下面提剑上前
    {
      名: '1-03',
      起: 事件.现身 + 2.3,
      机位: (_u, s) =>
        机位样条(
          [
            [0, { pos: 本地(1.6, -12.0, 2.4), tgt: 本地(0, 0, 3.7), lens: 35 }],
            [1.4, { pos: 本地(1.0, -8.2, 3.1), tgt: 本地(0, 0, 3.65), lens: 38 }],
            [2.7, { pos: 本地(0.5, -4.2, 3.7), tgt: 本地(0, 0, 3.6), lens: 44 }],
          ],
          s,
        ),
    },
  ];
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  const 史 = 史蒂夫走.在(t);
  const 提示 = 仪式秒 >= 方案.提示 && 现身后 < 0;
  const 血条透明 = clamp01((现身后 - 2.2) / 0.6);
  return (
    <台地画布
      仪式结构
      机位={机位}
      界面={
        <>
          {/* 黑暗效果（游戏里提示那一刻给 32 格内的玩家上「黑暗」）：压暗到现身 */}
          <div style={{ position: 'absolute', inset: 0, background: '#000', opacity: 0.45 * clamp01((仪式秒 - 方案.提示) / 0.5) * (1 - clamp01(现身后 / 0.3)) }} />
          {提示 && (
            <div style={{ position: 'absolute', left: 0, right: 0, bottom: 画幅.高 * 0.2, textAlign: 'center', color: '#FF5555', fontFamily: 'Minecraft, monospace', fontSize: 26, textShadow: '2px 2px 0 #3F1515' }}>{游戏.提示文字}</div>
          )}
          {血条透明 > 0 && <亚波伦血条 宽={画幅.宽} s={2} 血比={1} 透明度={血条透明} />}
        </>
      }
    >
      <group position={祭坛}>
        <安息仪式演出 秒={仪式秒} 方案={方案}>
          <娘化亚波伦 pose={{ loc: [...现身位置], yaw: 180 }} 秒={Math.max(0, 现身后)} 表演={站立} 持杖 />
        </安息仪式演出>
      </group>
      <反应史蒂夫 状态={{ ...史, 看: 亚波伦头(t), 秒, 右手: 仪式秒 > 方案.完成 + 1 ? '剑' : '空' }} />
    </台地画布>
  );
});
