// 第 1 幕 召唤的画面：台地上的安息仪式（特效/安息仪式.tsx，短方案）→ 过渡 → 亚波伦现身、持杖站在祭坛上；史蒂夫在祭坛南边看着、后退、拔剑。
// 镜头照分镜第二稿 1-01～1-04 排，机位是 Agent 摆的。和分镜不一样：1-01 没有「手落在祭坛上」的特写（史蒂夫站在基座圈外够不着，环直接出现在祭坛上）。
import React from 'react';
import { clamp01, lerp as 混, smoothstep01 as 平滑 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { 定义画面, use段 } from '@engine/段/段画面.tsx';
import { 娘化亚波伦, 站立 } from '../../角色/娘化亚波伦.tsx';
import { 反应史蒂夫 } from '../../角色/反应史蒂夫.tsx';
import { 亚波伦血条 } from '../../界面/战斗界面.tsx';
import { 安息仪式演出 } from '../../特效/安息仪式.tsx';
import { 召唤方案们, 游戏, 现身位置 } from '../../特效/安息仪式时序.ts';
import { 史蒂夫召唤位, 祭坛 } from '../../场/1-台地/布局.ts';
import { 取镜头, 台地画布, 画幅, type 镜头 } from '../../场/1-台地/台地场.tsx';
import 段 from './段.ts';
import 声音 from './声音地址.生成.ts';

const 方案 = 召唤方案们.短;
const 加 = (a: V3, b: readonly number[]): V3 => [a[0] + b[0]!, a[1] + b[1]!, a[2] + b[2]!];

export default 定义画面(段, 声音, () => {
  const { 秒, 事件, 段: 本段 } = use段(段);
  const 仪式秒 = 秒 - 事件.放环;
  const 现身后 = 秒 - 事件.现身;
  const 亚波伦头 = 加(祭坛, [现身位置[0], 现身位置[1], 现身位置[2] + 1.75]);
  const 镜头表: 镜头[] = [
    // 1-01 近景，平视祭坛：环落上去，碎屑开始往祭坛收
    { 名: '1-01', 起: 0, 机位: (u) => ({ pos: 加(祭坛, [混(5.6, 5.0, u), -8.2, 3.8]), tgt: 加(祭坛, [0, 0, 2.3]), lens: 32 }) },
    // 1-02 中景，绕祭坛转四分之一圈：完成的光柱、法阵、聚风带；史蒂夫后退拔剑
    {
      名: '1-02',
      起: 事件.放环 + 1.3,
      机位: (u) => {
        const 角 = 混(-0.55, 0.45, 平滑(u)) * Math.PI;
        return { pos: 加(祭坛, [Math.sin(角) * 11, -Math.cos(角) * 11, 5.2]), tgt: 加(祭坛, [0, 0, 3]), lens: 26 };
      },
    },
    // 1-03 全景，低机位仰拍：火焰炸开，她出现在祭坛上
    { 名: '1-03', 起: 事件.现身 - 0.4, 机位: (u) => ({ pos: 加(祭坛, [-6.5, -10.5, 混(0.9, 1.2, u)]), tgt: 加(祭坛, [0.5, 0, 3.6]), lens: 22 }) },
    // 1-04 中近景推到脸：史蒂夫在前景
    {
      名: '1-04',
      起: 事件.现身 + 2,
      机位: (u) => {
        const k = 平滑(u);
        return { pos: [混(史蒂夫召唤位[0] + 1.1, 祭坛[0] + 0.5, k), 混(史蒂夫召唤位[1] - 3.2, 祭坛[1] - 3.8, k), 混(史蒂夫召唤位[2] + 2.0, 亚波伦头[2] + 0.1, k)], tgt: 亚波伦头, lens: 混(35, 42, k) };
      },
    },
  ];
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  // 史蒂夫：过渡开始后退两步（1 秒退 1.6 格），一直看着祭坛上方
  const 退 = 平滑(clamp01((仪式秒 - 方案.完成 - 0.3) / 1)) * 1.6;
  const 史位: V3 = [史蒂夫召唤位[0], 史蒂夫召唤位[1] - 退, 史蒂夫召唤位[2]];
  const 提示 = 仪式秒 >= 方案.提示 && 现身后 < 0;
  const 血条透明 = clamp01((现身后 - 2.2) / 0.6);
  return (
    <台地画布
      机位={机位}
      界面={
        <>
          {/* 黑暗效果（游戏里提示那一刻给 32 格内的玩家上「黑暗」）：压暗到现身 */}
          <div style={{ position: 'absolute', inset: 0, background: '#000', opacity: 0.45 * clamp01((仪式秒 - 方案.提示) / 0.5) * (1 - clamp01(现身后 / 0.3)) }} />
          {提示 && (
            <div style={{ position: 'absolute', left: 0, right: 0, bottom: 画幅.高 * 0.2, textAlign: 'center', color: '#FF5555', fontFamily: 'Minecraft, monospace', fontSize: 26, textShadow: '2px 2px 0 #3F1515' }}>{游戏.提示文字}</div>
          )}
          {血条透明 > 0 && <亚波伦血条 宽={画幅.宽} s={2} 血比={1} 透明度={血条透明} />}
        </>
      }
    >
      <group position={祭坛}>
        <安息仪式演出 秒={仪式秒} 方案={方案}>
          <娘化亚波伦 pose={{ loc: [...现身位置], yaw: 180 }} 秒={Math.max(0, 现身后)} 表演={站立} 持杖 />
        </安息仪式演出>
      </group>
      <反应史蒂夫 状态={{ 位置: 史位, 朝向: 0, 看: 亚波伦头, 秒, 右手: 仪式秒 > 方案.完成 + 1 ? '剑' : '空' }} />
    </台地画布>
  );
});
