const 方案 = 召唤方案们.短;
const 加 = (a: readonly number[], b: readonly number[], k = 1): V3 => [a[0]! + b[0]! * k, a[1]! + b[1]! * k, a[2]! + b[2]! * k];
const 插 = (a: readonly number[], b: readonly number[], k: number): V3 => [混(a[0]!, b[0]!, k), 混(a[1]!, b[1]!, k), 混(a[2]!, b[2]!, k)];
const 本地 = (x: number, y: number, z: number): V3 => 加(祭坛, [x, y, z]);
/** 段内秒 → 编排的钟（现身后几秒） */
const 钟 = (段秒: number) => 编排钟(线.事件.开始.秒 + 段秒);
const 段秒于 = (编排秒: number) => 编排秒 - 钟(0);
const 胸 = (t: number) => 加(史蒂夫位(t), [0, 0, 1.2]);
/**
 * 黑暗效果有多暗（0～0.45）。照原版 LightTexture.calculateDarknessScale（1.20.1，javap 读的）：0.45 × max(0, cos(刻 × π × 0.025))，
 * 4 秒一起伏、一半时间不暗。原来一直压着 0.45，1-03 整段太暗（11-11 看片意见）。相位（玩家的 tickCount）游戏里是随的，
 * 这里取提示后 1 秒最暗（Agent 取的）；游戏里压的是光照图、暗处更暗，这里还是整片盖一层黑
 */
const 黑暗 = (仪式秒: number) => {
  const 过 = 仪式秒 - 方案.提示;
  return 过 < 0 ? 0 : 0.45 * clamp01(过 / 0.5) * Math.max(0, Math.cos((过 - 1) * 20 * Math.PI * 0.025));
};

/** 从 pos 看 a、b 两点：视线取两个方向的加权平均（w 偏向 a），远近差得多时也能把两样都框住 */
const 两看 = (pos: V3, a: readonly number[], b: readonly number[], w: number): V3 => {
  const 向 = (q: readonly number[]) => {
    const d = 加(q, pos, -1);
    const n = Math.hypot(...d);
    return d.map((v) => v / n);
  };
  return 加(pos, 加(向(a).map((v) => v * w), 向(b), 1 - w));
};
const 祭顶 = 本地(0, 0, 2.4);

// 机位都在他前方、侧前方：他脑后斜挂着晋升之环（1 格的方片），从背后拍，环挡掉一大块、人又是一团金色，看不见脸和手（11-11 看片意见）
const 镜头表: 镜头[] = (() => {
  const 切 = { 二: 2.6, 三: 5.3, 四: 段秒于(0.35), 五: 段秒于(0.95), 止: 段秒于(编排钟(线.事件.召唤完.秒)) };
  return [
    // 1-01 他右前方跟着他从南边走上来：看得见脸和拿着环的右手；他在基座外站住、右键放环（环落到祭坛上在 1-02 的前景里）。
    // 祭坛不进这个镜头：从侧前方框祭坛，四角的灵魂火总有一团挡在中间，机位抬过火顶又吃满火上的烟
    { 名: '1-01', 起: 0, 机位: 跟拍(切.二, (s) => {
      const t = 钟(s);
      return { pos: 加(史蒂夫位(t), [3.0, 1.5, 1.2]), tgt: 胸(t), lens: 26 };
    }) },
    // 1-02 祭坛东北边、越过祭坛往南看他：祭品消失、光柱起来都在前景，他在后面正对着镜头往后退，光柱起来一缩、拔剑；镜头慢慢往前压
    { 名: '1-02', 起: 切.二, 机位: 跟拍(切.三 - 切.二, (s, k) => {
      const t = 钟(切.二 + s);
      const pos = 本地(混(2.2, 1.9, k), 混(4.8, 4.4, k), 混(3.6, 3.3, k));
      return { pos, tgt: 两看(pos, 祭顶, 胸(t), 0.3), lens: 30 };
    }) },
    // 1-03 他正前方、慢半拍跟着他左右挪：黑暗、低语、大烟里他握着剑压着步子横移，看得见脸；火焰炸开、她出现，他往后一退，镜头跟着往后让
    { 名: '1-03', 起: 切.三, 机位: 跟拍(切.四 - 切.三, (s) => {
      const t = 钟(切.三 + s);
      const p = 史蒂夫位(t - 0.2);
      return { pos: [p[0] * 0.6 + 祭坛[0] * 0.4 + 1.2, p[1] + 3.0, p[2] + 1.3], tgt: 胸(t), lens: 24 };
    }) },
    // 1-04 她的脸：低着头闭着眼，睁眼、开始抬头；镜头从她面前往脸上推（11-11 提速：0.95 秒就切走，抬头、转身、甩杖都在 1-05 里）
    { 名: '1-04', 起: 切.四, 机位: 跟拍(切.五 - 切.四, (_s, k): Cam => ({ pos: 本地(混(2.5, 1.85, 平滑(k)), 混(-0.65, -0.45, k), 混(3.85, 4.0, k)), tgt: 本地(0, 0, 混(3.85, 4.0, 平滑(k))), lens: 混(30, 38, 平滑(k)) })) },
    // 1-05 越过她右肩看他：她抬头、转过身来对着他、杖一甩；他在远处压低身子，起步冲过来
    { 名: '1-05', 起: 切.五, 机位: 跟拍(切.止 - 切.五, (s, k): Cam => {
      const t = 钟(切.五 + s);
      return { pos: 本地(混(-1.7, -2.0, k), 混(2.7, 2.3, k), 混(5.0, 4.8, k)), tgt: 插(亚波伦头(t), 胸(t), 混(0.55, 0.65, k)), lens: 混(26, 28, k) };
    }) },
  ];
})();

export default 定义画面(段, 声音, () => {
  const { 秒, 事件, 段: 本段 } = use段(段);
  const 仪式秒 = 秒 - 事件.放环;
  const t = 钟(秒);
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  const 提示 = 仪式秒 >= 方案.提示 && t < 0;
  const 血条透明 = clamp01((t - 2.2) / 0.6);
  return (
    <台地画布
      仪式结构
      机位={机位}
      界面={
        <>
          {/* 黑暗效果（游戏里提示那一刻给 32 格内的玩家上「黑暗」）：一起一伏地压暗，到现身 */}
          <div style={{ position: 'absolute', inset: 0, background: '#000', opacity: 黑暗(仪式秒) * (1 - clamp01(t / 0.3)) }} />
          {提示 && (
            <div style={{ position: 'absolute', left: 0, right: 0, bottom: 画幅.高 * 0.2, textAlign: 'center', color: '#FF5555', fontFamily: 'Minecraft, monospace', fontSize: 26, textShadow: '2px 2px 0 #3F1515' }}>{游戏.提示文字}</div>
          )}
          {血条透明 > 0 && <亚波伦血条 宽={画幅.宽} s={2} 血比={1} 透明度={血条透明} />}
        </>
      }
    >
      <group position={祭坛}>
        <安息仪式演出 秒={仪式秒} 方案={方案} />
      </group>
      {t >= 0 && <娘化亚波伦 {...演.在(t).属性} 持杖 />}
      <反应史蒂夫 状态={{ ...史蒂夫走.在(t), 看: 史蒂夫看(t), 秒, 右手: 史蒂夫右手(t), 左手: '空', 挥剑秒: 史蒂夫挥剑秒(t), 招: 史蒂夫招(t), 蓄招: 史蒂夫蓄招(t), 蓄力: 史蒂夫蓄力(t) }} />
    </台地画布>
  );
});
