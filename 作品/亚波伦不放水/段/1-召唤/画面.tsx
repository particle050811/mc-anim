// 第 1 幕 召唤的画面：史蒂夫拿着破碎之环走上来、右键放上祭坛 → 安息仪式（特效/安息仪式.tsx，短方案）里他退开、拔剑、紧张地挪步 →
// 亚波伦现身：闭着眼低着头，睁眼、抬头、转向他、杖一甩，第 2 幕接他冲上来。走位和她的动作在 场/1-台地/编排-开盘.ts，这里摆镜头。
// 用户 11-10 嫌前面「意义不明的环绕镜头」太多、人物「就像暂停了」：五个镜头都拍着人在动，机位跟着人走（跟拍，场/1-台地/台地场.tsx），不绕着空景转。
// 镜头是 Agent 摆的，用户没看过。和分镜第二稿不一样：没有「手落在祭坛上」的特写，放环是一个跟拍镜头里的右键。
import React from 'react';
import type { Cam } from '@engine/core/机位.ts';
import { clamp01, lerp as 混, smoothstep01 as 平滑 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { 定义画面, use段 } from '@engine/段/段画面.tsx';
import { 娘化亚波伦 } from '../../角色/娘化亚波伦.tsx';
import { 反应史蒂夫 } from '../../角色/反应史蒂夫.tsx';
import { 亚波伦血条 } from '../../界面/战斗界面.tsx';
import { 安息仪式演出 } from '../../特效/安息仪式.tsx';
import { 召唤方案们, 游戏 } from '../../特效/安息仪式时序.ts';
import { 祭坛 } from '../../场/1-台地/布局.ts';
import { 亚波伦头, 史蒂夫位, 史蒂夫右手, 史蒂夫看, 史蒂夫蓄力, 史蒂夫挥剑秒, 史蒂夫走, 演, 现身后 as 编排钟 } from '../../场/1-台地/编排-开盘.ts';
import 线 from '../../场/1-台地/时间线.ts';
import { 取镜头, 台地画布, 画幅, 跟拍, type 镜头 } from '../../场/1-台地/台地场.tsx';
import 段 from './段.ts';
import 声音 from './声音地址.生成.ts';

const 方案 = 召唤方案们.短;
const 加 = (a: readonly number[], b: readonly number[], k = 1): V3 => [a[0]! + b[0]! * k, a[1]! + b[1]! * k, a[2]! + b[2]! * k];
const 插 = (a: readonly number[], b: readonly number[], k: number): V3 => [混(a[0]!, b[0]!, k), 混(a[1]!, b[1]!, k), 混(a[2]!, b[2]!, k)];
const 本地 = (x: number, y: number, z: number): V3 => 加(祭坛, [x, y, z]);
/** 段内秒 → 编排的钟（现身后几秒） */
const 钟 = (段秒: number) => 编排钟(线.事件.开始.秒 + 段秒);
const 段秒于 = (编排秒: number) => 编排秒 - 钟(0);
const 胸 = (t: number) => 加(史蒂夫位(t), [0, 0, 1.2]);

const 镜头表: 镜头[] = (() => {
  const 切 = { 二: 2.6, 三: 5.3, 四: 段秒于(0.35), 五: 段秒于(1.35), 止: 段秒于(编排钟(线.事件.召唤完.秒)) };
  return [
    // 1-01 跟着他从南边走上来：机位在他右后方，跟着他往北走；他在基座外站住、右键，环落到祭坛上
    { 名: '1-01', 起: 0, 机位: 跟拍(切.二, (s, k) => {
      const t = 钟(s);
      return { pos: 加(史蒂夫位(t), [3.0, -3.6 + 0.4 * k, 1.3 + 0.2 * k]), tgt: 插(胸(t), 本地(0, 0, 2.4), 混(0.3, 0.42, 平滑(k))), lens: 28 };
    }) },
    // 1-02 他侧前方跟着他往后退：祭坛、祭品消失、光柱起来都在他身后；光柱起来他一缩、拔剑
    { 名: '1-02', 起: 切.二, 机位: 跟拍(切.三 - 切.二, (s, k) => {
      const t = 钟(切.二 + s);
      return { pos: 加(史蒂夫位(t), [5.5, 3.0 - 0.4 * k, 1.0 + 0.4 * k]), tgt: 插(胸(t), 本地(0, 0, 2.4), 0.32), lens: 22 };
    }) },
    // 1-03 他背后跟着他左右挪：黑暗、低语、大烟里他压着步子横移，镜头慢半拍跟着横移；火焰炸开、她出现，他往后一退，镜头跟着往后让
    { 名: '1-03', 起: 切.三, 机位: 跟拍(切.四 - 切.三, (s) => {
      const t = 钟(切.三 + s);
      const p = 史蒂夫位(t - 0.2);
      return { pos: [p[0] * 0.75 + 祭坛[0] * 0.25 + 1.7, p[1] - 5.2, 祭坛[2] + 2.6], tgt: 本地(0.3 * (p[0] - 祭坛[0]), 0, 2.4), lens: 28 };
    }) },
    // 1-04 她的脸：低着头闭着眼，睁眼、抬头；镜头从她面前往脸上推
    { 名: '1-04', 起: 切.四, 机位: 跟拍(切.五 - 切.四, (_s, k): Cam => ({ pos: 本地(混(2.5, 1.85, 平滑(k)), 混(-0.65, -0.45, k), 混(3.85, 4.0, k)), tgt: 本地(0, 0, 混(3.85, 4.0, 平滑(k))), lens: 混(30, 38, 平滑(k)) })) },
    // 1-05 越过她右肩看他：她转过身来对着他、杖一甩；他在远处压低身子，起步冲过来
    { 名: '1-05', 起: 切.五, 机位: 跟拍(切.止 - 切.五, (s, k): Cam => {
      const t = 钟(切.五 + s);
      return { pos: 本地(混(-1.7, -2.0, k), 混(2.7, 2.3, k), 混(5.0, 4.8, k)), tgt: 插(亚波伦头(t), 胸(t), 混(0.55, 0.65, k)), lens: 混(26, 28, k) };
    }) },
  ];
})();

export default 定义画面(段, 声音, () => {
  const { 秒, 事件, 段: 本段 } = use段(段);
  const 仪式秒 = 秒 - 事件.放环;
  const t = 钟(秒);
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  const 提示 = 仪式秒 >= 方案.提示 && t < 0;
  const 血条透明 = clamp01((t - 2.2) / 0.6);
  return (
    <台地画布
      仪式结构
      机位={机位}
      界面={
        <>
          {/* 黑暗效果（游戏里提示那一刻给 32 格内的玩家上「黑暗」）：压暗到现身 */}
          <div style={{ position: 'absolute', inset: 0, background: '#000', opacity: 0.45 * clamp01((仪式秒 - 方案.提示) / 0.5) * (1 - clamp01(t / 0.3)) }} />
          {提示 && (
            <div style={{ position: 'absolute', left: 0, right: 0, bottom: 画幅.高 * 0.2, textAlign: 'center', color: '#FF5555', fontFamily: 'Minecraft, monospace', fontSize: 26, textShadow: '2px 2px 0 #3F1515' }}>{游戏.提示文字}</div>
          )}
          {血条透明 > 0 && <亚波伦血条 宽={画幅.宽} s={2} 血比={1} 透明度={血条透明} />}
        </>
      }
    >
      <group position={祭坛}>
        <安息仪式演出 秒={仪式秒} 方案={方案} />
      </group>
      {t >= 0 && <娘化亚波伦 {...演.在(t).属性} 持杖 />}
      <反应史蒂夫 状态={{ ...史蒂夫走.在(t), 看: 史蒂夫看(t), 秒, 右手: 史蒂夫右手(t), 左手: '空', 挥剑秒: 史蒂夫挥剑秒(t), 蓄力: 史蒂夫蓄力(t) }} />
    </台地画布>
  );
});
