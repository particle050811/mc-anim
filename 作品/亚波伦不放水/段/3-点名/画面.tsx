// 第 3 幕 结界和点名的画面：编排在 场/1-台地/编排-点名.ts，这里摆镜头（分镜第二稿 3-01～3-07，机位是 Agent 摆的）和界面（血条、计数、名签）。
// 没做：猩红雨、伤害数字、史蒂夫吃金苹果（3-06 他只是站着）、她冲刺时的旋转姿势、声音。
import React from 'react';
import { lerp as 混, smoothstep01 as 平滑 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { 定义画面, use段 } from '@engine/段/段画面.tsx';
import { Arrow } from '@库/物品/箭.tsx';
import { 娘化亚波伦 } from '../../角色/娘化亚波伦.tsx';
import { 反应史蒂夫 } from '../../角色/反应史蒂夫.tsx';
import { 战斗界面 } from '../../界面/战斗界面.tsx';
import { 杖尖轮盘 } from '../../界面/杖尖轮盘.tsx';
import { 安息仪式演出 } from '../../特效/安息仪式.tsx';
import { 召唤方案们 } from '../../特效/安息仪式时序.ts';
import { 炼狱结界演出 } from '../../特效/炼狱结界演出.tsx';
import { 祭坛 } from '../../场/1-台地/布局.ts';
import { 出手们, 出手名签, 已出手 } from '../../场/1-台地/出手.tsx';
import { 取镜头, 台地画布, 画幅, type 镜头 } from '../../场/1-台地/台地场.tsx';
import 线 from '../../场/1-台地/时间线.ts';
import { 每像素格, 盘摆 } from '../../场/1-台地/编排-开盘.ts';
import { 中箭, 亚波伦位, 出手表, 况, 史蒂夫状态在, 史蒂夫脚, 幕起, 扔, 演, 盘位, 箭们, 结界设定, 轮盘参 } from '../../场/1-台地/编排-点名.ts';
import 段 from './段.ts';
import 声音 from './声音地址.生成.ts';

const 加 = (a: readonly number[], b: readonly number[], k = 1): V3 => [a[0]! + b[0]! * k, a[1]! + b[1]! * k, a[2]! + b[2]! * k];
const S = 史蒂夫脚;

export default 定义画面(段, 声音, () => {
  const { 秒, 段: 本段 } = use段(段);
  const t = 幕起 + 秒;
  const 她 = 演.在(t);
  const 她位 = 亚波伦位(t);
  const 她胸 = 加(她位, [0, 0, 1.1]);
  const 盘 = 盘位(t);
  const 参 = 轮盘参(t);
  // 从她到史蒂夫的水平方向、它的垂直方向（镜头按这条动作线摆）
  const 线长 = Math.hypot(S[0] - 她位[0], S[1] - 她位[1]);
  const 向: V3 = [(S[0] - 她位[0]) / 线长, (S[1] - 她位[1]) / 线长, 0];
  const 侧: V3 = [向[1], -向[0], 0];
  const 镜头表: 镜头[] = [
    // 3-01 全景，侧面，两人同框：结界从杖尖飞出、涨大、罩住
    { 名: '3-01', 起: 0, 机位: () => ({ pos: 加(祭坛, [-2.5, -22, 2.6]), tgt: 加(祭坛, [4.2, -2, 7.2]), lens: 20 }) },
    // 3-02 中景，结界里，侧面：火球、冰刺打中
    { 名: '3-02', 起: 3.5, 机位: (u) => ({ pos: 加(加(加(S, 侧, 混(7.4, 6.6, u)), 向, 1.2), [0, 0, 1.1]), tgt: 加(加(S, 向, -2.4), [0, 0, 3.4]), lens: 19 }) },
    // 3-03 史蒂夫身后仰拍：拉弓、放箭
    { 名: '3-03a', 起: 6.5, 机位: () => ({ pos: 加(加(加(S, 向, 3.8), 侧, 1.3), [0, 0, 1.9]), tgt: 加(她胸, [0, 0, -5.5]), lens: 22 }) },
    // 再切她的近景：中箭，低头看一眼
    { 名: '3-03b', 起: 7.75, 机位: (u) => ({ pos: 加(加(加(她位, 侧, 混(4.6, 4.1, u)), 向, -0.8), [0, 0, 0.9]), tgt: 她胸, lens: 34 }) },
    // 3-04 全景，侧面：第二箭被风吹偏，她闪到结界另一侧上空
    { 名: '3-04', 起: 9.5, 机位: () => ({ pos: 加(S, [-13, -19, 3]), tgt: 加(S, [0, 0, 7.5]), lens: 17 }) },
    // 3-05 结界里，俯视 3/4：大牙砸下、风刃切过来
    { 名: '3-05', 起: 13, 机位: (u) => ({ pos: 加(S, [混(-7.5, -6.8, u), -8, 7.5]), tgt: 加(S, [0.4, 0.4, 2.6]), lens: 22 }) },
    // 3-06 史蒂夫近景：一道闪电劈下来
    { 名: '3-06', 起: 16.5, 机位: () => ({ pos: 加(加(加(S, 向, -3.2), 侧, 2.2), [0, 0, 1.3]), tgt: 加(S, [0, 0, 1.9]), lens: 26 }) },
    // 3-07 史蒂夫近景，再摇上去看轮盘
    {
      名: '3-07',
      起: 19.5,
      机位: (u) => {
        const k = 平滑(Math.min(1, u * 1.6));
        const 头 = 加(S, [0, 0, 1.6]);
        return { pos: 加(加(加(S, 向, 3.4), 侧, 1.4), [0, 0, 1.1]), tgt: [混(头[0], 盘.心[0], k), 混(头[1], 盘.心[1], k), 混(头[2], 盘.心[2], k)], lens: 混(30, 38, k) };
      },
    },
  ];
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  return (
    <台地画布
      机位={机位}
      界面={
        <战斗界面
          宽={画幅.宽}
          高={画幅.高}
          s={2}
          血条={{ 血比: t >= 中箭 ? 0.985 : 1 }}
          计数={t >= 扔 ? { n: 1 + 已出手(出手表, t) } : undefined}
          名签们={出手名签([{ id: 'revelation', 秒: 扔, 起点: 结界设定.起点 }, ...出手表], t, 况, 机位)}
        />
      }
    >
      <group position={祭坛}>
        <安息仪式演出 秒={线.事件.开盘完.秒 - 线.事件.放环.秒 + 秒} 方案={召唤方案们.短} />
      </group>
      <娘化亚波伦 {...她.属性} 持杖 受伤={t >= 中箭 && t < 中箭 + 0.5 ? 1 : 0} />
      {参 && <杖尖轮盘 杖={演.杖(t)} {...盘摆} 参={参} 每像素格={每像素格} />}
      <炼狱结界演出 秒={t - 扔} 设定={结界设定} />
      <出手们 表={出手表} 秒={t} 况={况} />
      {箭们(t).map((箭, i) => (
        <Arrow key={i} p={箭.p} dir={箭.dir} />
      ))}
      <反应史蒂夫 状态={史蒂夫状态在(t)} />
    </台地画布>
  );
});
