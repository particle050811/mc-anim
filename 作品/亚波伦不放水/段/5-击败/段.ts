// 第 5 幕 击败：火光退去、死亡界面、收盘落地。窗口、声音 cue。纯模块。
// 声音（用户 11-11「为什么没有声音啊」）：时刻从 场/1-台地/击败拍.ts 取，不抄数。他死（原版死亡声），结界没了（原版 stopSpell 的信标熄灭），
// 她一冲、俯冲各一声破风，死亡界面点「重生」，收盘，落地。响度两档同第 4 幕：主要峰值 −10 dBFS、次要 −18 dBFS。
// 收盘、落地游戏里没有专门的声音：收盘借本体 goety.cast_spell、落地借原版 small_fall，都是 Agent 取的，用户没听过。
import { 窗口段 } from '@engine/段/窗口段.ts';
import { 真下界包 } from '../../地点/真下界位置.ts';
import 线 from '../../场/1-台地/时间线.ts';
import { 光标, 她拍, 幕长, 幕起, 落地, 镜起 } from '../../场/1-台地/击败拍.ts';
import 声音表 from './声音表.生成.ts';

const 主 = -10;
const 次 = -18;

export default 窗口段(线, {
  起: '齐放完',
  止: '击败完',
  地形: [真下界包],
  声音表,
  声音: ({ 放, 秒 }) => {
    if (Math.abs(秒 - 幕长) > 1 / 60) throw new Error(`击败段长 ${秒} 秒和 击败拍.ts 的幕长 ${幕长} 对不上`);
    return [
      // 他死在本幕第 0 秒（第 4 幕结界烧完那一刻）
      放('音效/entity.player.death.1', 0, { 峰值: 主, 名: '他死' }),
      放('音效/block.beacon.deactivate', 0, { 峰值: 次, 名: '结界灭' }),
      放('音效/诡厄巫法/goety.heavy_woosh.1', 她拍.冲起, { 峰值: 次, 名: '她冲' }),
      // 5-02 光标点「重生」
      放('音效/ui.button.click', 镜起.二 + 光标.点, { 峰值: 主, 名: '点重生' }),
      放('音效/诡厄巫法/goety.cast_spell.2', 她拍.收起, { 峰值: 次, 名: '收盘' }),
      放('音效/诡厄巫法/goety.heavy_woosh.2', 她拍.降起, { 峰值: 次, 名: '俯冲' }),
      放('音效/entity.generic.small_fall', 落地 - 幕起, { 峰值: 次, 名: '落地' }),
    ];
  },
});
