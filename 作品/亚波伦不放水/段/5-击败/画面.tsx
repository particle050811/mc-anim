// 第 5 幕 击败的画面：编排在 场/1-台地/编排-击败.ts，这里摆镜头（分镜第二稿 5-01～5-03，机位是 Agent 摆的，用户没看过）和界面。
// 5-01 全景固定：第 4 幕末的火光糊屏退掉，地上是史蒂夫的掉落物（原版死亡掉落，照 角色/史蒂夫掉落.tsx）和死亡白烟的尾巴，她还在空中开着盘。
// 5-02 史蒂夫第一人称：原版死亡界面（库/界面/死亡界面.tsx），光标移到「重生」上点下去。镜头停在他死时看的方向，带原版死后的侧倾。
// 5-03 她中景略仰、跟着往下：轮盘一圈圈收回杖尖、杖收到身侧、落地；左下聊天栏出现死亡消息。
// 游戏界面，用户没看过，不要就关：5-02 的死亡界面和 5-03 聊天栏的死亡消息是游戏自带的界面，照分镜做上的，开关是 场/1-台地/编排-击败.ts 的 游戏界面。
// 没做：经验球、地上留的火冰酸、猩红雨、声音（雨声、火声、点击声、合盘声）；5-02 背后的物品栏、血条（全片第一人称都没画 HUD），只留 boss 血条。
// 点「重生」以后不演重生，幕末硬切第 6 幕教堂（分镜 5-02 下的说明）。
import React, { useMemo } from 'react';
import { lerp as 混 } from '@engine/core/数学.ts';
import type { Cam } from '@engine/core/机位.ts';
import { png } from '@engine/model/贴图.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { 定义画面, use段 } from '@engine/段/段画面.tsx';
import { ChatOverlay } from '@库/界面/聊天栏.tsx';
import { 死亡界面, 死亡界面按钮延迟刻, 在死亡界面按钮上, 界面尺寸, type 死亡界面按钮态 } from '@库/界面/死亡界面.tsx';
import { deathPoof, VanillaParticles } from '@库/特效/原版粒子.tsx';
import { 娘化亚波伦 } from '../../角色/娘化亚波伦.tsx';
import { 史蒂夫掉落件, 史蒂夫掉落件数, 死亡掉落, 死亡掉落轨迹 } from '../../角色/史蒂夫掉落.tsx';
import { 战斗界面, 死亡消息行 } from '../../界面/战斗界面.tsx';
import { 杖尖轮盘 } from '../../界面/杖尖轮盘.tsx';
import { 取镜头, 台地画布, 画幅, type 镜头 } from '../../场/1-台地/台地场.tsx';
import { 每像素格, 盘摆 } from '../../场/1-台地/编排-开盘.ts';
import { 亚波伦位, 光标, 光标在, 史蒂夫眼, 史蒂夫脚, 幕起, 死亡消息, 死后秒, 游戏界面, 演, 落脚, 轮盘参, 镜起 } from '../../场/1-台地/编排-击败.ts';
import 段 from './段.ts';
import 声音 from './声音地址.生成.ts';
import 按钮图 from 'asset:贴图/法术/minecraft/gui/widgets';

const 加 = (a: readonly number[], b: readonly number[], k = 1): V3 => [a[0]! + b[0]! * k, a[1]! + b[1]! * k, a[2]! + b[2]! * k];
const S = 史蒂夫脚;
const s界 = 2;
/** 原版死后的侧倾：GameRenderer.bobHurt 里 min(deathTime, 20) 刻后定在 40 − 8000 / 220 ≈ 3.64 度（世界逆时针转 = 相机 roll 取负） */
const 死后侧倾 = -(40 - 8000 / 220);
/** 原版默认 fov 70（竖直） */
const 第一人称焦距 = 14.46;

export default 定义画面(段, 声音, () => {
  const { 秒, 段: 本段 } = use段(段);
  const t = 幕起 + 秒;
  const 她 = 演.在(t);
  const 她位 = 亚波伦位(t);
  const 参 = 轮盘参(t);
  const 死 = 死后秒(t);
  const 轨迹 = useMemo(() => 死亡掉落轨迹(S, 史蒂夫掉落件数, 3), []);
  const 白烟 = useMemo(() => deathPoof(S, 0.6, 1.8, 0, 5), []);
  // 从她（空中）到史蒂夫的水平方向、它的垂直方向（同第 3、4 幕按动作线摆镜头）
  const 线长 = Math.hypot(S[0] - 落脚[0], S[1] - 落脚[1]);
  const 向: V3 = [(S[0] - 落脚[0]) / 线长, (S[1] - 落脚[1]) / 线长, 0];
  const 侧: V3 = [向[1], -向[0], 0];
  const 镜头表: 镜头[] = [
    // 5-01 全景固定：低机位在他背后那一侧，掉落物在画面中下，她和盘在血条下面
    { 名: '5-01', 起: 镜起.一, 机位: () => ({ pos: 加(加(加(S, 向, 4.5), 侧, 1), [0, 0, 0.6]), tgt: 加(加(加(S, 向, -4), 侧, -1), [0, 0, 4]), lens: 11 }) },
    // 5-02 史蒂夫第一人称：眼睛在他死的地方，看着他死时看的她
    ...(游戏界面 ? [{ 名: '5-02', 起: 镜起.二, 机位: (): Cam => ({ pos: 史蒂夫眼, tgt: 加(她位, [0, 0, 1.5]), lens: 第一人称焦距, roll: 死后侧倾 }) }] : []),
    // 5-03 她中景略仰，跟着她往下：镜头在她左前方（杖在右手，从右边拍杖头会挡脸）、比她腰低一点；开头离得远些把盘收进来，往下时推近。高度晚她 0.4 秒跟，看得出在往下落
    {
      名: '5-03',
      起: 镜起.三,
      机位: (u) => {
        const 迟 = 亚波伦位(t - 0.4);
        const k = Math.min(1, u * 1.4);
        return { pos: 加(加(加([她位[0], 她位[1], 迟[2]], 向, 混(4.5, 3.5, k)), 侧, -混(7.5, 5.2, k)), [0, 0, 0.5]), tgt: 加(她位, [0, 0, 1.8]), lens: 混(22, 23, k) };
      },
    },
  ];
  const { 机位, 镜, 镜内秒 } = 取镜头(镜头表, 秒, 本段.秒);
  // 5-01 开头接第 4 幕末的火光糊屏，0.7 秒退掉
  const 糊 = 镜.名 === '5-01' ? 1 - Math.min(1, Math.max(0, 秒 / 0.7)) ** 1.5 : 0;
  // 死亡界面：打开后 20 刻按钮才能按；光标在「重生」上是指着，点下去以后不能按
  const 界 = 界面尺寸(画幅.宽, 画幅.高, s界);
  const 光 = 光标在(镜内秒);
  const 重生: 死亡界面按钮态 = 镜内秒 * 20 < 死亡界面按钮延迟刻 || 镜内秒 >= 光标.点 ? '不能按' : 在死亡界面按钮上(0, 光[0], 光[1], 界.宽, 界.高) ? '指着' : '平常';
  const 标题屏幕: 死亡界面按钮态 = 镜内秒 * 20 < 死亡界面按钮延迟刻 ? '不能按' : 在死亡界面按钮上(1, 光[0], 光[1], 界.宽, 界.高) ? '指着' : '平常';
  const 聊天 = 镜.名 === '5-03' && 游戏界面 ? [死亡消息行((镜起.三 + 0.3) * 20, { 模板: 死亡消息 })] : [];
  return (
    <台地画布
      机位={机位}
      界面={
        <>
          {糊 > 0 && <div style={{ position: 'absolute', inset: 0, opacity: 糊, background: 'radial-gradient(circle at 50% 50%, #fff6dc 0%, #ffc060 45%, #ff8a28 100%)' }} />}
          <战斗界面 宽={画幅.宽} 高={画幅.高} s={s界} 血条={{ 血比: 1 }}>
            {聊天.length > 0 && <ChatOverlay lines={聊天} 刻={秒 * 20} s={s界} />}
          </战斗界面>
          {镜.名 === '5-02' && <死亡界面 宽={画幅.宽} 高={画幅.高} s={s界} 按钮图={png(按钮图)} 死因={死亡消息} 重生={重生} 标题屏幕={标题屏幕} 光标={光} />}
        </>
      }
    >
      <娘化亚波伦 {...她.属性} 持杖 />
      {参 && <杖尖轮盘 杖={演.杖(t)} {...盘摆} 参={参} 每像素格={每像素格} />}
      <死亡掉落 轨迹={轨迹} 件={史蒂夫掉落件(死)} 秒={死} />
      <VanillaParticles spawns={白烟} 秒={死} />
    </台地画布>
  );
});
