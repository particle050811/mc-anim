export default 定义画面(段, 声音, () => {
  const { 秒, 段: 本段 } = use段(段);
  const t = 幕起 + 秒;
  const 她 = 演.在(t);
  const 参 = 轮盘参(t);
  const 死 = 死后秒(t);
  const 轨迹 = useMemo(() => 死亡掉落轨迹(S, 史蒂夫掉落件数, 掉落种子), []);
  const 白烟 = useMemo(() => deathPoof(S, 0.6, 1.8, 0, 5), []);
  const { 机位 } = 取镜头(镜头表, 秒, 本段.秒);
  // 死亡界面：他一死就打开，20 刻后按钮才能按；光标在「重生」上是指着，点下去以后不能按
  const 界 = 界面尺寸(画幅.宽, 画幅.高, s界);
  const 光 = 光标在(秒);
  const 重生: 死亡界面按钮态 = 秒 * 20 < 死亡界面按钮延迟刻 || 秒 >= 光标.点 ? '不能按' : 在死亡界面按钮上(0, 光[0], 光[1], 界.宽, 界.高) ? '指着' : '平常';
  const 标题屏幕: 死亡界面按钮态 = 秒 * 20 < 死亡界面按钮延迟刻 ? '不能按' : 在死亡界面按钮上(1, 光[0], 光[1], 界.宽, 界.高) ? '指着' : '平常';
  // 死亡消息和死亡界面同一刻出（原版死的那一刻发系统消息）
  const 聊天 = 游戏界面 ? [死亡消息行(0, 死亡消息)] : [];
  // 他：死了不再挣，倒下 1 秒后人没了（反应史蒂夫 照 死后秒 自己藏）
  const 他 = { ...史蒂夫状态在(t), 挣扎: 0 };
  return (
    <台地画布
      仪式结构
      机位={机位}
      界面={
        <>
          <战斗界面 宽={画幅.宽} 高={画幅.高} s={s界} 血条={{ 血比: 1 }}>
            {聊天.length > 0 && <ChatOverlay lines={聊天} 刻={秒 * 20} s={s界} />}
          </战斗界面>
          {游戏界面 && <死亡界面 宽={画幅.宽} 高={画幅.高} s={s界} 按钮图={png(按钮图)} 死因={死亡消息字} 重生={重生} 标题屏幕={标题屏幕} 光标={光} />}
        </>
      }
    >
      {/* 仪式做完后留在台地上的结构和四角灵魂火，同第 2 幕；仪式的钟走编排的钟，同第 4 幕 */}
      <group position={祭坛}>
        <安息仪式演出 秒={t + 线.事件.现身.秒 - 线.事件.放环.秒} 方案={召唤方案们.短} />
      </group>
      <娘化亚波伦 {...她.属性} 持杖 />
      {参 && <杖尖轮盘 杖={演.杖(t)} {...盘摆} 参={参} 每像素格={每像素格} />}
      <反应史蒂夫 状态={他} />
      <死亡掉落 轨迹={轨迹} 件={史蒂夫掉落件(死)} 秒={死} />
      <VanillaParticles spawns={白烟} 秒={死} />
    </台地画布>
  );
});
