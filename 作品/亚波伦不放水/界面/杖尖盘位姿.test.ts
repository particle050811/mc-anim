import { describe, expect, it } from 'vitest';
import { 杖尖盘位姿, 盘上点, 盘格位置 } from './杖尖盘位姿.ts';
import { 排盘 } from './轮盘法术.ts';

const 近 = (a: readonly number[], b: readonly number[]) => a.forEach((v, i) => expect(v).toBeCloseTo(b[i]!, 6));
const 杖 = { 尖: [1, 2, 5] as [number, number, number], 轴: [0, -0.6, 0.8] as [number, number, number] };

describe('杖尖盘位姿', () => {
  it('垂直杖身：圆心在杖尖，法向顺着杖身，上、右都在盘面里', () => {
    const 盘 = 杖尖盘位姿(杖, { 朝向: '垂直杖身' });
    近(盘.心, 杖.尖);
    近(盘.法向, 杖.轴);
    近(盘.上, [0, 0.8, 0.6]);
    近(盘.右, [1, 0, 0]);
    近(杖尖盘位姿(杖, { 朝向: '垂直杖身', 反面: true }).法向, [0, 0.6, -0.8]);
  });
  it('正对镜头：盘面和画面平行，圆心还在杖尖；浮起沿法向往镜头挪', () => {
    const 盘 = 杖尖盘位姿(杖, { 朝向: { 正对: { pos: [1, -8, 5], tgt: [1, 2, 5] } }, 浮起: 0.2 });
    近(盘.法向, [0, -1, 0]);
    近(盘.上, [0, 0, 1]);
    近(盘.右, [1, 0, 0]);
    近(盘.心, [1, 1.8, 5]);
  });
  it('定死朝上（张在头顶）：上取北；离尖沿杖身往外', () => {
    const 盘 = 杖尖盘位姿({ 尖: [0, 0, 4], 轴: [0, 0, 1] }, { 朝向: { 法向: [0, 0, -1] }, 离尖: 0.5 });
    近(盘.心, [0, 0, 4.5]);
    近(盘.上, [0, 1, 0]);
    // 朝下的盘从下面仰看、北在上：右手边是西
    近(盘.右, [-1, 0, 0]);
  });
  it('盘上点、盘格位置：第 0 圈第 0 格朝正上，离圆心 45 GUI 像素；没弹开的圈返回 null', () => {
    const 盘 = 杖尖盘位姿(杖, { 朝向: { 正对: { pos: [1, -8, 5], tgt: [1, 2, 5] } } });
    近(盘上点(盘, 0.1, 10, -20), [2, 2, 7]);
    const { 项 } = 排盘({});
    const 首 = 项.find((p) => p.圈 === 0 && p.格 === 0)!;
    const 外 = 项.find((p) => p.圈 === 2)!;
    const 位 = 盘格位置(盘, 0.02, { 刻: 2.5, 开合: { 转速: 0 } }, 首.键)!;
    expect(Math.hypot(位[0] - 1, 位[2] - 5)).toBeCloseTo(0.9, 6);
    expect(位[2]).toBeGreaterThan(5);
    expect(盘格位置(盘, 0.02, { 刻: 2.5 }, 外.键)).toBeNull();
    expect(盘格位置(盘, 0.02, { 刻: 40 }, 'goety:没有这个')).toBeNull();
  });
});
