// 多圈聚晶轮盘的分圈和开合：给 N 个法术算几圈、每圈几格，和每圈在打开后第几刻的半径、转角。纯模块。
// 多圈是本片原创（用户 11-09 定「原版玩家法术轮盘只有一圈，我想改成多圈以容纳所有法术」），原版和启示录都只有一圈。
// 最里一圈就是原版那一圈（内 30、外 60 GUI 像素，数见 库/界面/径向轮盘数.ts）；往外每圈再加一个环宽。
// 每圈格数的上限：图标沿图标圆的间距不小于原版一圈放 20 格时的间距（2π × 45 / 20 ≈ 14.1 GUI 像素；图标 16 像素，原版 20 格时相邻图标本来就叠 2 像素）。
import { 径向轮盘数 } from '@库/界面/径向轮盘数.ts';

export type 分法 = '按周长' | '均分' | '填满内圈';

export type 圈形 = {
  /** 最里一圈的内半径，默认原版的 30 */
  内半径: number;
  /** 每圈的宽，默认原版的 30（外 60 − 内 30） */
  环宽: number;
  /** 间距基准：原版一圈放这么多格时的图标间距算最小间距，默认 20 */
  基准格数: number;
};

export const 默认圈形: 圈形 = { 内半径: 径向轮盘数.内半径, 环宽: 径向轮盘数.内半径 * (径向轮盘数.外内比 - 1), 基准格数: 20 };

/** 第 k 圈（0 起）张开后的内、外半径和图标所在的半径 */
export const 圈半径 = (k: number, 形: 圈形 = 默认圈形) => {
  const 内 = 形.内半径 + 形.环宽 * k;
  return { 内, 外: 内 + 形.环宽, 图标: 内 + 形.环宽 / 2 };
};

/** 第 k 圈最多几格：格数 ÷ 图标半径 不超过原版基准（基准格数 ÷ 45） */
export const 圈容量 = (k: number, 形: 圈形 = 默认圈形) => Math.floor((形.基准格数 * 圈半径(k, 形).图标) / 圈半径(0, 形).图标 + 1e-9);

/** 装得下 N 格的最少圈数 */
export const 最少圈数 = (N: number, 形: 圈形 = 默认圈形) => {
  let 圈 = 0;
  for (let 剩 = N; 剩 > 0; 圈++) 剩 -= 圈容量(圈, 形);
  return Math.max(1, 圈);
};

/** 每圈格数（由里向外），加起来正好 N，每圈不超过容量。
 *  按周长：各圈按容量的比例分，图标间距各圈差不多；均分：各圈格数尽量一样，超过容量的往外挪；填满内圈：从里往外装满为止。
 *  圈数不给就取装得下的最少圈数；给的圈数装不下就报错 */
export const 分圈 = (N: number, 选项: { 圈数?: number; 分法?: 分法; 形?: 圈形 } = {}): number[] => {
  const 形 = 选项.形 ?? 默认圈形;
  const 圈数 = 选项.圈数 ?? 最少圈数(N, 形);
  const 容量 = Array.from({ length: 圈数 }, (_, k) => 圈容量(k, 形));
  const 总容量 = 容量.reduce((a, b) => a + b, 0);
  if (!Number.isInteger(N) || N < 0) throw new Error(`分圈：格数要是非负整数，给的是 ${N}`);
  if (N > 总容量) throw new Error(`分圈：${圈数} 圈最多 ${总容量} 格，装不下 ${N} 格`);
  const 分法 = 选项.分法 ?? '按周长';
  if (分法 === '填满内圈') {
    let 剩 = N;
    return 容量.map((c) => {
      const n = Math.min(c, 剩);
      剩 -= n;
      return n;
    });
  }
  // 按权重分，超过容量的那圈定在容量上，剩下的在其余圈里重分；最后按小数部分从大到小补齐零头（并列时里圈优先）
  const 权重 = 分法 === '均分' ? 容量.map(() => 1) : 容量;
  const 得 = 容量.map(() => -1);
  let 剩 = N;
  for (;;) {
    const 活 = 得.flatMap((n, k) => (n < 0 ? [k] : []));
    const 权和 = 活.reduce((a, k) => a + 权重[k]!, 0);
    const 满 = 活.filter((k) => (剩 * 权重[k]!) / 权和 > 容量[k]!);
    if (满.length === 0) {
      const 份 = 活.map((k) => ({ k, 值: (剩 * 权重[k]!) / 权和 }));
      for (const { k, 值 } of 份) 得[k] = Math.floor(值 + 1e-9);
      let 零头 = 剩 - 份.reduce((a, { k }) => a + 得[k]!, 0);
      const 排 = [...份].sort((a, b) => b.值 - Math.floor(b.值 + 1e-9) - (a.值 - Math.floor(a.值 + 1e-9)) || a.k - b.k);
      for (let i = 0; 零头 > 0; i = (i + 1) % 排.length) {
        const k = 排[i]!.k;
        if (得[k]! < 容量[k]!) {
          得[k]!++;
          零头--;
        }
      }
      return 得;
    }
    for (const k of 满) {
      得[k] = 容量[k]!;
      剩 -= 容量[k]!;
    }
  }
};

/** 把排好序的 N 项按每圈格数切开：返回每项在第几圈第几格，不重不漏 */
export const 落格 = (每圈格数: readonly number[]): { 圈: number; 格: number }[] => 每圈格数.flatMap((n, 圈) => Array.from({ length: n }, (_, 格) => ({ 圈, 格 })));

export type 开合 = {
  /** 每圈弹开用几刻，默认原版的 2.5 */
  每圈刻: number;
  /** 相邻两圈起弹相隔几刻，默认 2.5（里一圈弹完外一圈才起）；0 = 各圈一起弹 */
  圈间隔刻: number;
  /** 每圈转多快（度每秒），0 = 不转；原版不转 */
  转速: number;
  /** 相邻圈反着转 */
  反向: boolean;
};

export const 默认开合: 开合 = { 每圈刻: 径向轮盘数.开合刻, 圈间隔刻: 径向轮盘数.开合刻, 转速: 3, 反向: true };

/** 全部圈弹完要几刻 */
export const 开完刻 = (圈数: number, 开: 开合 = 默认开合) => (圈数 - 1) * 开.圈间隔刻 + 开.每圈刻;

export type 圈态 = {
  进度: number;
  /** 这一圈还在弹：只画带子，不画图标（照原版 isReady() 才画图标） */
  动画中: boolean;
  内: number;
  外: number;
  图标半径: number;
  /** 这一圈整体转了多少弧度（正 = 顺时针） */
  转角: number;
};

/** 第 k 圈在打开后第几刻的状态；还没轮到它返回 null。
 *  最里一圈照原版从圆心放大（内 = max(0.1, 内半径 × 进度)，外 = 内 × (内半径 + 环宽) ÷ 内半径，默认圈形下就是 GenericRadialMenu 的 radiusIn、radiusOut = radiusIn × 2）；
 *  外面的圈内沿不动、外沿从内沿长到位（内 = 张开后的内半径，外 = 内 + 环宽 × 进度），进度线性，同原版。 */
export const 圈态 = (k: number, 刻: number, 形: 圈形 = 默认圈形, 开: 开合 = 默认开合): 圈态 | null => {
  const 本圈刻 = 刻 - k * 开.圈间隔刻;
  if (本圈刻 < 0) return null;
  const 进度 = Math.min(1, 本圈刻 / 开.每圈刻);
  const 动画中 = 进度 < 1;
  const 满 = 圈半径(k, 形);
  const 内 = k === 0 ? (动画中 ? Math.max(0.1, 形.内半径 * 进度) : 形.内半径) : 满.内;
  const 外 = k === 0 ? (内 * (形.内半径 + 形.环宽)) / 形.内半径 : 内 + 形.环宽 * 进度;
  const 向 = 开.反向 && k % 2 === 1 ? -1 : 1;
  return { 进度, 动画中, 内, 外, 图标半径: (内 + 外) / 2, 转角: (向 * 开.转速 * Math.PI * Math.max(0, 刻)) / 20 / 180 };
};

/** 外半径 R（GUI 像素）的轮盘放进高 H 的画面、上下各留 留边（画面像素），GUI 缩放最大取多少。
 *  步 是缩放的最小单位：取 1 ÷ 出片倍数（1280×720 出 4K 是 1/3），得出的缩放 × 出片倍数是整数，图标每个贴图像素一样大 */
export const 适配缩放 = (R: number, H: number, 留边: number, 步: number, 上限 = Infinity) => Math.max(步, Math.min(上限, Math.floor((H / 2 - 留边) / R / 步 + 1e-9) * 步));
