/** 圆心默认画的聚晶：启示录的炼狱聚晶（goety_revelation:revelation_focus），用户 11-09 定 */
export const 默认圆心 = 'goety_revelation:revelation_focus';

export type 多圈轮盘参数 = 排盘选项 & {
  /** 打开后第几刻（可带小数，1 刻 = 1/20 秒） */
  刻: number;
  /** 高亮的格（聚晶键，如 goety:fireball_focus；齐放时给一串），画成原版的悬停色；那一圈弹完才亮 */
  选中?: string | readonly string[];
  /** 圆心画哪个聚晶的图标（聚晶键）；不给 = 默认圆心（炼狱聚晶），null = 不画。最里一圈弹完才画，同原版 */
  圆心?: string | null;
  /** 圆心图标放大几倍，默认 1（原版 16 GUI 像素）。封面草稿里放大当「头顶的第二个光环」试过，正片不用 */
  圆心倍?: number;
  /** 背景贴图：原大 = 和原版一圈时一样大（默认）；随外圈 = 按最外圈和原版外半径的比例放大；无 = 不画 */
  底纹?: '原大' | '随外圈' | '无';
  /** 带子按学派上色（原创，默认关） */
  学派分色?: boolean;
  /** 学派分色时带子颜色的不透明度，默认 0.4 */
  分色不透明度?: number;
  /** 「全部」档里不进齐放的图标亮度，默认 0.35 */
  压暗?: number;
  /** 弹开节奏和转速，没给的项用 默认开合 */
  开合?: Partial<开合>;
  /** 收盘：开始收后第几刻（原创，第 5 幕；分圈.ts 的 收圈态）。不给 = 不收 */
  收刻?: number;
};

const 图 = (键: string): Png | null => {
  const 地址 = (聚晶图标 as Record<string, string | undefined>)[键];
  return 地址 ? png(地址) : null;
};

/** 排盘里图标对照表（物品/聚晶图标.ts）没有的聚晶键 */
export const 缺图标 = (选项: 排盘选项 = {}): string[] => 排盘(选项).项.flatMap((项) => (图(项.键) ? [] : [项.键]));

const 带透明 = (色: string, 不透明度: number) => `rgba(${parseInt(色.slice(1, 3), 16)},${parseInt(色.slice(3, 5), 16)},${parseInt(色.slice(5, 7), 16)},${不透明度})`;

/** 最外圈张开后的外半径（GUI 像素）：摆位置、定缩放用 */
export const 轮盘外半径 = (选项: 排盘选项 = {}) => 圈半径(排盘(选项).每圈格数.length - 1, 选项.形 ?? 默认圈形).外;

export const 画多圈轮盘 = (位: 画布位, 参: 多圈轮盘参数) => {
  if (参.刻 < 0) return;
  const 形 = 参.形 ?? 默认圈形;
  const 开 = { ...默认开合, ...参.开合 };
  const { 每圈格数, 项 } = 排盘(参);
  const 圈数 = 每圈格数.length;
  const 态们 = 每圈格数.map((_, k) => (参.收刻 === undefined ? 圈态(k, 参.刻, 形, 开) : 收圈态(k, 参.刻, 参.收刻, 圈数, 形, 开)));
  if (!态们[0]) return;

  const 底纹 = 参.底纹 ?? '原大';
  if (底纹 === '原大') 画底纹(位, png(底纹地址), 态们[0]!.进度);
  else if (底纹 === '随外圈') 画底纹(位, png(底纹地址), (圈半径(圈数 - 1, 形).外 / (径向轮盘数.内半径 * 径向轮盘数.外内比)) * Math.min(1, 参.刻 / 开完刻(圈数, 开)));

  const 按圈: 轮盘项[][] = 每圈格数.map(() => []);
  for (const 一项 of 项) 按圈[一项.圈]!.push(一项);

  // 先画完各圈的带子，再画图标：相邻圈的图标不会被外一圈的带子盖住
  态们.forEach((态, k) => {
    if (!态) return;
    const n = 每圈格数[k]!;
    画环带(
      位,
      态.内,
      态.外,
      按圈[k]!.map((一项, i) => {
        const { 起, 止 } = 格范围(i, n);
        const 亮 = !态.动画中 && (typeof 参.选中 === 'string' ? 一项.键 === 参.选中 : !!参.选中?.includes(一项.键));
        const 色 = 亮 ? argb色(径向轮盘数.悬停色) : 参.学派分色 ? 带透明(学派色[一项.法.学派], 参.分色不透明度 ?? 0.4) : argb色(径向轮盘数.底色);
        return { 起: 起 + 态.转角, 止: 止 + 态.转角, 色 };
      }),
    );
  });
  态们.forEach((态, k) => {
    if (!态 || 态.动画中) return;
    const n = 每圈格数[k]!;
    按圈[k]!.forEach((一项, i) => {
      const 贴图 = 图(一项.键);
      if (!贴图) return;
      const 角 = 格范围(i, n).中 + 态.转角;
      // 不转时照原版把图标落在 GUI 像素格上；转起来还落格的话图标会一格一格跳，改成只对齐到画布像素
      const 边 = 径向轮盘数.图标边;
      const [左, 上] = 开.转速 === 0 ? 图标左上(角, 态.图标半径) : [态.图标半径 * Math.cos(角) - 边 / 2, 态.图标半径 * Math.sin(角) - 边 / 2];
      画像素图(位, 贴图, 左, 上, 边, 边, { 亮度: 一项.齐放 ? 1 : (参.压暗 ?? 0.35) });
    });
  });
  const 圆心键 = 参.圆心 === undefined ? 默认圆心 : 参.圆心;
  const 圆心图 = 圆心键 && !态们[0]!.动画中 ? 图(圆心键) : null;
  const 圆心边 = 径向轮盘数.图标边 * (参.圆心倍 ?? 1);
  if (圆心图) 画像素图(位, 圆心图, -圆心边 / 2, -圆心边 / 2, 圆心边, 圆心边);
};

/** 屏幕上的多圈轮盘：圆心在容器正中；s 是 GUI 缩放（见 库/界面/径向轮盘.tsx） */
export const 多圈轮盘: React.FC<多圈轮盘参数 & { 宽: number; 高: number; s: number }> = ({ 宽, 高, s, ...参 }) => <轮盘画布 宽={宽} 高={高} s={s} 画={(位) => 画多圈轮盘(位, 参)} />;
