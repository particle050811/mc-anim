// 核对-法术录制 的视图表（纯，段.ts 也读）：录过的法术每个一槽 120 帧，同 核对-法术演出 的槽法和机位（全景 60 帧 + 近景 60 帧，各把长秒走一遍）。
// 近景和 核对-法术演出 不同：这两个法术以施法者为中心，近景对着起点（施法者）拍，不对着史蒂夫。
// 一帧三格并排，同一机位、同一时刻：左 手写演出，中 录制回放（照录下的轨迹），右 录制回放（位置由录下的出生字段按 particlePath 重算）。
// 法术第 t 秒的全景帧 = i × 120 + round(t ÷ 长秒 × 60)，近景再 + 60。
import { 法术时长, type 法术元 } from '../../法术/演出/接口.ts';
import { 法术元表 } from '../../法术/演出/元表.ts';
import type { 点 } from '../../法术/演出/接口.ts';

// 场地、种子、槽长、全景机位照抄 核对-法术演出/视图.ts（核对段之间不许互引），那边改了这里跟着改
export const 起点: 点 = [-10, 0, 7];
export const 目标: 点 = [0, 0, 0];
export const 种子 = 1;
export const 每槽秒 = 2;
const 每半槽秒 = 每槽秒 / 2;
export type 机位 = { 名: '全景' | '近景'; 眼: 点; 看: 点; 视角: number };
const 全景: 机位 = { 名: '全景', 眼: [-5, -24, 5], 看: [-5, 0, 3.4], 视角: 40 };
/** 一格的尺寸（同 核对-法术演出 的 16:9），三格并排 */
export const 格 = { 宽: 960, 高: 540 } as const;
export const 画幅 = { 宽: 格.宽 * 3, 高: 格.高 } as const;

/** 录过的法术；近距 = 近景离起点几格；起点高 = 手写演出把 起点 当成 施法者脚底 + 几格（自身为中心的两个都是 0.5），回放的脚底 = 起点 − 起点高 */
export const 录过的 = [
  { id: 'weakening', 起点高: 0.5, 近距: 13 },
  { id: 'frost_nova', 起点高: 0.5, 近距: 7 },
] as const;

export interface 视图 {
  元: 法术元;
  第几个: number;
  起点高: number;
  机位: 机位;
  秒: number;
  长秒: number;
}

const 元们 = 录过的.map((x) => {
  const 元 = 法术元表.find((m) => m.id === x.id);
  if (!元) throw new Error(`核对-法术录制：手写演出里没有 ${x.id}`);
  return 元;
});

const 近景 = (距: number): 机位 => ({ 名: '近景', 眼: [起点[0], 起点[1] - 距, 起点[2] + 距 * 0.15], 看: [起点[0], 起点[1], 起点[2] - 0.6], 视角: 40 });

export const 槽数 = 录过的.length;

export const 视图在 = (段秒: number): 视图 => {
  const 第几个 = Math.min(槽数 - 1, Math.max(0, Math.floor(段秒 / 每槽秒 + 1e-9)));
  const 元 = 元们[第几个]!;
  const 槽内 = Math.max(0, 段秒 - 第几个 * 每槽秒);
  const 半 = 槽内 + 1e-9 >= 每半槽秒 ? 1 : 0;
  const { 长秒 } = 法术时长(元, 起点, 目标);
  return { 元, 第几个, 起点高: 录过的[第几个]!.起点高, 机位: 半 ? 近景(录过的[第几个]!.近距) : 全景, 秒: Math.min(1, Math.max(0, (槽内 - 半 * 每半槽秒) / 每半槽秒)) * 长秒, 长秒 };
};
