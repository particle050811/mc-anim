// 核对-法术演出 的视图表（纯，段.ts 也读）：照 元表 自动生成，不用手改。坐标照场景约定（Z 朝上：x 东、y 北、z 上，单位格）。
// 每个法术一槽 120 帧（2 秒），槽的顺序 = 元表.ts 的顺序（样板、甲、乙、丙、丁，组内照各组表）：
//   槽内第 0～59 帧 全景（起点和史蒂夫都在画里），第 60～119 帧 近景（对着史蒂夫）；
//   两半各把这个法术从出手到结束（长秒）走一遍：法术的秒 = 半槽里的第几帧 ÷ 60 × 长秒。
// 第 i 个（从 0 数）法术的全景在第 i × 120 帧起，近景在第 i × 120 + 60 帧起；法术第 t 秒的全景帧 = i × 120 + round(t ÷ 长秒 × 60)。
import { 法术时长, type 法术元, type 点 } from '../../法术/演出/接口.ts';
import { 法术元表 } from '../../法术/演出/元表.ts';

export const 画幅 = { 宽: 1280, 高: 720 } as const;
export const 每槽秒 = 2;
export const 每半槽秒 = 每槽秒 / 2;

/** 法术从这出来（左上空中）；目标：史蒂夫脚底 */
export const 起点: 点 = [-10, 0, 7];
export const 目标: 点 = [0, 0, 0];
export const 种子 = 1;

export type 机位 = { 名: '全景' | '近景'; 眼: 点; 看: 点; 视角: number };
// 机位在南边朝北看：西（起点）在画面左边
export const 机位们: readonly [机位, 机位] = [
  { 名: '全景', 眼: [-5, -24, 5], 看: [-5, 0, 3.4], 视角: 40 },
  { 名: '近景', 眼: [1.2, -9, 2.4], 看: [0, 0, 1.1], 视角: 40 },
];

export interface 视图 {
  元: 法术元;
  第几个: number;
  机位: 机位;
  /** 法术出手后的秒 */
  秒: number;
  长秒: number;
  命中秒?: number;
}

/** 段里第几秒 → 看哪个法术、哪个机位、法术的第几秒 */
export const 视图在 = (段秒: number): 视图 => {
  const 第几个 = Math.min(法术元表.length - 1, Math.max(0, Math.floor(段秒 / 每槽秒 + 1e-9)));
  const 元 = 法术元表[第几个]!;
  const 槽内 = Math.max(0, 段秒 - 第几个 * 每槽秒);
  const 半 = 槽内 + 1e-9 >= 每半槽秒 ? 1 : 0;
  const 时 = 法术时长(元, 起点, 目标);
  return { 元, 第几个, 机位: 机位们[半], 秒: Math.min(1, Math.max(0, (槽内 - 半 * 每半槽秒) / 每半槽秒)) * 时.长秒, ...时 };
};
