/** 第 秒 秒落在哪个视图、是它的第几秒 */
export const 视图在 = (秒: number): { v: 视图; τ: number } => {
  let 起 = 0;
  for (const v of 视图们) {
    if (秒 < 起 + v.长 - 1e-9) return { v, τ: Math.max(0, 秒 - 起) };
    起 += v.长;
  }
  const 末 = 视图们[视图们.length - 1]!;
  return { v: 末, τ: 末.长 };
};
export const 总秒 = 视图们.reduce((和, v) => 和 + v.长, 0);
