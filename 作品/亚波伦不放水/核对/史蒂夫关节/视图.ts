// —— 连拍 ——
const 连拍侧 = (n: number, 距 = 1.5) => ({ 眼: [-(n * 距 * 1.12 + 2), 0, 1.3] as V3, 看: [0, 0, 1.1] as V3, 视角: 30 });
const 连拍斜 = (n: number, 距 = 1.5) => ({ 眼: [-(n * 距 * 0.75), -(n * 距 * 0.8), 3.4] as V3, 看: [0, 0, 0.9] as V3, 视角: 30 });
/** 第 i 格站在哪（从北到南排，侧机位里从左到右） */
const 格位 = (i: number, n: number, 距 = 1.5, 高 = 0): V3 => [0, ((n - 1) / 2 - i) * 距, 高];
type 格 = (i: number, u: number) => Partial<史蒂夫状态> & { 高?: number };
const 连拍 = (n: number, 格: 格, 装备?: 史蒂夫装备) => (): 人[] =>
  Array.from({ length: n }, (_, i) => {
    const { 高, ...状 } = 格(i, n > 1 ? i / (n - 1) : 0);
    const 位 = 格位(i, n, 1.5, 高);
    return { 状态: { 位置: 位, 朝向: 180, 秒: 0, 看: [0, 位[1] - 4, 1.6], ...状 }, 装备 };
  });
/** 一个动作出两个视图：不穿甲的（姿势看得清）在前，穿全套的（看盔甲跟不跟、穿不穿帮）在后 */
const 两版 = (名: string, 机位: (n: number) => Pick<视图, '眼' | '看' | '视角'>, n: number, 格: 格, 说明?: string): 视图[] => [
  { 名: `${名}-不穿甲`, 长: 1, ...机位(n), 人们: 连拍(n, 格, 光身), 说明 },
  { 名, 长: 1, ...机位(n), 人们: 连拍(n, 格), 说明 },
];
/** 一圈摆腿（两步）切 n 格；摆 = 相位 ÷ 0.6662 */
const 一圈 = (步幅: number, 向: number, 多: Partial<史蒂夫状态> = {}) => (_i: number, u: number) => ({ 走: { 摆: (u * Math.PI * 2 * 7) / 8 / 0.6662, 步幅, 向 }, ...多 });

// 照第 2 幕编排的那一跳（场/1-台地/编排-开盘.ts）另写的一条直线轨迹：助跑越来越快 → 0.75 秒起跳（竖直 8.15 格/秒、重力 24.6）→ 1.0 秒点挥剑 →
// 1.25 秒落在高一格的地方刹住 → 1.6 秒往后跳下来 → 2.05 秒落地、倒退着走开。往南（−y）是前
const 跳高 = (τ: number, v0: number) => v0 * τ - 12.3 * τ * τ;
const 跳劈位 = (s: number): V3 => {
  if (s < 0) return [0, 3.2, 0];
  if (s < 0.75) return [0, 3.2 - 3.2 * (s / 0.75) ** 2.2, 0];
  if (s < 1.25) return [0, -3.6 * (s - 0.75), 跳高(s - 0.75, 8.15)];
  if (s < 1.6) {
    const τ = Math.min(0.2, s - 1.25);
    return [0, -1.8 - 3.6 * (τ - (τ * τ) / 0.4), 1];
  }
  if (s < 2.05) return [0, -2.16 + 3.7 * (s - 1.6), 1 + 跳高(s - 1.6, 3.31)];
  return [0, -0.495 + 3.7 * (s - 2.05), 0];
};
const 跳劈走 = 定走位({ 位: 跳劈位, 看: () => [0, -40, 3], 起: -1, 初朝向: 180 });
const 跳劈格 = (起: number, 止: number) => (_i: number, u: number) => {
  const s = 起 + (止 - 起) * u;
  const { 走, 跳, 位置 } = 跳劈走.在(s);
  return { 走, 跳, 高: 位置[2], 秒: s, 挥剑秒: s >= 1 ? s - 1 : undefined };
};

