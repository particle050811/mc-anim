// 核对-真下界的视图表（纯数据，段.ts 也读）：一秒一个视图，第 i 个在第 60i 帧。照原版光和雾的 11 个在前（第 0～10 秒），提亮、雾放远的同样 11 个在后（第 11～21 秒）。
// 每组：封面空中点（地点/真下界位置.ts 的 真下界选点）平视北、东、南、西，仰视 45 度，俯视 70 度；
// 正片场地（真下界场地）中心人眼高度平视北、东、南、西，再从场地南边 14 格处仰看中心头顶 30 格的地方（亚波伦悬停的高度）。竖直视角都是 70 度（原版默认 fov）。
import type { V3 } from '@engine/model/parts.tsx';
import { 真下界场地, 真下界场景, 真下界选点 } from '../../地点/真下界位置.ts';

export const 画幅 = { 宽: 1920, 高: 1080 } as const;

export type 视图 = { 名: string; 光: '原版' | '提亮'; /** 眼、看的点（场景坐标：x 东、y 北、z 上） */ 眼: V3; 看: V3 };

const 空中 = 真下界场景(真下界选点.x, 真下界选点.y, 真下界选点.z);
const 人眼高 = 1.62;
const 地心 = 真下界场景(真下界场地.心.x + 0.5, 真下界场地.心.y, 真下界场地.心.z + 0.5);
const 地眼: V3 = [地心[0], 地心[1], 地心[2] + 人眼高];
const 朝 = (眼: V3, 向: readonly number[]): V3 => [眼[0] + 向[0]!, 眼[1] + 向[1]!, 眼[2] + 向[2]!];
const 斜 = (仰角: number) => [0, Math.cos((仰角 * Math.PI) / 180), Math.sin((仰角 * Math.PI) / 180)];
const 四向 = [
  ['北', [0, 1, 0]],
  ['东', [1, 0, 0]],
  ['南', [0, -1, 0]],
  ['西', [-1, 0, 0]],
] as const;

const 一组: readonly Omit<视图, '光'>[] = [
  ...四向.map(([名, 向]) => ({ 名: `空中点 平视${名}`, 眼: 空中, 看: 朝(空中, 向) })),
  { 名: '空中点 仰视 45 度（朝北）', 眼: 空中, 看: 朝(空中, 斜(45)) },
  { 名: '空中点 俯视 70 度（朝北）', 眼: 空中, 看: 朝(空中, 斜(-70)) },
  ...四向.map(([名, 向]) => ({ 名: `场地中心 人眼平视${名}`, 眼: 地眼, 看: 朝(地眼, 向) })),
  { 名: '场地南边 14 格 仰看中心头顶 30 格', 眼: [地眼[0], 地眼[1] - 14, 地眼[2]], 看: [地心[0], 地心[1], 地心[2] + 30] },
];

export const 视图们: readonly 视图[] = (['原版', '提亮'] as const).flatMap((光) => 一组.map((v) => ({ ...v, 名: `${光} ${v.名}`, 光 })));
