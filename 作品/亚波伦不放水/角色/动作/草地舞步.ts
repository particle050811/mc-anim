import { sample, type Key } from '@engine/anim/anim.ts';

type Step = [sec: number, across: number, lift: number, forward: number, toe: number];
const footTrack = (steps: Step[]) => {
  const channels = [1, 2, 3, 4].map(axis => steps.map(step => [step[0], step[axis]!] as Key));
  return (sec: number) => {
    const [across, lift, forward, toe] = channels.map(channel => sample(channel, sec));
    return { point: [across!, lift!, forward!] as [number, number, number], toe: toe! };
  };
};

