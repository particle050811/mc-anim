/** 一条：从 起 秒开始往 做 这个姿势过渡，到 到 秒摆好（不写 = 起 + 0.4 秒），之后保持到下一条的 起。第一条从它的 起 之前就是这个姿势 */
export type 演出条 = { 起: number; 到?: number; 做: 姿势名 };

type 随时<T> = T | ((秒: number) => T);
const 取 = <T>(x: 随时<T>, 秒: number): T => (typeof x === 'function' ? (x as (秒: number) => T)(秒) : x);

export type 演出设定 = {
  轴: readonly 演出条[];
  /** 她脚底在哪（场景坐标，格）：起飞、换位、落地的位移由段来写 */
  位: 随时<V3>;
  /** 身子朝哪（度，0 朝北、180 朝南）；不给 = 水平上朝着目标 */
  yaw?: 随时<number>;
  /** 杖指着谁（史蒂夫、结界中心） */
  目标: 随时<V3>;
  /** 每次出手的时刻（秒）：杖小幅抖一下 */
  出手?: readonly number[];
  /** 弹簧（头发、胸）：默认 '推进' */
  弹簧?: '推进' | '稳态';
  /** 身子跟着动作倾（见 倾角）；不给 = 不倾（第 4、5 幕照旧） */
  倾?: 倾设定;
  /** 位 在这些秒上跳变（瞬移）：算速度、加速度时不跨过去 */
  断点?: readonly number[];
  /** 闭眼 0～1（1 = 闭着）；不给 = 照动画眨眼 */
  闭眼?: (秒: number) => number;
};

/** 倾：前倾、侧倾（度）= 速度（格/秒）× 每速 + 加速度（格/秒²）× 每加速，各自夹在 ±上限；加速度在前后 窗 秒里取三角加权平均，免得关键点上一顿 */
export type 倾设定 = { 每速: number; 每加速: number; 上限: number; 窗: number };

export type 演出此刻 = {
  /** 直接摊给 <娘化亚波伦 {...属性} 持杖 /> */
  属性: { pose: { loc: V3; yaw: number }; 秒: number; 表演: 亚波伦表演; 姿势: Record<string, BonePose> };
  /** 这一刻在两条之间：从哪个姿势到哪个、走了多少（0～1，已缓动） */
  过渡: { 从: 姿势名; 到: 姿势名; 比: number };
};


/** 抖杖：出手后 0.3 秒里手腕带着杖头往上一挑再落回（最大约 4 度），不改瞄准的右肩。原创，幅度小是因为轮盘钉在杖尖上，杖一甩整个盘跟着甩 */
export const 抖杖秒 = 0.3;
export const 抖杖角 = (秒: number, 出手: readonly number[]): number => {
  let 和 = 0;
  for (const t0 of 出手) {
    const t = (秒 - t0) / 抖杖秒;
    if (t > 0 && t < 1) 和 += 4 * Math.sin(Math.PI * Math.min(1, t * 2.5)) * (1 - t) ** 2;
  }
  return 和;
};

/**
 * 悬在空中时的起伏：竖直 ±0.1 格、3.4 秒一个来回，水平再带一点不同周期的漂（±0.04 格）。原创（游戏里的亚波伦不会飞）；
 * 位置一动不动地钉在空中看着像贴上去的（用户 11-10 要人物动作流畅）。叠在 位 上，杖、盘、出手点都跟着走；编排里算距离、站点用的还是不带起伏的 位。
 */
export const 浮动 = (秒: number): V3 => [0.04 * Math.sin((2 * Math.PI * 秒) / 5.3 + 1.1), 0.04 * Math.sin((2 * Math.PI * 秒) / 4.1), 0.1 * Math.sin((2 * Math.PI * 秒) / 3.4)];

/** 这一刻在轴上的位置：前一个姿势、后一个姿势、走了多少 */
export const 轴上 = (轴: readonly 演出条[], 秒: number): 演出此刻['过渡'] => {
  if (!轴.length) throw new Error('亚波伦演出：轴是空的');
  let i = 0;
  while (i + 1 < 轴.length && 轴[i + 1]!.起 <= 秒) i++;
  const 条 = 轴[i]!;
  if (i === 0) return { 从: 条.做, 到: 条.做, 比: 1 };
  const 到 = 条.到 ?? 条.起 + 0.4;
  const t = 到 <= 条.起 ? 1 : Math.min(1, Math.max(0, (秒 - 条.起) / (到 - 条.起)));
  // 上一条还没摆好就被这一条接走：从上一条的目标姿势出发（不追中间态），段里别把两条排得比过渡还密
  return { 从: 轴[i - 1]!.做, 到: 条.做, 比: smoothstep01(t) };
};

const 差步 = 1 / 60;
/** 秒 附近 [a, b] 里没有断点就返回 true */
const 不跨 = (断点: readonly number[], a: number, b: number) => !断点.some((d) => d > a && d <= b);
/** 位置的一阶、二阶差分（水平两分量），跨断点时换成单边差分 */
export const 速加速 = (位: (秒: number) => V3, 秒: number, 断点: readonly number[] = []): { 速: [number, number]; 加速: [number, number] } => {
  const h = 差步;
  let [a, b] = [秒 - h, 秒 + h];
  if (!不跨(断点, a, b)) [a, b] = 不跨(断点, 秒 - 2 * h, 秒) ? [秒 - 2 * h, 秒] : [秒, 秒 + 2 * h];
  const m = (a + b) / 2;
  const [p, q, r] = [位(a), 位(m), 位(b)];
  const H = (b - a) / 2;
  return {
    速: [(r[0] - p[0]) / (2 * H), (r[1] - p[1]) / (2 * H)],
    加速: [(r[0] - 2 * q[0] + p[0]) / (H * H), (r[1] - 2 * q[1] + p[1]) / (H * H)],
  };
};
/**
 * 跟着动作倾的角度（度，原创）：往哪边加速、往哪边飞，身子就往哪边倒（起步前压、刹住后仰、拐弯往里侧倒），这样闪避有预备和收势，
 * 位置写成速度连续的曲线，倾也就跟着连续。前 = 身子正面的方向（yaw 0 朝 +y），右 = 她的右手边。返回 [前倾, 右倾]
 */
export const 倾角 = (设: 倾设定, 位: (秒: number) => V3, yaw: number, 秒: number, 断点: readonly number[] = []): [number, number] => {
  const n = 4;
  let [vx, vy, ax, ay, w和] = [0, 0, 0, 0, 0];
  for (let k = -n; k <= n; k++) {
    const t = 秒 + (k / n) * 设.窗;
    if (!不跨(断点, Math.min(t, 秒), Math.max(t, 秒))) continue;
    const w = n + 1 - Math.abs(k);
    const { 速, 加速 } = 速加速(位, t, 断点);
    vx += w * 速[0];
    vy += w * 速[1];
    ax += w * 加速[0];
    ay += w * 加速[1];
    w和 += w;
  }
  const r = (yaw * Math.PI) / 180;
  const [前x, 前y, 右x, 右y] = [-Math.sin(r), Math.cos(r), Math.cos(r), Math.sin(r)];
  const 夹 = (x: number) => Math.max(-设.上限, Math.min(设.上限, x));
  const 倾 = (dx: number, dy: number) => 夹((设.每速 * (vx * dx + vy * dy) + 设.每加速 * (ax * dx + ay * dy)) / w和);
  return [倾(前x, 前y), 倾(右x, 右y)];
};

export const 定演出 = (设定: 演出设定) => {
  const 位 = (秒: number) => 取(设定.位, 秒);
  const 目标 = (秒: number) => 取(设定.目标, 秒);
  const yaw = (秒: number) => {
    if (设定.yaw !== undefined) return 取(设定.yaw, 秒);
    const [p, q] = [位(秒), 目标(秒)];
    // yaw 0 朝北（+y），逆时针为正：朝向 = (−sin, cos)
    return (Math.atan2(-(q[0] - p[0]), q[1] - p[1]) * 180) / Math.PI;
  };
  const 飞权 = (秒: number) => {
    const { 从, 到, 比 } = 轴上(设定.轴, 秒);
    return lerp(姿势们[从].飞, 姿势们[到].飞, 比);
  };
  const h = 1 / 120;
  const 表演 = 定表演({
    主: (秒) => {
      const w = 飞权(秒);
      return w <= 0 ? [{ 名: 'idle' }] : w >= 1 ? [{ 名: 'fly' }] : [{ 名: 'idle' }, { 名: 'fly', 权重: w }];
    },
    // 头发、胸的弹簧吃速度：竖直速度按米/秒（YSM wiki）；水平速度 YSM 的单位没查到，飞行时写的是 20，这里按 10 格/秒 ≈ 20 估
    环境: (秒) => {
      const 断 = 设定.断点 ?? [];
      const [甲, 乙] = 不跨(断, 秒 - h, 秒 + h) ? [秒 - h, 秒 + h] : 不跨(断, 秒 - 2 * h, 秒) ? [秒 - 2 * h, 秒] : [秒, 秒 + 2 * h];
      const [a, b] = [位(甲), 位(乙)];
      return { 查询: { vertical_speed: (b[2] - a[2]) / (2 * h), ground_speed: Math.min(20, (Math.hypot(b[0] - a[0], b[1] - a[1]) / (2 * h)) * 2) } };
    },
    弹簧: 设定.弹簧,
  });

  const 缓存 = new Map<number, 演出此刻>();
  const 在 = (秒: number): 演出此刻 => {
    const 有 = 缓存.get(秒);
    if (有) return 有;
    const 过渡 = 轴上(设定.轴, 秒);
    const [甲, 乙] = [姿势们[过渡.从], 姿势们[过渡.到]];
    const k = 过渡.比;
    const 浮权 = lerp(甲.浮, 乙.浮, k);
    const [原位, 浮] = [位(秒), 浮动(秒)];
    const pose = { loc: [原位[0] + 浮[0] * 浮权, 原位[1] + 浮[1] * 浮权, 原位[2] + 浮[2] * 浮权] as V3, yaw: yaw(秒) };
    // 手摆的转角在两个姿势间插；一边没摆的骨骼，从动画这一刻的转角插过去
    const 动画 = 动画骨骼表(秒, 表演);
    const 混: Record<string, BonePose> = {};
    for (const 骨 of new Set([...Object.keys(甲.手), ...Object.keys(乙.手)])) {
      const 底 = 动画[骨]?.rot ?? [0, 0, 0];
      const [a, b] = [甲.手[骨]?.rot ?? 底, 乙.手[骨]?.rot ?? 底];
      混[骨] = { rot: [0, 1, 2].map((j) => lerp(a[j]!, b[j]!, k)) };
    }
    const 解 = (朝: '目标' | '上') => 瞄杖({ pose, 秒, 表演, 姿势: 混, 朝: 朝 === '目标' ? { 点: 目标(秒) } : { 向: [0, 0, 1] } });
    let 姿势 = 混;
    if (甲.杖朝 && 甲.杖朝 === 乙.杖朝) 姿势 = 解(甲.杖朝);
    else if (甲.杖朝 || 乙.杖朝) {
      // 两头瞄的不一样（或只有一头瞄）：各解各的右肩，再按过渡插
      const 肩 = (定: 姿势定义) => (定.杖朝 ? 解(定.杖朝) : 混).RightArm!.rot!;
      const [a, b] = [肩(甲), 肩(乙)];
      姿势 = { ...混, RightArm: { rot: [0, 1, 2].map((j) => lerp(a[j]!, b[j]!, k)) } };
    }
    if (设定.倾) {
      // MAllBody（轴心在髋，idle 和 fly 都不动它）整个转：前倾 = 绕 x，侧倾 = 绕 z
      const [前, 右] = 倾角(设定.倾, 位, pose.yaw, 秒, 设定.断点);
      姿势 = { ...姿势, MAllBody: { rot: [前, 0, 右] } };
    }
    const 闭 = 设定.闭眼 ? Math.min(1, Math.max(0, 设定.闭眼(秒))) : 0;
    if (闭 > 0) {
      const 睑 = { scale: [1, 1 - 闭, 1] };
      姿势 = { ...姿势, LeftEyelid: 睑, RightEyelid: 睑 };
    }
    const 抖 = 抖杖角(秒, 设定.出手 ?? []);
    if (抖) {
      const 腕 = 姿势.RightHand?.rot ?? [0, 0, 0];
      姿势 = { ...姿势, RightHand: { rot: [腕[0]! - 抖, 腕[1]!, 腕[2]!] } };
    }
    const 出: 演出此刻 = { 属性: { pose, 秒, 表演, 姿势 }, 过渡 };
    缓存.set(秒, 出);
    return 出;
  };
  /** 这一刻杖在场景里的位置和朝向（界面/杖尖轮盘.tsx 的 杖、法术的出手点） */
  const 杖 = (秒: number): 杖位姿 => 持杖位姿(在(秒).属性);
  return { 在, 杖, 表演, 设定 };
};
export type 亚波伦演出 = ReturnType<typeof 定演出>;
