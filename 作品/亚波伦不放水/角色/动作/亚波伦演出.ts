// 亚波伦的演出：正片的段按「几秒到几秒做什么」排她的姿势（现身站立、起飞、悬停持杖、举杖指向目标、开盘、收盘、落地），加上每次出手的小幅抖杖。
// 姿势都是本片自己摆的（包里没有施法、举杖的动作，见 ../说明.md），没经用户看过；身子的底子是包里的 idle 和 fly（按「飞」的权重混）。
// 用法：模块里建一次 定演出({...})，画面里 演.在(秒) 拿到 <娘化亚波伦> 的属性，演.杖(秒) 拿到杖尖位姿（给 界面/杖尖轮盘.tsx 和法术的出手点）。
// 结果只看时间：姿势按关键帧表插值，指向目标的右臂每帧用 瞄杖 解一次（身子在 fly 里晃，杖尖照样指着目标）。
import { lerp, smoothstep01 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import type { BonePose } from '@engine/model/基岩模型.tsx';
import { 动画骨骼表, 定表演, 持杖位姿, 斜举, 瞄杖, type 亚波伦表演, type 杖位姿 } from '../娘化亚波伦.tsx';

export type 姿势名 = '站立' | '起飞' | '悬停' | '指向' | '开盘' | '收盘' | '落地';

type 手摆 = Readonly<Record<string, BonePose>>;
export type 姿势定义 = {
  /** 身子的底子：0 = idle（站着），1 = fly（前倾侧身、蜘蛛腿扇、身后出缺口环），中间按权重混 */
  飞: number;
  /** 盖在动画上的骨骼转角；右臂三根（RightArm、RightForeArm、RightHand）都要写，杖才握得住 */
  手: 手摆;
  /** 杖身朝哪：目标 = 杖尖指着演出的 目标；上 = 竖起来。给了就用 瞄杖 改右肩，手 里的右臂只当起点 */
  杖朝?: '目标' | '上';
};

// 右臂往前伸、杖从手里朝前指出去的起点（封面六稿的「前指」：肘微弯，手腕以绕小臂长轴转为主，杖从手的侧面穿过）；指哪由 瞄杖 解右肩
// 施法时把上身扶正一些：fly 原样是 UpBody [−5, −60, −43]（往右倒 43 度、拧 60 度），照它指向目标的话人是横躺着的、脸背着目标。
// 这里只留一点侧身；腿、蜘蛛腿、身后的缺口环照 fly。左臂从胸前放下来摊在身侧（封面六稿的左臂）
// 用户 11-10 定：正片里她站着飞，不用 fly 那个侧倒在缺口环（弯月）上的坐姿（「他可以站着飞呀」）。所以空中的姿势底子都是 idle（飞 = 0），上身不用再扶正
const 扶正: 手摆 = { LeftArm: { rot: [20, 0, -35] }, LeftForeArm: { rot: [-25, 0, 0] } };
const 前伸: 手摆 = { ...扶正, RightArm: { rot: [-61, 25, -1.25] }, RightForeArm: { rot: [-22, 0, 0] }, RightHand: { rot: [33, -90, 0] } };
// 开盘那一下：肘伸直（杖往前送约 0.15 格），左臂往外后方甩开，头抬一点
const 送出: 手摆 = { ...前伸, RightForeArm: { rot: [-3.75, 0, 0] }, LeftArm: { rot: [25, 0, -70] }, LeftForeArm: { rot: [-10, 0, 0] }, Head: { rot: [-8, 0, 0] } };
// 收盘：肘收回来，杖竖在身前右侧（杖朝上由 瞄杖 解）
const 收回: 手摆 = { ...扶正, RightArm: { rot: [-35, 10, 15] }, RightForeArm: { rot: [-70, 0, 0] }, RightHand: { rot: [0, 70, 0] } };
// 起飞前蓄一下、落地缓一下：两膝微屈（袍子里只露出一点）
const 屈膝: 手摆 = { RightLeg: { rot: [-22, 0, 0] }, RightLowerLeg: { rot: [40, 0, 0] }, LeftLeg: { rot: [-22, 0, 0] }, LeftLowerLeg: { rot: [40, 0, 0] } };

export const 姿势们: Record<姿势名, 姿势定义> = {
  /** 现身站立：idle，杖斜举（用户 11-10 定魔杖平时「斜举着」） */
  站立: { 飞: 0, 手: 斜举.站 },
  /** 起飞的中间一拍：还没完全进 fly，两膝屈着、杖略收 */
  起飞: { 飞: 0, 手: { ...斜举.站, ...屈膝, RightArm: { rot: [0, 0, 28] } } },
  /** 悬停持杖：站着浮在空中，杖斜举 */
  悬停: { 飞: 0, 手: 斜举.站 },
  /** 举杖指向目标：杖尖朝目标 */
  指向: { 飞: 0, 手: 前伸, 杖朝: '目标' },
  /** 张开轮盘的一下：杖往前一送、左臂甩开；排完这一拍再回到 指向 */
  开盘: { 飞: 0, 手: 送出, 杖朝: '目标' },
  /** 收盘：杖收回来竖在身前 */
  收盘: { 飞: 0, 手: 收回, 杖朝: '上' },
  /** 落地的一拍：回到 idle，两膝屈着缓一下；之后接 站立 */
  落地: { 飞: 0, 手: { ...斜举.站, ...屈膝 } },
};

/** 一条：从 起 秒开始往 做 这个姿势过渡，到 到 秒摆好（不写 = 起 + 0.4 秒），之后保持到下一条的 起。第一条从它的 起 之前就是这个姿势 */
export type 演出条 = { 起: number; 到?: number; 做: 姿势名 };

type 随时<T> = T | ((秒: number) => T);
const 取 = <T>(x: 随时<T>, 秒: number): T => (typeof x === 'function' ? (x as (秒: number) => T)(秒) : x);

export type 演出设定 = {
  轴: readonly 演出条[];
  /** 她脚底在哪（场景坐标，格）：起飞、换位、落地的位移由段来写 */
  位: 随时<V3>;
  /** 身子朝哪（度，0 朝北、180 朝南）；不给 = 水平上朝着目标 */
  yaw?: 随时<number>;
  /** 杖指着谁（史蒂夫、结界中心） */
  目标: 随时<V3>;
  /** 每次出手的时刻（秒）：杖小幅抖一下 */
  出手?: readonly number[];
  /** 弹簧（头发、胸）：默认 '推进' */
  弹簧?: '推进' | '稳态';
};

export type 演出此刻 = {
  /** 直接摊给 <娘化亚波伦 {...属性} 持杖 /> */
  属性: { pose: { loc: V3; yaw: number }; 秒: number; 表演: 亚波伦表演; 姿势: Record<string, BonePose> };
  /** 这一刻在两条之间：从哪个姿势到哪个、走了多少（0～1，已缓动） */
  过渡: { 从: 姿势名; 到: 姿势名; 比: number };
};


/** 抖杖：出手后 0.3 秒里手腕带着杖头往上一挑再落回（最大约 4 度），不改瞄准的右肩。原创，幅度小是因为轮盘钉在杖尖上，杖一甩整个盘跟着甩 */
export const 抖杖秒 = 0.3;
export const 抖杖角 = (秒: number, 出手: readonly number[]): number => {
  let 和 = 0;
  for (const t0 of 出手) {
    const t = (秒 - t0) / 抖杖秒;
    if (t > 0 && t < 1) 和 += 4 * Math.sin(Math.PI * Math.min(1, t * 2.5)) * (1 - t) ** 2;
  }
  return 和;
};

/** 这一刻在轴上的位置：前一个姿势、后一个姿势、走了多少 */
export const 轴上 = (轴: readonly 演出条[], 秒: number): 演出此刻['过渡'] => {
  if (!轴.length) throw new Error('亚波伦演出：轴是空的');
  let i = 0;
  while (i + 1 < 轴.length && 轴[i + 1]!.起 <= 秒) i++;
  const 条 = 轴[i]!;
  if (i === 0) return { 从: 条.做, 到: 条.做, 比: 1 };
  const 到 = 条.到 ?? 条.起 + 0.4;
  const t = 到 <= 条.起 ? 1 : Math.min(1, Math.max(0, (秒 - 条.起) / (到 - 条.起)));
  // 上一条还没摆好就被这一条接走：从上一条的目标姿势出发（不追中间态），段里别把两条排得比过渡还密
  return { 从: 轴[i - 1]!.做, 到: 条.做, 比: smoothstep01(t) };
};

export const 定演出 = (设定: 演出设定) => {
  const 位 = (秒: number) => 取(设定.位, 秒);
  const 目标 = (秒: number) => 取(设定.目标, 秒);
  const yaw = (秒: number) => {
    if (设定.yaw !== undefined) return 取(设定.yaw, 秒);
    const [p, q] = [位(秒), 目标(秒)];
    // yaw 0 朝北（+y），逆时针为正：朝向 = (−sin, cos)
    return (Math.atan2(-(q[0] - p[0]), q[1] - p[1]) * 180) / Math.PI;
  };
  const 飞权 = (秒: number) => {
    const { 从, 到, 比 } = 轴上(设定.轴, 秒);
    return lerp(姿势们[从].飞, 姿势们[到].飞, 比);
  };
  const h = 1 / 120;
  const 表演 = 定表演({
    主: (秒) => {
      const w = 飞权(秒);
      return w <= 0 ? [{ 名: 'idle' }] : w >= 1 ? [{ 名: 'fly' }] : [{ 名: 'idle' }, { 名: 'fly', 权重: w }];
    },
    // 头发、胸的弹簧吃速度：竖直速度按米/秒（YSM wiki）；水平速度 YSM 的单位没查到，飞行时写的是 20，这里按 10 格/秒 ≈ 20 估
    环境: (秒) => {
      const [a, b] = [位(秒 - h), 位(秒 + h)];
      return { 查询: { vertical_speed: (b[2] - a[2]) / (2 * h), ground_speed: Math.min(20, (Math.hypot(b[0] - a[0], b[1] - a[1]) / (2 * h)) * 2) } };
    },
    弹簧: 设定.弹簧,
  });

  const 缓存 = new Map<number, 演出此刻>();
  const 在 = (秒: number): 演出此刻 => {
    const 有 = 缓存.get(秒);
    if (有) return 有;
    const 过渡 = 轴上(设定.轴, 秒);
    const [甲, 乙] = [姿势们[过渡.从], 姿势们[过渡.到]];
    const k = 过渡.比;
    const pose = { loc: 位(秒), yaw: yaw(秒) };
    // 手摆的转角在两个姿势间插；一边没摆的骨骼，从动画这一刻的转角插过去
    const 动画 = 动画骨骼表(秒, 表演);
    const 混: Record<string, BonePose> = {};
    for (const 骨 of new Set([...Object.keys(甲.手), ...Object.keys(乙.手)])) {
      const 底 = 动画[骨]?.rot ?? [0, 0, 0];
      const [a, b] = [甲.手[骨]?.rot ?? 底, 乙.手[骨]?.rot ?? 底];
      混[骨] = { rot: [0, 1, 2].map((j) => lerp(a[j]!, b[j]!, k)) };
    }
    const 解 = (朝: '目标' | '上') => 瞄杖({ pose, 秒, 表演, 姿势: 混, 朝: 朝 === '目标' ? { 点: 目标(秒) } : { 向: [0, 0, 1] } });
    let 姿势 = 混;
    if (甲.杖朝 && 甲.杖朝 === 乙.杖朝) 姿势 = 解(甲.杖朝);
    else if (甲.杖朝 || 乙.杖朝) {
      // 两头瞄的不一样（或只有一头瞄）：各解各的右肩，再按过渡插
      const 肩 = (定: 姿势定义) => (定.杖朝 ? 解(定.杖朝) : 混).RightArm!.rot!;
      const [a, b] = [肩(甲), 肩(乙)];
      姿势 = { ...混, RightArm: { rot: [0, 1, 2].map((j) => lerp(a[j]!, b[j]!, k)) } };
    }
    const 抖 = 抖杖角(秒, 设定.出手 ?? []);
    if (抖) {
      const 腕 = 姿势.RightHand?.rot ?? [0, 0, 0];
      姿势 = { ...姿势, RightHand: { rot: [腕[0]! - 抖, 腕[1]!, 腕[2]!] } };
    }
    const 出: 演出此刻 = { 属性: { pose, 秒, 表演, 姿势 }, 过渡 };
    缓存.set(秒, 出);
    return 出;
  };
  /** 这一刻杖在场景里的位置和朝向（界面/杖尖轮盘.tsx 的 杖、法术的出手点） */
  const 杖 = (秒: number): 杖位姿 => 持杖位姿(在(秒).属性);
  return { 在, 杖, 表演, 设定 };
};
export type 亚波伦演出 = ReturnType<typeof 定演出>;
