const 通道名 = Object.keys(立) as (keyof 舞姿)[];
const 摊平 = (p: 舞姿): number[] => 通道名.flatMap((k) => (typeof p[k] === 'number' ? [p[k] as number] : (p[k] as number[])));
const 轨道: Key[][] = 摊平(立).map((_, i) => 时间线.map(([秒, p]) => [秒, 摊平(p)[i]!] as Key));

/** 这一秒的舞姿（舞台坐标）；0 秒以前、一遍结束以后停在首尾 */
export const 舞姿在 = (秒: number): 舞姿 => {
  const 值 = 轨道.map((keys) => sample(keys, 秒));
  let i = 0;
  const 出: Record<string, number | number[]> = {};
  for (const k of 通道名) {
    if (typeof 立[k] === 'number') 出[k] = 值[i++]!;
    else {
      const n = (立[k] as number[]).length;
      出[k] = 值.slice(i, i + n);
      i += n;
    }
  }
  return 出 as unknown as 舞姿;
};

// ---------- 解成骨骼 ----------
// 骨骼自己的坐标（engine/model/基岩模型.tsx）：X = 她的右，Y 上，Z = 后；转角 = Euler(−x, −y, z, 'ZYX')（度），和骨骼自带的 rotation 相加；pos 的 x 取负。

const 度 = Math.PI / 180;
const 三 = ([左, 上, 前]: 向) => new THREE.Vector3(-左, 上, -前);
const 朝下 = new THREE.Vector3(0, -1, 0);
const 轴X = new THREE.Vector3(1, 0, 0);
const 轴Y = new THREE.Vector3(0, 1, 0);
const 轴Z = new THREE.Vector3(0, 0, 1);
const 绕 = (轴: THREE.Vector3, 角: number) => new THREE.Quaternion().setFromAxisAngle(轴, 角 * 度);
/** 把垂着的一节转到朝 向 的最小转动 */
const 指向 = (向: THREE.Vector3) => new THREE.Quaternion().setFromUnitVectors(朝下, 向.clone().normalize());
/** 四元数 → BonePose 的 rot（减掉骨骼自带的转角） */
const 转角 = (q: THREE.Quaternion, 自带: readonly number[] = [0, 0, 0]): number[] => {
  const e = new THREE.Euler().setFromQuaternion(q, 'ZYX');
  return [-e.x / 度 - 自带[0]!, -e.y / 度 - 自带[1]!, e.z / 度 - 自带[2]!];
};
const 位移 = ([左, 上, 前]: 向): number[] => [左, 上, -前];

// 模型尺寸（像素，models/main.json 的轴心）：UpBody、DownBody 的轴心高 20.65；髋 (±2.2, 21.15)，膝 11.7，踝 2.5；肩的自带转角 ±18 度
const 腰高 = 20.65;
const 髋 = { 左: new THREE.Vector3(-2.2, 21.15, 0), 右: new THREE.Vector3(2.2, 21.15, 0) };
const 大腿长 = 21.15 - 11.7;
const 小腿长 = 11.7 - 2.5;
const 踝高 = 2.5;
const 肩自带 = { 左: [0, 0, -18], 右: [0, 0, 18] } as const;
/** 头往回找镜头的比例：身子转 60 度时头只跟 21 度（08 里侧身时脸还是朝镜头多） */
const 回头 = 0.65;

const 臂 = (出: Record<string, BonePose>, 边: '左' | '右', 上臂: 向, 前臂: 向) => {
  const 名 = 边 === '左' ? 'Left' : 'Right';
  const 上 = 指向(三(上臂));
  const 前 = 指向(三(前臂));
  出[`${名}Arm`] = { rot: 转角(上, 肩自带[边]) };
  出[`${名}ForeArm`] = { rot: 转角(上.clone().invert().multiply(前)) };
};

/** 腿：胯的位置、朝向定了以后，按脚底落点反解大腿、小腿，脚掌按 脚向 摆（舞台坐标里摆平） */
const 腿 = (出: Record<string, BonePose>, 边: '左' | '右', 胯移: THREE.Vector3, 胯转: THREE.Quaternion, 脚: 向, [外八, 绷]: readonly number[]) => {
  const 名 = 边 === '左' ? 'Left' : 'Right';
  const 腰 = new THREE.Vector3(0, 腰高, 0);
  const 髋位 = 髋[边].clone().sub(腰).applyQuaternion(胯转).add(腰).add(胯移);
  const 脚转 = 绕(轴Y, (边 === '左' ? 1 : -1) * 外八).multiply(绕(轴X, -绷));
  const 踝 = 三(脚).add(new THREE.Vector3(0, 踝高, 0));
  const 反胯 = 胯转.clone().invert();
  const d = 踝.sub(髋位).applyQuaternion(反胯);
  const 距 = Math.min(d.length(), 大腿长 + 小腿长 - 1e-3);
  const 向踝 = d.clone().normalize();
  // 膝盖朝脚尖那边顶
  const 膝向 = new THREE.Vector3(0, 0, -1).applyQuaternion(脚转).applyQuaternion(反胯);
  const 垂 = 膝向.sub(向踝.clone().multiplyScalar(膝向.dot(向踝))).normalize();
  const 髋角 = Math.acos(Math.min(1, Math.max(-1, (大腿长 ** 2 + 距 ** 2 - 小腿长 ** 2) / (2 * 大腿长 * 距))));
  const 大腿向 = 向踝.clone().multiplyScalar(Math.cos(髋角)).add(垂.multiplyScalar(Math.sin(髋角)));
  const 小腿向 = 向踝.clone().multiplyScalar(距).sub(大腿向.clone().multiplyScalar(大腿长));
  const 大 = 指向(大腿向);
  const 小 = 指向(小腿向);
  出[`${名}Leg`] = { rot: 转角(大) };
  出[`${名}LowerLeg`] = { rot: 转角(大.clone().invert().multiply(小)) };
  出[`${名}Foot`] = { rot: 转角(小.clone().invert().multiply(反胯).multiply(脚转)) };
};

/** 舞姿 → 骨骼姿势（给 <娘化亚波伦 姿势>） */
export const 解骨骼 = (p: 舞姿): Record<string, BonePose> => {
  const 出: Record<string, BonePose> = {};
  const 胯移 = 三(p.胯);
  const 胯转 = 绕(轴Y, p.转).multiply(绕(轴Z, p.胯倾));
  const 身 = 绕(轴Y, p.转 + p.身转).multiply(绕(轴Z, p.身倾)).multiply(绕(轴X, -p.前俯));
  出.DownBody = { rot: 转角(胯转), pos: 位移(p.胯) };
  出.UpBody = { rot: 转角(身), pos: 位移(p.胯) };
  出.Head = { rot: 转角(绕(轴Y, -回头 * (p.转 + p.身转) + p.头[0]).multiply(绕(轴Z, -0.5 * p.身倾 + p.头[1]))) };
  臂(出, '左', p.左上臂, p.左前臂);
  臂(出, '右', p.右上臂, p.右前臂);
  腿(出, '左', 胯移, 胯转, p.左脚, p.左脚向);
  腿(出, '右', 胯移, 胯转, p.右脚, p.右脚向);
  return 出;
};

/** 这一秒的骨骼姿势；循环 = 一遍跳完从头再来（默认停在收住的站姿） */
export const 忘情牛肉面姿势 = (秒: number, 设定: { 循环?: boolean } = {}): Record<string, BonePose> =>
  解骨骼(舞姿在(设定.循环 ? ((秒 % 一遍秒) + 一遍秒) % 一遍秒 : 秒));

/**
 * 给头发、胸部弹簧的输入（定表演 的 环境）：从舞姿差分出转身速度（度/秒）和竖直速度（米/秒）。
 * 弹簧吃的 q.yaw_speed 单位包里没写，这里按度/秒给（推断）；这支舞转身最快约 250 度/秒，头发因此只偏几度。
 */
export const 忘情牛肉面环境 = (秒: number): Molang环境 => {
  const h = 1 / 120;
  const [前, 后] = [舞姿在(秒 - h), 舞姿在(秒 + h)];
  const 每秒 = (a: number, b: number) => (b - a) / (2 * h);
  return { 查询: { yaw_speed: 每秒(前.转 + 前.身转, 后.转 + 后.身转), vertical_speed: (每秒(前.胯[1], 后.胯[1]) * 0.7) / 16 } };
};
