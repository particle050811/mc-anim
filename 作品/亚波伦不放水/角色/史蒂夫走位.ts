// 史蒂夫的走位：把一条脚底轨迹（几秒在哪）照原版算出走路的摆腿和身子朝向，交给 史蒂夫反应.ts（状态的 走、朝向）。纯计算。
// 位置平移、腿不动、朝向一帧切过去看着僵（用户 11-10：「人物的动作也要非常流畅」），这里按刻往前推一遍再在两刻之间插值，结果只看时间。
// 照原版（1.20.1）：
// - 摆腿 WalkAnimationState：目标 = min(1, 这一刻水平位移 × 4)，步幅每刻往目标靠 0.4，摆 每刻加当前步幅（同 库/角色/史蒂夫.tsx 的 vanillaWalk，那个只算匀速）。
// - 身子朝向 LivingEntity.tick：这一刻水平位移超过 0.05 格时身子往移动方向转，移动方向和视线差 95°～265°（倒着走）就取反方向；每刻转差的 0.3。
//   站着不动时身子不转（头偏出 50° 再带着身子转由 steveLookAt 管）。
// 离地（跳）时水平位移照算，原版跳起来腿也照摆。
import type { V3 } from '@engine/model/parts.tsx';

export type 走位此刻 = { 位置: V3; 朝向: number; 走: { 摆: number; 步幅: number } };

const 刻秒 = 1 / 20;
const 绕180 = (a: number) => ((((a + 180) % 360) + 360) % 360) - 180;

/**
 * 位：脚底在哪（场景坐标，时钟自定）；看：这一刻看向哪（决定倒着走时身子朝哪）；起：从哪一秒开始推（之前当站着不动）；初朝向：起 那一刻身子朝哪（度，0 朝 +Y，正 = 往左）。
 * 返回 在(秒)：位置原样取 位(秒)，朝向和摆腿在两刻之间线性插。
 */
export const 定走位 = (设定: { 位: (秒: number) => V3; 看: (秒: number) => V3; 起: number; 初朝向: number }) => {
  const { 位, 看, 起 } = 设定;
  // 第 k 刻末的状态（k = 0 是 起）
  const 表: { 朝向: number; 摆: number; 步幅: number }[] = [{ 朝向: 设定.初朝向, 摆: 0, 步幅: 0 }];
  const 推到 = (k: number) => {
    while (表.length <= k) {
      const n = 表.length;
      const 前 = 表[n - 1]!;
      const [a, b] = [位(起 + (n - 1) * 刻秒), 位(起 + n * 刻秒)];
      const [dx, dy] = [b[0] - a[0], b[1] - a[1]];
      const 距 = Math.hypot(dx, dy);
      const 步幅 = 前.步幅 + (Math.min(1, 距 * 4) - 前.步幅) * 0.4;
      let 朝向 = 前.朝向;
      if (距 > 0.05) {
        const 目 = 看(起 + n * 刻秒);
        const 视 = (Math.atan2(-(目[0] - b[0]), 目[1] - b[1]) * 180) / Math.PI;
        let 向 = (Math.atan2(-dx, dy) * 180) / Math.PI;
        if (Math.abs(绕180(向 - 视)) > 95) 向 += 180;
        朝向 += 绕180(向 - 朝向) * 0.3;
      }
      表.push({ 朝向, 摆: 前.摆 + 步幅, 步幅 });
    }
  };
  const 在 = (秒: number): 走位此刻 => {
    const 刻 = Math.max(0, (秒 - 起) / 刻秒);
    const k = Math.floor(刻);
    const f = 刻 - k;
    推到(k + 1);
    const [甲, 乙] = [表[k]!, 表[k + 1]!];
    return {
      位置: 位(秒),
      朝向: 甲.朝向 + (乙.朝向 - 甲.朝向) * f,
      走: { 摆: 甲.摆 + (乙.摆 - 甲.摆) * f, 步幅: 甲.步幅 + (乙.步幅 - 甲.步幅) * f },
    };
  };
  return { 在 };
};
