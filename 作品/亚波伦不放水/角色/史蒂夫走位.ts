// 史蒂夫的走位：把一条脚底轨迹（几秒在哪）照原版算出走路的摆腿和身子朝向，交给 史蒂夫反应.ts（状态的 走、朝向、跳）。纯计算。
// 位置平移、腿不动、朝向一帧切过去看着僵（用户 11-10：「人物的动作也要非常流畅」），这里按刻往前推一遍再在两刻之间插值，结果只看时间。
// 照原版（1.20.1）：
// - 摆腿 WalkAnimationState：目标 = min(1, 这一刻水平位移 × 4)，步幅每刻往目标靠 0.4，摆 每刻加当前步幅（同 库/角色/史蒂夫.tsx 的 vanillaWalk，那个只算匀速）。
// - 身子朝向 LivingEntity.tick：这一刻水平位移超过 0.05 格时身子往移动方向转，移动方向和视线差 95°～265°（倒着走）就取反方向；每刻转差的 0.3。
//   站着不动时身子不转（头偏出 50° 再带着身子转由 steveLookAt 管）。
// 离地（跳）时水平位移照算，原版跳起来腿也照摆。
// 原版没有、给关节用的两样（用户 11-10 定史蒂夫加关节，姿势在 角色/史蒂夫关节动作.ts）：
// - 向：往前走还是倒着走（移动方向在身子朝向上的分量，每刻往目标靠一半）。原版两种摆法一样，有了膝要分：往移动方向迈的那条腿收小腿。
// - 跳：从轨迹里认出腾空的那几段（竖直加速度接近重力、连着几个采样），给出离起跳、落地多久，蓄力下蹲、空中收腿、落地缓冲用。
//   只看轨迹不看地形：脚下高一格一格变的地方竖直位置是跳变，只占一两个采样，不会认成腾空。
import type { V3 } from '@engine/model/parts.tsx';

/** 这一刻和跳的关系（都不给 = 在地上、前后都没有跳）。空长 = 说的那一跳在空中一共多久 */
export type 腾空此刻 = {
  /** 在地上、0.5 秒内要起跳：还有几秒 */
  起跳前秒?: number;
  /** 在空中：离地多久了、还有多久落地 */
  空中?: { 已: number; 剩: number };
  /** 在地上、0.6 秒内落过地：落地后几秒、落地时往下的速度（格/秒） */
  落地后秒?: number;
  落地速?: number;
  空长?: number;
};
export type 走位此刻 = { 位置: V3; 朝向: number; 走: { 摆: number; 步幅: number; 向: number }; 跳: 腾空此刻 };

const 刻秒 = 1 / 20;
const 绕180 = (a: number) => ((((a + 180) % 360) + 360) % 360) - 180;
/** 认腾空：采样间隔（秒）、竖直加速度低于多少算腾空（格/秒²；原版重力折合 32，编排里的跳用 24.6）、至少连着几个采样、往前往后各找多远（秒） */
const 采样 = 1 / 120;
const 腾空加速度 = -10;
const 腾空最少 = 4;
const 找起跳 = 0.5;
const 找落地 = 0.6;

/**
 * 位：脚底在哪（场景坐标，时钟自定）；看：这一刻看向哪（决定倒着走时身子朝哪）；起：从哪一秒开始推（之前当站着不动）；初朝向：起 那一刻身子朝哪（度，0 朝 +Y，正 = 往左）。
 * 返回 在(秒)：位置原样取 位(秒)，朝向和摆腿在两刻之间线性插。
 */
export const 定走位 = (设定: { 位: (秒: number) => V3; 看: (秒: number) => V3; 起: number; 初朝向: number }) => {
  const { 位, 看, 起 } = 设定;
  // 第 k 刻末的状态（k = 0 是 起）
  const 表: { 朝向: number; 摆: number; 步幅: number; 向: number }[] = [{ 朝向: 设定.初朝向, 摆: 0, 步幅: 0, 向: 1 }];
  const 推到 = (k: number) => {
    while (表.length <= k) {
      const n = 表.length;
      const 前 = 表[n - 1]!;
      const [a, b] = [位(起 + (n - 1) * 刻秒), 位(起 + n * 刻秒)];
      const [dx, dy] = [b[0] - a[0], b[1] - a[1]];
      const 距 = Math.hypot(dx, dy);
      const 步幅 = 前.步幅 + (Math.min(1, 距 * 4) - 前.步幅) * 0.4;
      let 朝向 = 前.朝向;
      if (距 > 0.05) {
        const 目 = 看(起 + n * 刻秒);
        const 视 = (Math.atan2(-(目[0] - b[0]), 目[1] - b[1]) * 180) / Math.PI;
        let 行 = (Math.atan2(-dx, dy) * 180) / Math.PI;
        if (Math.abs(绕180(行 - 视)) > 95) 行 += 180;
        朝向 += 绕180(行 - 朝向) * 0.3;
      }
      let 向 = 前.向;
      if (距 > 0.02) 向 += (Math.cos(Math.atan2(-dx, dy) - (朝向 * Math.PI) / 180) - 向) * 0.5;
      表.push({ 朝向, 摆: 前.摆 + 步幅, 步幅, 向 });
    }
  };
  // 第 k 个采样（起 + k × 采样）的竖直加速度（位置的二阶差分）够不够腾空
  const 空表 = new Map<number, boolean>();
  const 空样 = (k: number) => {
    let 空 = 空表.get(k);
    if (空 === undefined) {
      const t = 起 + k * 采样;
      空 = (位(t + 采样)[2] - 2 * 位(t)[2] + 位(t - 采样)[2]) / (采样 * 采样) < 腾空加速度;
      空表.set(k, 空);
    }
    return 空;
  };
  /** 第 k 个采样所在的腾空段 [起跳时刻, 落地时刻]；不在腾空段里 = null。起跳、落地那一下差分里混着速度突变，两头各少认一个采样，补回去 */
  const 空段 = (k: number): readonly [number, number] | null => {
    if (!空样(k)) return null;
    let [a, b] = [k, k];
    while (k - a < 1200 && 空样(a - 1)) a--;
    while (b - k < 1200 && 空样(b + 1)) b++;
    return b - a + 1 < 腾空最少 ? null : [起 + (a - 1) * 采样, 起 + (b + 1) * 采样];
  };
  const 跳在 = (秒: number): 腾空此刻 => {
    const k = Math.round((秒 - 起) / 采样);
    for (const j of [k, k - 1, k + 1]) {
      const 段 = 空段(j);
      if (段 && 秒 >= 段[0] && 秒 < 段[1]) return { 空中: { 已: 秒 - 段[0], 剩: 段[1] - 秒 }, 空长: 段[1] - 段[0] };
    }
    const 出: 腾空此刻 = {};
    for (let j = k; j <= k + 找起跳 / 采样 + 1; j++) {
      const 段 = 空段(j);
      if (!段) continue;
      if (段[0] >= 秒 && 段[0] - 秒 <= 找起跳) Object.assign(出, { 起跳前秒: 段[0] - 秒, 空长: 段[1] - 段[0] });
      break;
    }
    for (let j = k; j >= k - 找落地 / 采样 - 1; j--) {
      const 段 = 空段(j);
      if (!段) continue;
      if (段[1] <= 秒 && 秒 - 段[1] <= 找落地) {
        出.落地后秒 = 秒 - 段[1];
        出.落地速 = Math.max(0, (位(段[1] - 2 * 采样)[2] - 位(段[1] - 采样)[2]) / 采样);
        出.空长 ??= 段[1] - 段[0];
      }
      break;
    }
    return 出;
  };
  const 在 = (秒: number): 走位此刻 => {
    const 刻 = Math.max(0, (秒 - 起) / 刻秒);
    const k = Math.floor(刻);
    const f = 刻 - k;
    推到(k + 1);
    const [甲, 乙] = [表[k]!, 表[k + 1]!];
    return {
      位置: 位(秒),
      朝向: 甲.朝向 + (乙.朝向 - 甲.朝向) * f,
      走: { 摆: 甲.摆 + (乙.摆 - 甲.摆) * f, 步幅: 甲.步幅 + (乙.步幅 - 甲.步幅) * f, 向: 甲.向 + (乙.向 - 甲.向) * f },
      跳: 跳在(秒),
    };
  };
  return { 在 };
};
