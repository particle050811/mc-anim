/** 几种蹲并在一起：都不蹲是 0，哪种蹲满了就是 1，叠起来不超过 1 */
const 并 = (权: readonly number[]) => 1 - 权.reduce((积, w) => 积 * (1 - clamp01(w)), 1);

/** 起跳前的蓄力下蹲 0～1：起跳前 蓄力起 秒开始往下蹲，最后 蓄力蹬 秒蹬直 */
export const 蓄力权 = (跳: 腾空此刻) => {
  const τ = 跳.起跳前秒;
  if (τ === undefined) return 0;
  const { 蓄力起, 蓄力沉, 蓄力蹬 } = 动作参.蹲;
  return smoothstep01((蓄力起 - τ) / 蓄力沉) * smoothstep01(τ / 蓄力蹬) * 跳大小(跳);
};
/** 落地缓冲 0～1：落地后 落地压 秒压到底，再 落地起 秒站直；落得越快压得越深 */
export const 落地权 = (跳: 腾空此刻) => {
  const τ = 跳.落地后秒;
  if (τ === undefined) return 0;
  const { 落地压, 落地起 } = 动作参.蹲;
  return clamp((跳.落地速 ?? 0) / 7, 0.35, 1) * smoothstep01(τ / 落地压) * (1 - smoothstep01((τ - 落地压) / 落地起)) * 跳大小(跳);
};
/** 空中收腿 0～1 */
export const 收腿权 = (跳: 腾空此刻) => (跳.空中 ? smoothstep01(跳.空中.已 / 动作参.空中.收) * smoothstep01(跳.空中.剩 / 动作参.空中.伸) * 跳大小(跳) : 0);
const 跳大小 = (跳: 腾空此刻) => clamp01(((跳.空长 ?? 0.4) - 0.15) / 0.25);

export type 关节动作入 = {
  /** 摆腿（原版 limbSwing、limbSwingAmount）；向：1 往前走、−1 倒着走，不给 = 1 */
  摆: number;
  步幅: number;
  向?: number;
  跳?: 腾空此刻;
  /** 挣扎强度 0～1、时钟（秒） */
  挣?: number;
  秒: number;
  /** 挨打后仰的包络 0～1（后仰的角度本身已经加在 pose.pitch 上） */
  仰?: number;
  /** 两只手拿没拿东西；右手拿的是不是剑 */
  右持: boolean;
  左持: boolean;
  持剑: boolean;
  /** 正在拉弓、举盾：那只手臂照原版的姿势，肘不弯 */
  拉弓?: boolean;
  举盾?: boolean;
  /** 距上次挥剑点击几秒（没在挥 = 不给）；挥过 = 这一段里已经点过挥剑 */
  挥秒?: number;
  挥过?: boolean;
  /** 点下去的是哪一招、正在蓄的是哪一招；不给 = 下劈 */
  招?: 招名;
  蓄招?: 招名;
  /** 举剑蓄力 0～1（摆到 蓄招 的蓄）；不给 = 拿着剑往前跳、还没挥过就举 跳蓄 那一招（起跳前蓄力时举起来）。斩、停的时候不算 */
  蓄力?: number;
};

/** pose：stevePose（加上看向、拧身、后仰）出来的；返回加了肘、膝、蹲、收腿、前倾的姿势 */
export const 加关节动作 = (pose: StevePose, 入: 关节动作入): 关节姿 => {
  const 参 = 动作参;
  const 幅 = clamp01(入.步幅);
  const 向 = clamp(入.向 ?? 1, -1, 1);
  const 跳 = 入.跳 ?? {};
  const 挣 = clamp01(入.挣 ?? 0);
  const 仰 = clamp01(入.仰 ?? 0);
  const φ = 入.摆 * 0.6662;

  // 剑招：点下去那一招的斩（权 1 → 收的时候降到 0），再盖上下一招的蓄（蓄力）
  const 斩 = 入.持剑 && 入.挥秒 !== undefined ? 斩此刻(入.招 ?? '下劈', 入.挥秒) : null;
  const 在斩 = 入.挥秒 !== undefined && 入.挥秒 >= 0 && 入.挥秒 < 剑招拍.斩 + 剑招拍.停;
  let 蓄权 = 0;
  let 蓄姿: 招姿 = 招表[入.蓄招 ?? '下劈'].蓄;
  if (入.持剑 && !在斩) {
    if (入.蓄力 !== undefined) 蓄权 = clamp01(入.蓄力);
    else {
      const 起跳 = 跳.空中 ? smoothstep01(跳.空中.剩 / 参.空中.伸) : 跳.起跳前秒 !== undefined ? smoothstep01((参.蹲.蓄力起 - 跳.起跳前秒) / 参.蹲.蓄力沉) : 0;
      蓄权 = 入.挥过 || 斩 ? 0 : 起跳 * smoothstep01((向 - 0.2) / 0.5) * 跳大小(跳);
      蓄姿 = 招表[参.挥剑.跳蓄].蓄;
    }
  }
  /** 平时的值 → 套上斩和蓄以后的值（叠加的键平时是 0） */
  const 套 = (键: keyof 招姿, 平: number) => lerp(斩 ? lerp(平, 斩.姿[键], 斩.权) : 平, 蓄姿[键], 蓄权);

  // 走、跑：大腿照原版的相位摆（右腿 −cos φ），迈步的那条腿收小腿（往前走时右腿在 sin φ > 0 的半圈里往前迈，倒着走反过来）
  const 收 = (u: number) => ((1 + u) / 2) ** 参.走.收膝指数;
  const 迈 = Math.sin(φ + 参.走.收膝提前) * 向;
  let 腿右 = 幅 * (-参.走.摆腿 * Math.cos(φ) + 参.走.前偏 * 向);
  let 腿左 = 幅 * (参.走.摆腿 * Math.cos(φ) + 参.走.前偏 * 向);
  let 膝右 = 幅 * (参.走.撑膝 + 参.走.收膝 * 收(迈));
  let 膝左 = 幅 * (参.走.撑膝 + 参.走.收膝 * 收(-迈));
  let 前倾 = 幅 * Math.max(0, 参.走.前倾[0] + 参.走.前倾[1] * 向) + 参.挣扎.前倾 * 挣 + 套('倾', 0);

  // 蹲：蓄力、落地、马步、腿软并在一起；两膝加弯，大腿抬到脚底还在髋的正下方
  const 蹲 = 并([参.蹲.蓄力 * 蓄力权(跳), 参.蹲.落地 * 落地权(跳), 参.蹲.挣扎 * 挣, 参.蹲.挨打 * 仰, 套('沉', 0)]);
  const 蹲膝 = 参.蹲.膝 * 蹲;
  腿右 += 蹲腿角(蹲膝);
  腿左 += 蹲腿角(蹲膝);
  膝右 += 蹲膝;
  膝左 += 蹲膝;
  前倾 += 参.蹲.前倾 * 蹲;

  // 空中收腿：往前跳一前一后，往后跳两腿一起收
  const 空 = 收腿权(跳);
  if (空 > 0) {
    const 前 = (向 + 1) / 2;
    const 目 = (甲: readonly [number, number], i: 0 | 1) => lerp(参.空中.后跳[i], 甲[i], 前);
    腿左 = lerp(腿左, 目(参.空中.前腿, 0), 空);
    膝左 = lerp(膝左, 目(参.空中.前腿, 1), 空);
    腿右 = lerp(腿右, 目(参.空中.后腿, 0), 空);
    膝右 = lerp(膝右, 目(参.空中.后腿, 1), 空);
    前倾 += 参.空中.前倾 * 空 * 前;
  }

  // 髋：蹲的时候脚踩实；走的时候髋最多沉 沉髋 像素，再多的算两脚离地；空中不沉（脚收上去）
  const 伸 = Math.max(3, 腿伸(腿右, 膝右).下, 腿伸(腿左, 膝左).下);
  const 差 = 12 - 伸;
  const 踩实 = smoothstep01(蹲 * 2.5);
  let ground = 差 < 1e-6 ? 1 : clamp01((Math.min(差, 参.走.沉髋) + Math.max(0, 差 - 参.走.沉髋) * 踩实) / 差);
  if (跳.空中) ground *= 1 - smoothstep01(Math.min(跳.空中.已 / 0.07, 跳.空中.剩 / 0.05));

  // 肘：摆到前面多弯一点（两臂和腿反着摆：右臂 cos φ 往前）
  const 臂肘 = (持: boolean, 前摆: number) => {
    const [站, 基, 加] = 持 ? 参.臂.持物 : 参.臂.空手;
    return 站 + 幅 * (基 + 加 * 前摆);
  };
  let 肘右 = 臂肘(入.右持, (1 + Math.cos(φ)) / 2);
  let 肘左 = 臂肘(入.左持, (1 - Math.cos(φ)) / 2);
  let { armR, armL, armRRoll } = pose;

  // 挣扎：两肘轮流往回拽
  if (挣 > 0) {
    const 拽 = Math.sin(入.秒 * Math.PI * 2 * 参.挣扎.频率);
    肘右 += 挣 * (参.挣扎.肘[0] + 参.挣扎.肘[1] * 拽);
    肘左 += 挣 * (参.挣扎.肘[0] - 参.挣扎.肘[1] * 拽);
  }
  // 挨打：空着的手往后甩
  if (仰 > 0) {
    if (!入.左持) [armL, 肘左] = [armL - 参.挨打.甩臂 * 仰, 肘左 + 参.挨打.肘 * 仰];
    else if (!入.右持) [armR, 肘右] = [armR - 参.挨打.甩臂 * 仰, 肘右 + 参.挨打.肘 * 仰];
  }
  // 剑招：右臂、肘、腕、左臂照招摆，胸跟着拧
  let [armRYaw, armLRoll, twist, 腕R] = [pose.armRYaw ?? 0, pose.armLRoll, pose.twist ?? 0, 0];
  if (斩 || 蓄权 > 0) {
    [armR, armRRoll, armRYaw, 肘右, 腕R] = [套('臂', armR), 套('滚', armRRoll), 套('转', armRYaw), 套('肘', 肘右), 套('腕', 0)];
    [armL, armLRoll, twist] = [套('左臂', armL), 套('左滚', armLRoll), twist + 套('拧', 0)];
  }
  if (入.拉弓) [肘右, 肘左] = [0, 0];
  if (入.举盾) 肘左 = 0;

  // pitch 负 = 前倾；后仰已经在 pose.pitch 里。头把自己加的前倾抵掉，还看着原来的地方
  const pitch = pose.pitch - 前倾;
  return {
    ...pose,
    pitch,
    headPitch: pose.headPitch + 前倾,
    legR: 腿右 - pitch,
    legL: 腿左 - pitch,
    kneeR: 膝右,
    kneeL: 膝左,
    elbowR: 肘右,
    elbowL: 肘左,
    armR,
    armL,
    armRRoll,
    armRYaw,
    armLRoll,
    twist,
    腕R,
    ground,
  };
};
