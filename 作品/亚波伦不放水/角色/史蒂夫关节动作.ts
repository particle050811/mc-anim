    /** 身子前倾（度/步幅）：站着走的一份 + 往前走再加的一份（倒着走减掉） */
    前倾: [3, 6],
    /** 两腿都斜着时髋最多沉多少像素；再多就当腾空（两脚离地，跑起来的样子） */
