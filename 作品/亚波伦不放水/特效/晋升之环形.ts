/** 一个方盒：先在自己的坐标里按 小、大 两个角摆好，再绕层的 Z 轴转 绕Z 度（放射状的光芒用） */
export type 盒 = { 小: readonly [number, number, number]; 大: readonly [number, number, number]; 色: string; 绕Z?: number };
/** 层这一刻的摆法：先自转（绕自己的中心，XYZ 欧拉角，度），再挪到 中心，最后整层绕环心的 Z 轴公转 */
export type 层位姿 = { 公转: number; 中心?: readonly [number, number, number]; 自转?: readonly [number, number, number] };
export type 层 = { 盒们: readonly 盒[]; 位姿: (秒: number) => 层位姿 };
/** 环后面那圈加色的晕：离 [内, 外] 这条带多远算亮度，宽 个像素外落到 0；一个像素一格、分级，不做平滑渐变 */
export type 晕 = { 内: number; 外: number; 宽: number; 色: string; 强: number };
export type 候选 = { 名: string; 说明: string; 层们: readonly 层[]; 晕: 晕; /** 最外沿离环心多远（像素），摆大小用 */ 外径: number };

/** 像素圆环：格子中心离原点在 [内, 外) 里的格，一格一个 1×1 的盒；色、留 按格子中心的角度（度，0～360，从 +X 逆时针）和半径定 */
const 像素环 = (内: number, 外: number, z: readonly [number, number], 色: (角: number, 距: number) => string, 留: (角: number, 距: number) => boolean = () => true): 盒[] => {
  const 出: 盒[] = [];
  const n = Math.ceil(外);
  for (let i = -n; i < n; i++)
    for (let j = -n; j < n; j++) {
      const [x, y] = [i + 0.5, j + 0.5];
      const 距 = Math.hypot(x, y);
      if (距 < 内 || 距 >= 外) continue;
      const 角 = ((Math.atan2(y, x) * 180) / Math.PI + 360) % 360;
      if (留(角, 距)) 出.push({ 小: [i, j, z[0]], 大: [i + 1, j + 1, z[1]], 色: 色(角, 距) });
    }
  return 出;
};
/** 以 (cx, cy) 为中心、边长 边 的方块，z 从 z0 到 z1 */
const 方块 = (cx: number, cy: number, 边: number, z0: number, z1: number, 色: string, 绕Z?: number): 盒 => ({ 小: [cx - 边 / 2, cy - 边 / 2, z0], 大: [cx + 边 / 2, cy + 边 / 2, z1], 色, ...(绕Z === undefined ? {} : { 绕Z }) });
/** 角离最近的 周期 度的整数倍（加 偏）差几度 */
const 离整倍 = (角: number, 周期: number, 偏 = 0) => Math.abs(((((角 - 偏) % 周期) + 周期 * 1.5) % 周期) - 周期 / 2);
const 转 = (每秒度: number, 相位 = 0) => (秒: number): 层位姿 => ({ 公转: 相位 + 每秒度 * 秒 });

