// 第 5 幕击败的纯计算部分：幕内时刻、她怎么飞怎么落。段.ts 排声音也引，所以不引模型、贴图、React；她的姿势、盘在 编排-击败.ts。
// 用户 11-11 嫌慢（「飞行速度也很慢」）：她不再慢慢滑、落地后也不走路。他一死她一下冲过去刹住（5-01），死亡界面后面慢慢往下漂（5-02），
// 5-03 盘照原版的快慢收回（每圈 2.5 刻），一下俯冲落到那堆东西跟前、落地带着劲往前滑一小段站住低头看。时刻、冲法都是 Agent 取的，用户没看过。
// 五版自查的毛病（用户 11-11「那些毛病你发现的都修一下吧」）：5-01 她冲到离他 8 格、高 9.5 格，镜头里看不见；5-02 她在 12 格外、几乎不动；
// 5-03 落脚、站脚在撒出来的东西中间，可能踩穿。这版 5-01 冲得近、低，5-02 在他眼前横着往下漂，5-03 落在东西之间的空当、离每件都远（下面核对）。
import { clamp01, lerp as 混, lerpV, smoothstep01 as 平滑 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { 史蒂夫掉落件数, 死亡掉落轨迹 } from '../../角色/史蒂夫掉落轨迹.ts';
import { 台地点 } from './布局.ts';
import 线 from './时间线.ts';
import { 冲进度, 史蒂夫脚, 末位, 眼高 } from './齐放拍.ts';

const 事 = 线.事件;
/** 本幕开头（编排的钟，现身后几秒）：结界收缩焚烧完的那一刻 */
export const 幕起 = 事.齐放完.秒 - 事.现身.秒;
export const 幕长 = 事.击败完.秒 - 事.齐放完.秒;
export const 秒在 = (s: number) => 幕起 + s;

/** 各镜头的开头（幕内秒）：5-01 倒下化烟 1.8 秒，5-02 死亡界面 3.5 秒（和三版一样长），5-03 收盘、俯冲落地 2.3 秒 */
export const 镜起 = { 一: 0, 二: 1.8, 三: 5.3 } as const;
export const 五三长 = 2.3;
if (Math.abs(幕长 - (镜起.三 + 五三长)) > 1e-6) throw new Error(`击败的幕长 ${幕长} 秒要等于 5-03 起 ${镜起.三} + ${五三长} 秒（场/1-台地/时间线.ts 的 击败完）`);

/** 史蒂夫脚底 → 她（第 4 幕末停的地方）的水平单位向量 */
export const 往她: V3 = (() => {
  const [x, y] = [末位[0] - 史蒂夫脚[0], 末位[1] - 史蒂夫脚[1]];
  const 长 = Math.hypot(x, y);
  return [x / 长, y / 长, 0];
})();
/** 往她 往右转 90 度（从上往下看顺时针） */
export const 往右: V3 = [往她[1], -往她[0], 0];
/** 从史蒂夫脚底往她那边 前 格、往右 右 格、比他脚底高 高 格的点 */
const 空中点 = (前: number, 右: number, 高: number): V3 => [史蒂夫脚[0] + 往她[0] * 前 + 往右[0] * 右, 史蒂夫脚[1] + 往她[1] * 前 + 往右[1] * 右, 史蒂夫脚[2] + 高];

/** 她的拍子（幕内秒） */
export const 她拍 = {
  /** 5-01：他倒下 0.35 秒后她朝他一冲，0.45 秒（冲得远：从结界那头上空下来约 11 格） */
  冲起: 0.35,
  冲秒: 0.45,
  /** 5-03：开头 7 帧摆出收盘的姿势（杖竖到身前），姿势快到位时盘开始收 */
  收姿秒: 7 / 60,
  收起: 镜起.三 + 0.05,
  /** 盘收完（每圈 2.5 刻、相邻两圈隔 2.5 刻，三圈 7.5 刻 = 0.375 秒）就俯冲下去，0.25 秒落地（5-02 漂得低了，一下扎下去 4.5 格） */
  降起: 镜起.三 + 0.45,
  降秒: 0.25,
  /** 落地后带着劲往前滑到站住 */
  滑秒: 0.6,
} as const;
export const 落地 = 秒在(她拍.降起 + 她拍.降秒);
export const 站住 = 落地 + 她拍.滑秒;
/** 盘收的时刻（编排的钟） */
export const 收起 = 秒在(她拍.收起);

/** 5-01 冲：冲到他那边离他 5.5 格、比他脚高 5 格（头 10% 加到全速，后 30% 急刹）；5-01 侧面两人同框的机位里看得见她冲进来刹住 */
export const 冲到: V3 = 空中点(5.5, 0, 5);
/** 5-02 漂到：往右横着漂 3.6 格、凑近一点、降到高 4.5 格（3.5 秒约 1 格/秒），在他第一人称的画面里从中间往一侧走、一直在动 */
const 漂到平 = 空中点(4.2, 3.6, 4.5);
/** 站脚：撒出来的东西之间的空当（离他 3.4 格、往右偏 70 度那边；下面核对离每件都远）。俯冲、落地、滑停都在一条直线上：
 *  俯冲的水平一段照 滑速 匀速走，落地接得上滑，滑 滑距 匀减到站住 */
const 站平 = 空中点(1.2, 3.4, 0);
const 滑距 = 1.2;
const 滑速 = (2 * 滑距) / 她拍.滑秒;
const 平向: V3 = (() => {
  const [x, y] = [站平[0] - 漂到平[0], 站平[1] - 漂到平[1]];
  const 长 = Math.hypot(x, y);
  return [x / 长, y / 长, 0];
})();
const 地点 = (p: V3): V3 => 台地点(p[0], -p[1]);
const 站脚: V3 = 地点(站平);
export const 落脚: V3 = 地点([站平[0] - 平向[0] * 滑距, 站平[1] - 平向[1] * 滑距, 0]);
const 漂到: V3 = [落脚[0] - 平向[0] * 滑速 * 她拍.降秒, 落脚[1] - 平向[1] * 滑速 * 她拍.降秒, 漂到平[2]];
const 混3 = (a: V3, b: V3, u: number) => lerpV(a, b, u) as V3;

/** 她的脚底（编排的钟） */
export const 亚波伦位 = (t: number): V3 => {
  const s = t - 幕起;
  const 冲止 = 她拍.冲起 + 她拍.冲秒;
  if (s < 冲止) return 混3(末位, 冲到, 冲进度((s - 她拍.冲起) / 她拍.冲秒, 0.1, 0.3));
  // 5-02 死亡界面后面慢慢往下漂（冲完刹住以后从静止起、到俯冲前停）
  if (s < 她拍.降起) return 混3(冲到, 漂到, 平滑((s - 冲止) / (她拍.降起 - 冲止)));
  const 地 = 落脚;
  if (t < 落地) {
    const u = (s - 她拍.降起) / 她拍.降秒;
    const 平 = 混3(漂到, 地, u);
    return [平[0], 平[1], 漂到[2] + (地[2] - 漂到[2]) * 冲进度(u, 0.1, 0.3)];
  }
  const τ = Math.min(t - 落地, 她拍.滑秒) / 她拍.滑秒;
  return 混3(落脚, 站脚, 1 - (1 - τ) * (1 - τ));
};

/** 撒出来的东西（第 5 幕画面用同一份：角色/史蒂夫掉落轨迹.ts，种子 掉落种子）。她落地后的脚底离每一件（停在地上的位置）都要有 离物 格以上 */
export const 掉落种子 = 3;
const 离物 = 1.2;
{
  const 物们 = 死亡掉落轨迹(史蒂夫脚, 史蒂夫掉落件数, 掉落种子, { 眼高 }).map((x) => x.路[x.路.length - 1]!);
  for (let k = 0; k <= 10; k++) {
    const p = 亚波伦位(落地 + (她拍.滑秒 * k) / 10);
    const 近 = Math.min(...物们.map((q) => Math.hypot(q[0] - p[0], q[1] - p[1])));
    if (近 < 离物) throw new Error(`击败：她落地滑停时离地上的东西只有 ${近.toFixed(2)} 格（击败拍.ts 的 站平）`);
  }
}

// ── 5-02 的光标（GUI 像素，界面 640 × 360）：打开时原版把鼠标放在窗口正中；20 刻后按钮能按，移到「重生」上，点下去 ──
export const 光标 = { 起: [320, 180] as const, 到: [326, 170] as const, 移起: 1.35, 移秒: 0.45, 点: 2.6 };
export const 光标在 = (镜内秒: number): readonly [number, number] => {
  const u = 平滑(clamp01((镜内秒 - 光标.移起) / 光标.移秒));
  return [混(光标.起[0], 光标.到[0], u), 混(光标.起[1], 光标.到[1], u)];
};
