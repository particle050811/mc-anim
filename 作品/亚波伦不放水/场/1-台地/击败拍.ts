// 用户 11-11 看完七版：5-01 东西撒一地那一镜单拍没意义，去掉；「死后亚伯伦 环绕的镜头 我觉得做得挺好 不改」，又更正「就在死亡界面撒一地」。
// 所以本幕只剩一镜：七版 5-03（她收盘、一下俯冲落地滑停、低头看），机位、她的走位和姿势一帧不改，照七版的钟取；
// 死亡界面盖在上面，他一死（第 4 幕最后一刻 = 本幕第 0 秒）东西照原版死亡掉落从他身上撒出去。
// 七版的钟：本幕第 s 秒 = 七版第 5 幕第 七版五三 + s 秒。她的位置、浮动、待机动画都照七版的钟走，第 2 幕改长改短这里也不变（第 4 幕末她停在 第五幕起位，下面核对）。
import { clamp01, lerp as 混, lerpV, smoothstep01 as 平滑 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { 史蒂夫掉落件数, 死亡掉落轨迹 } from '../../角色/史蒂夫掉落轨迹.ts';
import { 台地点 } from './布局.ts';
import 线 from './时间线.ts';
import { 冲进度, 史蒂夫脚, 眼高, 第五幕起位 } from './齐放拍.ts';

const 事 = 线.事件;
/** 本幕开头（编排的钟，现身后几秒）：他死的那一刻 */
export const 幕起 = 事.齐放完.秒 - 事.现身.秒;
export const 幕长 = 事.击败完.秒 - 事.齐放完.秒;
export const 秒在 = (s: number) => 幕起 + s;

/** 七版：第 5 幕开头在现身后 19.45 秒，5-03 从第 5 幕第 5.3 秒起、长 2.3 秒 */
const 七版幕起 = 19.45;
const 七版五三 = 5.3;
const 五三长 = 2.3;
if (Math.abs(幕长 - 五三长) > 1e-6) throw new Error(`击败的幕长 ${幕长} 秒要等于七版 5-03 的 ${五三长} 秒（场/1-台地/时间线.ts 的 第五幕长）`);
/** 编排的钟 → 七版的编排钟 */
export const 七版钟 = (t: number) => t - 幕起 + 七版幕起 + 七版五三;
/** 七版的编排钟 → 七版第 5 幕幕内秒 */
const 七版幕内 = (τ: number) => τ - 七版幕起;

/** 七版第 4 幕末她停的地方（起位关于史蒂夫对称的那一点）：七版第 5 幕的走位都从它量，写死，第 4 幕起点再改也不跟着动 */
const 七版末位: V3 = [914.5, 287.5, 62];
/** 史蒂夫脚底 → 七版末位 的水平单位向量 */
export const 往她: V3 = (() => {
  const [x, y] = [七版末位[0] - 史蒂夫脚[0], 七版末位[1] - 史蒂夫脚[1]];
  const 长 = Math.hypot(x, y);
  return [x / 长, y / 长, 0];
})();
/** 往她 往右转 90 度（从上往下看顺时针） */
export const 往右: V3 = [往她[1], -往她[0], 0];
/** 从史蒂夫脚底往她那边 前 格、往右 右 格、比他脚底高 高 格的点 */
const 空中点 = (前: number, 右: number, 高: number): V3 => [史蒂夫脚[0] + 往她[0] * 前 + 往右[0] * 右, 史蒂夫脚[1] + 往她[1] * 前 + 往右[1] * 右, 史蒂夫脚[2] + 高];

/** 她的拍子（本幕幕内秒，七版的减 七版五三） */
export const 她拍 = {
  /** 开头 7 帧摆出收盘的姿势（杖竖到身前），姿势快到位时盘开始收 */
  收姿秒: 7 / 60,
  收起: 0.05,
  /** 盘收完（每圈 2.5 刻、相邻两圈隔 2.5 刻，三圈 7.5 刻 = 0.375 秒）就俯冲下去，0.25 秒落地 */
  降起: 0.45,
  降秒: 0.25,
  /** 落地后带着劲往前滑到站住 */
  滑秒: 0.6,
} as const;
export const 落地 = 秒在(她拍.降起 + 她拍.降秒);
export const 站住 = 落地 + 她拍.滑秒;
/** 盘收的时刻（编排的钟） */
export const 收起 = 秒在(她拍.收起);

// 七版的走位（七版第 5 幕幕内秒）：0.35 秒起冲到 冲到、0.8 秒起慢慢往下漂到 漂到、5.75 秒俯冲。本幕从 5.3 秒接上，只剩漂的尾巴、俯冲、滑停
const 七版冲止 = 0.8;
const 七版降起 = 七版五三 + 她拍.降起;
const 冲到: V3 = 空中点(5.5, 0, 5);
const 漂到平 = 空中点(4.2, 3.6, 4.5);
/** 站脚：撒出来的东西之间的空当。俯冲的水平一段照 滑速 匀速走，落地接得上滑，滑 滑距 匀减到站住 */
const 站平 = 空中点(1.2, 3.4, 0);
const 滑距 = 1.2;
const 滑速 = (2 * 滑距) / 她拍.滑秒;
const 平向: V3 = (() => {
  const [x, y] = [站平[0] - 漂到平[0], 站平[1] - 漂到平[1]];
  const 长 = Math.hypot(x, y);
  return [x / 长, y / 长, 0];
})();
const 地点 = (p: V3): V3 => 台地点(p[0], -p[1]);
const 站脚: V3 = 地点(站平);
export const 落脚: V3 = 地点([站平[0] - 平向[0] * 滑距, 站平[1] - 平向[1] * 滑距, 0]);
const 漂到: V3 = [落脚[0] - 平向[0] * 滑速 * 她拍.降秒, 落脚[1] - 平向[1] * 滑速 * 她拍.降秒, 漂到平[2]];
const 混3 = (a: V3, b: V3, u: number) => lerpV(a, b, u) as V3;

/** 她的脚底（七版的编排钟） */
export const 七版位 = (τ: number): V3 => {
  const s = 七版幕内(τ);
  if (s < 七版降起) return 混3(冲到, 漂到, 平滑((s - 七版冲止) / (七版降起 - 七版冲止)));
  const 落 = 七版降起 + 她拍.降秒;
  if (s < 落) {
    const u = (s - 七版降起) / 她拍.降秒;
    const 平 = 混3(漂到, 落脚, u);
    return [平[0], 平[1], 漂到[2] + (落脚[2] - 漂到[2]) * 冲进度(u, 0.1, 0.3)];
  }
  const τ滑 = Math.min(s - 落, 她拍.滑秒) / 她拍.滑秒;
  return 混3(落脚, 站脚, 1 - (1 - τ滑) * (1 - τ滑));
};
/** 她的脚底（编排的钟） */
export const 亚波伦位 = (t: number): V3 => 七版位(七版钟(t));
if (Math.hypot(...亚波伦位(幕起).map((x, i) => x - 第五幕起位[i]!)) > 1e-6) throw new Error('击败：本幕开头她不在第 4 幕末停的 第五幕起位（齐放拍.ts）');

/** 撒出来的东西（第 5 幕画面用同一份：角色/史蒂夫掉落轨迹.ts，种子 掉落种子，停下的地方同七版）。她落地后的脚底离每一件（停在地上的位置）都要有 离物 格以上 */
export const 掉落种子 = 3;
const 离物 = 1.2;
{
  const 物们 = 死亡掉落轨迹(史蒂夫脚, 史蒂夫掉落件数, 掉落种子, { 眼高 }).map((x) => x.路[x.路.length - 1]!);
  for (let k = 0; k <= 10; k++) {
    const p = 亚波伦位(落地 + (她拍.滑秒 * k) / 10);
    const 近 = Math.min(...物们.map((q) => Math.hypot(q[0] - p[0], q[1] - p[1])));
    if (近 < 离物) throw new Error(`击败：她落地滑停时离地上的东西只有 ${近.toFixed(2)} 格（击败拍.ts 的 站平）`);
  }
}

// ── 死亡界面的光标（GUI 像素，界面 640 × 360，幕内秒）：打开时原版把鼠标放在窗口正中；20 刻后按钮能按，移到「重生」上，幕末前点下去 ──
export const 光标 = { 起: [320, 180] as const, 到: [326, 170] as const, 移起: 1.1, 移秒: 0.35, 点: 1.9 };
export const 光标在 = (幕内秒: number): readonly [number, number] => {
  const u = 平滑(clamp01((幕内秒 - 光标.移起) / 光标.移秒));
  return [混(光标.起[0], 光标.到[0], u), 混(光标.起[1], 光标.到[1], u)];
};
