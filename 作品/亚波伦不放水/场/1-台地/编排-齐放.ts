/** 罩严（编排的钟） */
export const 罩严 = 扔 + 结界飞出秒;
/** 画的全部：卫射的光束起点每帧跟着真杖尖 */
export const 出手表: readonly 一发[] = 纯出手表.map((发) => (跟杖的.includes(发.id) ? { ...发, 随: (t: number) => 演.杖(t).尖 } : 发));

// ── 史蒂夫：钉在原地，一直转着身子对着她、挥剑劈飞来的弹、一下下挨打踉跄、在结界里挣；晋升之环救他那一下不倒（原版图腾救下来不倒地），幕末死 ──
const 朝史蒂夫 = (p: readonly number[]): V3 => {
  const 长 = Math.hypot(史蒂夫脚[0] - p[0]!, 史蒂夫脚[1] - p[1]!) || 1;
  return [(史蒂夫脚[0] - p[0]!) / 长, (史蒂夫脚[1] - p[1]!) / 长, 0];
};
/** 劈之前把剑举过头顶的时间（秒） */
const 举剑秒 = 0.12;
/** 挨打的反应（照 Linker 打戏知识库 animation.md 第 7 节的受击反应）：9 帧仰到头、0.4 秒回正（0.5 秒一下，回正得比七版快），顺着弹来的方向往后让 0.45 格再被结界拽回。Agent 取的 */
const 后仰拍 = { 到顶: 9 / 60, 回正: 0.4 } as const;
const 让格 = 0.45;
export const 史蒂夫状态在 = (t: number): 史蒂夫状态 => {
  // 他的局部钟：索命劈中定住 16 帧。s 是局部钟上的幕内秒，w 是世界钟（停着时取停顿开头）
  const s = 他钟(t - 幕起);
  const w = 他回世界(s);
  const 她 = 亚波伦位(秒在(w));
  const 她头 = 加(她, [0, 0, 1.5]);
  const 朝她 = (Math.atan2(-(她头[0] - 史蒂夫脚[0]), 她头[1] - 史蒂夫脚[1]) * 180) / Math.PI;
  const 前挥 = 挥剑们.filter((c) => c <= s).pop();
  const 后挥 = 挥剑们.find((c) => c > s);
  const 挥剑秒 = 前挥 !== undefined && s - 前挥 < 0.5 ? s - 前挥 : undefined;
  const 举 = 后挥 !== undefined && 后挥 - s < 举剑秒 ? 平滑(1 - (后挥 - s) / 举剑秒) : 0;
  const 放 = 挥剑秒 !== undefined ? 1 - 平滑(挥剑秒 / 0.1) : 0;
  // 每一剑身子往左右轮着拧一下，劈不同方向飞来的弹
  const 拧 = 挥剑们.reduce((和, c, i) => 和 + (i % 2 ? -18 : 18) * 平滑(clamp01((s - c + 举剑秒) / 举剑秒)) * (1 - 平滑(clamp01((s - c - 0.15) / 0.35))), 0);
  const 近 = 挨打们.filter((h) => h.秒 <= s).pop();
  const 受击秒 = 近 && s - 近.秒 < 后仰拍.回正 ? s - 近.秒 : undefined;
  const 重后 = 近 && 近.重 ? s - 近.秒 : Infinity;
  const 歪 = 重后 < 0.6 ? 20 * Math.sin(Math.PI * clamp01(重后 / 0.6)) : 0;
  // 挣：罩严那一下想跑（脚抬不起来）、挨了重的腿软；钉住以后一直扎着马步晃，越到后面越使劲
  const 罩 = 罩严 - 幕起;
  const 罩挣 = 平滑(clamp01((w - (罩 - 0.05)) / 0.2)) * (1 - 平滑(clamp01((w - (罩 + 0.7)) / 0.35)));
  const 重挣 = 重后 < 0.6 ? 0.7 * (1 - 重后 / 0.6) : 0;
  const 钉着 = w >= 罩 ? 混(0.15, 0.45, clamp01((w - 罩) / (死 - 罩))) : 0;
  const 挣扎 = Math.min(1, Math.max(罩挣 * 0.9, 重挣, 钉着));
  // 看：看着她（弹从她那边来）
  const 看: V3 = 她头;
  const 死后 = t - 秒在(死);
  const 让 = 受击秒 === undefined ? 0 : 让格 * 后仰包络(受击秒, 后仰拍.到顶, 后仰拍.回正);
  return {
    位置: 加(史蒂夫脚, 朝史蒂夫(她), 让),
    朝向: 朝她 + 拧 + 歪,
    看,
    秒: s,
    右手: '剑',
    左手: '空',
    ...(挥剑秒 !== undefined ? { 挥剑秒 } : {}),
    蓄力: Math.max(举, 放),
    受击秒,
    后仰度: 近?.重 ? 24 : 16,
    后仰拍,
    ...(死后 >= 0 ? { 死后秒: 死后 } : {}),
    ...(挣扎 > 0 ? { 挣扎 } : {}),
  };
};
