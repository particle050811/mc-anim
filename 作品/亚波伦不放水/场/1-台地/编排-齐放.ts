// ── 史蒂夫：钉在原地，一直转着身子对着她、挥剑劈飞来的弹、挨打踉跄；索命打倒、图腾救回；收缩时抬头看她，烧死 ──
const 朝史蒂夫 = (p: readonly number[]): V3 => {
  const 长 = Math.hypot(史蒂夫脚[0] - p[0]!, 史蒂夫脚[1] - p[1]!) || 1;
  return [(史蒂夫脚[0] - p[0]!) / 长, (史蒂夫脚[1] - p[1]!) / 长, 0];
};
const 倒起 = (s: number): number | undefined => {
  const d = s - 倒.起;
  if (d < 0 || d >= 倒完 - 倒.起) return undefined;
  if (d < 倒.下) return 0.8 * (d / 倒.下);
  if (d < 倒.下 + 倒.躺) return 0.8;
  return 0.8 * (1 - (d - 倒.下 - 倒.躺) / 倒.起来);
};
/** 劈之前把剑举过头顶的时间（秒） */
const 举剑秒 = 0.16;
/** 挨打的反应（照 Linker 打戏知识库 animation.md 第 7 节的受击反应、恢复成本）：9 帧仰到头、0.55 秒慢慢回正，
 *  顺着弹来的方向（她那边打过来）往后让 0.45 格再被结界拽回；膝弯 60～70 度（轻的仰 20 度、重的 21 度再加腿软，关节动作里蹲的权 = 0.3 × 仰 ÷ 10）。Agent 取的，用户没看过 */
const 后仰拍 = { 到顶: 9 / 60, 回正: 0.55 } as const;
const 让格 = 0.45;
/** 焚烧时每一下只变红、身子微仰 */
const 焚仰度 = 4;
export const 史蒂夫状态在 = (t: number): 史蒂夫状态 => {
  // 他的局部钟：索命、冰砸两下定住（齐放拍.ts 的 他钟）。s 是局部钟上的幕内秒，w 是世界钟（停着时取停顿开头）：她在哪、罩严、收缩这些按世界钟比
  const s = 他钟(t - 幕起);
  const w = 他回世界(s);
  const 她 = 亚波伦位(秒在(w));
  const 她头 = 加(她, [0, 0, 1.5]);
  const 朝她 = (Math.atan2(-(她头[0] - 史蒂夫脚[0]), 她头[1] - 史蒂夫脚[1]) * 180) / Math.PI;
  // 挥剑：最近一次点击、下一次点击
  const 前挥 = 挥剑们.filter((c) => c <= s).pop();
  const 后挥 = 挥剑们.find((c) => c > s);
  const 挥剑秒 = 前挥 !== undefined && s - 前挥 < 0.6 ? s - 前挥 : undefined;
  const 举 = 后挥 !== undefined && 后挥 - s < 举剑秒 ? 平滑(1 - (后挥 - s) / 举剑秒) : 0;
  const 放 = 挥剑秒 !== undefined ? 1 - 平滑(挥剑秒 / 0.1) : 0;
  // 每一剑身子往左右轮着拧一下，劈不同方向飞来的弹
  const 拧 = 挥剑们.reduce((和, c, i) => 和 + (i % 2 ? -18 : 18) * 平滑(clamp01((s - c + 举剑秒) / 举剑秒)) * (1 - 平滑(clamp01((s - c - 0.15) / 0.4))), 0);
  // 挨打；收缩以后是焚烧的一下下
  const 近 = 挨打们.filter((h) => h.秒 <= s).pop();
  const 焚 = 焚伤们.filter((x) => x <= w).pop();
  const 受击秒 = 焚 !== undefined && w - 焚 < 后仰拍.回正 ? w - 焚 : 近 && s - 近.秒 < 后仰拍.回正 ? s - 近.秒 : undefined;
  const 重后 = 近 && 近.重 ? s - 近.秒 : Infinity;
  // 挨了重的被打得往后一歪、扭开
  const 歪 = 重后 < 0.9 ? 25 * Math.sin(Math.PI * clamp01(重后 / 0.9)) : 0;
  // 挣：罩严那一下想跑（脚抬不起来）、挨了重的腿软、收缩时在火里挣；平时也一直扎着马步晃
  const 罩挣 = 平滑(clamp01((w - (拍.罩严 - 0.05)) / 0.2)) * (1 - 平滑(clamp01((w - (拍.罩严 + 0.7)) / 0.35)));
  const 重挣 = 重后 < 0.8 ? 0.7 * (1 - 重后 / 0.8) : 0;
  const 火挣 = 平滑(clamp01((w - 拍.收缩 - 0.2) / 0.5));
  const 钉着 = w >= 拍.罩严 ? 0.15 : 0;
  // 抬头看她时剑放下了，脚下使劲想往她那边挣
  const 抬挣 = 0.55 * 平滑(clamp01((s - (抬头 - 0.3)) / 0.3));
  const 挣扎 = Math.min(1, Math.max(罩挣 * 0.9, 重挣, 火挣, 钉着, 抬挣));
  // 看：打的时候看飞过来的弹（她那边、平视略高），收缩前抬头看她
  const 平看 = 加(加(史蒂夫脚, 朝史蒂夫(她), -4), [0, 0, 2.8]);
  const 抬 = 平滑(clamp01((s - 抬头) / 0.35));
  const 看: V3 = [混(平看[0], 她头[0], 抬), 混(平看[1], 她头[1], 抬), 混(平看[2], 她头[2], 抬)];
  const 焚后 = t - 焚死;
  const 倒下 = 倒起(s);
  const 让 = 受击秒 === undefined || 焚 !== undefined ? 0 : 让格 * 后仰包络(受击秒, 后仰拍.到顶, 后仰拍.回正);
  return {
    位置: 加(史蒂夫脚, 朝史蒂夫(她), 让),
    朝向: 朝她 + 拧 + 歪,
    看,
    秒: s,
    右手: '剑',
    左手: w >= 换图腾 && t < 图腾秒 ? '图腾' : '空',
    ...(挥剑秒 !== undefined ? { 挥剑秒 } : {}),
    蓄力: Math.max(举, 放),
    受击秒,
    后仰度: 焚 !== undefined ? 焚仰度 : 近?.重 ? 21 : 20,
    后仰拍,
    死后秒: 焚后 >= 0 ? 焚后 : 倒下,
    ...(挣扎 > 0 ? { 挣扎 } : {}),
  };
};
