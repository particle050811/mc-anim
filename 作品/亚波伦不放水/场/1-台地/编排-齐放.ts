const 起角 = Math.atan2(起位[1] - 史蒂夫脚[1], 起位[0] - 史蒂夫脚[0]);
const 起半径 = Math.hypot(起位[0] - 史蒂夫脚[0], 起位[1] - 史蒂夫脚[1]);
/** 绕飞的角速度（相对）：后坐力缓下来后起步，匀速绕，收缩那一挥前刹到三成，再慢慢滑停在末位 */
const 绕速 = (s: number): number => {
  if (s < 0.9) return 0;
  if (s < 2.2) return 平滑((s - 0.9) / 1.3);
  if (s < 拍.收缩 - 0.4) return 1;
  if (s < 拍.收缩 + 0.1) return 混(1, 0.3, 平滑((s - (拍.收缩 - 0.4)) / 0.5));
  return 0.3 * clamp01((幕长 - s) / (幕长 - 拍.收缩 - 0.1));
};
const 步 = 1 / 240;
const 累: number[] = [0];
for (let i = 1; i * 步 < 幕长 + 步; i++) 累.push(累[i - 1]! + 绕速((i - 0.5) * 步) * 步);
const 绕进度 = (s: number): number => {
  const x = clamp(s, 0, 幕长) / 步;
  const i = Math.min(Math.floor(x), 累.length - 2);
  return (累[i]! + (累[i + 1]! - 累[i]!) * (x - i)) / 累[累.length - 1]!;
};
export const 亚波伦位 = (t: number): V3 => {
  const s = t - 幕起;
  const 让 = 0.3 * 平滑(clamp01((s - 拍.蓄) / (拍.放 - 拍.蓄)));
  const 推 = easeOutCubic(clamp01((s - 拍.放) / 0.7));
  // 绕飞的一路上把后坐力推开的那段慢慢收回来，落到末位时半径、高度和起位一样
  const 收 = 平滑(clamp01((s - 1) / (幕长 - 1)));
  const 进 = 绕进度(s);
  const 半径 = 起半径 + (让 + 1.4 * 推) * (1 - 收);
  const 角 = 起角 - Math.PI * 进;
  // 绕到半路往下沉 2.5 格再拉起来（离结界外接球最近还有 3 格多）
  const 高 = 起位[2] + (0.2 * 让 + 0.6 * 推) * (1 - 收) - 2.5 * Math.sin(Math.PI * 进) ** 2;
  return [史蒂夫脚[0] + 半径 * Math.cos(角), 史蒂夫脚[1] + 半径 * Math.sin(角), 高];
};
