/** 他在第 2 幕的位置（本地，幕内世界秒）：冲之前站着，冲的时候照 冲刺位，冲完蹲着不动 */
export const 史二本地 = (w: number): [number, number, number] => {
  if (w < 拍.冲一) return [起点[0], 起点[1], 站高(...起点)];
  if (w < 拍.冲二) return [...冲刺位(一冲, w - 拍.冲一)];
  // 冲停的地方和 受困本地 差不到 0.01 格（迭代剩下的）：冲出去 0.5～0.7 秒（第 10～14 刻，已经慢得几乎不动）里挪过去，之后就站在 受困本地
  if (w >= 拍.冲二 + 0.7) return [受困本地[0], 受困本地[1], 站高(...受困本地)];
  const p = 冲刺位(二冲, w - 拍.冲二);
  const 末 = 二冲.点[二冲.点.length - 1]!;
  const k = Math.min(1, Math.max(0, (w - 拍.冲二 - 0.5) / 0.2));
  return [p[0] + (受困本地[0] - 末[0]) * k, p[1] + (受困本地[1] - 末[1]) * k, p[2]];
};
