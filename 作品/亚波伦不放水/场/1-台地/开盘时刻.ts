/** 第 1 幕他的脚步声（编排的钟）：照原版 Entity.move，走过的路程每 1/0.6 格响一步 */
export const 第一幕步们: readonly number[] = (() => {
  const 步 = 1 / 240;
  const 出: number[] = [];
  let [路, 下一步] = [0, 1 / 0.6];
  let 前 = 史一轨(史一[0]![0]);
  for (let t = 史一[0]![0] + 步; t <= 幕起; t += 步) {
    const p = 史一轨(t);
    路 += Math.hypot(p[0]! - 前[0]!, p[1]! - 前[1]!);
    前 = p;
    if (路 >= 下一步) {
      出.push(t);
      下一步 += 1 / 0.6;
    }
  }
  return 出;
})();

// ── 第 2 幕：断曜流光冲两次 ──
// 站位倒着定：第 4 幕要他停在 受困本地、她停在祭坛上空 悬停高。他第二次冲（视线不往上，第一刻就贴地，10.8 格）正好停在 受困本地；
