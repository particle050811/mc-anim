const 祭坛游戏 = { x: 898.5, z: -299.5 };
const 祭坛脚高 = 脚高(祭坛游戏.x, 祭坛游戏.z);
/** 本地 (x, y) 那一列的地面比祭坛那层高几格 */
export const 本地地高 = (x: number, y: number) => 脚高(祭坛游戏.x + x, 祭坛游戏.z - y) - 祭坛脚高;
/** 基座、灵魂土、哭泣黑曜石台子比地面高一格 */
export const 结构高 = (x: number, y: number): number => {
  const [i, j] = [Math.round(x), Math.round(y)];
  if (Math.abs(i) <= 1 && Math.abs(j) <= 1) return 1;
  if (基座格.some(([a, b]) => a === i && b === j)) return 1;
  if (灵魂火格.some(([a, b]) => a === i && b === j)) return 1;
  return 0;
};
/** 站得住的高（本地） */
export const 站高 = (x: number, y: number) => 本地地高(x, y) + 结构高(x, y);

