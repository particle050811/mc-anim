/** 冲、俯冲时身子往冲的方向倒、急刹往后仰（同第 4 幕） */
const 倾: 倾设定 = { 每速: 1.0, 每加速: 0.03, 上限: 25, 窗: 0.08 };
export const 演 = 定演出({ 轴, 位: 亚波伦位, 目标: () => 史蒂夫眼, 倾 });
export const 盘位 = (t: number) => 杖尖盘位姿(演.杖(t), 盘摆);

const 圈数 = 排盘({ 放: '有画面' }).每圈格数.length;
/** 收盘照原版开合的快慢倒着走（每圈 2.5 刻、相邻两圈隔 2.5 刻；第 2 幕张盘放慢到每圈 5 刻、隔 7 刻，用户 11-11 嫌慢，这里收的时候不跟着慢），转速、转角照第 2 幕接着转 */
const 收开合 = { 每圈刻: 默认开合.每圈刻, 圈间隔刻: 默认开合.圈间隔刻 };
/** 轮盘：一直开着（不再亮格，没在放法术）；5-03 从最外圈往里一圈圈收回杖尖，最里一圈缩没时圆心的炼狱聚晶一起灭 */
export const 轮盘参 = (t: number): 多圈轮盘参数 | null => {
  const 参 = 开盘参(t);
  if (!参) return null;
  if (t < 收起) return { ...参, 选中: [] };
  const 收刻 = (t - 收起) * 20;
  const 开合 = { ...参.开合, ...收开合 };
  return 收刻 >= 开完刻(圈数, { ...默认开合, ...开合 }) ? null : { ...参, 选中: [], 收刻, 开合 };
};
/** 盘收完的时刻（编排的钟） */
export const 收完 = 收起 + 开完刻(圈数, { ...默认开合, ...收开合 }) / 20;
if (收完 > 秒在(她拍.降起) + 1e-6) throw new Error(`击败：盘 ${收完 - 幕起} 秒才收完，俯冲在 ${她拍.降起} 秒（击败拍.ts 的 她拍）`);
