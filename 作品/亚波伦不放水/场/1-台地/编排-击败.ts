const 圈数 = 排盘({ 放: '有画面' }).每圈格数.length;
/** 七版 5-03 开头盘转到第 328 刻（盘的转角照它，和七版一样） */
const 七版起刻 = 328;
/** 轮盘：开着、不亮格（没在放法术）；从最外圈往里一圈圈收回杖尖（照原版开合的快慢倒着走：每圈 2.5 刻、相邻两圈隔 2.5 刻），
 *  最里一圈缩没时圆心的炼狱聚晶一起灭 */
export const 轮盘参 = (t: number): 多圈轮盘参数 | null => {
  const 刻 = 七版起刻 + (t - 幕起) * 20;
  if (t < 收起) return { 放: '有画面', 刻, 开合: 默认开合, 选中: [] };
  const 收刻 = (t - 收起) * 20;
  return 收刻 >= 开完刻(圈数, 默认开合) ? null : { 放: '有画面', 刻, 开合: 默认开合, 选中: [], 收刻 };
};
/** 盘收完的时刻（编排的钟） */
export const 收完 = 收起 + 开完刻(圈数, 默认开合) / 20;
if (收完 > 秒在(她拍.降起) + 1e-6) throw new Error(`击败：盘 ${收完 - 幕起} 秒才收完，俯冲在 ${她拍.降起} 秒（击败拍.ts 的 她拍）`);
