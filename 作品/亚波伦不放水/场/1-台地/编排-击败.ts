/** 各镜头的开头（幕内秒）：5-01 倒下化烟 1.8 秒，5-02 死亡界面 3.5 秒（和三版一样长），5-03 收盘落地走过去 */
export const 镜起 = { 一: 0, 二: 1.8, 三: 5.3 } as const;
if (Math.abs(幕长 - (镜起.三 + 4.4)) > 1e-6) throw new Error(`击败的幕长 ${幕长} 秒要等于 5-03 起 ${镜起.三} + 4.4 秒（场/1-台地/时间线.ts 的 击败完）`);

// ── 史蒂夫：第 4 幕最后一刻（焚死）死的，倒下、20 刻后化烟、东西撒一地（角色/史蒂夫掉落.tsx 照原版） ──
export const 死后秒 = (t: number) => t - 焚死;
export { 史蒂夫脚, 史蒂夫眼 };
/** 死亡消息：结界每刻用 34 种原版伤害来源轮着打（RevelationFix 4.9 DeathPerformance.damageSourcesFromForge，来源记在施法者名下），
 *  哪一下打死他是随机的。这里取 ON_FIRE 那一种（对得上焚烧的画面）：来源带实体、她手里的杖没改名，所以用 death.attack.onFire（原版 zh_cn「%1$s被烧死了」，只填死者）*/
export const 死亡消息 = 'Steve被烧死了';

// ── 她：他一死就把杖放下来、开着盘往他那边滑下来一点（5-01、5-02）；5-03 盘一圈圈收回杖尖、杖收到身侧，同时往那堆东西前面落下去，
//    落地后朝那堆东西走两步、站住低头看 ──
/** 史蒂夫脚底 → 她（第 4 幕末停的地方）的水平单位向量 */
const 往她: V3 = (() => {
  const [x, y] = [末位[0] - 史蒂夫脚[0], 末位[1] - 史蒂夫脚[1]];
  const 长 = Math.hypot(x, y);
  return [x / 长, y / 长, 0];
})();
/** 从史蒂夫脚底往她那边 距 格的地面 */
const 地上 = (距: number): V3 => {
  const [x, y] = [史蒂夫脚[0] + 往她[0] * 距, 史蒂夫脚[1] + 往她[1] * 距];
  return 台地点(x, -y);
};
const 滑起 = 秒在(0);
/** 5-03 开头她滑到的地方：往他那边 4 格、低 2.5 格（还在空中） */
const 滑到: V3 = [末位[0] - 往她[0] * 4, 末位[1] - 往她[1] * 4, 末位[2] - 2.5];
const 降起 = 秒在(镜起.三 + 0.3);
export const 落地 = 秒在(镜起.三 + 2.4);
/** 落脚点：离他倒下的地方 4.5 格的地面。落地时还带着往前的劲（1.2 格/秒），顺势走到离他 2.6 格处站住 */
export const 落脚: V3 = 地上(4.5);
const 落地速: V3 = [-往她[0] * 1.2, -往她[1] * 1.2, 0];
/** 走路动画起步（落地缓冲完、腿直起来以后）、站住 */
const 走起 = 落地 + 0.27;
const 走止 = 秒在(镜起.三 + 4.25);
const 站脚: V3 = 地上(2.6);
const 空中 = 过点轨([
  [滑起, 末位, [0, 0, 0]],
  [降起, 滑到, [-往她[0] * 1.0, -往她[1] * 1.0, -0.8]],
  [落地, 落脚, 落地速],
]);
const 地面 = 过点轨([
  [落地, 落脚, 落地速],
  [走止, 站脚, [0, 0, 0]],
]);
export const 亚波伦位 = (t: number): V3 => {
  const p = t < 落地 ? 空中(t) : 地面(t);
  return [p[0]!, p[1]!, p[2]!];
};
const 收起 = 秒在(镜起.三 + 0.1);
const 轴: readonly 演出条[] = [
  ...开盘轴,
  // 他一死就把杖收回来斜举着（不再指着他）
  { 起: 秒在(0.05), 到: 秒在(0.5), 做: '悬停' },
  // 收盘：杖竖到身前，盘收完再把杖放到身侧
  { 起: 秒在(镜起.三 + 0.05), 到: 秒在(镜起.三 + 0.45), 做: '收盘' },
  { 起: 秒在(镜起.三 + 1.1), 到: 秒在(镜起.三 + 1.5), 做: '悬停' },
  { 起: 落地 - 0.1, 到: 落地 + 0.08, 做: '落地' },
  { 起: 落地 + 0.09, 到: 落地 + 0.24, 做: '站立' },
  // 起步前再写一条 站立：上一条的 从 是 落地，腿会一直按 idle 盖住，走路的腿出不来（这一刻 walk 权重还是 0，换过去不跳）
  { 起: 走起 - 0.02, 到: 走起 - 0.01, 做: '站立' },
  // 走慢下来时低头看地上那堆东西
  { 起: 走止 - 0.4, 到: 走止 + 0.1, 做: '低头' },
];
/** 走路的权重：起步、站住各 0.2 秒过渡（包里的 walk，1 秒两步）；落地到起步那 0.27 秒是借着落下来的劲往前滑 */
const 走权 = (t: number) => 平滑(clamp01((t - 走起) / 0.2)) * (1 - 平滑(clamp01((t - (走止 - 0.2)) / 0.2)));
const h = 1 / 120;
/** 走那一截换用的表演：idle 上叠 walk（演出 的表演只有 idle、fly），头发、胸的弹簧照 定演出 的算法吃速度 */
export const 走表演: 亚波伦表演 = 定表演({
  主: (秒) => {
    const w = 走权(秒);
    return w <= 0 ? [{ 名: 'idle' }] : [{ 名: 'idle' }, { 名: 'walk', 秒: 秒 - 走起, 权重: w }];
  },
  环境: (秒) => {
    const [a, b] = [亚波伦位(秒 - h), 亚波伦位(秒 + h)];
    return { 查询: { vertical_speed: (b[2] - a[2]) / (2 * h), ground_speed: Math.min(20, (Math.hypot(b[0] - a[0], b[1] - a[1]) / (2 * h)) * 2) } };
  },
});
/** 从起步起一直用 走表演：走完换回来的话，两份表演的头发弹簧走过的路不一样，换的那一下会跳 */
export const 用走表演 = (t: number) => t >= 走起;
export const 演 = 定演出({ 轴, 位: 亚波伦位, 目标: () => 史蒂夫眼 });
export const 盘位 = (t: number) => 杖尖盘位姿(演.杖(t), 盘摆);

const 圈数 = 排盘({ 放: '有画面' }).每圈格数.length;
/** 轮盘：一直开着（不再亮格，没在放法术）；5-03 从最外圈往里一圈圈收回杖尖，最里一圈缩没时圆心的炼狱聚晶一起灭 */
export const 轮盘参 = (t: number): 多圈轮盘参数 | null => {
  const 参 = 开盘参(t);
  if (!参) return null;
  if (t < 收起) return { ...参, 选中: [] };
  const 收刻 = (t - 收起) * 20;
  return 收刻 >= 开完刻(圈数, { ...默认开合, ...参.开合 }) ? null : { ...参, 选中: [], 收刻 };
};

// ── 5-02 的光标（GUI 像素，界面 640 × 360）：打开时原版把鼠标放在窗口正中；20 刻后按钮能按，移到「重生」上，点下去 ──
export const 光标 = { 起: [320, 180] as const, 到: [326, 170] as const, 移起: 1.35, 移秒: 0.45, 点: 2.6 };
export const 光标在 = (镜内秒: number): readonly [number, number] => {
  const u = 平滑(clamp01((镜内秒 - 光标.移起) / 光标.移秒));
  return [混(光标.起[0], 光标.到[0], u), 混(光标.起[1], 光标.到[1], u)];
};
