// 正片场地（真下界的台地，地点/真下界位置.ts 的 真下界场地）上各样东西摆在哪。纯数据、纯计算，段.ts 也能引。
// 游戏坐标（x 东、y 上、z 南）写位置，用 台地点 换成场景坐标（Z 朝上：x 东、y 北、z 上）；高度照 脚高表.ts 逐列取，地不整平。
// 这些位置都是 Agent 取的，用户没看过。
import type { V3 } from '@engine/model/parts.tsx';
import { 真下界场景 } from '../../地点/真下界位置.ts';
import { 脚高范围, 脚高行 } from './脚高表.ts';

const 表 = 脚高行.map((行) => 行.split(' ').map(Number));

/** 游戏 (x, z) 那一列脚的高度（游戏 y）；出了表的范围报错（没查过的列不猜） */
export const 脚高 = (x: number, z: number): number => {
  const [i, j] = [Math.floor(x) - 脚高范围.x[0], Math.floor(z) - 脚高范围.z[0]];
  const y = 表[j]?.[i];
  if (y === undefined) throw new Error(`台地脚高表没有 (${x}, ${z}) 这一列（范围 x ${脚高范围.x}，z ${脚高范围.z}）`);
  return y;
};

/** 游戏 (x, z) 站在地上的点 → 场景坐标；抬 = 离地几格 */
export const 台地点 = (x: number, z: number, 抬 = 0): V3 => 真下界场景(x, 脚高(x, z) + 抬, z);

/** 祭坛那一列的中心（安息仪式结构的原点：黑曜石底的顶）。7×7 黑曜石底换掉 x 895～901、z −303～−297 的地面那一层，这 49 列脚高都是 50 */
export const 祭坛 = 台地点(898.5, -299.5);
/** 黑曜石底占的那一层地面（游戏坐标，两端都含）：画仪式结构的段要把导入地形的这 49 格挖掉，不挖的话下界岩和黑曜石共面，镜头一动就整片闪 */
export const 祭坛底挖 = { 框: [{ from: [895, 49, -303], to: [901, 49, -297] }], 键后缀: ':挖祭坛底' };
/** 史蒂夫召唤时站的地方：祭坛南边 5 格（基座圈外），面朝北看祭坛 */
export const 史蒂夫召唤位 = 台地点(898.5, -293.5);
/** 结界罩住他的地方（第 3 幕起他被钉在这里）：祭坛东南，四周 10 格内脚高 49～51 */
export const 史蒂夫受困位 = 台地点(906.5, -293.5);
