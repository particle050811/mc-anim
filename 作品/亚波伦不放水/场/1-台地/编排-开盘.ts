/** 转身：他穿过去那一下起转、0.46 秒（世界秒，几乎整段慢放）转完，往他那边转短的那头（顺时针）；2-03 的机位跟着她转身绕 */
const 转身 = [拍.冲二 + 0.04, 拍.冲二 + 0.5] as const;
/** 她身子朝向（度）：现身时朝东、头垂着，1.0～1.35 秒转向他；之后一直朝着他，只有他从她脚底下穿过去那一下另算（不然一帧转 180 度） */
export const 她朝向 = (t: number): number => {
  if (t < 1.0) return -95;
  if (t < 1.35) return 转向(-95, 朝他(t), 平滑((t - 1.0) / 0.35));
  const w = t - 幕起;
  if (w < 拍.冲二 || w >= 转身[1]) return 朝他(t);
  return 转向(二冲前朝, 朝他(t), 段内(w, 转身[0], 转身[1]));
};
