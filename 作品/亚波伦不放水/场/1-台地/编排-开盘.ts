/** 两人在第 1、2 幕里什么时候算「静止」：位置不动（速度低于 0.15 格/秒）且没在做动作（挥剑、姿势在过渡、转身、转激流）。给 编排-开盘.test.ts 报占比 */
export const 静止判定 = {
  史蒂夫: (t: number) => {
    const [a, b] = [史蒂夫位(t - 0.05), 史蒂夫位(t + 0.05)];
    const 挥 = 史蒂夫挥剑秒(t);
    const 在挥 = 挥 !== undefined && 挥 < 剑招长;
    const 转 = t >= 幕起 && (!!激流(t - 幕起) || Math.abs(绕180(史蒂夫朝向(t + 0.05) - 史蒂夫朝向(t - 0.05))) / 0.1 > 5);
    return Math.hypot(b[0] - a[0], b[1] - a[1], b[2] - a[2]) / 0.1 < 0.15 && !在挥 && !转 && Math.abs(史蒂夫蓄力(t + 0.05) - 史蒂夫蓄力(t - 0.05)) < 0.002;
  },
  亚波伦: (t: number) => {
    if (t < 0) return false; // 还没现身，不在场上
    const [a, b] = [亚波伦位(t - 0.05), 亚波伦位(t + 0.05)];
    const 在过渡 = 轴上(开盘轴, t).比 < 1;
    const 转 = Math.abs(绕180(她朝向(t + 0.05) - 她朝向(t - 0.05))) / 0.1 > 5;
    const 眼 = t >= 0 && t < 0.85;
    return Math.hypot(b[0] - a[0], b[1] - a[1], b[2] - a[2]) / 0.1 < 0.15 && !在过渡 && !转 && !眼;
  },
};
