const 度 = 180 / Math.PI;
const 绕180 = (a: number) => ((((a + 180) % 360) + 360) % 360) - 180;
/** 水平方向 → 朝向（度，0 朝北，逆时针为正） */
const 朝向角 = (dx: number, dy: number) => Math.atan2(-dx, dy) * 度;
/** 从 a 转到 b（度）走短的那边 */
const 转向 = (a: number, b: number, k: number) => lerp(a, a + 绕180(b - a), k);
const 段内 = (t: number, a: number, b: number) => 平滑((t - a) / (b - a));

