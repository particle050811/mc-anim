/**
 * 冲：t0 在 p0 停着，加 秒匀加速到全速、匀速、刹 秒匀减速，t1 停在 p1。返回四个轨点（三次埃尔米特在这几个点之间正好是匀加速、匀速、匀减速：
 * 一段两头的速度是 v0、v1、位移是 (v0 + v1) / 2 × 段长时，埃尔米特的速度是线性的）。几维都行
 */
const 冲 = (t0: number, p0: readonly number[], t1: number, p1: readonly number[], 加 = 0.05, 刹 = 0.08): 轨点[] => {
  const 全 = 1 / (t1 - t0 - (加 + 刹) / 2);
  const v = p0.map((x, j) => (p1[j]! - x) * 全);
  const 零 = p0.map(() => 0);
  return [
    [t0, p0, 零],
    [t0 + 加, p0.map((x, j) => x + (v[j]! * 加) / 2), v],
    [t1 - 刹, p1.map((x, j) => x - (v[j]! * 刹) / 2), v],
    [t1, p1, 零],
  ];
};
/** 空中匀速：起跳、落地两点的水平速度都取 (落 − 起) / 空中秒 */
const 空速 = (t起: number, p起: readonly number[], t落: number, p落: readonly number[]) => p起.map((x, j) => (p落[j]! - x) / (t落 - t起));

