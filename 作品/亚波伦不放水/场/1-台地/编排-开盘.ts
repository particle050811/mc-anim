/** 第 1 幕拔剑后摆的架势：举到下劈蓄的 0.3（Agent 取的） */
const 架势 = 0.3;
/** 举剑蓄力 0～1（摆到下一刀那一招的蓄）：每刀点下前 蓄 秒蓄满；第 1 幕拔剑后 0.1 秒起到第一刀前一直摆着架势 */
export const 史蒂夫蓄力 = (t: number): number => {
  const 刀 = 刀表.find((x) => 幕(x.点) > t);
  if (!刀) return 0;
  const 点 = 幕(刀.点);
  const 蓄 = 平滑((t - (点 - 刀.蓄)) / 刀.蓄);
  const 底 = 刀 === 刀表[0] ? 架势 * 平滑((t - 第一幕.拔剑 - 0.1) / 0.3) : 0;
  return Math.max(蓄, 底);
};

