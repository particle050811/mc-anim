// 基座、灵魂土、哭泣黑曜石台子比地面高一格：他跳上去、跳下来的起落高度照这个
const 结构高 = (x: number, y: number): number => {
  const [i, j] = [Math.round(x), Math.round(y)];
  if (Math.abs(i) <= 1 && Math.abs(j) <= 1) return 1;
  if (基座格.some(([a, b]) => a === i && b === j)) return 1;
  if (灵魂火格.some(([a, b]) => a === i && b === j)) return 1;
  return 0;
};
const 站高 = (x: number, y: number) => 地上(x, y)[2] + 结构高(x, y);

const 史蒂夫本地 = (t: number): V3 => {
  const [x, y] = 史平(t) as [number, number];
  for (const [a, b, g] of 跳们) {
    const [ta, tb] = [幕(a), 幕(b)];
    if (t > ta && t < tb) {
      const [pa, pb] = [史平(ta), 史平(tb)];
      return [x, y, 抛高(t - ta, tb - ta, 站高(pa[0]!, pa[1]!), 站高(pb[0]!, pb[1]!), g)];
    }
  }
  return [x, y, 站高(x, y)];
};
export const 史蒂夫位 = (t: number): V3 => {
  const [x, y, z] = 史蒂夫本地(t);
  const p = 地上(x, y);
  return [p[0], p[1], z];
};
