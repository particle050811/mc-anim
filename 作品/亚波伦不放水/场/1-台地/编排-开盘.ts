// 第 2 幕他的几种状态（幕内世界秒）：潜行（断曜流光要潜行着挥）、激流姿势（冲出去以后横着转 15 刻）
/** 蹲着的几段 [起, 止)：按下潜行 → 冲（转的时候是激流姿势，不显潜行）→ 转完还按着 → 再冲 → 转完 → 起身松开 */
const 蹲段 = [
  [拍.潜一, 拍.冲一],
  [转们[0]![1], 拍.冲二],
  [转们[1]![1], 拍.起身],
] as const;
/** 潜行 0～1：游戏里一刻切过去，这里用 1 刻（0.05 秒）过渡；冲出去那一下直接换成激流姿势 */
const 潜行 = (w: number) => {
  for (const [a, b] of 蹲段) {
    const 出 = b === 拍.起身 ? 0.05 : 0;
    if (w >= a && w < b + 出) return Math.min(1, (w - a) / 0.05, w < b ? 1 : 1 - (w - b) / 0.05);
  }
  return 0;
};
/** 激流：转了几刻、冲的仰角；转完 1 刻里从横着回到站着（游戏里一刻切过去，这里给 1 刻过渡） */
const 激流 = (w: number): { 刻: number; 仰角: number; 权: number } | undefined => {
  for (const [i, [a, b]] of 转们.entries()) {
    if (w < a || w >= b + 0.05) continue;
    return { 刻: (w - a) * 20, 仰角: i === 0 ? 一仰 : 二仰, 权: w < b ? 1 : 1 - (w - b) / 0.05 };
  }
  return undefined;
};
const 眼高 = (t: number) => {
  const s = steveSize(STEVE.scale);
  return t < 幕起 ? s.eye : s.eye + (s.eyeCrouch - s.eye) * 潜行(t - 幕起);
};
/** 他眼睛（她的杖指着这里） */
