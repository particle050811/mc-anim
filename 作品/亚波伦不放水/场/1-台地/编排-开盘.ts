/** 第 1 幕：她的头往前 0.1 秒里平均一下（她动的时候他的头是跟过去的，不是一帧跳过去） */
const 看她 = (t: number): V3 => {
  const 样 = [0, 0.02, 0.04, 0.06, 0.08, 0.1].map((d) => 亚波伦头(t - d));
  return [0, 1, 2].map((j) => 样.reduce((和, p) => 和 + p[j]!, 0) / 样.length) as V3;
};
/** 她往下沉到的地方的胸口（本地）：他第二次冲瞄的是这里 */
const 沉处 = [悬二[0], 悬二[1], 沉到 + 她胸高] as const;
/** 冲的时候视线顺着冲的方向（游戏里冲的方向就是视线） */
const 顺冲看 = (t: number, i: 0 | 1): V3 => {
  const 眼 = 史蒂夫眼(t);
  const [向, 仰] = i === 0 ? [一向, 一仰] : [二向, 二仰];
  return [眼[0] + 向[0] * 10, 眼[1] + 向[1] * 10, 眼[2] + Math.tan(仰 / 度) * 10];
};
/** 他看的点：第 2 幕冲之前盯着她胸口（瞄着冲）、冲的时候顺着冲的方向、转完回头找她，最后抬头看祭坛上空的她 */
export const 史蒂夫看 = (t: number): V3 => {
  if (t < 幕起) return 看她(t);
  const w = t - 幕起;
  if (w < 拍.冲一) return lerpV(看她(t), 她胸(t), 段内(w, 拍.潜一 - 0.1, 拍.潜一)) as V3;
  if (w < 拍.回头[0]) return 顺冲看(t, 0);
  // 回头找她、瞄着她往下沉到的地方（她往上一拉的时候他已经在蓄剑，视线不跟着往上）
  if (w < 拍.冲二) return lerpV(顺冲看(t, 0), 空中(沉处), 段内(w, 拍.回头[0], 拍.回头[1])) as V3;
  if (w < 转们[1]![1]) return 顺冲看(t, 1);
  return lerpV(顺冲看(t, 1), 亚波伦头(t), 段内(w, 转们[1]![1], 转们[1]![1] + 0.15)) as V3;
};
/** 史蒂夫第 1 幕的位置、身子朝向、摆腿（从第 1 幕开头推起，那时面朝北）；第 2 幕的朝向另算（见 史蒂夫朝向） */
export const 史蒂夫走 = 定走位({ 位: 史蒂夫位, 看: 史蒂夫看, 起: 现身后(事.开始.秒), 初朝向: 0 });
const [一冲朝, 二冲朝] = [朝向角(一向[0], 一向[1]), 朝向角(二向[0], 二向[1])];
/** 第 2 幕末他面朝她（水平） */
const 末朝 = (() => {
  const [p, q] = [史蒂夫位(幕末), 亚波伦位(幕末)];
  return 朝向角(q[0] - p[0], q[1] - p[1]);
})();
/** 身子朝向（度）：第 2 幕冲之前转向冲的方向、冲的时候就是冲的方向，转完蹲着一扭身对着她（她在他背后），第二次冲完站起来转过来对着祭坛上空的她 */
export const 史蒂夫朝向 = (t: number): number => {
  const 走朝 = 史蒂夫走.在(t).朝向;
  if (t < 幕起) return 走朝;
  const w = t - 幕起;
  if (w < 拍.冲一) return 转向(走朝, 一冲朝, 段内(w, 拍.潜一, 拍.冲一 - 0.04));
  if (w < 拍.冲二) return 转向(一冲朝, 二冲朝, 段内(w, 拍.回头[0], 拍.回头[1]));
  return 转向(二冲朝, 末朝, 段内(w, 转们[1]![1], 转们[1]![1] + 0.3));
};

// ── 他手里 ──
/** 他右手拿什么：环 → 放下后空手 → 光柱起来拔剑 */
export const 史蒂夫右手 = (t: number): 右手物 => (t < 第一幕.放环点 ? '环' : t < 第一幕.拔剑 ? '空' : '剑');
/** 挥手的点击（编排的钟）、招、蓄几秒：右键放环那一下也是挥手；两次冲各是潜行着左键挥一下。
 *  第一次挥跳劈（接第 1 幕拔剑后一直摆着的跳劈架势，不换招）、第二次横斩，挥剑的样子是本片的剑招（角色/剑招.ts），不是原版挥手 */
const 点击们: readonly { 秒: number; 招?: 招名; 蓄?: number }[] = [
  { 秒: 第一幕.放环点 },
  { 秒: 幕(拍.冲一), 招: '跳劈', 蓄: 拍.冲一 - 拍.潜一 },
  { 秒: 幕(拍.冲二), 招: '横斩', 蓄: 拍.冲二 - 拍.回头[0] },
];
const 上一击 = (t: number) => {
  let 近: (typeof 点击们)[number] | undefined;
  for (const c of 点击们) if (t >= c.秒) 近 = c;
  return 近;
};
/** 距上一次点击几秒；还没点过 = undefined */
export const 史蒂夫挥剑秒 = (t: number): number | undefined => {
  const c = 上一击(t);
  return c && t - c.秒;
};
/** 上一刀是哪一招 */
export const 史蒂夫招 = (t: number): 招名 | undefined => 上一击(t)?.招;
const 下一刀 = (t: number) => 点击们.find((c) => c.招 && c.秒 > t);
/** 下一刀（正在蓄的）是哪一招 */
export const 史蒂夫蓄招 = (t: number): 招名 | undefined => 下一刀(t)?.招;
/** 第 1 幕拔剑后摆的架势：举到跳劈蓄的 0.3（Agent 取的） */
const 架势 = 0.3;
/** 举剑蓄力 0～1：每刀点下前 蓄 秒蓄满；第 1 幕拔剑后 0.1 秒起到第一刀前一直摆着架势 */
export const 史蒂夫蓄力 = (t: number): number => {
  const 刀 = 下一刀(t);
  if (!刀) return 0;
  const 蓄 = 平滑((t - (刀.秒 - 刀.蓄!)) / 刀.蓄!);
  const 底 = 刀 === 点击们[1] ? 架势 * 平滑((t - 第一幕.拔剑 - 0.1) / 0.3) : 0;
  return Math.max(蓄, 底);
};

/** 第 1、2 幕他这一刻的状态（给 <反应史蒂夫>）。秒：两臂轻晃的钟（第 2 幕给世界秒，慢放里跟着慢） */
export const 史蒂夫状态在 = (t: number, 秒: number): 史蒂夫状态 => {
  const 走 = 史蒂夫走.在(t);
  const 第二幕 = t >= 幕起;
  const 流 = 第二幕 ? 激流(t - 幕起) : undefined;
  return {
    ...走,
    // 第 2 幕朝向另算；冲刺贴地、高低差只有几厘米，不让 定走位 认跳
    ...(第二幕 ? { 朝向: 史蒂夫朝向(t), 跳: {} } : {}),
    看: 史蒂夫看(t),
    秒,
    右手: 史蒂夫右手(t),
    // 用户 11-10 定：高端局，史蒂夫不拿盾
    左手: '空',
    挥剑秒: 史蒂夫挥剑秒(t),
    招: 史蒂夫招(t),
    蓄招: 史蒂夫蓄招(t),
    蓄力: 史蒂夫蓄力(t),
    ...(第二幕 ? { 潜行: 潜行(t - 幕起) } : {}),
    ...(流 ? { 激流: 流 } : {}),
  };
};

