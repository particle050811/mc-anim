/** 举剑蓄力 0～1：空中的刀从起跳前 0.3 秒举起，地上的刀出手前 0.25 秒小举一下；出手后照挥手进度放掉 */
export const 史蒂夫蓄力 = (t: number): number => {
  let 蓄 = 0;
  七刀.forEach((c, i) => {
    const 点 = 幕(c);
    const 满 = 空中刀.has(i) ? 1 : 0.55;
    const 起 = 空中刀.has(i) ? 幕(跳们.find(([a, b]) => c > a && c < b)![0]) - 0.3 : 点 - 0.25;
    if (t >= 起 && t < 点) 蓄 = Math.max(蓄, 满 * 平滑((t - 起) / Math.min(0.25, 点 - 起)));
    else if (t >= 点) 蓄 = Math.max(蓄, 满 * (1 - 平滑(挥手进度(t - 点) / 0.35)));
  });
  return 蓄;
};

