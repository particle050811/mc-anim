  const 收 = 本冲们.reduce((和, c) => 和 + c.收 * 冲比(c, s), 0);
  const 角 = 起角 - 漂角(s) - 本冲们.reduce((和, c) => 和 + (c.度 * Math.PI * 冲比(c, s)) / 180, 0);
  const 半径 = 起半径 + 崩.外 * (崩比 - 收);
