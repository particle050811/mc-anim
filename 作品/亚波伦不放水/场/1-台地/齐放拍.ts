/** 他局部钟上的命中 */
const 本命中们 = 命中们.map((h) => ({ ...h, 秒: 他钟(h.秒) }));
/** 打得最重的几下：后仰大、腿软一下 */
export const 重的 = ['iceology', 'teeth', 'cyclone', 'eruption'];
/** 倒下、躺着、站起来（索命；他的局部钟，停完 16 帧才往下倒）：原版死亡是 1 秒倒平、倒平就没人了，这里把死后秒走到 0.8 再往回走，借它的倒下角度 */
export const 倒 = { 起: 拍.索命 + 0.05, 下: 0.6, 躺: 0.25, 起来: 0.45 } as const;
export const 倒完 = 倒.起 + 倒.下 + 倒.躺 + 倒.起来;
/** 不死图腾：罩严后换到左手（原版副手一按就换），倒平那一下用掉 */
export const 换图腾 = 拍.罩严 + 0.9;
/** 图腾用掉的时刻（编排的钟，世界钟） */
export const 图腾秒 = 秒在(他回世界(倒.起 + 倒.下));
export const 躺着 = (s: number) => s >= 倒.起 - 0.15 && s < 倒完 + 0.1;
/** 收缩那一挥在他局部钟上的时刻 */
const 本收缩他 = 他钟(拍.收缩);
/** 挨打（他的局部钟）：同一秒里挨好几下只红一次（原版受伤后 20 刻无敌、10 刻变红），所以按 1 秒的间隔取 */
export const 挨打们: readonly { 秒: number; 重: boolean }[] = 本命中们.reduce<{ 秒: number; 重: boolean }[]>((出, h) => {
  const 前 = 出[出.length - 1];
  if (躺着(h.秒) || h.秒 >= 本收缩他) return 出;
  if (前 && h.秒 - 前.秒 < 1) {
    if (重的.includes(h.id) && !前.重) 前.重 = true;
    return 出;
  }
  return [...出, { 秒: h.秒, 重: 重的.includes(h.id) }];
}, []);
/** 收缩焚烧时他在火里挨烧（世界钟；停顿都在这之前，局部钟上再减 他停们 的总长）：原版受伤后 10 刻才能再挨（hurtTime），结界每刻都打，所以每 0.5 秒一下，到他死 */
export const 焚伤们: readonly number[] = Array.from({ length: Math.floor((幕长 - 拍.收缩 - 0.3) / 0.5) + 1 }, (_, i) => 拍.收缩 + 0.3 + 0.5 * i);
/** 抬头看她（收缩前 0.3 秒；他的局部钟），之后不挥剑 */
export const 抬头 = 他钟(拍.收缩 - 0.3);
/** 挥剑（他的局部钟）：赶在弹到之前 0.1 秒劈；两下至少隔 0.55 秒；空档超过 0.75 秒的补几剑（劈结界里飞的碎片），倒地前后各算一段。抬头看她以后不挥 */
export const 挥剑们: readonly number[] = ((): number[] => {
  const 首 = 0.5;
  const 可 = (c: number) => c >= 首 && c < 抬头 - 0.3 && !躺着(c) && !躺着(c + 0.2);
  const 出: number[] = [];
  for (const h of 本命中们) {
    const c = h.秒 - 0.1;
    if (可(c) && (!出.length || c - 出[出.length - 1]! >= 0.55)) 出.push(c);
  }
  // 补剑：倒地前、站起来后两段里，相邻两剑（段头段尾也算一剑的位置）隔得远的，按不少于 补隔 的间隔匀着插
  const 补隔 = 0.5;
  const 补: number[] = [];
  for (const [起, 止] of [[首, 倒.起 - 0.35], [倒完 + 0.1, 抬头 - 0.3]] as const) {
    const 点 = [起 - 补隔, ...出.filter((c) => c >= 起 && c <= 止), 止 + 补隔];
    for (let i = 1; i < 点.length; i++) {
      const [a, b] = [点[i - 1]!, 点[i]!];
      const n = Math.floor((b - a) / 补隔);
      for (let k = 1; k < n; k++) if (可(a + ((b - a) * k) / n)) 补.push(a + ((b - a) * k) / n);
    }
  }
  return [...出, ...补].sort((a, b) => a - b);
})();
/** 声音用的世界钟（幕内秒）：挨打、挥剑 */
export const 挨打世界们 = 挨打们.map((h) => ({ ...h, 秒: 他回世界(h.秒) }));
export const 挥剑世界们 = 挥剑们.map(他回世界);
