// 第 3 幕的编排：这一幕只剩结界。结界几时扔、盘上几时全亮、史蒂夫怎么挣。纯计算，时钟接第 2 幕（现身后几秒），第 4 幕接着用。
// 用户 11-10 看了成片定：不点名，罩上就齐放（「应该是齐放，虽然最后看到了齐放，但是你这拖得也太久了」）。
// 原来一个个放的七个法术在第 4 幕的波里（编排-齐放.ts 的 并入），没有射箭、拿弓、冲刺换位；文件名、段键里的「点名」是永久身份，不跟着改。
// 时刻是 Agent 取的，用户没看过。
import { clamp01, smoothstep01 as 平滑 } from '@engine/core/数学.ts';
import type { V3 } from '@engine/model/parts.tsx';
import { STEVE, steveSize } from '@库/角色/史蒂夫.tsx';
import { 定演出 } from '../../角色/动作/亚波伦演出.ts';
import type { 史蒂夫状态 } from '../../角色/史蒂夫反应.ts';
import { 杖尖盘位姿 } from '../../界面/杖尖盘位姿.ts';
import type { 多圈轮盘参数 } from '../../界面/多圈轮盘.tsx';
import { 排盘 } from '../../界面/轮盘法术.ts';
import { 结界演出默认, type 结界演出设定 } from '../../特效/炼狱结界演出状态.ts';
import { 发键, type 场况 } from './出手.tsx';
import 线 from './时间线.ts';
import { 亚波伦位 as 开盘位, 史蒂夫位 as 开盘史位, 开盘轴, 每像素格, 演 as 开盘演, 现身后, 盘摆, 轮盘参 as 开盘参 } from './编排-开盘.ts';

const 事 = 线.事件;
/** 本幕开头（编排的钟） */
export const 幕起 = 现身后(事.开盘完.秒);
const 加 = (a: readonly number[], b: readonly number[], k = 1): V3 => [a[0]! + b[0]! * k, a[1]! + b[1]! * k, a[2]! + b[2]! * k];
const 秒在 = (s: number) => 幕起 + s;

/** 史蒂夫被钉住的地方（脚底）：第 2 幕退到的受困位 */
export const 史蒂夫脚: V3 = 开盘史位(幕起);
export const 史蒂夫眼: V3 = 加(史蒂夫脚, [0, 0, steveSize(STEVE.scale).eye]);
/** 结界中心：史蒂夫半身高（原版结界中心也在半身高） */
export const 结界心: V3 = 加(史蒂夫脚, [0, 0, 0.9]);

/** 她这一幕不挪地方：悬在第 2 幕末的位置（祭坛上空）；第 4 幕第一波也从这里放 */
export const 悬停位: V3 = 开盘位(幕起);
export const 亚波伦位 = (_t: number): V3 => 悬停位;

/** 结界扔出的时刻；计数里炼狱算第 1 个 */
export const 扔 = 现身后(事.扔结界.秒);
/** 3-02 的开头（幕内秒）：结界罩严了，切到史蒂夫 */
export const 全亮镜起 = 3.5;
/** 盘上所有格同时亮 */
export const 全亮起 = 秒在(全亮镜起 + 0.8);

export const 演 = 定演出({ 轴: 开盘轴, 位: 亚波伦位, 目标: () => 史蒂夫眼, 出手: [扔] });
export const 盘位 = (t: number) => 杖尖盘位姿(演.杖(t), 盘摆);

const 全键 = 排盘({ 放: '有画面' }).项.map((项) => 项.键);
export const 轮盘参 = (t: number): 多圈轮盘参数 | null => {
  const 参 = 开盘参(t);
  return 参 && { ...参, 选中: t >= 全亮起 ? 全键 : t >= 扔 && t < 扔 + 0.5 ? [发键('revelation')] : [] };
};
export const 况: 场况 = { 盘位, 轮盘参, 每像素格, 杖尖: (t) => 演.杖(t).尖, 史蒂夫脚: () => 史蒂夫脚 };

/** 结界：从杖尖扔出，1.5 秒飞到、涨满；之后一直罩着 */
export const 结界设定: 结界演出设定 = {
  ...结界演出默认,
  起点: 开盘演.杖(扔).尖,
  目标: 结界心,
  // 一直罩到第 4 幕 4-18 开头（齐放完往前数最后一镜 2.5 秒）才收缩焚烧
  罩住秒: 事.齐放完.秒 - 事.扔结界.秒 - 结界演出默认.收缩焚烧秒 - 结界演出默认.飞出秒,
};

// ── 史蒂夫：结界飞过来时转身想跑，脚抬不起来；挣不动了回身看她，盘全亮前抬头看盘 ──
const 逃段 = [1.2, 3.2] as const;
export const 史蒂夫状态在 = (t: number): 史蒂夫状态 => {
  const s = t - 幕起;
  const 逃 = s >= 逃段[0] && s < 逃段[1];
  const 背向 = (Math.atan2(-(史蒂夫脚[0] - 悬停位[0]), 史蒂夫脚[1] - 悬停位[1]) * 180) / Math.PI;
  const 她头 = 加(悬停位, [0, 0, 1.5]);
  const 朝她 = (Math.atan2(-(她头[0] - 史蒂夫脚[0]), 她头[1] - 史蒂夫脚[1]) * 180) / Math.PI;
  return {
    位置: 史蒂夫脚,
    朝向: 逃 ? 背向 : 朝她,
    // 逃的时候看前面
    看: 逃 ? undefined : t >= 全亮起 - 0.6 ? 盘位(t).心 : 她头,
    秒: s,
    右手: '剑',
    左手: '空',
    挣扎: 逃 ? 平滑(clamp01((s - 逃段[0] - 0.4) / 0.4)) * 0.9 : 0,
  };
};
