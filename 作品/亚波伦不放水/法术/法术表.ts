//   META-INF/jarjar/[Forge]RevelationFix-1.20.1-4.9.jar；启示录条目里 com/Polarice3/、assets/goety/ 开头的仍在本体 jar。
//   「minecraft:…」「minecraft SoundEvents.X / ParticleTypes.X」是原版资源，写的是官方映射里的常量名，不在这两个 jar 里。
//
// 判类标准（主 Agent 11-09 派活时给的，用户只定了「功能性的、召唤整只生物的不放」）：
//   召唤 = 主要效果是召出一只会自己行动的生物（仆从、坐骑）。召出的是弹射物、陷阱、图腾、柱子、藤蔓、云这类不算，归有画面。
//   功能 = 对着玩家放出来，屏幕上没有可见的攻击画面（开界面、传送、增益、回溯、指挥仆从等）。
//   空壳 = 注册了物品但法术是 EmptySpell，放不出东西。
//   待定 = 两边都说得通，留给用户定；`待定.候选` 是两个可能的类，`待定.理由` 各写一句。用户定之前不进齐放。
// 施放：瞬发 = 右键即放（含 TouchSpell、BlockSpell 对着生物、方块点一下）；蓄力 = 举杖 `施放刻` 刻后放出一次；
//   引导 = 按住期间持续生效（EverChargeSpell、BreathingSpell、ChargingSpell），`施放刻` 是开始生效前的前摇。1 刻 = 1/20 秒。
//   数是配置默认值（本体 SpellConfig，启示录 GRSpellConfig）。
// 画面、难度是照默认法杖写的；配对应学派法杖时的变体只在依据或画面里带一句。难度是 Agent 估的：
//   易 = 原版就有的模型、面片或普通贴图粒子；中 = 要翻 Java 写死的模型，或粒子量大、有程序画的环；难 = 程序画的光束、闪电、裂隙，要读写场地方块，或多段动作的大模型。
// 粒子、声音两栏含法术类直接用的，和（非召唤类）它生成的实体类里用的；召唤物自己的叫声、受伤声没收。
// 实体栏只列法术类直接生成的；这些实体落地、命中后再生成的次生实体（岩浆怪、尖桩、火山弹等）没列全，清单见 说明.md。

export type 法术定类 = '有画面' | '功能' | '召唤' | '空壳';
export type 法术类 = 法术定类 | '待定';
export type 法术学派 = '魔法' | '灾厄' | '死灵' | '占卜' | '霜冻' | '荒野' | '烈风' | '风暴' | '深渊' | '下界' | '虚空';

export interface 法术实体 {
  /** 实体注册 id；不走实体、由客户端直接画的写「（无实体，客户端直接画）」 */
  readonly 注册名: string;
  readonly 类: string;
  readonly 渲染器: string | null;
  readonly 模型: readonly string[];
  readonly 贴图: readonly string[];
}

export interface 法术声音 {
  readonly 事件: string;
  /** sounds.json 里这个事件的全部变体；原版事件不列文件 */
  readonly 文件: readonly string[];
}

export interface 法术 {
  /** 聚晶物品 id 去掉命名空间和 `_focus`，如 goety:fireball_focus 的 fireball */
  readonly 注册名: string;
  readonly 来源: '本体' | '启示录';
  /** lang/zh_cn.json、en_us.json 里聚晶物品的名字 */
  readonly 中文名: string;
  readonly 英文名: string;
  /** 中文取 zh_cn.json 的 spell.goety.*（geomancy 游戏里译「占卜」） */
  readonly 学派: 法术学派;
  readonly 施放: '瞬发' | '引导' | '蓄力';
  readonly 施放刻: number;
  readonly 类: 法术类;
  readonly 依据: string;
  readonly 待定?: { readonly 候选: readonly [法术定类, 法术定类]; readonly 理由: Partial<Record<法术定类, string>> };
  /** 放出来屏幕上是什么 */
  readonly 画面: string;
  /** 搬进 three.js 的难度 */
  readonly 难度: '易' | '中' | '难';
  readonly 难度理由: string;
  /** 轮盘上的 16×16 物品图标 */
  readonly 图标: string;
  readonly 法术类: string;
  readonly 实体: readonly 法术实体[];
  readonly 粒子: readonly string[];
  readonly 声音: readonly 法术声音[];
}

