// 虚空震弹（Goety 的 VoidShock）的运动（纯）：星陨、虚空闪共用。
// 生出来先悬着（有信号点的先飘到信号点，速度每刻衰减），到 锁刻 时锁定目标，之后以 1 格/刻（power = 方向 × 5 × 0.2）直线冲过去，碰到就爆。
import type { 点 } from '../../接口.ts';
import { 减, 加, 乘, 单位, 长, 混 } from '../弹道.ts';
import { 瞄点 } from './共用.ts';

export interface 虚空震 {
  /** 出手后第几刻生出来 */
  出刻: number;
  生位: 点;
  /** 悬停的地方（没有信号点的就是 生位） */
  悬位: 点;
  /** 生出来后第几刻锁定目标（initTime） */
  锁刻: number;
}

/** 生出来后 t 刻在哪；锁定后朝史蒂夫胸口冲 */
export const 虚空震位 = (震: 虚空震, 目标: 点, t: number): 点 => {
  // 飘向信号点：游戏里速度每刻连乘衰减，这里用每刻走剩下路程的 15% 近似
  const 悬 = (k: number) => 混(震.悬位, 震.生位, 0.85 ** k);
  if (t <= 震.锁刻) return 悬(Math.max(0, t));
  const 起 = 悬(震.锁刻);
  return 加(起, 乘(单位(减(瞄点(目标), 起)), t - 震.锁刻));
};
/** 生出来后第几刻撞上（离胸口 0.5 格） */
export const 虚空震撞刻 = (震: 虚空震, 目标: 点): number => 震.锁刻 + Math.max(0, 长(减(瞄点(目标), 虚空震位(震, 目标, 震.锁刻))) - 0.5);
