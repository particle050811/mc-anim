const 窗 = 段窗口(键);
export const 帧数 = 窗.帧数;
/** 段内帧 → 歌曲帧（颗粒的种子、歌词用它） */
export const 歌曲帧 = (f: number) => 窗.起帧 + f;

const 插 = (a: number, b: number, t: number) => a + (b - a) * t;
const 夹 = (x: number) => Math.min(1, Math.max(0, x));
const 缓 = (t: number) => t * t * (3 - 2 * t);
const 拍帧 = 网格.拍长 * fps;

type 骨表 = Record<string, BonePose>;
/** 两张骨骼表逐字段插值（转角、位移、缩放；一边没有的当 0° / 0 / 1） */
const 插骨 = (a: 骨表, b: 骨表, t: number): 骨表 => {
  const r: 骨表 = {};
  const 三 = (x: number | number[] | undefined, 缺: number) => (x === undefined ? [缺, 缺, 缺] : typeof x === 'number' ? [x, x, x] : x);
  for (const k of new Set([...Object.keys(a), ...Object.keys(b)])) {
    const [p, q] = [a[k] ?? {}, b[k] ?? {}];
    const 插3 = (u: number[], v: number[]) => u.map((x, i) => 插(x, v[i]!, t));
    r[k] = { rot: 插3(三(p.rot, 0), 三(q.rot, 0)), pos: 插3(三(p.pos, 0), 三(q.pos, 0)), scale: 插3(三(p.scale, 1), 三(q.scale, 1)) };
  }
  return r;
};

// ---------- 她 ----------
export type 她态 = {
  loc: V3;
  /** 度，0 朝北（背对镜头）、90 朝西（门）、180 朝镜头、−90 朝东（床） */
  yaw: number;
  表情: 魔法酒狐全部表情;
  看: [number, number];
  骨骼: 骨表;
};

/** 转身起（抚平到这一帧之前为止）、坐下起：倒推到 坐床沿 那一帧正好坐稳 */
export const 坐下起 = 事.坐床沿 - 参.坐下帧;
export const 转身起 = 坐下起 - 参.转身帧;

/** 抚平：每拍抹一下，七成拍长往床沿抹回来（缓进缓出）、三成拍长伸回床里侧 */
export const 抹 = (f: number) => {
  if (f < 事.抚平被子) return 0;
  const p = (((f - 事.抚平被子) / 拍帧) % 1 + 1) % 1;
  if (p < 0.7) return 缓(p / 0.7);
  return 1 - (p - 0.7) / 0.3;
};

/** 抚平那几帧的骨骼：手的远近、弯腰深浅都跟着 抹 走；手顺着她的朝向伸出去 */
export const 抚平姿 = (f: number) => {
  const m = 抹(f);
  const { 远, 近, 远弯, 近弯, 头抬 } = 参.抚平手;
  return 抚平骨骼(插(远, 近, m), 床面高, 插(远弯[0], 近弯[0], m), 插(远弯[1], 近弯[1], m), 头抬, 参.抚平尾压);
};

/** 坐着时的朝向写成从抚平的朝向往镜头那边转过去的连续角度：抚平朝向 → −180（朝镜头）→ 坐朝向 − 360 */
const 坐yaw = 参.坐朝向 - 360;

/** 坐床沿骨骼上叠天亮那一挺（UpperBody 往后仰） */
const 挺 = (x: number): 骨表 => ({ ...坐床沿骨骼, UpperBody: { rot: [x, 0, 2] } });

export const 她态 = (f: number): 她态 => {
  const 站: V3 = [...参.抚平站位];
  const 坐: V3 = [...参.床沿坐位];
  const 抚平头: [number, number] = [参.抚平手.头抬, 0];
  if (f < 转身起) return { loc: 站, yaw: 参.抚平朝向, 表情: '无', 看: 抚平头, 骨骼: 抚平姿(f) };
  if (f < 坐下起) {
    // 直起身、从朝镜头那边转过去（看得见一眼脸）：弯腰的骨骼、朝向、头一起插
    const k = 缓((f - 转身起 + 1) / 参.转身帧);
    return { loc: 站, yaw: 插(参.抚平朝向, 坐yaw, k), 表情: '无', 看: [插(抚平头[0], -10, k), 0], 骨骼: 插骨(抚平姿(转身起 - 1), {}, k) };
  }
  if (f < 事.坐床沿) {
    // 退半步、坐下：位置和骨骼一起从站着插到坐床沿
    const k = 缓((f - 坐下起 + 1) / (参.坐下帧 + 1));
    const loc: V3 = [插(站[0], 坐[0], k), 插(站[1], 坐[1], k), 插(站[2], 坐[2], k)];
    return { loc, yaw: 坐yaw, 表情: '无', 看: [插(-10, 参.守夜看[0], k), 插(0, 参.守夜看[1], k)], 骨骼: 插骨({}, 坐床沿骨骼, k) };
  }
  if (f < 事.天亮转头) return { loc: 坐, yaw: 坐yaw, 表情: '无', 看: 参.守夜看, 骨骼: 坐床沿骨骼 };
  // 天亮：转头帧 帧里转到过头，下一帧回到正对门口
  const i = f - 事.天亮转头;
  if (i < 参.转头帧) {
    const k = (i + 1) / 参.转头帧;
    const 看: [number, number] = [插(参.守夜看[0], 参.看门口过头[0], k), 插(参.守夜看[1], 参.看门口过头[1], k)];
    return { loc: 坐, yaw: 坐yaw, 表情: '惊讶', 看, 骨骼: 挺(插(0, 参.转头上身挺过头, k)) };
  }
  return { loc: 坐, yaw: 坐yaw, 表情: '惊讶', 看: 参.看门口, 骨骼: 挺(参.转头上身挺) };
};

/** 她的平涂色调：屋里的色调往白里提 她提亮（夜里读成月光落在她身上） */
export const 她色调 = (屋: string) => {
  const c = /^#([0-9a-f]{6})$/i.exec(屋);
  if (!c) throw new Error(`色调要写成 #rrggbb：${屋}`);
  const v = parseInt(c[1]!, 16);
  return '#' + [16, 8, 0].map((s) => Math.round(插((v >> s) & 255, 255, 参.她提亮)).toString(16).padStart(2, '0')).join('');
};

// ---------- 窗光、调子 ----------
/** 这一帧窗光在第几档（参数.ts 的 窗光档们）：坐床沿 之前也是第一档 */
export const 光档 = (f: number) => [事.窗光二, 事.窗光三, 事.月落, 事.天亮转头].filter((e) => f >= e).length;

export const 光态 = (f: number) => {
  const i = 光档(f);
  const t: 调子 = 插调子(色板.夜, 色板.日落, 参.晓们[i]!);
  return { 光: 参.窗光档们[i]!, 调子: t, 天: 参.天们[i]!, 门外亮: i >= 参.门外亮档 };
};

// ---------- 镜头 ----------
/** 横移进度 0～1：横移起 那一帧开始动，段尾最后一帧正好走完（t^幂 加速，最后一帧还在最快的时候） */
export const 横移进度 = (f: number) => {
  const n = 帧数 - 事.横移起;
  return 夹((f - 事.横移起 + 1) / n) ** 参.横移.幂;
};

/** 取景中心挪到成片的偶数像素上（像素网格不闪） */
const 吸 = (格: number, 每格: number) => (Math.round((格 * 每格) / 2) * 2) / 每格;

export const 镜 = (f: number): 侧取景 => {
  const { 中心, 每格 } = 参.卧室取景;
  return { 中心: [吸(中心[0] + 参.横移.右 * 横移进度(f), 每格), 中心[1]], 每格 };
};

/** 最后一帧镜头的速度（格/帧、成片像素/帧）：交给分屏那一路接（t^幂 的导数 幂·t^(幂−1)/n，t = 1） */
export const 末帧速度 = () => {
  const n = 帧数 - 事.横移起;
  return { 右: (参.横移.右 * 参.横移.幂) / n, 每格: 参.卧室取景.每格 };
};

// ---------- 屋外、接缝 ----------
/** 2-时差 第一帧（分屏起）服务器那半的调子：横移时屋外的林子照它的色调画，整片后期往它走 */
const 接缝调子 = 服务器调子于(正片事件.分屏起.帧);

/** 屋外林子的 林偏（场/2-门口/林间门口.tsx）：末帧再往右走一帧（末帧速度），中景正好落在 2-时差 第一帧服务器那半的中景上，
 *  切过去林子接着同一个速度滑（远景 N 是中景的一半，同一个林偏两层一起对上）。
 *  2-时差 第一帧服务器那块画布（场/2-门口/时差分屏.tsx 接入中）：宽 服务器宽 + 成形.横、左沿 成形偏于(分屏起) − 成形.横，近景中心往左挪 成形.横 的一半 */
export const 屋外林偏 = (() => {
  const 末 = 镜(帧数 - 1);
  const 页每格 = (每格: number) => 每格 / 成片倍数;
  const 层每格 = 16 * 中景.N;
  const 时差宽 = 分屏版式.服务器宽 + 成形.横;
  const 时差左 = 成形偏于(正片事件.分屏起.帧) - 成形.横;
  const 时差近x = 服务器取景.中心[0] - 成形.横 / 页每格(服务器取景.每格) / 2;
  const 时差中 = (时差近x * 分屏N) / 中景.N;
  const 速 = 末帧速度();
  const 一帧 = 页每格(速.右 * 速.每格);
  // 卧室末帧：1280 宽、中景中心 c；中景 x 在页面 640 + (x − c)·层每格页，再左移 一帧 = 2-时差 第一帧的 时差左 + 时差宽/2 + (x − 时差中)·层每格页
  const c = 时差中 + (640 - 一帧 - 时差左 - 时差宽 / 2) / 页每格(层每格);
  return 末.中心[0] - (c * 中景.N) / (末.每格 / 16);
})();

/** 这一帧的屋外：横移起 以前不给（屋外不在画里，画法照旧）；亮 = 横移进度（后窗那块天亮的橙跟着淡成屋外的天） */
export const 屋外态 = (f: number): 卧室屋外 | undefined =>
  f < 事.横移起
    ? undefined
    : { 亮: 横移进度(f), 色调: 接缝调子.色调, 天色, 刻: 白天刻, 群系, 生长: 分屏态(正片事件.分屏起.帧).生长, 林偏: 屋外林偏, 天每格: 16 * 分屏N };

/** 整片后期的调色：横移起 以前是这一档窗光的调子；横移时按 横移进度 往 接缝调子 插，末帧和 2-时差 第一帧服务器那半一样 */
export const 后期调色 = (f: number) => {
  const t = 光态(f).调子;
  const k = f < 事.横移起 ? 0 : 横移进度(f);
  return k > 0 ? 插调子(t, 接缝调子, k).调色 : t.调色;
};
