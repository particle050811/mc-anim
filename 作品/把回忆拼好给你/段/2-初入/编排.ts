// 2-初入 每一帧：选择世界（钻进图标）和新世界（镜头、天、剖面、调子）两场在这一段里怎么接。两场互不引用，接法写在段里：
// 钻入的进度、透掉多少、调子回暖多少照 场/2-选择世界/编排.ts（和 2-选择世界 同一套，接缝那一帧对得上），新世界的镜头、天刻、撤排照 场/2-新世界/编排.ts。
import { 插调子 } from '@engine/三渲二/调子.ts';
import { 正片事件 } from '../../分镜.ts';
import { 天亮 } from '../../地点/天体.ts';
import { 色板 } from '../../色板.ts';
import { 钻入 } from '../../场/2-选择世界/参数.ts';
import { 钻入回暖, 钻入进度 } from '../../场/2-选择世界/编排.ts';
import { 天刻在, 机位在 } from '../../场/2-新世界/编排.ts';

/** 钻完那一帧（歌曲帧）：从这一帧起没有选择世界界面了，整屏是新世界 */
export const 钻完 = 正片事件.开场鼓点.帧 + 钻入.帧;

/** 新世界的镜头 */
export const 镜头在 = (歌帧: number) => 机位在(钻入进度(歌帧).p, 歌帧);

/** 新世界本身的调子：按原版天亮程度在夜和夏日白天之间插（第 1 句整句天亮 1，就是夏日白天；2-第一晚 同一个插法，接缝那一帧对得上） */
export const 世界调子在 = (歌帧: number) => 插调子(色板.夜, 色板.夏日白天, 天亮(天刻在(歌帧)));

/** 调子：选择世界是现实（冷），钻进图标跟着照片透掉的比例回暖到新世界的调子 */
export const 调子在 = (歌帧: number) => 插调子(色板.现实, 世界调子在(歌帧), 钻入回暖(钻入进度(歌帧).q));
