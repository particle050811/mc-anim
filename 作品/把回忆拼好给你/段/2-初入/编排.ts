// 2-初入 每一帧：启动器（钻进图标）和新世界（镜头、调子）两场在这一段里怎么接。两场互不引用，接法写在段里：
// 钻入的进度、透掉多少、调子回暖多少照 场/2-启动器/编排.ts（和 2-六月樱 同一套，接缝那一帧对得上），新世界的镜头照 场/2-新世界/编排.ts。
import { 正片事件 } from '../../分镜.ts';
import { 色板 } from '../../色板.ts';
import { 插调子 } from '@engine/三渲二/调子.ts';
import { 钻入 } from '../../场/2-启动器/参数.ts';
import { 钻入进度, 钻入回暖 } from '../../场/2-启动器/编排.ts';
import { 机位在 } from '../../场/2-新世界/编排.ts';

/** 钻完那一帧（歌曲帧）：从这一帧起没有启动器了，整屏是新世界 */
export const 钻完 = 正片事件.开场鼓点.帧 + 钻入.帧;

const clamp01 = (x: number) => Math.min(1, Math.max(0, x));

/** 落定以后推镜的进度（0～1，线性）：钻完那一帧 0，推到第 2 句开口 */
export const 推进度 = (歌帧: number) => clamp01((歌帧 - 钻完) / (正片事件.第1句推完.帧 - 钻完));

/** 新世界的镜头 */
export const 镜头在 = (歌帧: number) => 机位在(钻入进度(歌帧).p, 推进度(歌帧));

/** 调子：启动器是现实（冷），钻进图标跟着照片透掉的比例回暖到夏日白天 */
export const 调子在 = (歌帧: number) => 插调子(色板.现实, 色板.夏日白天, 钻入回暖(钻入进度(歌帧).q));
