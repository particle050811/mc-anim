// 正片第 6 句「在最灰暗的日子你陪着我发呆」：雷雨里炸掉一角的门口小木屋，她和你坐在坑沿发呆，透视一个镜头从全景慢慢推到两人背影（和 2-拨开阴霾 是同一个镜头，画法在 场/2-雷雨/画面.tsx）。
// 帧数、场窗口、原声和音效 cue 都从 分镜.ts 推（雨声、两声雷是歌上的声音，声音/跨段音效.ts 切出这一段的那截），增益在场参数，段里不写数字。
import { 定义段 } from '@engine/段/段定义.ts';
import { fps, 段时钟, 画幅 } from '../../分镜.ts';
import { 正片原声增益 } from '../../配乐/正片.ts';
import { 段里那截, type 歌上音效 } from '../../声音/跨段音效.ts';
import { 近雷, 雨声们, 雷 } from '../../场/2-雷雨/声音.ts';

const 键 = '2-雷雨';
const 钟 = 段时钟(键);
const 截 = (音: 歌上音效) => {
  const c = 段里那截(钟.场窗口, 音);
  if (!c) throw new Error(`${音.名} 不在 ${键} 的窗口里`);
  return c;
};

export default 定义段({
  场: '2-雷雨',
  帧数: 钟.帧数,
  fps,
  宽: 画幅.宽,
  高: 画幅.高,
  地形: [],
  场窗口: 钟.场窗口,
  声音: [{ ...钟.原声, 资产: '配乐/把回忆拼好给你-抖音原声', 名: '原声', 增益: 正片原声增益 }, 截(雷), 截(近雷), ...雨声们.map((音) => 段里那截(钟.场窗口, 音)).filter((c) => c !== null)],
});
