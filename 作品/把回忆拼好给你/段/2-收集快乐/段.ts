// 正片第 8 句「将快乐全都收集将不开心全都淘汰」：门这个机位整句一个镜头（段首从晴天下摇）。墙上已经挂着三张照片，她把最新那张挂进最后一只荧光框，
// 苦力怕摸过来，她挡在你身前冲它哈气、把它吓跑。
// 帧数、场窗口、原声和各音效 cue 的帧都从 分镜.ts 推，增益在场参数，段里不写数字。
import { 定义段 } from '@engine/段/段定义.ts';
import type { 资产cue } from '@engine/段/段定义.ts';
import { fps, 段内正片事件帧, 段时钟, 画幅 } from '../../分镜.ts';
import { 原声增益, 原声让哈气, 哈气声增益, 挂照片声 } from '../../场/2-门口/第8句参数.ts';

const 键 = '2-收集快乐';
const 钟 = 段时钟(键);
const 事 = 段内正片事件帧(键);
const 到段尾 = (起: number, 秒: number) => Math.min(Math.ceil(秒 * fps), 钟.帧数 - 起);

// 照片挂进框：原版荧光框放东西的声音，起音（文件一开头就最响）落在 挂照片 那一帧（照片进框同一帧）
const 挂照片: 资产cue = { 帧: 事.挂照片, 资产: 挂照片声.资产, 名: '挂照片', 帧数: 到段尾(事.挂照片, 挂照片声.秒), 增益: 挂照片声.增益 };

// 猫的哈气声（entity.cat.hiss.1，1.17 秒，前 0.1 秒渐起、0.35 秒最响、0.6 秒后只剩尾音）：比哈气那一帧早 2 帧起放，劲头落在她摆好架势之后；段尾截掉的是尾音，最后 4 帧淡掉
const 哈气起 = 事.哈气 - 2;
const 哈气: 资产cue = { 帧: 哈气起, 资产: '音效/把回忆拼好给你/entity.cat.hiss.1', 名: '哈气', 帧数: 到段尾(哈气起, 1.169), 增益: 哈气声增益, 淡出: 4 };

// 原声：固定增益，哈气最响那一截让一让（线性渐变进出）。段在一串歌中间，不淡入
const 让起 = 事.哈气 - 原声让哈气.前, 让止 = 事.哈气 + 原声让哈气.后;
const 让 = (f: number) => Math.min(1, Math.max(0, (f - 让起 + 原声让哈气.渐) / 原声让哈气.渐), Math.max(0, (让止 + 原声让哈气.渐 - f) / 原声让哈气.渐));
const 原声增益帧 = Array.from({ length: 钟.原声.帧数 }, (_, f) => Math.round((原声增益 + (原声让哈气.增益 - 原声增益) * 让(f)) * 1e6) / 1e6);

export default 定义段({
  场: '2-门口',
  帧数: 钟.帧数,
  fps,
  宽: 画幅.宽,
  高: 画幅.高,
  地形: [],
  场窗口: 钟.场窗口,
  声音: [{ ...钟.原声, 资产: '配乐/把回忆拼好给你-抖音原声', 名: '原声', 增益: 原声增益帧 }, 挂照片, 哈气],
});
