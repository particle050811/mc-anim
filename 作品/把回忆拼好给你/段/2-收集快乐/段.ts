// 正片第 8 句「将快乐全都收集将不开心全都淘汰」：门这个机位整屏、整句一个镜头。她把四张照片收进箱子，苦力怕摸过来，她挡在你身前冲它哈气、把它吓跑。
// 帧数、场窗口、原声和各音效 cue 的帧都从 分镜.ts 推，增益在场参数，段里不写数字。
import { 定义段 } from '@engine/段/段定义.ts';
import type { 资产cue } from '@engine/段/段定义.ts';
import { fps, 段内正片事件帧, 段时钟, 画幅 } from '../../分镜.ts';
import { 原声增益, 哈气声增益, 纸声增益 } from '../../场/2-门口/第8句参数.ts';

const 键 = '2-收集快乐';
const 钟 = 段时钟(键);
const 事 = 段内正片事件帧(键);
const 到段尾 = (起: number, 秒: number) => Math.min(Math.ceil(秒 * fps), 钟.帧数 - 起);

// 放照片的纸声（原版 item.book.page_turn，0.5～0.7 秒、最响在 0.1～0.4 秒）：照片开始往箱子里落那一帧起放，响在照片落进去前后；三个文件轮着用
const 纸声长 = [0.73, 0.7, 0.54] as const;
const 纸声: 资产cue[] = [事.收照片一, 事.收照片二, 事.收照片三, 事.收照片四].map((落, i) => {
  const 起 = Math.max(0, 落 - 3);
  const k = i % 3;
  return { 帧: 起, 资产: `音效/item.book.page_turn.${k + 1}`, 名: `放照片${i + 1}`, 帧数: 到段尾(起, 纸声长[k]!), 增益: 纸声增益 };
});

// 猫的哈气声（entity.cat.hiss.1，1.17 秒，前 0.1 秒渐起、0.35 秒最响、0.6 秒后只剩尾音）：比哈气那一帧早 2 帧起放，劲头落在她摆好架势之后；段尾截掉的是尾音，最后 4 帧淡掉
const 哈气起 = 事.哈气 - 2;
const 哈气: 资产cue = { 帧: 哈气起, 资产: '音效/把回忆拼好给你/entity.cat.hiss.1', 名: '哈气', 帧数: 到段尾(哈气起, 1.169), 增益: 哈气声增益, 淡出: 4 };

export default 定义段({
  场: '2-门口',
  帧数: 钟.帧数,
  fps,
  宽: 画幅.宽,
  高: 画幅.高,
  地形: [],
  场窗口: 钟.场窗口,
  声音: [{ ...钟.原声, 资产: '配乐/把回忆拼好给你-抖音原声', 名: '原声', 增益: 原声增益 }, ...纸声, 哈气],
});
