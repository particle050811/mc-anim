// 正片第 2 句「祈愿小世界里不只有挫败」：你的第一晚。宽景里两条死亡消息、从崖上摔死、死亡画面、点重生；6.50 切近景剖面一镜拍完「挖三填一」、快进一夜、挖开天窗。
// 帧数、场窗口、原声和各音效 cue 的帧都从 分镜.ts 推，增益按 场/2-第一晚/参数.ts 的实测峰值配，段里不写数字。
import { 定义段 } from '@engine/段/段定义.ts';
import type { 资产cue } from '@engine/段/段定义.ts';
import { fps, 段内正片事件帧, 段时钟, 画幅 } from '../../分镜.ts';
import { 僵尸吼起, 原声增益, 音效们 } from '../../场/2-第一晚/参数.ts';

const 键 = '2-第一晚';
const 钟 = 段时钟(键);
const 事 = 段内正片事件帧(键);
const 到段尾 = (起: number, 秒: number) => Math.min(Math.ceil(秒 * fps), 钟.帧数 - 起);

type 音效名 = keyof typeof 音效们;
/** 一个音效：在第 帧 帧起放，增益把文件峰值配到 参数.ts 的 到（dBFS），放到文件完或段尾 */
const 放 = (名: 音效名, 帧: number): 资产cue => {
  const 声 = 音效们[名];
  const 增益 = Math.round(10 ** ((声.到 - 声.峰值) / 20) * 1e6) / 1e6;
  return { 帧, 资产: 声.资产, 名, 帧数: 到段尾(帧, 声.秒), 增益 };
};

// 摔到地上那一下和死掉的那声叫同时（原版落地伤害一下扣完血，big_fall 和受伤声同一刻）；点按钮在点重生那一拍；挖、放土在方块碎、方块出现的那一帧
const 音效cue们: readonly 资产cue[] = [
  放('摔', 事.摔死),
  放('死', 事.摔死),
  放('点', 事.点重生),
  放('挖一', 事.挖一),
  放('挖二', 事.挖二),
  放('挖三', 事.挖三),
  放('填土', 事.填土),
  放('挖开天窗', 事.挖开天窗),
  放('僵尸', 事.挖一 + 僵尸吼起),
];

export default 定义段({
  场: '2-第一晚',
  帧数: 钟.帧数,
  fps,
  宽: 画幅.宽,
  高: 画幅.高,
  地形: [],
  场窗口: 钟.场窗口,
  声音: [{ ...钟.原声, 资产: '配乐/把回忆拼好给你-抖音原声', 名: '原声', 增益: 原声增益 }, ...音效cue们],
});
