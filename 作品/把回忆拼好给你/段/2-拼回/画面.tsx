// 2-拼回 的画面：构图同第 0 镜第一帧（「选择世界」界面、平常取景，没有光标、没选中，搜索框拿着焦点闪「_」），能接回开头循环。
// 第一帧整屏纯白（接 2-合照 最后的闪白），白光慢慢退；回色前界面是灰的，新合照的碎片（16 块）带着颜色从四周吸进图标框、一块块拼上
// （碎片层叠在白光上面，只过调色，不再叠一遍暗角颗粒）。片尾回色那一帧「啪」地回到现实的调子、碎片都已经拼进图标、图标弹一下。
// 白光盖在界面的整片后期外面（纯白，不被调色染蓝）。歌词这时已经收了（第 15 句在 片尾歌词收 退场）。
import type React from 'react';
import { AbsoluteFill, useCurrentFrame } from 'remotion';
import { 整片后期 } from '@engine/三渲二/整片后期.tsx';
import { 段内正片事件帧, 段窗口 } from '../../分镜.ts';
import { 色板 } from '../../色板.ts';
import { 原声 } from '../../配乐/原声.ts';
import { 配乐音轨 } from '../../配乐/配乐音轨.tsx';
import { 音效轨 } from '../../声音/音效轨.tsx';
import { 符文歌词, 符文歌词默认 } from '../../界面/符文歌词.tsx';
import { 正片歌词行 } from '../../界面/符文歌词数据.ts';
import { 碎片层, 选择世界 } from '../../场/2-选择世界/选择世界.tsx';
import { 平常取景, 框光标亮, 片尾弹, 片尾白光 } from '../../场/2-选择世界/编排.ts';
import { 新图标, 旧图标 } from '../../场/2-选择世界/图标源.ts';
import 段 from './段.ts';
import 咔哒url from 'asset:音效/车万女仆/item.camera_use';

const 起帧 = 段窗口('2-拼回').起帧;
const 事 = 段内正片事件帧('2-拼回');
const 行们 = Array.from({ length: 15 }, (_, i) => 正片歌词行(i + 1, 起帧));
const 调 = 色板.现实;
/** 回色前：现实的调色把饱和拉到 0（白光里的界面是黑白的） */
const 灰调色 = { ...调.调色, 饱和: 0 };
/** 碎片只过现实的调色（暗角、颗粒在下面那层整片后期里已经叠过一遍） */
const 碎片调色 = { ...调.调色, 暗角: 0, 颗粒: 0 };

const 画面: React.FC = () => {
  const f = useCurrentFrame();
  const 回色 = f >= 事.片尾回色;
  const 白 = 片尾白光(f, 事.片尾回色);
  return (
    <>
      <整片后期 调色={回色 ? 调.调色 : 灰调色} 种子={起帧 + f}>
        <选择世界
          状态={{
            取景: 平常取景,
            指着: 0,
            选中: false,
            框光标: 框光标亮(起帧 + f, 起帧),
            光标: null,
            图标: 回色 ? 新图标 : 旧图标,
            图标弹: 片尾弹(f, 事.片尾回色),
          }}
        />
        <符文歌词 行们={行们} 样式={{ ...符文歌词默认, 描边色: 调.描边 }} 收={事.片尾歌词收} />
      </整片后期>
      {白 > 0 && <AbsoluteFill style={{ background: `rgba(255,255,255,${白})` }} />}
      {!回色 && (
        <整片后期 调色={碎片调色}>
          <碎片层 f={f} 新={新图标} />
        </整片后期>
      )}
      <配乐音轨 song={原声} 段={段} />
      <音效轨 src={咔哒url} 资产="音效/车万女仆/item.camera_use" 段={段} />
    </>
  );
};

export default 画面;
