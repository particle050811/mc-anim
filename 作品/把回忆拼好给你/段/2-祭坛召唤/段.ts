// 正片第 3 句「直到遇见你我以为就光明起来」：樱花林边的车万女仆祭坛，两个镜头。远景立住地方，你拿御币点祭坛，材料化成光汇到圈心；
// 她站在光里出现时切到圈里的近景：她抬头，你递蛋糕驯服她（爱心），镜头推进她的右眼，接第 4 句的眼睛特写。画法见 场/2-祭坛/。
// 帧数、场窗口、原声和各音效 cue 的帧都从 分镜.ts 推，增益在场参数，段里不写数字。
import { 定义段 } from '@engine/段/段定义.ts';
import type { 资产cue } from '@engine/段/段定义.ts';
import { fps, 段内正片事件帧, 段时钟, 画幅 } from '../../分镜.ts';
import { 原声增益, 音效 } from '../../场/2-祭坛/参数.ts';

const 键 = '2-祭坛召唤';
const 钟 = 段时钟(键);
const 事 = 段内正片事件帧(键);
const 到段尾 = (起: number, 秒: number) => Math.min(Math.ceil(秒 * fps), 钟.帧数 - 起);
const 配峰 = (峰值: number) => Math.round(10 ** ((音效.峰值 - 峰值) / 20) * 1e6) / 1e6;

// 祭坛合成声：文件头对着点祭坛那一帧（一开头就响）
const 合成: 资产cue = { 帧: 事.第3句点祭坛, 资产: 音效.祭坛.资产, 名: '祭坛合成', 帧数: 到段尾(事.第3句点祭坛, 音效.祭坛.秒), 增益: 配峰(音效.祭坛.峰值) };

export default 定义段({
  场: '2-祭坛',
  帧数: 钟.帧数,
  fps,
  宽: 画幅.宽,
  高: 画幅.高,
  地形: [],
  场窗口: 钟.场窗口,
  声音: [{ ...钟.原声, 资产: '配乐/把回忆拼好给你-抖音原声', 名: '原声', 增益: 原声增益 }, 合成],
});
