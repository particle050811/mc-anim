// 启动器这一场每一帧的样子（光标在哪、六月樱那一行亮没亮、钻进图标到哪了、片尾碎片飞到哪了），按歌曲帧算：2-六月樱、2-初入 一镜不切，两段都从这里取，接缝那一帧才对得上。
// 纯计算（不 import react、three），测试直接引。时刻从 分镜.ts 的正片事件来，比例、帧数在 参数.ts。
import { 正片事件 } from '../../分镜.ts';
import { 散, 图标边 } from '../../界面/实例图标.ts';
import { 光标, 取景中心, 尺, 布局, 碎片, 钻入, 片尾白, 回色弹 } from './参数.ts';

const clamp01 = (x: number) => Math.min(1, Math.max(0, x));
const 平滑 = (q: number) => q * q * (3 - 2 * q);

/** 六月樱那一格图标的界面像素框（布局.ts 里第 0 行） */
export const 图标框 = { x: 布局.卡.左 + 布局.图标.x, y: 布局.行起 + 布局.图标.y, 边: 布局.图标.边 };
const 图标心 = { x: 图标框.x + 图标框.边 / 2, y: 图标框.y + 图标框.边 / 2 };

/** 平常的取景（第 0 镜、片尾） */
export const 平常取景 = { 中心: { ...取景中心 }, 尺 };

// ---------- 第 0 镜：光标、悬停 ----------

/** 光标箭头尖（界面像素，取整：光标一个屏幕像素一个屏幕像素地走）；开场鼓点那一帧（按下）还在，之后钻进图标就不画了 */
export const 光标在 = (歌帧: number): { x: number; y: number } | null => {
  const 入 = 正片事件.开场光标入.帧, 到 = 正片事件.开场光标到.帧, 按 = 正片事件.开场鼓点.帧;
  if (歌帧 < 入 || 歌帧 > 按) return null;
  const q = 平滑(clamp01((歌帧 - 入) / (到 - 入)));
  return { x: Math.round(光标.起.x + (光标.停.x - 光标.起.x) * q), y: Math.round(光标.起.y + (光标.停.y - 光标.起.y) * q) };
};

/** 六月樱那一行：0 平常；光标尖进了这一行就悬停（1）；开场鼓点起按下（2），一直按到钻完 */
export const 行态在 = (歌帧: number): 0 | 1 | 2 => {
  if (歌帧 >= 正片事件.开场鼓点.帧 && 歌帧 < 正片事件.开场鼓点.帧 + 钻入.帧) return 2;
  const c = 光标在(歌帧);
  if (!c) return 0;
  const r = 布局.悬停让;
  const 在 = c.x >= 布局.卡.左 + r.左 && c.x < 布局.卡.右 - r.右 && c.y >= 布局.行起 + r.上 && c.y < 布局.行起 + 布局.行高 - r.下;
  return 在 ? 1 : 0;
};

// ---------- 第 1 句开头：钻进图标 ----------

/** 钻入进度 0～1（开场鼓点那一帧是 0，钻入.帧 − 1 帧后是 1：最后一帧有启动器的画面图标已经铺满、照片全透，下一帧去掉启动器不跳）和缓入后的 q */
export const 钻入进度 = (歌帧: number) => {
  const p = clamp01((歌帧 - 正片事件.开场鼓点.帧) / (钻入.帧 - 1));
  return { p, q: p ** 钻入.缓入 };
};

/** 钻到 q 时的取景：尺 按指数从 尺 涨到 终尺；图标中心在画面上的位置从原来那里线性挪到画面正中 */
export const 钻入取景 = (q: number) => {
  const s = 尺 * (钻入.终尺 / 尺) ** q;
  const dx = (图标心.x - 取景中心.x) * 尺 * (1 - q);
  const dy = (图标心.y - 取景中心.y) * 尺 * (1 - q);
  return { 中心: { x: 图标心.x - dx / s, y: 图标心.y - dy / s }, 尺: s };
};

const 拜耳 = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
/** 4×4 Bayer 阈值（0～1 之间）：透掉的比例超过它的那个照片像素就透掉（同 界面/符文歌词.tsx 的抖动） */
export const 阈 = (i: number, j: number) => (拜耳[(j & 3) * 4 + (i & 3)]! + 0.5) / 16;

/** 钻到 q 时图标透掉了多少（0～1） */
export const 钻入透 = (q: number) => clamp01((q - 钻入.透起) / (钻入.透满 - 钻入.透起));

/** 钻到 q 时调子从现实（启动器）往夏日白天（新世界）走了多少：跟着图标透掉的比例走 */
export const 钻入回暖 = (q: number) => 平滑(clamp01(q / 钻入.透满));

// ---------- 片尾：碎片拼回、回色 ----------

const 块数 = 图标边 / 碎片.碎块边;
const 块界面边 = (图标框.边 * 碎片.碎块边) / 图标边;

/** 一块碎片：第 (i, j) 块（从左上数），从 起 飞进图标框里它那一格；料 = 飞着时一开始是哪种方块的贴图（第 11 句碎掉的那片世界：门口的地、屋子） */
export type 碎块 = { i: number; j: number; 起: { x: number; y: number }; 起倍: number; 起帧: number; 料: string };

const 料们 = ['oak_planks', 'grass_block_top', 'dirt', 'cobblestone', 'oak_log', 'cherry_leaves', 'stone', 'oak_planks'] as const;

/** 64 块碎片，起点在图标框四周一圈（离图标中心 60～150 界面像素，方向、远近、起飞帧、大小都按散列定死） */
export const 碎块们: readonly 碎块[] = Array.from({ length: 块数 * 块数 }, (_, n) => {
  const i = n % 块数, j = Math.floor(n / 块数);
  const 角 = Math.atan2(j - (块数 - 1) / 2, i - (块数 - 1) / 2) + (散(i, j, 1) - 0.5) * 2.2;
  const 远 = 60 + 90 * 散(i, j, 2);
  return {
    i,
    j,
    起: { x: 图标心.x + Math.cos(角) * 远 * 1.6, y: 图标心.y + Math.sin(角) * 远 },
    起倍: 碎片.起倍[0] + (碎片.起倍[1] - 碎片.起倍[0]) * 散(i, j, 3),
    起帧: Math.floor(散(i, j, 4) * 碎片.错开帧),
    料: 料们[Math.floor(散(i, j, 5) * 料们.length)]!,
  };
});

export type 碎块态 = { x: number; y: number; 边: number; 换: number; 到: boolean };

/** 片尾第 f 帧（段内，0 = 片尾白光）这块碎片在哪（左上角，界面像素）、多大、换成照片换了多少；还没起飞的在起点、到了的就在格子里 */
export const 碎块在 = (块: 碎块, f: number): 碎块态 => {
  const p = clamp01((f - 块.起帧) / 碎片.飞帧);
  const q = p ** 碎片.缓入;
  const 终 = { x: 图标框.x + 块.i * 块界面边, y: 图标框.y + 块.j * 块界面边 };
  const 倍 = 块.起倍 + (1 - 块.起倍) * q;
  const 边 = 块界面边 * 倍;
  // 中心从起点直线飞到格子中心
  const cx = 块.起.x + (终.x + 块界面边 / 2 - 块.起.x) * q;
  const cy = 块.起.y + (终.y + 块界面边 / 2 - 块.起.y) * q;
  return { x: cx - 边 / 2, y: cy - 边 / 2, 边, 换: clamp01(p / 碎片.换完), 到: p >= 1 };
};

/** 片尾第 f 帧（段内）的白光不透明度：回色那一帧起没有 */
export const 片尾白光 = (f: number, 回色帧: number) => (f >= 回色帧 ? 0 : 片尾白.白起 + (片尾白.白止 - 片尾白.白起) * clamp01(f / Math.max(1, 回色帧 - 1)));

/** 回色时图标弹出去几个界面像素 */
export const 片尾弹 = (f: number, 回色帧: number) => (f >= 回色帧 && f < 回色帧 + 回色弹.弹帧 ? 回色弹.弹 : 0);
