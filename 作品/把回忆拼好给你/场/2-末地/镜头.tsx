// 第 5 句末地这一镜的成片画法（段 2-抢龙蛋、核对-扑龙蛋照片 共用）：三渲二透视（平涂、不抗锯齿；描边照 画风.ts，全片关）、末地那套调子、整片后期，
// 上面叠她头顶的女仆气泡（2D，按同一台相机投到画面上）、龙蛋转场和符文歌词。谁在哪、什么样全在 编排.ts，这里只按段内帧 f 画。
// 干净 = 不画歌词（第 8 句收的照片用：照片那一帧还没有气泡，这一镜也没有聊天栏，只差歌词）。
import React from 'react';
import { 三渲二画布 } from '@engine/三渲二/画布.tsx';
import { 整片后期 } from '@engine/三渲二/整片后期.tsx';
import { VanillaParticles } from '@库/特效/原版粒子.tsx';
import { 女仆气泡, 气泡像素格 } from '@库/界面/女仆气泡.tsx';
import { 做透视相机, 投影到页面, Z朝上转three } from '@库/界面/投影.ts';
import { 成片倍数 } from '@engine/三渲二/像素.ts';
import { fps, 段窗口, 画幅 } from '../../分镜.ts';
import { 画布调子, 描边 as 描边默认 } from '../../画风.ts';
import { 色板 } from '../../色板.ts';
import { 符文歌词, 符文歌词默认 } from '../../界面/符文歌词.tsx';
import { 正片歌词行 } from '../../界面/符文歌词数据.ts';
import { 像素字 } from '../../界面/像素字.ts';
import { 末地布景, 龙蛋 } from './布景.tsx';
import { 事, 你态, 传送粒子们, 刻, 她态, 机位, 死刻, 歌曲帧, 气泡态, 经验球们, 蛋格, 转场进度, 龙位 } from './编排.ts';
import { 末地天空 } from './末地天空.tsx';
import { 末地传送门 } from './末地传送门.tsx';
import { 死亡光束 } from './死亡光束.tsx';
import { 经验球面片 } from './经验球面片.tsx';
import { 末地角色 } from './角色.tsx';
import { 龙蛋转场 } from './转场.tsx';

const 调 = 色板.末地;
const 宽 = 画幅.宽, 高 = 画幅.高;

/** 全片 15 句的符文歌词行（段内帧），样式照歌词艺术字定稿、描边色跟末地调子 */
const 行们 = Array.from({ length: 15 }, (_, i) => 正片歌词行(i + 1, 段窗口('2-抢龙蛋').起帧));
const 歌词样式 = { ...符文歌词默认, 描边色: 调.描边 };

const 相机 = (f: number) => {
  const 机 = 机位(f);
  return 做透视相机({ 眼: Z朝上转three(机.眼), 看: Z朝上转three(机.看), 视角: 机.视角, 宽, 高 });
};

/** 转场从哪儿涌出来：再点龙蛋那一帧，蛋（第一次瞬移后那格）中心在画面上的位置 */
export const 转场原点 = (() => {
  const 格 = 蛋格(事.再点龙蛋 - 1);
  const p = 投影到页面(相机(事.再点龙蛋), Z朝上转three([格[0] + 0.5, 格[1] + 0.5, 格[2] + 0.5]), 宽, 高);
  return { x: p.x, y: p.y };
})();

/** 气泡一个像素占几个成片像素：照游戏里的大小（一个气泡像素 0.025 格），按镜头推完停住那一帧她那里一格多大算，取整以后整段不变（推镜时跟着跳一级会闪） */
export const 气泡缩放 = (() => {
  const 锚 = 气泡态(事.再点龙蛋)!.锚;
  return Math.max(1, Math.round(投影到页面(相机(事.再点龙蛋), Z朝上转three(锚), 宽, 高).每格 * 成片倍数 * 气泡像素格));
})();

const 气泡: React.FC<{ f: number }> = ({ f }) => {
  const 泡 = 气泡态(f);
  if (!泡) return null;
  const p = 投影到页面(相机(f), Z朝上转three(泡.锚), 宽, 高);
  return <女仆气泡 锚={p} 缩放={气泡缩放} 文字={泡.字} 字体={像素字} 弹出={泡.弹出} />;
};

/** 三渲二画布里的东西（场景坐标） */
export const 末地场景: React.FC<{ f: number }> = ({ f }) => {
  const t = 死刻(f);
  return (
    <>
      <末地天空 眼={机位(f).眼} />
      <末地布景 />
      <末地传送门 刻={刻(f)} />
      <龙蛋 格={蛋格(f)} />
      <末地角色 她={她态(f)} 你={你态(f)} 描边={描边默认.开} />
      <死亡光束 死刻={t} 龙位={龙位(t)} />
      <经验球面片 球们={经验球们(f)} />
      <VanillaParticles spawns={传送粒子们} 秒={f / fps} />
    </>
  );
};

/** 一整帧（1280×720 页面）：f 是段内帧；干净 = 不画歌词；后期 只在核对里关（比较用） */
export const 末地镜头: React.FC<{ f: number; 干净?: boolean; 后期?: boolean }> = ({ f, 干净 = false, 后期 = true }) => (
  <整片后期 调色={后期 ? 调.调色 : null} 种子={歌曲帧(f)}>
    <三渲二画布 宽={宽} 高={高} 机位={机位(f)} {...画布调子('末地')}>
      <末地场景 f={f} />
    </三渲二画布>
    <气泡 f={f} />
    <龙蛋转场 宽={宽} 高={高} 原点={转场原点} 进={转场进度(f)} />
    {!干净 && <符文歌词 行们={行们} 样式={歌词样式} 帧={f} />}
  </整片后期>
);
