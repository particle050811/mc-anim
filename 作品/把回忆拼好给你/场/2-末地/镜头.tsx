// 第 5 句末地这一镜的成片画法（段 2-抢龙蛋、核对-扑龙蛋照片 共用）：三渲二透视（平涂、不抗锯齿、她和你描边）、末地那套调子、整片后期，
// 上面叠龙蛋转场和符文歌词。谁在哪、什么样全在 编排.ts，这里只按段内帧 f 画。
// 干净 = 不画歌词（第 8 句收的照片用：这一镜没有聊天栏、气泡，只差歌词）。
import React from 'react';
import { 三渲二画布 } from '@engine/三渲二/画布.tsx';
import { 整片后期 } from '@engine/三渲二/整片后期.tsx';
import { VanillaParticles } from '@库/特效/原版粒子.tsx';
import { 做透视相机, 投影到页面, Z朝上转three } from '@库/界面/投影.ts';
import { fps, 段窗口, 画幅 } from '../../分镜.ts';
import { 色板 } from '../../色板.ts';
import { 符文歌词, 符文歌词默认 } from '../../界面/符文歌词.tsx';
import { 正片歌词行 } from '../../界面/符文歌词数据.ts';
import { 末地描边宽 } from './参数.ts';
import { 末地布景, 龙蛋 } from './布景.tsx';
import { 事, 你态, 传送粒子们, 刻, 她态, 机位, 死刻, 歌曲帧, 经验球们, 蛋格, 转场进度, 龙位 } from './编排.ts';
import { 末地天空 } from './末地天空.tsx';
import { 末地传送门 } from './末地传送门.tsx';
import { 死亡光束 } from './死亡光束.tsx';
import { 经验球面片 } from './经验球面片.tsx';
import { 末地角色 } from './角色.tsx';
import { 龙蛋转场 } from './转场.tsx';

const 调 = 色板.末地;
const 宽 = 画幅.宽, 高 = 画幅.高;

/** 全片 15 句的符文歌词行（段内帧），样式照歌词艺术字定稿、描边色跟末地调子 */
const 行们 = Array.from({ length: 15 }, (_, i) => 正片歌词行(i + 1, 段窗口('2-抢龙蛋').起帧));
const 歌词样式 = { ...符文歌词默认, 描边色: 调.描边 };

/** 转场从哪儿涌出来：再点龙蛋那一帧，蛋（第一次瞬移后那格）中心在画面上的位置 */
export const 转场原点 = (() => {
  const 机 = 机位(事.再点龙蛋);
  const cam = 做透视相机({ 眼: Z朝上转three(机.眼), 看: Z朝上转three(机.看), 视角: 机.视角, 宽, 高 });
  const 格 = 蛋格(事.再点龙蛋 - 1);
  const p = 投影到页面(cam, Z朝上转three([格[0] + 0.5, 格[1] + 0.5, 格[2] + 0.5]), 宽, 高);
  return { x: p.x, y: p.y };
})();

/** 三渲二画布里的东西（场景坐标） */
export const 末地场景: React.FC<{ f: number; 描边?: boolean }> = ({ f, 描边 = true }) => {
  const t = 死刻(f);
  return (
    <>
      <末地天空 眼={机位(f).眼} />
      <末地布景 />
      <末地传送门 刻={刻(f)} />
      <龙蛋 格={蛋格(f)} />
      <末地角色 她={她态(f)} 你={你态(f)} 描边={描边} />
      <死亡光束 死刻={t} 龙位={龙位(t)} />
      <经验球面片 球们={经验球们(f)} />
      <VanillaParticles spawns={传送粒子们} 秒={f / fps} />
    </>
  );
};

/** 一整帧（1280×720 页面）：f 是段内帧；干净 = 不画歌词；后期、描边 只在核对里关（比较用） */
export const 末地镜头: React.FC<{ f: number; 干净?: boolean; 后期?: boolean; 描边?: boolean }> = ({ f, 干净 = false, 后期 = true, 描边 = true }) => (
  <整片后期 调色={后期 ? 调.调色 : null} 种子={歌曲帧(f)}>
    <三渲二画布 宽={宽} 高={高} 机位={机位(f)} 天={调.天} 色调={调.色调} 描边={描边 ? { 宽: 末地描边宽, 色: 调.描边 } : false}>
      <末地场景 f={f} 描边={描边} />
    </三渲二画布>
    <龙蛋转场 宽={宽} 高={高} 原点={转场原点} 进={转场进度(f)} />
    {!干净 && <符文歌词 行们={行们} 样式={歌词样式} 帧={f} />}
  </整片后期>
);
