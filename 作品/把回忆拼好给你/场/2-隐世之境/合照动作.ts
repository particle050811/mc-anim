// 15 尾随歌曲帧走的几样（纯函数，合照.tsx 画、测试核）：这一帧是哪一镜、靠肩那一镜的正交机位。时刻取 分镜.ts 的 正片事件，数取 合照参数.ts。
import type { 正交机位参数 } from '@engine/三渲二/机位.tsx';
import { 正片事件 } from '../../分镜.ts';
import { 合照镜 } from './合照参数.ts';

const 事 = 正片事件;

export type 合照镜名 = '笑' | '靠肩' | '白';

/** 第几镜：笑、靠肩、白（按歌曲帧，时刻取 分镜 的 尾笑、靠肩、合照咔哒） */
export const 合照镜头 = (帧: number): 合照镜名 => (帧 < 事.靠肩.帧 ? '笑' : 帧 < 事.合照咔哒.帧 ? '靠肩' : '白');

/** 靠肩这一镜的正交机位（朝东） */
export const 靠肩机位: 正交机位参数 = { 种: '正交', 朝: '东', N: 合照镜.N, 顶面: 合照镜.顶面, 看: 合照镜.看, 剖: 合照镜.剖, 深: 合照镜.深 };
