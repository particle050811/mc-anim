// 15 尾随歌曲帧走的几样（纯函数，合照.tsx 画、测试核）：这一帧是哪一镜、她靠到哪、靠肩那一镜的正交机位。时刻取 分镜.ts 的 正片事件，数取 合照参数.ts。
import type { 正交机位参数 } from '@engine/三渲二/机位.tsx';
import { clamp01 } from '@engine/anim/anim.ts';
import { 正片事件 } from '../../分镜.ts';
import { 合照镜 } from './合照参数.ts';

const 事 = 正片事件;
const 缓 = (t: number) => t * t * (3 - 2 * t);

export type 合照镜名 = '靠肩' | '白';

/** 第几镜：靠肩（侧面合照）、白（咔哒起）；按歌曲帧 */
export const 合照镜头 = (帧: number): 合照镜名 => (帧 < 事.合照咔哒.帧 ? '靠肩' : '白');

/** 她靠到哪（0～1，缓过的，按歌曲帧）：靠肩起 那一帧是 0（同 2-重逢 末尾的样子），到 靠肩 那一帧缓缓靠好，之后停住 */
export const 靠肩进度 = (帧: number) => 缓(clamp01((帧 - 事.靠肩起.帧) / (事.靠肩.帧 - 事.靠肩起.帧)));

/** 靠肩这一镜的正交机位（朝东） */
export const 靠肩机位: 正交机位参数 = { 种: '正交', 朝: '东', N: 合照镜.N, 顶面: 合照镜.顶面, 看: 合照镜.看, 剖: 合照镜.剖, 深: 合照镜.深 };
