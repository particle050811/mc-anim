// 第 15 句隐世之境这一镜随时间走的几样（纯函数，重逢.tsx 画、测试核）：她回头转到哪、她笑到哪、机位、接过来的聊天行淡到哪。
// 秒都是歌上的秒；时刻取 分镜.ts 的 正片事件，数取 重逢参数.ts。
import { clamp01, rad } from '@engine/anim/anim.ts';
import { fps, 正片事件 } from '../../分镜.ts';
import { 回头, 对视镜, 推镜, 笑, 聊天行 } from './重逢参数.ts';

type 点 = [number, number, number];
const 事 = 正片事件;
const 缓 = (t: number) => t * t * (3 - 2 * t);

/** 对视那一帧画的是哪一秒（帧号取整以后）：回头在这一刻到位，这一帧的机位、她和封面帧一样 */
export const 对视那帧秒 = 事.第15句对视.帧 / fps;
const 段尾秒 = 事.第15句段尾.帧 / fps;
// 回头、风散开都取帧号取整以后的秒：这一拍落在段头那一帧上，段头那一帧要正好是 0（同 2-摇铃 末帧接得上）
const 回头秒 = 事.回头.帧 / fps;
const 风散开秒 = 事.风散开.帧 / fps;

/** 她回头转到哪（0～1，缓过的）：身子从回头（风散开那一拍）到对视那一帧转完，头先转、头转秒 里转完 */
export const 回头进度 = (秒: number) => ({
  身: 缓(clamp01((秒 - 回头秒) / (对视那帧秒 - 回头秒))),
  头: 缓(clamp01((秒 - 回头秒) / 回头.头转秒)),
});

/** 她的头歪到哪（0～1，缓过的）：第15句笑 起 渐秒 里歪到位 */
export const 笑进度 = (秒: number) => 缓(clamp01((秒 - 事.第15句笑.秒) / 笑.渐秒));
/** 这一刻她笑着没有（表情、闭眼一下换上） */
export const 笑了 = (秒: number) => 秒 >= 事.第15句笑.秒;

const 半 = (度: number) => Math.tan(rad(度) / 2);
const 度 = (半正切: number) => (2 * Math.atan(半正切) * 180) / Math.PI;

/** 推镜的视角：整镜按同一个速度收（视角一半的正切按指数收），对视那一帧正好是 对视镜.视角，段尾那一刻是 推镜.末视角 */
export const 推镜视角 = (秒: number) => {
  const u = (秒 - 对视那帧秒) / (段尾秒 - 对视那帧秒);
  if (u === 0) return 对视镜.视角;
  return 度(半(对视镜.视角) * (半(推镜.末视角) / 半(对视镜.视角)) ** u);
};

/** 这一刻的机位：眼睛不动（对视镜.脚 + 原版眼高 1.62）；看点对视那一帧以前是封面帧的，之后缓缓挪到 推镜.看（段尾到）；视角 推镜视角 */
export const 重逢机位 = (秒: number) => {
  const k = 缓(clamp01((秒 - 对视那帧秒) / (段尾秒 - 对视那帧秒)));
  const 眼: 点 = [对视镜.脚[0], 对视镜.脚[1], 对视镜.脚[2] + 1.62];
  const 看 = 对视镜.看.map((v, i) => v + (推镜.看[i]! - v) * k) as 点;
  return { 种: '透视' as const, 眼, 看, 视角: 推镜视角(秒) };
};

/** 接过来的「Steve加入了游戏」这一刻多不透明（1 = 同 2-摇铃 末帧，0 = 不画）：风散开那一拍是 1，淡秒 里缓到 0；不接过来就一直是 0 */
export const 聊天行不透明 = (秒: number) => (聊天行.接过来 ? 1 - 缓(clamp01((秒 - 风散开秒) / 聊天行.淡秒)) : 0);
