// 第 15 句隐世之境这一镜随时间走的几样（纯函数，重逢.tsx 画、测试核）：门开多少、你走到哪、眼睛多高、她回头转到哪、机位。
// 秒都是歌上的秒；时刻取 分镜.ts 的 正片事件，数取 重逢参数.ts。
import { clamp01, rad } from '@engine/anim/anim.ts';
import { fps, 正片事件 } from '../../分镜.ts';
import { 进门起脚, 推门, 回头, 对视镜, 推脸, 推近, 蹲下 } from './重逢参数.ts';

type 点 = [number, number, number];
const 事 = 正片事件;
const 缓 = (t: number) => t * t * (3 - 2 * t);

/** 对视那一帧画的是哪一秒（帧号取整以后）：进门、回头都在这一刻到位，这一帧和封面帧一样 */
export const 对视那帧秒 = 事.第15句对视.帧 / fps;

/** 门开多少（0～1）：推门那一刻起 开秒 内开到底，先快后慢 */
export const 门开 = (秒: number) => {
  const t = clamp01((秒 - 事.推门.秒) / 推门.开秒);
  return 1 - (1 - t) ** 2;
};

/** 你的脚：进门 起从门外走到对视那一帧的站位，先快后慢地停住（演绎：原版走路 4.3 格/秒，这里峰值约 5.5） */
export const 你的脚 = (秒: number): 点 => {
  const k = clamp01((秒 - 事.进门.秒) / (对视那帧秒 - 事.进门.秒));
  if (k >= 1) return 对视镜.脚;
  const s = 缓(k);
  return [0, 1, 2].map((i) => 进门起脚[i]! + (对视镜.脚[i]! - 进门起脚[i]!) * s) as 点;
};

/** 你的眼高：原版站着 1.62；蹲下那一刻起照原版 Camera.tick 每刻往潜行眼高靠一半，按刻内插值 */
export const 眼高 = (秒: number) => {
  const 站 = 对视镜.脚[2] + 1.62;
  const 蹲 = 对视镜.脚[2] + 蹲下.眼高;
  const k = (秒 - 事.蹲下.秒) * 20;
  if (k <= 0) return 站;
  const n = Math.floor(k);
  const 第 = (i: number) => 蹲 + (站 - 蹲) * 0.5 ** i;
  return 第(n) + (第(n + 1) - 第(n)) * (k - n);
};

/** 她回头转到哪（0～1，缓过的）：身子从回头到对视那一帧转完，头先转、头转秒 里转完 */
export const 回头进度 = (秒: number) => ({
  身: 缓(clamp01((秒 - 事.回头.秒) / (对视那帧秒 - 事.回头.秒))),
  头: 缓(clamp01((秒 - 事.回头.秒) / 回头.头转秒)),
});

const 半 = (度: number) => Math.tan(rad(度) / 2);
const 度 = (半正切: number) => (2 * Math.atan(半正切) * 180) / Math.PI;

/** 推近的视角：风散开起按同一个速度收（视角一半的正切按指数收，看着是匀匀地放大），对视那一帧正好是 对视镜.视角，蹲下以后停住 */
export const 推近视角 = (秒: number) => {
  const u = (Math.min(秒, 事.蹲下.秒) - 事.风散开.秒) / (对视那帧秒 - 事.风散开.秒);
  if (Math.abs(u - 1) < 1e-9) return 对视镜.视角;
  return 度(半(推近.起视角) * (半(对视镜.视角) / 半(推近.起视角)) ** u);
};

/** 这一刻的机位：眼睛跟着你走进门、蹲下；看点到对视那一帧是封面帧的（对视镜），之后挪到 推近.看，蹲下后抬到 蹲下.看；视角先 推近视角，推向她的脸时再收到 推脸.视角、看点挪到 推脸.看 */
export const 重逢机位 = (秒: number) => {
  const 脚 = 你的脚(秒);
  const 眼: 点 = [脚[0], 脚[1], 眼高(秒)];
  const 抬 = 缓(clamp01((秒 - 事.蹲下.秒) / 蹲下.抬头秒));
  const 推 = 缓(clamp01((秒 - 事.推向她的脸.秒) / (事.第15句段尾.秒 - 事.推向她的脸.秒)));
  const 插 = (a: readonly number[], b: readonly number[], k: number) => a.map((v, i) => v + (b[i]! - v) * k) as 点;
  const 推近k = clamp01((秒 - 对视那帧秒) / (事.蹲下.秒 - 对视那帧秒));
  const 看 = 插(插(插(对视镜.看, 推近.看, 推近k), 蹲下.看, 抬), 推脸.看, 推);
  // 推脸那一段同样按放大倍数的对数插值（同 1-一如既往 的推镜）
  const 起 = 推近视角(秒);
  const 视角 = 推 > 0 ? 度(半(起) * (半(推脸.视角) / 半(起)) ** 推) : 起;
  return { 种: '透视' as const, 眼, 看, 视角 };
};
