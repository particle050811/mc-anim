const 调子 = '归隐之地' as const;
const 事 = 正片事件;

/** 她：回头之前背对着门（背身），回头时头先转、身子跟着转，对视那一帧起同 对视.tsx 的 对视她（站、侧身、头转过来看你、认出你、举着月铃兰），
 *  只是头跟着你的眼睛走（你蹲下她就低头看你），中间眨一次眼。花跟着身子转一起举起来 */
const 重逢她: React.FC<{ 秒: number; 眼: V3 }> = ({ 秒, 眼 }) => {
  const { 身: 身k, 头: 头k } = 回头进度(秒);
  const pose: FigurePose = { ...standPose(她.脚), yaw: 身k >= 1 ? 她.身子朝向 : 背身.朝向 + (她.身子朝向 - 背身.朝向) * 身k };
  const 末看 = 她看你(眼, pose);
  const p: 魔法酒狐新动作Props = {
    pose,
    姿势: '站',
    表情: 身k >= 0.5 ? '认出你' : 背身.表情,
    看: 头k >= 1 ? 末看 : [背身.看[0] + (末看[0] - 背身.看[0]) * 头k, 背身.看[1] + (末看[1] - 背身.看[1]) * 头k],
    眨眼: magicalWineFoxBlinkAt(秒, [事.第15句眨眼.秒]),
    秒,
    右手: 空手拿,
  };
  return <拿着花的她 p={p} 举={身k} 起={背身.拿花} />;
};

/** 驯服的 7 颗爱心（碰撞箱 0.6 × 1.5，同 1-一如既往） */
const 爱心 = tamingHearts(她.脚, 0.6, 1.5, 0, 驯服爱心种子);
/** 段内帧那一套换成歌曲帧：从某个事件那一帧起数的原版刻 */
const 刻 = (帧: number, 起帧: number) => ((帧 - 起帧) / fps) * 20;

/** 三渲二画布里的东西：布景、门、门光同封面帧（隐世之境重逢布景，不放灯、门光不撒浮尘、光带关、不挖影子，背景褪色），西门照 门开。
 *  她整镜都描边；你在门外、门洞里时她有一截被门洞南墙挡着，西门描边挡板 让墙面上不透出那截的轮廓（挡深度.tsx） */
const 场景: React.FC<{ 帧: number; 秒: number; 眼: V3; 描边: boolean; 她?: 换她 }> = ({ 帧, 秒, 眼, 描边: 描, 她: 换 }) => (
  <背景褪色 参数={背景褪色参数}>
    <隐世之境重逢布景 开={门开(秒)} 眼={眼} 秒={秒} 灯光={false} 门光参数={对视门光}>
      <不褪色>
        <描边 开={描}>
          {换 ? 换(秒, 眼) : <重逢她 秒={秒} 眼={眼} />}
        </描边>
        <西门描边挡板 开={门开(秒)} />
        <HeartParticles spawns={爱心} 刻={刻(帧, 事.第15句驯服.帧)} />
      </不褪色>
    </隐世之境重逢布景>
  </背景褪色>
);

// 手：右键在第 0 刻；换上蛋糕在右键前 8 刻（分镜的 换上蛋糕）；第 1 刻蛋糕被吃掉（同 1-一如既往）。
// 对视那一帧不画手（对视.tsx 文件头：空手的右臂会压在她身上），蛋糕吃掉以后空手的右臂照原版升上来
const 换上蛋糕刻 = Math.round((事.换上蛋糕.秒 - 事.递蛋糕右键.秒) * 20);
const 手剧本: HandScript = { start: null, swings: [0], changes: [{ tick: 换上蛋糕刻, to: '蛋糕' }, { tick: 1, to: null }] };

const 手: React.FC<{ 帧: number; 描边: boolean }> = ({ 帧, 描边: 描 }) => {
  const k = 刻(帧, 事.递蛋糕右键.帧);
  const h = handTimeline(k, 手剧本);
  const 拿着 = h.item === '蛋糕';
  if (!拿着 && k < 1) return null;
  const t = 色板[调子];
  // 手那一遍的视图坐标（Y 朝上、−Z 朝前）放进三渲二画布 Z 朝上的场景里：画布的看点朝 +y（北）就是视图的 −Z，再把画布里那层 −90° 转回来
  return (
    <三渲二画布
      宽={画幅.宽}
      高={画幅.高}
      机位={{ 种: '透视', 眼: [0, 0, 0], 看: [0, 1, 0], 视角: HAND_FOV, 近: HAND_NEAR, 远: 16 }}
      色调={门光色调}
      描边={描边默认.开 ? { 宽: 描边默认.宽, 色: t.描边 } : false}
      style={{ position: 'absolute', left: 0, top: 0 }}
    >
      <group rotation={[Math.PI / 2, 0, 0]}>
        <描边 开={描}>
          <FirstPersonHand
            held={拿着 ? <ItemSprite layers={CAKE} emissive={0} shadow={false} /> : null}
            arm={<SteveFirstPersonArm />}
            swing={h.swing}
            equip={h.equip}
          />
        </描边>
      </group>
    </三渲二画布>
  );
};

type 透视机 = { 眼: V3; 看: V3; 视角: number };

/** 她头顶的气泡：按这一刻的机位挂在帽顶（对视气泡.锚高），倍数同对视那一帧（片 16）；驯服那一帧起换成台词，「啵」地一级级弹到原来的倍数。
 *  门推开到 气泡露出门开 以前不画（气泡是叠在画面上的 2D，门扇挡不住它，不然关着的门上会浮着一个气泡） */
const 气泡: React.FC<{ 帧: number; 机: 透视机; 字?: string }> = ({ 帧, 机, 字 }) => {
  if (门开(帧 / fps) < 气泡露出门开) return null;
  const cam = 做透视相机({ 眼: Z朝上转three(机.眼), 看: Z朝上转three(机.看), 视角: 机.视角, 宽: 画幅.宽, 高: 画幅.高 });
  const p = 投影到页面(cam, Z朝上转three([她.脚[0], 她.脚[1], 她.脚[2] + 对视气泡.锚高]), 画幅.宽, 画幅.高);
  const s = 对视气泡.缩放.片;
  if (字 !== undefined) return <女仆气泡 锚={{ x: p.x, y: p.y }} 缩放={s} 锚对齐={s} 文字={字} 字体={像素字} />;
  const 换了 = 帧 >= 事.第15句驯服.帧;
  const 弹出 = 换了 ? clamp01((帧 - 事.第15句驯服.帧 + 1) / 啵帧) : 1;
  return <女仆气泡 锚={{ x: p.x, y: p.y }} 缩放={s} 锚对齐={s} 文字={换了 ? 台词气泡字 : 气泡字} 字体={像素字} 弹出={弹出} />;
};

/** 樱花风从这里散开（页面坐标）：门推开到底那一刻，她脚底以上 风散心高 那一点在画面上的位置。花瓣先从推开的门里她的背影那块吹开 */
export const 风散心 = (() => {
  const 机 = 重逢机位(事.推门.秒 + 推门.开秒);
  const cam = 做透视相机({ 眼: Z朝上转three(机.眼), 看: Z朝上转three(机.看), 视角: 机.视角, 宽: 画幅.宽, 高: 画幅.高 });
  const p = 投影到页面(cam, Z朝上转three([她.脚[0], 她.脚[1], 她.脚[2] + 风散心高]), 画幅.宽, 画幅.高);
  return { x: p.x, y: p.y };
})();

/** 换掉画里的她（15 尾硬切到她的笑用）：按这一刻的秒、你的眼睛画，放在原来她的位置（描边、不褪色那一层里） */
export type 换她 = (秒: number, 眼: V3) => React.ReactNode;

export type 重逢画面属性 = {
  /** 歌曲帧 */
  帧: number;
  /** 不给 = 重逢她（回头、认出你、拿着花） */
  她?: 换她;
  /** 给了就整句换成这一句、不「啵」（15 尾硬切过来气泡已经换好）；不给 = 哭脸，驯服起换台词 */
  气泡字?: string;
  /** 叠在 3D 和气泡上面、整片后期里面的 2D（聊天栏、樱花风） */
  叠层?: React.ReactNode;
  描边?: boolean;
  后期?: boolean;
};

/** 一整帧（1280×720 页面），自己铺满 */
export const 重逢画面: React.FC<重逢画面属性> = ({ 帧, 她: 换, 气泡字: 字, 叠层, 描边: 描 = 描边默认.开, 后期 = true }) => {
  const 秒 = 帧 / fps;
  const t = 色板[调子];
  const 机 = 重逢机位(秒);
  return (
    <整片后期 调色={后期 ? t.调色 : null}>
      <三渲二画布 宽={画幅.宽} 高={画幅.高} 机位={机} {...画布调子(调子)} 色调={门光色调} 发光区={重逢发光区}>
        <场景 帧={帧} 秒={秒} 眼={机.眼} 描边={描} 她={换} />
      </三渲二画布>
      <手 帧={帧} 描边={描} />
      <气泡 帧={帧} 机={机} 字={字} />
      {叠层}
    </整片后期>
  );
};
