// 第 6、7 句的声音：雨声（两段一直下，破云起收掉）、第 6 句一声闷雷、第 7 句光柱撞云时的信标声。按歌曲帧排，段.ts 用 声音/跨段音效.ts 切出落在自己窗口里的那一截。
// 纯数据。增益、文件长度在 参数.ts。
import { clamp01 } from '@engine/anim/anim.ts';
import { fps, 正片事件 } from '../../分镜.ts';
import type { 歌上音效 } from '../../声音/跨段音效.ts';
import * as 参 from './参数.ts';

/** 雨量（0～1，歌曲帧）：破云前满，破云到阳光铺地之间收到 0（演绎：原版雨停要 5 秒，雨量每刻减 0.01） */
export const 雨量 = (帧: number) => clamp01((正片事件.阳光铺地.帧 - 帧) / (正片事件.阳光铺地.帧 - 正片事件.破云.帧));

/** 雨声：rain 1～4 首尾相接，从第 6 句起一直接到雨停 */
export const 雨声们: readonly 歌上音效[] = (() => {
  const out: 歌上音效[] = [];
  const 止 = 正片事件.阳光铺地.帧;
  for (let 起 = 正片事件.第6句开口.帧, k = 0; 起 < 止; k++) {
    const 文件 = 参.雨声们[k % 参.雨声们.length]!;
    const 帧数 = Math.min(Math.round(文件.秒 * fps), 止 - 起);
    out.push({ 资产: 文件.资产, 名: `雨声${k + 1}`, 起帧: 起, 帧数, 时长秒: 文件.秒, 增益: (帧) => 参.雨声增益 * 雨量(帧) });
    起 += 帧数;
  }
  return out;
})();

/** 闷雷：滚雷和闪光同时到；她站起来放法术（第 7 句首字）之前淡掉，只落在 2-雷雨 里 */
const 雷起 = 正片事件.第6句闷雷.帧 - Math.round(参.雷声.提前秒 * fps);
const 雷止 = 正片事件.她站起.帧;
export const 雷: 歌上音效 = {
  资产: 参.雷声.资产,
  名: '闷雷',
  起帧: 雷起,
  帧数: 雷止 - 雷起,
  时长秒: 参.雷声.秒,
  增益: (帧) => 参.雷声.增益 * clamp01((雷止 - 帧) / 参.雷声.淡出),
};

/** 信标声：「拨」那一帧起放，接第 8 句时截掉，截之前淡掉 */
const 信标起 = 正片事件.拨.帧;
const 信标止 = 正片事件.第8句开口.帧;
export const 信标: 歌上音效 = {
  资产: 参.信标声.资产,
  名: '信标激活',
  起帧: 信标起,
  帧数: 信标止 - 信标起,
  时长秒: 参.信标声.秒,
  增益: (帧) => 参.信标声.增益 * clamp01((信标止 - 帧) / 参.信标声.淡出),
};
