// 新世界这一场每一帧的样子：镜头在哪（钻进图标时往前冲、你起步后往前往下落到剖面）、游戏时间（下午；第 2 句边挖边天黑）、剖面撤到第几排、你（史蒂夫）站哪、朝哪、走了几步。
// 纯计算（不 import react、three），测试直接引。按歌曲帧算：2-初入、2-第一晚 两段一镜不切，都从这里取，接缝那一帧才对得上。
// 钻入的进度由段算好传进来（钻入的帧数在 场/2-选择世界：场只接上一场的末态，这一场不引它）；别的时刻对 分镜.ts 的正片事件。
import type { V3 } from '@engine/model/parts.tsx';
import { fps, 正片事件 } from '../../分镜.ts';
import { 地面高 } from './地形.ts';
import { 天亮 } from '../../地点/天体.ts';
import { 你, 到了, 剖面, 剥帧, 坑, 机位们, 聊天, 走速, type 机位帧 } from './参数.ts';

const clamp01 = (x: number) => Math.min(1, Math.max(0, x));
const 平滑 = (q: number) => q * q * (3 - 2 * q);
const 插 = (a: number, b: number, k: number) => a + (b - a) * k;
const 插机位 = (a: 机位帧, b: 机位帧, k: number): 机位帧 => ({
  眼: a.眼.map((v, i) => 插(v, b.眼[i]!, k)) as unknown as V3,
  看: a.看.map((v, i) => 插(v, b.看[i]!, k)) as unknown as V3,
  视角: 插(a.视角, b.视角, k),
});

// ---------- 镜头 ----------

/** 落镜进度（0～1，缓起缓停）：你起步那一帧起，到剖开那一帧落到剖面 */
export const 落镜 = (歌帧: number) => 平滑(clamp01((歌帧 - 正片事件.第1句起步.帧) / (正片事件.第1句剖开.帧 - 正片事件.第1句起步.帧)));

/**
 * 镜头：钻 = 钻进图标的进度（0～1，线性，段算好传进来；钻完以后给 1）。
 * 钻的时候从 钻起 冲到 落定，越来越慢（缓出，接住图标放大越来越快的那股劲）；你起步以后从 落定 落到 剖面，之后不动
 */
export const 机位在 = (钻: number, 歌帧: number): 机位帧 => {
  const k = 落镜(歌帧);
  if (k > 0) return 插机位(机位们.落定, 机位们.剖面, k);
  const p = clamp01(钻);
  return 插机位(机位们.钻起, 机位们.落定, 1 - (1 - p) ** 2);
};

// ---------- 游戏时间 ----------

/** 真时间的刻（第 1 句加入游戏那一帧起算） */
const 实刻 = (歌帧: number) => ((歌帧 - 正片事件.第1句加入游戏.帧) * 20) / fps;

/** 在 [低, 高] 里二分：仍是 对 的最后一刻、不再 对 的第一刻（对 在 低 那头成立、高 那头不成立） */
const 二分 = (对: (刻: number) => boolean, 低: number, 高: number) => {
  for (let i = 0; i < 60; i++) {
    const m = (低 + 高) / 2;
    if (对(m)) 低 = m;
    else 高 = m;
  }
  return [低, 高] as const;
};
/** 原版天亮程度的四个拐点（第一天）：傍晚刚要从 1 往下掉（约 11870）、刚掉到 0（约 13670）；黎明刚要从 0 往上（约 22330）、刚升到 1（约 24130） */
export const 亮尽刻 = 二分((t) => 天亮(t) >= 1, 6000, 18000)[0];
export const 黑透刻 = 二分((t) => 天亮(t) > 0, 6000, 18000)[1];
export const 破晓刻 = 二分((t) => 天亮(t) <= 0, 18000, 30000)[0];
export const 亮满刻 = 二分((t) => 天亮(t) < 1, 18000, 30000)[1];

/** 天亮程度在 [低, 高] 里单调（傍晚往下、黎明往上）：返回天亮正好走到 亮 的那一刻 */
export const 天亮到 = (亮: number, 低: number, 高: number) => {
  const 升 = 天亮(高) > 天亮(低);
  return 二分((t) => (升 ? 天亮(t) < 亮 : 天亮(t) > 亮), 低, 高)[1];
};

const 入夜起 = 正片事件.第1句推完.帧, 入夜止 = 正片事件.填土.帧;

/** 第 1 句、第 2 句的游戏刻：第 1 句整句是下午（天亮 1，太阳在背后偏西不进画），第 2 句首字那一帧正好走到 亮尽刻；
 *  从第 2 句首字到填土那一拍，天亮程度缓起缓停地从 1 掉到 0（边挖边天黑：挖第一格时还亮、填土那一拍黑透，星星跟着出来），之后照真时间接着走。
 *  按天亮缓动而不按刻缓动：天亮只在日落前后那 1800 刻里掉，按刻缓动的话天黑挤在几帧里。
 *  核查 10-24：原来入夜在第 1 句最后一秒，和落镜、撤排、换歌词叠在一起；挪到第 2 句里，第 1 句尾只剩剖开这一件事。演绎，Agent 暂定 */
export const 天刻在 = (歌帧: number) => {
  if (歌帧 <= 入夜起) return 亮尽刻 + 实刻(歌帧) - 实刻(入夜起);
  if (歌帧 < 入夜止) return 天亮到(1 - 平滑((歌帧 - 入夜起) / (入夜止 - 入夜起)), 亮尽刻, 黑透刻);
  return 黑透刻 + 实刻(歌帧) - 实刻(入夜止);
};

/** 聊天栏的钟（刻，加入游戏那一帧 0）：起步前照真时间；起步后加快，「Steve加入了游戏」在剖开那一帧正好走完原版的 200 刻（最后 20 刻淡掉，铺在 聊天.淡帧 帧里），
 *  剖开、第 2 句里没有聊天字（文字一时只走一路，用户 10-24 规矩 看得懂的速度；撤排从左下角扫上去，聊天行先淡掉） */
const 淡起 = 正片事件.第1句剖开.帧 - 聊天.淡帧;
export const 聊天刻在 = (歌帧: number) => {
  const 起 = 正片事件.第1句起步.帧;
  if (歌帧 <= 起) return 实刻(歌帧);
  if (歌帧 <= 淡起) return 实刻(起) + (180 - 实刻(起)) * 平滑((歌帧 - 起) / (淡起 - 起));
  if (歌帧 <= 正片事件.第1句剖开.帧) return 180 + (20 * (歌帧 - 淡起)) / 聊天.淡帧;
  return 200 + 实刻(歌帧) - 实刻(正片事件.第1句剖开.帧);
};

// ---------- 剖面 ----------

/** 撤掉了几排（0～剖面.剥排）：剖开那一帧起，每 剥帧 帧从镜头脚下往坑那边撤一排 */
export const 剥了 = (歌帧: number) => Math.min(剖面.剥排, Math.max(0, Math.floor((歌帧 - 正片事件.第1句剖开.帧) / 剥帧) + 1));

// ---------- 你 ----------

/** 出生点到坑那一格的距离、方向（yaw，同 stevePose：0 朝北、正 = 往左） */
const 终点 = [坑.i + 0.5, 坑.j + 0.5] as const;
const 路长 = Math.hypot(终点[0] - 你.脚[0], 终点[1] - 你.脚[1]);
export const 走向 = -Math.atan2(终点[0] - 你.脚[0], 终点[1] - 你.脚[1]) * (180 / Math.PI);

/** 原版平地上的走：按住前进时每刻速度往 走速 收 40%（同 库/角色/史蒂夫.tsx vanillaWalk 的 fromRest），位置是它的累加；
 *  松开以后每刻速度乘 0.546（草地滑度 0.6 × 空气阻力 0.91），滑一小段停下。步幅（limbSwingAmount）每刻往目标收 40%，limbSwing 累加步幅 */
const 每刻 = 走速 / 20;
const 按住走出 = (刻: number) => 每刻 * (刻 - (0.6 * (1 - 0.6 ** 刻)) / 0.4);
const 按住速度 = (刻: number) => 每刻 * (1 - 0.6 ** 刻);
const 松开滑 = (v: number, 刻: number) => (v * 0.546 * (1 - 0.546 ** 刻)) / (1 - 0.546);
/** 松开的那一刻（起步后几刻）：按住走出 + 滑到停 = 路长（二分） */
export const 松开刻 = (() => {
  let lo = 0, hi = 200;
  for (let n = 0; n < 60; n++) {
    const m = (lo + hi) / 2;
    if (按住走出(m) + 松开滑(按住速度(m), Infinity) < 路长) lo = m;
    else hi = m;
  }
  return (lo + hi) / 2;
})();
const 步幅目标 = Math.min(1, (走速 / 20) * 4);

/** 起步后 刻 刻：走出多远（格）、limbSwing、步幅 */
export const 走 = (刻: number): { 出: number; 摆: number; 步幅: number } => {
  if (刻 <= 0) return { 出: 0, 摆: 0, 步幅: 0 };
  const 按刻 = Math.min(刻, 松开刻);
  const 按摆 = 步幅目标 * (按刻 - (0.6 * (1 - 0.6 ** 按刻)) / 0.4);
  if (刻 <= 松开刻) return { 出: 按住走出(刻), 摆: 按摆, 步幅: 步幅目标 * (1 - 0.6 ** 刻) };
  const 松 = 刻 - 松开刻;
  const 幅0 = 步幅目标 * (1 - 0.6 ** 松开刻);
  return { 出: 按住走出(松开刻) + 松开滑(按住速度(松开刻), 松), 摆: 按摆 + (幅0 * 0.6 * (1 - 0.6 ** 松)) / 0.4, 步幅: 幅0 * 0.6 ** 松 };
};

/** 停稳的那一帧（歌曲帧）：松开后滑 8 刻（剩不到 0.01 格），之后转身、低头 */
export const 停稳帧 = 正片事件.第1句起步.帧 + Math.ceil(((松开刻 + 8) * fps) / 20);

export type 你的样子 = {
  脚: V3;
  /** 身子朝向（度，同 stevePose 的 yaw） */
  朝向: number;
  /** 头的俯仰（度，负 = 低头） */
  头: number;
  /** 原版 limbSwing、limbSwingAmount（给 stevePose） */
  摆: number;
  步幅: number;
  /** 游戏时间（秒），两臂的轻晃 */
  秒: number;
};

/** 第 歌帧 帧你的样子：站在出生点朝着樱花林，起步走到坑那一格停下，转身朝东、低头看脚下（2-第一晚 从这个样子接着挖） */
export const 你在 = (歌帧: number): 你的样子 => {
  const 刻 = ((歌帧 - 正片事件.第1句起步.帧) * 20) / fps;
  const w = 走(刻);
  const a = (走向 * Math.PI) / 180;
  const d = Math.min(路长, w.出);
  const x = 你.脚[0] - Math.sin(a) * d, y = 你.脚[1] + Math.cos(a) * d;
  const 脚: V3 = [x, y, 地面高(Math.floor(x), Math.floor(y))];
  const 转 = clamp01((歌帧 - 停稳帧) / 到了.转身帧);
  const 低 = clamp01((歌帧 - 停稳帧 - 到了.转身帧) / 到了.低头帧);
  return { 脚, 朝向: 插(走向, 到了.朝向, 平滑(转)), 头: 插(0, 到了.头, 平滑(低)), 摆: w.摆, 步幅: w.步幅, 秒: 歌帧 / fps };
};
