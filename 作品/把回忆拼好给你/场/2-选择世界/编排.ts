// 选择世界这一场每一帧的样子（光标在哪、指没指着那一项、选没选中、搜索框光标亮不亮、钻进图标到哪了、片尾碎片飞到哪了），按歌曲帧算：
// 2-选择世界、2-初入 一镜不切，两段都从这里取，接缝那一帧才对得上。纯计算（不 import react、three），测试直接引。
// 时刻从 分镜.ts 的正片事件来，比例、帧数在 参数.ts。
import { fps, 正片事件 } from '../../分镜.ts';
import { 散, 图标边 } from '../../界面/实例图标.ts';
import { 光标, 取景中心, 尺, 存档, 界面, 碎片, 钻入, 片尾白, 片尾拉回, 回色弹, 闪刻 } from './参数.ts';

const clamp01 = (x: number) => Math.min(1, Math.max(0, x));
const 平滑 = (q: number) => q * q * (3 - 2 * q);

/** 存档那一格图标的界面像素框 */
export const 图标框 = { x: 界面.行.左, y: 界面.行.顶, 边: 界面.图标边 };
const 图标心 = { x: 图标框.x + 图标框.边 / 2, y: 图标框.y + 图标框.边 / 2 };

/** 平常的取景（第 0 镜、片尾） */
export const 平常取景 = { 中心: { ...取景中心 }, 尺 };

// ---------- 存档那一行的字 ----------

/** 原版 WorldListEntry 的第二行：存档文件夹名 + 「 (」+ 上次游玩时间 + 「)」。时间是 new SimpleDateFormat()（Java 17、zh_CN 的短格式 y/M/d ah:mm：
 *  月日不补零，十二小时制、0 点写 12，上午下午写在前面） */
export const 上次游玩字 = (t: { 年: number; 月: number; 日: number; 时: number; 分: number }) => {
  const 午 = t.时 < 12 ? '上午' : '下午';
  const 时 = t.时 % 12 === 0 ? 12 : t.时 % 12;
  return `${t.年}/${t.月}/${t.日} ${午}${时}:${String(t.分).padStart(2, '0')}`;
};

/** 三行字：存档名（白）、文件夹名和上次游玩、模式和版本（LevelSummary.getInfo：模式 + 「, 」+ 版本： + 「 」+ 版本号） */
const 三行 = (t: typeof 存档.上次游玩 | typeof 存档.重逢游玩) => [存档.名, `${存档.名} (${上次游玩字(t)})`, `${存档.模式}, 版本： ${存档.版本}`] as const;
/** 第 0 镜、片尾回色前：上次游玩是去年 */
export const 行字 = 三行(存档.上次游玩);
/** 片尾回色起：上次游玩换成这次重逢 */
export const 重逢行字 = 三行(存档.重逢游玩);

// ---------- 第 0 镜：光标、指着、选中 ----------

/** 光标箭头尖（界面像素，取到半个界面像素：光标一个光标像素一个光标像素地走）；开场鼓点那一帧（点下去）还在，之后钻进图标就不画了 */
export const 光标在 = (歌帧: number): { x: number; y: number } | null => {
  const 入 = 正片事件.开场光标入.帧, 到 = 正片事件.开场光标到.帧, 按 = 正片事件.开场鼓点.帧;
  if (歌帧 < 入 || 歌帧 > 按) return null;
  const q = 平滑(clamp01((歌帧 - 入) / (到 - 入)));
  const 取半 = (v: number) => Math.round(v * 2) / 2;
  return { x: 取半(光标.起.x + (光标.停.x - 光标.起.x) * q), y: 取半(光标.起.y + (光标.停.y - 光标.起.y) * q) };
};

/** 指着那一项时图标上蒙灰、画播放箭头：0 没指着；1 指着字那边（灰箭头，world_selection v 0）；2 指着图标（蓝箭头，v 32）。
 *  点下去那一帧起不画（钻进去的是照片，不是蒙着灰的播放键） */
export const 指着在 = (歌帧: number): 0 | 1 | 2 => {
  if (歌帧 >= 正片事件.开场鼓点.帧) return 0;
  const c = 光标在(歌帧);
  const r = 界面.指着;
  if (!c || c.x < r.左 || c.x >= r.右 || c.y < r.上 || c.y >= r.下) return 0;
  return c.x < 界面.行.左 + 界面.图标边 ? 2 : 1;
};

/** 点下去以后选中了那一项（原版 setSelected：选中框；列表拿走焦点，搜索框白边变灰、光标不闪了） */
export const 选中在 = (歌帧: number) => 歌帧 >= 正片事件.开场鼓点.帧;

/** 搜索框里的「_」亮不亮：拿着焦点时按原版 EditBox 的刻数闪（界面一打开 frame 从 0 数，第 0 帧亮）；段内帧给 起帧 = 这一段界面打开的歌曲帧 */
export const 框光标亮 = (歌帧: number, 起帧 = 0) => Math.floor(Math.floor(((歌帧 - 起帧) * 20) / fps) / 闪刻) % 2 === 0;

// ---------- 第 1 句开头：钻进图标 ----------

/** 钻入进度 0～1（开场鼓点那一帧是 0，钻入.帧 − 1 帧后是 1：最后一帧有界面的画面图标已经铺满、照片全透，下一帧去掉界面不跳）和缓入后的 q */
export const 钻入进度 = (歌帧: number) => {
  const p = clamp01((歌帧 - 正片事件.开场鼓点.帧) / (钻入.帧 - 1));
  return { p, q: p ** 钻入.缓入 };
};

/** 钻到 q 时的取景：尺 按指数从 尺 涨到 终尺；图标中心在画面上的位置从原来那里线性挪到画面正中 */
export const 钻入取景 = (q: number) => {
  const s = 尺 * (钻入.终尺 / 尺) ** q;
  const dx = (图标心.x - 取景中心.x) * 尺 * (1 - q);
  const dy = (图标心.y - 取景中心.y) * 尺 * (1 - q);
  return { 中心: { x: 图标心.x - dx / s, y: 图标心.y - dy / s }, 尺: s };
};

const 拜耳 = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
/** 4×4 Bayer 阈值（0～1 之间）：透掉的比例超过它的那个照片像素就透掉（同 界面/符文歌词.tsx 的抖动） */
export const 阈 = (i: number, j: number) => (拜耳[(j & 3) * 4 + (i & 3)]! + 0.5) / 16;

/** 钻到 q 时图标透掉了多少（0～1） */
export const 钻入透 = (q: number) => clamp01((q - 钻入.透起) / (钻入.透满 - 钻入.透起));

/** 钻到 q 时调子从现实（界面）往夏日白天（新世界）走了多少：跟着图标透掉的比例走 */
export const 钻入回暖 = (q: number) => 平滑(clamp01(q / 钻入.透满));

// ---------- 片尾：白一闪、从图标跟前拉回、碎片拼回、回色 ----------

/** 片尾第 f 帧（段内，0 = 片尾白光 = 咔哒那一帧）的取景：钻入取景 倒着走，q 从 起尺 对应的那一点按 (1 − p)^缓出 收到 0（平常取景） */
export const 片尾取景 = (f: number) => {
  const q0 = Math.log(片尾拉回.起尺 / 尺) / Math.log(钻入.终尺 / 尺);
  const q = q0 * (1 - clamp01(f / 片尾拉回.帧)) ** 片尾拉回.缓出;
  return q <= 0 ? 平常取景 : 钻入取景(q);
};

const 块数 = 图标边 / 碎片.碎块边;
const 块界面边 = (图标框.边 * 碎片.碎块边) / 图标边;

/** 一块碎片：第 (i, j) 块（从左上数），从 起 飞进图标框里它那一格 */
export type 碎块 = { i: number; j: number; 起: { x: number; y: number }; 起倍: number; 起帧: number };

/** 16 块碎片，起点在图标框四周一圈（离图标中心 碎片.远 界面像素，横向拉宽 1.6 倍贴合宽画面；方向、远近、起飞帧、大小都按散列定死） */
export const 碎块们: readonly 碎块[] = Array.from({ length: 块数 * 块数 }, (_, n) => {
  const i = n % 块数, j = Math.floor(n / 块数);
  const 角 = Math.atan2(j - (块数 - 1) / 2, i - (块数 - 1) / 2) + (散(i, j, 1) - 0.5) * 2.2;
  const 远 = 碎片.远[0] + (碎片.远[1] - 碎片.远[0]) * 散(i, j, 2);
  return {
    i,
    j,
    起: { x: 图标心.x + Math.cos(角) * 远 * 1.6, y: 图标心.y + Math.sin(角) * 远 },
    起倍: 碎片.起倍[0] + (碎片.起倍[1] - 碎片.起倍[0]) * 散(i, j, 3),
    起帧: 碎片.首帧 + Math.floor(散(i, j, 4) * 碎片.错开帧),
  };
});

export type 碎块态 = { x: number; y: number; 边: number; 到: boolean };

/** 片尾第 f 帧（段内，0 = 片尾白光）这块碎片在哪（左上角，界面像素）、多大；还没起飞的不画（null）、到了的就在格子里 */
export const 碎块在 = (块: 碎块, f: number): 碎块态 | null => {
  if (f < 块.起帧) return null;
  const p = clamp01((f - 块.起帧) / 碎片.飞帧);
  const q = p ** 碎片.缓入;
  const 终 = { x: 图标框.x + 块.i * 块界面边, y: 图标框.y + 块.j * 块界面边 };
  const 倍 = 块.起倍 + (1 - 块.起倍) * q;
  const 边 = 块界面边 * 倍;
  // 中心从起点直线飞到格子中心
  const cx = 块.起.x + (终.x + 块界面边 / 2 - 块.起.x) * q;
  const cy = 块.起.y + (终.y + 块界面边 / 2 - 块.起.y) * q;
  return { x: cx - 边 / 2, y: cy - 边 / 2, 边, 到: p >= 1 };
};

/** 片尾第 f 帧（段内）的白光不透明度：第 0 帧纯白，(1 − f/闪白帧)² 几帧就退完 */
export const 片尾白光 = (f: number) => (f >= 0 && f < 片尾白.闪白帧 ? (1 - f / 片尾白.闪白帧) ** 2 : 0);

/** 回色时图标弹出去几个界面像素 */
export const 片尾弹 = (f: number, 回色帧: number) => (f >= 回色帧 && f < 回色帧 + 回色弹.弹帧 ? 回色弹.弹 : 0);
