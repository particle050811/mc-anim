// 第 14 句（段 2-归隐）的符文歌词怎么摆：第 1～14 句照全片在顶上，第 15 句「爱炙热的你却忘了爱自己」放到底部（三稿第 15 句的特例，同 2-摇铃 的底部歌词）。
// 核查 10-24：原来第 15 句在顶上进场，合屏那 9 帧压在太阳和树冠上（合屏画面同 2-摇铃 开头，太阳不能挪）。
// 纯模块（测试也读）：顶上那一套少了第 15 句，第 14 句退场照有第 15 句时一样算（接下句收），测试逐帧核两种算法一样。
import { 符文歌词默认, 解码时段, type 时间样式, type 符文歌词样式, type 符文歌词行 } from '../../界面/符文排版.ts';
import { 正片歌词行 } from '../../界面/符文歌词数据.ts';

/** 底部那一句的样式：只把位置换成「下」，边距、字点、颜色、进出同全片 */
export const 第15句符文样式: Readonly<符文歌词样式> = { ...符文歌词默认, 位置: '下' };

/** 一句后面接着 下 一句时从哪一帧起退场（界面/符文排版.ts 的 字状态 里有下一句时那条算法）：顶上那一套拿掉第 15 句以后当 收 给，第 14 句照样按第 15 句进场让开 */
export const 接下句收 = (行: 符文歌词行, 下: 符文歌词行, 样式: 时间样式): number => {
  const 末解完 = Math.max(...解码时段(行, 样式).map((d) => d.完));
  return Math.max(下.入 - 样式.出帧, Math.min(末解完, 下.入), 行.入 + 样式.入帧);
};

/** 段 2-归隐 的两套歌词（帧都是段内帧）：顶上第 1～14 句和它的 收，底部第 15 句 */
export const 归隐歌词 = (起帧: number) => {
  const 上行们 = Array.from({ length: 14 }, (_, i) => 正片歌词行(i + 1, 起帧));
  const 第15行 = 正片歌词行(15, 起帧);
  return { 上行们, 上收: 接下句收(上行们[13]!, 第15行, 符文歌词默认), 下行们: [第15行] };
};
