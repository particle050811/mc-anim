// 分屏线淡（47.66）：分屏线 4 帧淡完，纸、花瓣飘过线就混到对面。挂铃（47.83）：换成整屏镜头（同 2-摇铃 开头），纸和花瓣接着飘（纸花.ts 按歌上的秒算，一刀两边一样），
//   她已经在告示牌前挂上寻风之铃；她消失（48.26）：她和合照一起不见了，门开着、屋里空了，墙上四张夏天的照片亮着、合照格空着，接 2-摇铃 第一帧。
