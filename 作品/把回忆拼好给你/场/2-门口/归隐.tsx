/** 栏杆顶在画面上的线（栏杆后沿，斜投影里抬 一格 × 顶面 ÷ N）：页面 y */
const 栏杆顶线 = 楼上投(0, 栏杆.顶 + 楼上顶面 / 归隐N).y;
