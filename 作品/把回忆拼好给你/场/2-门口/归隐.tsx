// ---------- 她 ----------
const 原显示 = DISPLAY.generated.thirdperson_righthand;
const 放大 = (k: number) => ({ ...原显示, scale: (原显示.scale ?? [1, 1, 1]).map((v) => v * k) as [number, number, number] });
const 花物 = <月铃兰 />;

/** 她（墙前在左屏，地图画按 N = 8 的 64；合屏以后整屏 N = 10 的 32）。倍 = 放大几倍（绕脚底）：左屏 她倍（同第 13 句），合屏同 2-摇铃 的你（1 倍） */
const 她: React.FC<{ 态: 她态; 秒: number; 倍: number; 边长: typeof 照片墙边长 }> = ({ 态, 秒, 倍, 边长 }) => {
  const 位: V3 = [态.x, 门口.站排y, 0];
  // 手里的花、合照总是正面朝镜头（偏 = 从她正前方往她左边转几度）：她转身向照片墙时物品不侧过去变成一条线
  const 偏 = 墙前朝向 - 态.yaw;
  const 拿 = (x: '花' | '合照' | null): 手持物 | undefined =>
    x === '花'
      ? { 物品: 花物, 朝向: { 偏 }, 显示: 放大(花倍) }
      : x === '合照'
        ? { 物品: <手持地图画 画={合照} 边长={边长} />, 朝向: { 偏 }, 显示: 放大(合照手持倍) }
        : undefined;
  // 贴图像素对齐 只吸附脚底
  return (
    <贴图像素对齐 锚={位}>
      <group position={位} scale={倍}>
        <group position={[-位[0], -位[1], -位[2]]}>
          <MagicalWineFoxEx
            pose={{ ...standPose(位), yaw: 态.yaw }}
            姿势="站"
            表情={态.表情}
            看={态.看}
            眨眼={0}
            秒={秒}
            右手={拿(态.右手)}
            左手={拿(态.左手)}
            骨骼={态.骨骼}
          />
        </group>
      </group>
    </贴图像素对齐>
  );
};

// ---------- 铃 ----------
/** 刚挂上的铃绕挂点摆的角（度）：挂铃那一刻碰一下，衰减着摆，段尾前收到 0（2-摇铃 开头铃是静的） */
const 挂铃角 = (秒: number) => {
  const t = 秒 - 事.挂铃.秒;
  if (t < 0) return 0;
  return 挂铃摆.振幅 * Math.sin((t / 挂铃摆.周期) * Math.PI * 2) * 挂铃摆.衰减 ** t * clamp01((段尾秒 - 1 / fps - 秒) / 0.25);
};

/** 挂着的铃（同 摇铃.tsx 的 挂着的铃：正对镜头的物品薄片绕挂点摆，挂绳一个铃像素宽） */
const 挂着的铃: React.FC<{ 角: number }> = ({ 角 }) => {
  const s = 铃.大小;
  return (
    <group position={铃.挂点} rotation={[0, rad(-角), 0]}>
      <mesh position={[0, 0, -(铃.垂 - s / 2) / 2]}>
        <boxGeometry args={[s / 16, s / 16, 铃.垂 - s / 2]} />
        <meshStandardMaterial color="#5a3a22" roughness={1} />
      </mesh>
      <group position={[0, 0, -铃.垂]} rotation={[Math.PI / 2, 0, 0]} scale={s}>
        <寻风之铃 />
      </group>
    </group>
  );
};

// ---------- 调子 ----------
const 中性: 调色 = { 饱和: 1, 对比: 1, 乘: '#ffffff', 抬: '#000000', 暗角: 0, 颗粒: 0 };
const 只调色 = (t: 调色): 调色 => ({ ...t, 暗角: 0, 颗粒: 0 });
/** 合屏以后（同 2-摇铃 开头）：褪色往夏日白天回 1/3 */
export const 合屏调子 = 插调子(色板.褪色, 色板.夏日白天, 回色.起);
/** 左屏的调子：第 13 句末那样一路褪到合屏那样 */
export const 左调子 = (帧: number) =>
  帧 >= 事.挂铃.帧 ? 合屏调子 : 插调子(色板.夏日白天, 色板.褪色, 褪色起 + (褪色止 - 褪色起) * clamp01((帧 - 窗.起帧) / (事.挂铃.帧 - 窗.起帧)));

/** 你在楼下这一帧的头：纸飘下 后 仰头迟 帧起仰起来 */
const 你的头于 = (帧: number): [number, number] => {
  const t = clamp01((帧 - 事.纸飘下.帧 - 仰头迟) / 仰头帧);
  const k = t * t * (3 - 2 * t);
  return [你的头.低[0] + (你的头.仰[0] - 你的头.低[0]) * k, 你的头.低[1] + (你的头.仰[1] - 你的头.低[1]) * k];
};

/** 分屏线这一帧的不透明度：分屏线淡 起 4 帧淡完（挂铃那一帧合屏） */
const 线不透明 = (帧: number) => clamp01((事.挂铃.帧 - 帧) / (事.挂铃.帧 - 事.分屏线淡.帧 + 1));

export type 归隐画面属性 = {
  /** 歌曲帧（分镜.ts 的时间轴） */
  帧: number;
  描边?: boolean;
  /** 整片后期开关（默认开） */
  后期?: boolean;
  /** 整页那层颗粒的种子（整片后期），段里给歌曲帧 */
  种子?: number;
  /** 盖在最上面、整页质感里面的东西（符文歌词），页面坐标 1280×720 */
  叠层?: React.ReactNode;
};

export const 归隐画面: React.FC<归隐画面属性> = ({ 帧, 描边 = 描边默认.开, 后期 = true, 种子, 叠层 }) => {
  const 秒 = 帧 / fps;
  const 她态 = 她于(帧);
  const 牌字 = <告示牌像素字 行们={告示牌行们} />;

  if (帧 >= 事.挂铃.帧) {
    // 合屏：整屏镜头（同 2-摇铃 开头），她在告示牌前挂铃，她消失 以后和合照一起不见了；纸和花瓣接着飘
    return (
      <整片后期 调色={后期 ? 合屏调子.调色 : null} 种子={种子}>
        <div style={{ position: 'absolute', inset: 0 }}>
          <林间门口画布
            宽={画幅.宽}
            高={画幅.高}
            {...整屏镜头}
            刻={白天刻}
            调子={合屏调子}
            门开
            树进度={1}
            告示牌
            告示牌字={牌字}
            照片墙={照片墙格们(第8句照片们, null)}
            照片墙边长={合屏照片墙边长}
            叠层={<纸花层 秒={秒} />}
          >
            <挂着的铃 角={挂铃角(秒)} />
            {她态 && <她 态={她态} 秒={秒} 倍={1} 边长={合屏照片墙边长} />}
          </林间门口画布>
          {叠层}
        </div>
      </整片后期>
    );
  }

  const 左调 = 左调子(帧);
  const { 左宽, 右宽, 线宽, 线色 } = 归隐版式;
  const 高 = 画幅.高;
  const 套 = (t: 调色, 内容: React.ReactNode) => (后期 ? <整片后期 调色={只调色(t)}>{内容}</整片后期> : 内容);
  const 质感: 调色 = { ...中性, 暗角: (色板.现实.调色.暗角 + 左调.调色.暗角) / 2, 颗粒: (色板.现实.调色.颗粒 + 左调.调色.颗粒) / 2 };
  const 页 = (
    <div style={{ position: 'absolute', inset: 0, background: '#000' }}>
      <div style={{ position: 'absolute', left: 0, top: 0, width: 左宽, height: 高, overflow: 'hidden' }}>
        {套(
          左调.调色,
          <林间门口画布
            宽={左宽}
            高={高}
            取景={左取景}
            描边宽={归隐N}
            刻={归隐刻}
            弧={左天弧}
            调子={左调}
            树进度={1}
            告示牌
            告示牌字={牌字}
            照片墙={照片墙格们(第8句照片们, 帧 >= 事.取照.帧 ? null : 合照)}
            照片墙边长={照片墙边长}
            叠层={<纸花层 秒={秒} 宽={中线} />}
          >
            {她态 && <她 态={她态} 秒={秒} 倍={她倍} 边长={照片墙边长} />}
          </林间门口画布>,
        )}
      </div>
      <div style={{ position: 'absolute', left: 左宽, top: 0, width: 右宽, height: 高, overflow: 'hidden' }}>
        {套(
          色板.现实.调色,
          <>
            <现实画布 宽={右宽} 高={高} 取景={楼下取景} 顶面={楼下顶面} 天={楼下天色} 描边={描边} 描边宽={归隐N}>
              <楼下 头={你的头于(帧)} 秒={秒} />
            </现实画布>
            <纸花层 秒={秒} 左={中线} 宽={1280 - 中线} />
          </>,
        )}
      </div>
      <div style={{ position: 'absolute', left: 左宽, top: 0, width: 线宽, height: 高, background: 线色, opacity: 线不透明(帧) }} />
      {叠层}
    </div>
  );
  return 后期 ? (
    <整片后期 调色={质感} 种子={种子}>
      {页}
    </整片后期>
  ) : (
    页
  );
};
