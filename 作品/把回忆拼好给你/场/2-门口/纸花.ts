/** 纸得在哪一刻以前全落出画面：2-摇铃 最后一帧（风散开 那一拍转场，2-重逢 不画纸） */
export const 纸落完秒 = 事.风散开.秒 - 1 / 24;

/** 分屏的中线（页面 x）：合屏前，纸只在右边、花瓣只在左边 */
export const 中线 = 归隐版式.左宽;

/** 合屏起：这一刻在现实那半里的纸从此留在画面上（推走现实那半时纸留下来），之前飘过线的纸已经出了右屏、不再出来 */
export const 混起 = 事.合屏起.秒;

/** 花瓣从哪一刻起生（2-归隐 第一帧画面里已经飘满）到哪一刻（2-摇铃 转场）；生在画面上沿外 出发高 页面像素，右边多生一截（往左飘着进画） */
const 生起 = 事.第14句分屏.秒 - 6;
const 生止 = 事.风散开.秒;
const 出发高 = 48;
const 左余 = 40;
const 右余 = 400;

/** 同 engine/model/parts.tsx 的 rng（mulberry32；纯模块不引 tsx） */
const rng = (seed: number) => {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};

const 取 = (a: readonly [number, number], r: () => number) => a[0] + r() * (a[1] - a[0]);

/** 纸要在 纸落完秒 以前出下沿，vy 至少多快：初速 w 按 拽秒 拽成 vy，T 秒走 vy·(T − k·E) + w·k·E（E = 1 − e^(−T/k)） */
const 最慢vy = (生: number, y0: number, w: number | undefined) => {
  const T = 纸落完秒 - 生;
  const k = 纸花参数.拽秒;
  const E = w === undefined ? 0 : k * (1 - Math.exp(-T / k));
  return (724 - y0 - (w ?? 0) * E) / (T - E);
};

/** 抛 = 带初速 [u, w]（纸从窗里扔出来）。纸的 vy 取够快的（落完秒 以前出下沿），花瓣不管 */
const 造一片 = (种: 片种, 生: number, x0: number, y0: number, 档: number, r: () => number, 抛?: readonly [number, number]): 纸花片 => {
  const p = 纸花参数;
  const vx = 取(p.vx, r);
  const vy = Math.max(取(p.vy, r), 种 === '纸' ? 最慢vy(生, y0, 抛?.[1]) : 0);
  return {
    种,
    生,
    x0,
    y0,
    vx,
    vy,
    u: 抛 ? 抛[0] : vx,
    w: 抛 ? 抛[1] : vy,
    摆: 取(p.摆, r),
    频: 取(p.频, r),
    相: r(),
    翻频: 取(p.翻频, r),
    轴: r() < 0.5 ? '横' : '竖',
    图: Math.floor(r() * (种 === '纸' ? 纸图们.length : 12)),
    转: 种 === '纸' ? 2 * Math.floor(r() * 2) : Math.floor(r() * 4),
    翻: r() < 0.5,
    档,
  };
};

/** 一片的外框多大（页面像素，宽、高；转了 90° 的奇数倍就横过来）：花瓣 3×3，纸照 纸图们 */
export const 片框 = (q: 纸花片): { 宽: number; 高: number } => {
  const 格 = q.档 / 成片倍数;
  if (q.种 === '瓣') return { 宽: 3 * 格, 高: 3 * 格 };
  const 图 = 纸图们[q.图]!;
  const [w, h] = [图[0]!.length * 格, 图.length * 格];
  return q.转 % 2 ? { 宽: h, 高: w } : { 宽: w, 高: h };
};

/** 窗口（楼下取景里的格）在合屏前的整页上的位置（页面像素）：右屏左沿在 中线 */
const 楼下投 = (() => {
  const 投 = 侧投影(楼下取景, 归隐版式.右宽, 720, 楼下顶面);
  return (x: number, z: number, y: number) => {
    const p = 投(x, z, y);
    return { x: 中线 + p.x, y: p.y };
  };
})();

/** 窗里扔的：窗洞下半截里随机一点出发（纸的中心），往两边扔开 */
const 窗里扔的 = (r: () => number): 纸花片[] =>
  撒纸.窗把们.flatMap((把) => {
    const 窗 = 撒纸窗们[把.窗]!;
    const a = 楼下投(窗.x[0], 窗.z[1], 窗.y);
    const b = 楼下投(窗.x[1], 窗.z[0], 窗.y);
    return Array.from({ length: 把.张 }, (_, i) => {
      const 档 = r() < 撒纸.窗远 ? 纸花参数.远档 : 纸花参数.近档;
      const 半 = (6 * 档) / 成片倍数 / 2;
      const cx = a.x + r() * (b.x - a.x);
      const cy = (a.y + b.y) / 2 + r() * ((b.y - a.y) / 2);
      return 造一片('纸', 事.纸飘下.秒 + 把.迟 + i * 把.隔秒, cx - 半, cy - 半, 档, r, [取(纸花参数.抛u, r), 取(纸花参数.抛w, r)]);
    });
  });

/** 楼上飘下来的：从右屏上沿外面（往右多一截，往左飘着进画）一路生 */
const 楼上飘的 = (r: () => number): 纸花片[] => {
  const s = 撒纸.楼上;
  const out: 纸花片[] = [];
  const dt = 1 / 240;
  let 攒 = 0;
  let 门 = r();
  for (let τ = s.起; τ < s.止; τ += dt) {
    攒 += s.密 * Math.min(1, (τ - s.起) / (s.满 - s.起)) * dt;
    while (攒 >= 门) {
      攒 -= 门;
      门 = 0.5 + r();
      const 档 = r() < s.远 ? 纸花参数.远档 : 纸花参数.近档;
      const 高 = (8 * 档) / 成片倍数;
      const 生 = 事.纸飘下.秒 + τ;
      const y0 = -高 - r() * s.高差;
      out.push(造一片('纸', 生, 中线 - 20 + r() * (640 + 80), y0, 档, r));
    }
  }
  return out;
};

/** 花瓣一路生：每 1/240 秒累计一次，攒满一片生一片（每片的门槛随机，不排成一排） */
const 一路生花瓣 = (种子: number): 纸花片[] => {
  const r = rng(种子);
  const out: 纸花片[] = [];
  const dt = 1 / 240;
  let 攒 = 0;
  let 门 = r();
  for (let t = 生起; t < 生止; t += dt) {
    攒 += 纸花参数.瓣密 * dt;
    while (攒 >= 门) {
      攒 -= 门;
      门 = 0.5 + r();
      out.push(造一片('瓣', t, -左余 + r() * (1280 + 左余 + 右余), -出发高 - r() * 24, 纸花参数.瓣档, r));
    }
  }
  return out;
};

let 缓存: 纸花片[] | null = null;
/** 全部的纸和花瓣（定死的种子，算一次）。纸先画远的、再画近的（近的压在远的上面） */
export const 纸花们 = (): readonly 纸花片[] =>
  (缓存 ??= (() => {
    const r = rng(纸花参数.种子 + 2);
    const 纸们 = [...窗里扔的(r), ...楼上飘的(r)].sort((a, b) => a.档 - b.档);
    return [...纸们, ...一路生花瓣(纸花参数.种子 + 1)];
  })());

/** 出发后 τ 秒走了多远（一个方向）：初速 v0 按 拽秒 指数地拽成 v */
const 走 = (v0: number, v: number, τ: number) => v * τ + (v0 - v) * 纸花参数.拽秒 * (1 - Math.exp(-τ / 纸花参数.拽秒));

/** 一片在 t 时的左上角（页面像素，没吸整）；翻 = 翻面的余弦（纸：1 正面朝前、0 侧成一条线、负 背面朝前）；转 = 转几个 90°（花瓣一圈转四下，纸不转） */
export const 纸花在 = (q: 纸花片, t: number): { x: number; y: number; 翻: number; 转: number } => {
  const τ = t - q.生;
  const 圈 = q.翻频 * τ + q.相;
  return {
    x: q.x0 + 走(q.u, q.vx, τ) + q.摆 * Math.sin(2 * Math.PI * (q.频 * τ + q.相)),
    y: q.y0 + 走(q.w, q.vy, τ),
    翻: Math.cos(2 * Math.PI * 圈),
    转: q.种 === '纸' ? q.转 : (q.转 + Math.floor(圈 * 4)) % 4,
  };
};

/** 这一刻看不看得见：花瓣在她那边，分屏线左边才看得见（分屏线推走以后哪儿都看得见）；
 *  纸在现实那边，合屏起 以前露在分屏线右边才看得见（飘过线就滑到线后面、出了右屏）；合屏起 那一刻露在右屏里的纸从此一直看得见（推走现实那半时留在画面上） */
export const 看得见 = (q: 纸花片, t: number): boolean => {
  if (t < q.生) return false;
  if (q.种 === '瓣') return 纸花在(q, t).x < 分屏线x(t);
  const 露 = (s: number) => 纸花在(q, s).x + 片框(q).宽 > 中线;
  return t < 混起 ? 露(t) : 混起 >= q.生 && 露(混起);
};

/** 这一片纸在 t 时出没出画面下沿（测试核纸在 2-摇铃 里落完） */
export const 落完 = (q: 纸花片, t: number) => 纸花在(q, t).y > 720;
