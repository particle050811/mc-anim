// 第 14、15 句飘的纸和樱花瓣：右屏你在教学楼下看纸从楼上飘下来，左屏她那边樱花林的花瓣也往下飘，两边方向、速度、大小一样（用户 10-24），
//   分屏线淡掉以后两样混在一起，合屏、到 2-摇铃 一直飘着。纯模块（测试也读），画法在 纸花层.tsx。
// 坐标是整页的页面像素（1280×720，原点左上），时间按歌上的秒：两段按同一个秒画出来一模一样，2-归隐 → 2-摇铃 的接缝接得上。
// 每一片匀速往左下飘（风从右往左，同 界面/歌词字效 的「放下」）、再左右晃；纸和花瓣的速度、晃法从同一套分布里取，只差长相。参数全是 Agent 暂定。
import { fps, 正片事件 } from '../../分镜.ts';

const 事 = 正片事件;

export type 片种 = '纸' | '瓣';
/** 一片：生 = 从画面上沿外面出发那一刻（歌上的秒）；x0、y0 出发点（页面像素）；vx、vy 速度（页面像素/秒）；
 *  摆、频、相 = 左右晃的幅度（页面像素）、每秒几下、相位；翻频 = 翻面（纸换形状、花瓣转 90°）每秒几圈；图、转、翻 = 花瓣用哪张贴图、起始转几个 90°、左右翻不翻 */
export type 纸花片 = {
  种: 片种;
  生: number;
  x0: number;
  y0: number;
  vx: number;
  vy: number;
  摆: number;
  频: number;
  相: number;
  翻频: number;
  图: number;
  转: number;
  翻: boolean;
};

export const 纸花参数 = {
  种子: 1424,
  /** 一个贴图像素几个成片像素（纸、花瓣一样大，都是 3 个贴图像素见方）：分屏 N = 8 的两倍（同 特效/樱花风参数.ts 风流 的 2N 那档），手机 390 宽上一片约 7 像素。
   *  核查 10-24：三倍（24）时一片片太大，一团团的 */
  档: 16,
  /** 速度（页面像素/秒）：往下 130～170、往左 50～80（斜着约 20°） */
  vy: [130, 170] as const,
  vx: [-80, -50] as const,
  摆: [4, 14] as const,
  频: [0.5, 1.1] as const,
  翻频: [0.6, 1.2] as const,
  /** 一种一秒生几片（整页宽上）：平时 底（原版樱花树叶一直零零星星掉花瓣；楼上的纸也早就在飘）；纸飘下 起一起涨，取照 那一拍涨到 满；
   *  混起 以后两种都铺满整页，各生一半，画面上合起来一样密。核查 10-24：纸原来 纸飘下 才开始生，合屏时只落到右屏上面三分之一 */
  密: { 底: 3.5, 满: 9 },
  /** 纸飘下 那一拍先一起飘进来几张（楼上有人撒了一把），横着落在右屏 头把x 之间 */
  头把: 4,
  头把x: [800, 1150] as const,
} as const;

/** 分屏的中线（页面 x）：分屏线淡 以前，纸只在右边、花瓣只在左边 */
export const 中线 = 640;

/** 什么时候开始混：分屏线淡 那一帧起，飘过线的不再藏起来 */
export const 混起 = 事.分屏线淡.帧 / fps;

/** 从哪一刻起生（2-归隐 第一帧画面里已经飘满花瓣）到哪一刻（2-摇铃 转场）；生在画面上沿外 出发高 页面像素、往右多生 右余 页面像素（往左飘着进画） */
const 生起 = 事.第14句分屏.秒 - 6;
const 生止 = 事.风散开.秒;
const 出发高 = 48;
const 右余 = 480;

/** 同 engine/model/parts.tsx 的 rng（mulberry32；纯模块不引 tsx） */
const rng = (seed: number) => {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};

const 线 = (t: number, a: number, b: number, 起: number, 止: number) => a + (b - a) * Math.min(1, Math.max(0, (t - 起) / (止 - 起)));

/** 这一刻一种每秒生几片（整页宽上；纸和花瓣一样） */
export const 生密 = (t: number): number => {
  const { 底, 满 } = 纸花参数.密;
  return t >= 混起 ? 满 / 2 : 线(t, 底, 满, 事.纸飘下.秒, 事.取照.秒);
};

const 造一片 = (种: 片种, 生: number, x0: number, y0: number, r: () => number): 纸花片 => {
  const 取 = (a: readonly [number, number]) => a[0] + r() * (a[1] - a[0]);
  const p = 纸花参数;
  return { 种, 生, x0, y0, vx: 取(p.vx), vy: 取(p.vy), 摆: 取(p.摆), 频: 取(p.频), 相: r(), 翻频: 取(p.翻频), 图: Math.floor(r() * 12), 转: Math.floor(r() * 4), 翻: r() < 0.5 };
};

/** 按 生密 一路生：每 1/240 秒累计一次，攒满一片生一片（每片的门槛随机，不排成一排） */
const 一路生 = (种: 片种, 种子: number): 纸花片[] => {
  const r = rng(种子);
  const out: 纸花片[] = [];
  const dt = 1 / 240;
  let 攒 = 0;
  let 门 = r();
  for (let t = 生起; t < 生止; t += dt) {
    攒 += 生密(t) * dt;
    while (攒 >= 门) {
      攒 -= 门;
      门 = 0.5 + r();
      out.push(造一片(种, t, r() * (1280 + 右余), -出发高 - r() * 24, r));
    }
  }
  return out;
};

let 缓存: 纸花片[] | null = null;
/** 全部的纸和花瓣（定死的种子，算一次） */
export const 纸花们 = (): readonly 纸花片[] => {
  if (缓存) return 缓存;
  const r = rng(纸花参数.种子 + 2);
  const [a, b] = 纸花参数.头把x;
  const 头把 = Array.from({ length: 纸花参数.头把 }, (_, i) =>
    造一片('纸', 事.纸飘下.秒 + i * 0.06, a + ((b - a) * (i + r() * 0.6)) / 纸花参数.头把, -出发高, r),
  );
  缓存 = [...头把, ...一路生('纸', 纸花参数.种子), ...一路生('瓣', 纸花参数.种子 + 1)];
  return 缓存;
};

/** 不晃的那条线上的 x（页面像素）：所有片都匀速，混起 那一刻在哪一边就一直归那一边 */
const 基x = (q: 纸花片, t: number) => q.x0 + q.vx * (t - q.生);

/** 这一刻看不看得见：混起 以前纸只在右边、花瓣只在左边（按不晃的 x 算，飘过线就出了自己那半屏）；
 *  混起 以后各自留住 混起 那一刻在自己那边的，飘过线就混到对面（不会突然冒出来一片）；混起 以后生的哪儿都看得见 */
export const 看得见 = (q: 纸花片, t: number): boolean => {
  if (t < q.生) return false;
  if (q.生 >= 混起) return true;
  const 在右 = 基x(q, Math.min(t, 混起)) >= 中线;
  return q.种 === '纸' ? 在右 : !在右;
};

/** 纸翻着飘的四个形状：0 平、1 斜、2 侧、3 斜（反） */
export type 纸形 = 0 | 1 | 2 | 3;

/** 一片在 t 时的左上角（页面像素，没吸整）、纸的形状、花瓣转几个 90° */
export const 纸花在 = (q: 纸花片, t: number): { x: number; y: number; 形: 纸形; 转: number } => {
  const τ = t - q.生;
  const 圈 = q.翻频 * τ + q.相;
  return {
    x: 基x(q, t) + q.摆 * Math.sin(2 * Math.PI * (q.频 * τ + q.相)),
    y: q.y0 + q.vy * τ,
    形: (((Math.floor(圈 * 4) % 4) + 4) % 4) as 纸形,
    转: (q.转 + Math.floor(圈 * 4)) % 4,
  };
};
