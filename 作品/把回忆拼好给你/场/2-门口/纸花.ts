/** 同 engine/model/parts.tsx 的 rng（mulberry32；纯模块不引 tsx） */
const rng = (seed: number) => {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};

const 取 = (a: readonly [number, number], r: () => number) => a[0] + r() * (a[1] - a[0]);
const 缓 = (u: number) => u * u * (3 - 2 * u);
const 夹 = (u: number) => Math.min(1, Math.max(0, u));

// ---------- 风 ----------
const 风起 = [事.纸飘下.秒 + 风.起[0], 事.纸飘下.秒 + 风.起[1]] as const;
const 风落 = [事.转向铃.秒, 事.摇铃.秒] as const;

/** 这一刻风刮得多大（0～1） */
export const 风力 = (t: number) => 缓(夹((t - 风起[0]) / (风起[1] - 风起[0]))) * (1 - 缓(夹((t - 风落[0]) / (风落[1] - 风落[0]))));

/** 这一片从哪一刻起被风带（出发、起风哪个晚从哪个算，再落 迟 秒） */
const 揽起 = (q: 纸花片) => Math.max(q.生, 事.纸飘下.秒) + q.迟;

/** 这一刻这一片被风带得多紧（0～1）：揽起 以前 0，升 秒里缓到 1 */
const 揽 = (q: 纸花片, t: number) => 缓(夹((t - 揽起(q)) / q.升));

/** 五点高斯—勒让德求积的节点、权重（[−1, 1] 上） */
const 高斯 = [
  [0, 0.5688888888888889],
  [-0.5384693101056831, 0.4786286704993665],
  [0.5384693101056831, 0.4786286704993665],
  [-0.906179845938664, 0.2369268850561891],
  [0.906179845938664, 0.2369268850561891],
] as const;

/** 这一片出发到 t 被风吹的量（秒，∫ 风力 × 揽）：被积的是三道 smoothstep 坡相乘，两个坡的端点之间是九次以内的多项式，五点高斯分段积出来是准的 */
const 吹量 = (q: 纸花片, t: number) => {
  const 起 = Math.max(q.生, 揽起(q));
  if (t <= 起) return 0;
  const 断们 = [起, ...[风起[0], 风起[1], 揽起(q) + q.升, 风落[0], 风落[1]].filter((s) => s > 起 && s < t), t].sort((a, b) => a - b);
  let 和 = 0;
  for (let i = 1; i < 断们.length; i++) {
    const 半 = (断们[i]! - 断们[i - 1]!) / 2;
    const 中 = (断们[i]! + 断们[i - 1]!) / 2;
    for (const [z, w] of 高斯) 和 += w * 半 * 风力(中 + 半 * z) * 揽(q, 中 + 半 * z);
  }
  return 和;
};

// ---------- 一片走到哪 ----------
/** 出发后 τ 秒走了多远（一个方向）：初速 v0 按 拽秒 指数地拽成 v */
const 走 = (v0: number, v: number, τ: number) => v * τ + (v0 - v) * 纸花参数.拽秒 * (1 - Math.exp(-τ / 纸花参数.拽秒));

/** 第几档（0 碎纸 … 变档数 樱花瓣）；花瓣一直是 变档数 */
