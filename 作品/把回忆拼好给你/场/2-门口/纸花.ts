/** 一片：生 = 出发那一刻（歌上的秒）；x0、y0 出发点（页面像素，左上角）；vx、vy 飘的速度（页面像素/秒）；u、w 出发时的初速（纸从窗里扔出来，其余同 vx、vy）；
 *  摆、频、相 = 左右晃的幅度（页面像素）、每秒几下、相位；翻频 = 翻面每秒几圈；轴 = 纸翻的轴（横 = 上下翻，矮下去；竖 = 左右翻，窄下去）；
 *  图 = 纸用 纸图们 的哪张、花瓣用哪张贴图；转、翻 = 起始转几个 90°（纸只正着、倒着放，字行总是横的，一看是一页字）、左右翻不翻；档 = 一个贴图像素几个成片像素 */
