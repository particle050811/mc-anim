// 第 14 句飘的纸和樱花瓣：右屏楼上的窗里撒出两把纸，你在楼下仰头看；左屏她那边樱花林的花瓣一直零零星星往下飘，纸和花瓣方向、速度、大小一样（用户 10-24），
//   合屏时现实那半被推出画面，纸留在画面上、分屏线扫过去以后就在她那边和花瓣一起飘；纸在 2-摇铃 里一秒多落完，花瓣接着零零星星飘（樱花林本来就掉花瓣）。
// 坐标是整页的页面像素（1280×720，原点左上），纸和花瓣都钉在画面上（合屏时底下的画面挪，它们不跟着挪：纸、花瓣一个样，「靠动作一样」）。
// 时间按歌上的秒：2-归隐、2-摇铃 按同一个秒画出来一模一样，接缝接得上。纯模块（测试也读），画法在 纸花层.tsx。
// 每一片往左下飘（风从右往左，同 界面/歌词字效 的「放下」）、再左右晃；纸从窗里扔出来时带着各自的初速，零点几秒里被空气拽成和花瓣一样的飘法。参数全是 Agent 暂定。
// 2D 自画的效果（规矩 可用2D自创效果 里没有）：归进「花瓣飘落」那一条（纸和原版 cherry_leaves 粒子同一种飘法、同一档像素），见 决策。
import { 正片事件 } from '../../分镜.ts';
import { 侧投影 } from '../../地点/侧剖面.tsx';
import { 撒纸窗们, 楼下顶面 } from '../../现实/楼下布局.ts';
import { 分屏线x, 归隐版式, 楼下取景 } from './归隐参数.ts';

const 事 = 正片事件;

export type 片种 = '纸' | '瓣';
/** 一片：生 = 出发那一刻（歌上的秒）；x0、y0 出发点（页面像素，左上角）；vx、vy 飘的速度（页面像素/秒）；u、w 出发时的初速（纸从窗里扔出来，花瓣同 vx、vy）；
 *  摆、频、相 = 左右晃的幅度（页面像素）、每秒几下、相位；翻频 = 翻面每秒几圈；轴 = 纸翻的轴（横 = 上下翻，矮下去；竖 = 左右翻，窄下去）；
 *  图、转、翻 = 花瓣用哪张贴图、起始转几个 90°、左右翻不翻 */
export type 纸花片 = {
  种: 片种;
  生: number;
  x0: number;
  y0: number;
  vx: number;
  vy: number;
  u: number;
  w: number;
  摆: number;
  频: number;
  相: number;
  翻频: number;
  轴: '横' | '竖';
  图: number;
  转: number;
  翻: boolean;
};

export const 纸花参数 = {
  种子: 1424,
  /** 一个贴图像素几个成片像素（纸、花瓣同一档）：N = 10 的两倍（同 特效/樱花风参数.ts 风流 的 2N 那档）。花瓣 3×3、纸 3×4（和花瓣差不多大，纸混进花瓣里看着是一样的东西），
   *  手机 390 宽上纸约 9×12 像素，还看得出两道横线（核查 10-24：3×3 的纸只是个白点认不出，4×5 又比花瓣大两倍多） */
  档: 20,
  /** 飘的速度（页面像素/秒）：往下 220～270、往左 50～80。核查 10-24「纸要在合屏后 1～2 秒内落完」：二楼窗里扔出来的纸 49.42 前全落出画面（2-重逢 49.54 起不画纸） */
  vy: [220, 270] as const,
  vx: [-80, -50] as const,
  摆: [4, 14] as const,
  频: [0.5, 1.1] as const,
  翻频: [0.7, 1.3] as const,
  /** 花瓣一秒生几片（整页宽上，从画面上沿外面飘进来；原版樱花树叶一直零零星星掉花瓣） */
  瓣密: 4,
  /** 纸从窗里扔出来时的初速（页面像素/秒）：往左右 u、往下 w（负 = 往上抛一点）；拽成飘的速度的时间常数（秒） */
  抛u: [-260, 140] as const,
  抛w: [-80, 80] as const,
  拽秒: 0.3,
} as const;

/** 两把纸：纸飘下 那一拍起楼上一扇窗里扔出 张 张、隔 隔秒 一张（撒纸窗们 的第 窗 扇），第二把晚 迟 秒 */
export const 撒纸 = [
  { 窗: 1, 迟: 0, 张: 8, 隔秒: 0.06 },
  { 窗: 0, 迟: 0.2, 张: 6, 隔秒: 0.07 },
] as const;

/** 分屏的中线（页面 x）：合屏前，纸只在右边、花瓣只在左边 */
export const 中线 = 归隐版式.左宽;

/** 合屏起：这一刻在现实那半里的纸从此留在画面上（推走现实那半时纸留下来），之前飘过线的纸已经出了右屏、不再出来 */
export const 混起 = 事.合屏起.秒;

/** 花瓣从哪一刻起生（2-归隐 第一帧画面里已经飘满）到哪一刻（2-摇铃 转场）；生在画面上沿外 出发高 页面像素，右边多生一截（往左飘着进画） */
const 生起 = 事.第14句分屏.秒 - 6;
const 生止 = 事.风散开.秒;
const 出发高 = 48;
const 左余 = 40;
const 右余 = 400;

/** 同 engine/model/parts.tsx 的 rng（mulberry32；纯模块不引 tsx） */
const rng = (seed: number) => {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};

const 造一片 = (种: 片种, 生: number, x0: number, y0: number, r: () => number): 纸花片 => {
  const 取 = (a: readonly [number, number]) => a[0] + r() * (a[1] - a[0]);
  const p = 纸花参数;
  const vx = 取(p.vx);
  const vy = 取(p.vy);
  const 抛 = 种 === '纸';
  return {
    种,
    生,
    x0,
    y0,
    vx,
    vy,
    u: 抛 ? 取(p.抛u) : vx,
    w: 抛 ? 取(p.抛w) : vy,
    摆: 取(p.摆),
    频: 取(p.频),
    相: r(),
    翻频: 取(p.翻频),
    轴: r() < 0.5 ? '横' : '竖',
    图: Math.floor(r() * 12),
    转: Math.floor(r() * 4),
    翻: r() < 0.5,
  };
};

/** 窗口（楼下取景里的格）在合屏前的整页上的位置（页面像素）：右屏左沿在 中线 */
const 楼下投 = 侧投影(楼下取景, 归隐版式.右宽, 720, 楼下顶面);

/** 两把纸：从窗里扔出来（窗洞下半截里随机一点出发，纸的左上角；从窗台上扔出来，也早一点落完） */
const 撒纸们 = (): 纸花片[] => {
  const r = rng(纸花参数.种子 + 2);
  return 撒纸.flatMap((把) => {
    const 窗 = 撒纸窗们[把.窗]!;
    const a = 楼下投(窗.x[0], 窗.z[1], 窗.y);
    const b = 楼下投(窗.x[1], 窗.z[0], 窗.y);
    return Array.from({ length: 把.张 }, (_, i) =>
      造一片('纸', 事.纸飘下.秒 + 把.迟 + i * 把.隔秒, 中线 + a.x + r() * (b.x - a.x - 40), (a.y + b.y) / 2 + r() * Math.max(0, (b.y - a.y) / 2 - 50), r),
    );
  });
};

/** 花瓣一路生：每 1/240 秒累计一次，攒满一片生一片（每片的门槛随机，不排成一排） */
const 一路生花瓣 = (种子: number): 纸花片[] => {
  const r = rng(种子);
  const out: 纸花片[] = [];
  const dt = 1 / 240;
  let 攒 = 0;
  let 门 = r();
  for (let t = 生起; t < 生止; t += dt) {
    攒 += 纸花参数.瓣密 * dt;
    while (攒 >= 门) {
      攒 -= 门;
      门 = 0.5 + r();
      out.push(造一片('瓣', t, -左余 + r() * (1280 + 左余 + 右余), -出发高 - r() * 24, r));
    }
  }
  return out;
};

let 缓存: 纸花片[] | null = null;
/** 全部的纸和花瓣（定死的种子，算一次） */
export const 纸花们 = (): readonly 纸花片[] => (缓存 ??= [...撒纸们(), ...一路生花瓣(纸花参数.种子 + 1)]);

/** 出发后 τ 秒走了多远（一个方向）：初速 v0 按 拽秒 指数地拽成 v */
const 走 = (v0: number, v: number, τ: number) => v * τ + (v0 - v) * 纸花参数.拽秒 * (1 - Math.exp(-τ / 纸花参数.拽秒));

/** 不晃的那条线上的 x（页面像素） */
const 基x = (q: 纸花片, t: number) => q.x0 + 走(q.u, q.vx, t - q.生);

/** 这一刻看不看得见：花瓣在她那边，分屏线左边才看得见（分屏线推走以后哪儿都看得见）；
 *  纸在现实那边，合屏起 以前分屏线右边才看得见（飘过线就出了右屏）；合屏起 那一刻还在右屏里的纸从此一直看得见（推走现实那半时留在画面上） */
export const 看得见 = (q: 纸花片, t: number): boolean => {
  if (t < q.生) return false;
  if (q.种 === '瓣') return 基x(q, t) < 分屏线x(t);
  if (t < 混起) return 基x(q, t) >= 中线;
  return 基x(q, 混起) >= 中线;
};

/** 纸翻着飘的八个样子（一圈）：正面、正面斜、侧边、背面斜、背面（白得发亮）、背面斜、侧边、正面斜 */
export type 纸形 = 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7;

/** 一片在 t 时的左上角（页面像素，没吸整）、纸的样子、花瓣转几个 90° */
export const 纸花在 = (q: 纸花片, t: number): { x: number; y: number; 形: 纸形; 转: number } => {
  const τ = t - q.生;
  const 圈 = q.翻频 * τ + q.相;
  return {
    x: 基x(q, t) + q.摆 * Math.sin(2 * Math.PI * (q.频 * τ + q.相)),
    y: q.y0 + 走(q.w, q.vy, τ),
    形: (((Math.floor(圈 * 8) % 8) + 8) % 8) as 纸形,
    转: (q.转 + Math.floor(圈 * 4)) % 4,
  };
};

/** 这一片纸在 t 时出没出画面下沿（测试核纸在 2-摇铃 里落完） */
export const 落完 = (q: 纸花片, t: number) => 纸花在(q, t).y > 720;
