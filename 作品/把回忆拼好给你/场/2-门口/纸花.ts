/** 碎纸的外框（页面像素，宽、高）；花瓣 3×3 */
export const 片框 = (q: 纸花片): { 宽: number; 高: number } => {
  const 格 = q.档 / 成片倍数;
  if (q.种 === '瓣') return { 宽: 3 * 格, 高: 3 * 格 };
  const 图 = 碎图们[q.图]!;
  return { 宽: 图[0]!.length * 格, 高: 图.length * 格 };
};

/** 一片在 t 时的外框左上角（页面像素，没吸整）；翻 = 翻面的余弦（碎纸：1 正面朝前、0 侧成一条线、负 背面朝前）；转 = 转几个 90°（樱花瓣一圈转四下，碎纸不转）；档 = 档位。
 *  碎纸变成樱花瓣的形状（第 3 档）以后，瓣画在外框正中 */
export const 纸花在 = (q: 纸花片, t: number): { x: number; y: number; 翻: number; 转: number; 档: number } => {
  const τ = t - q.生;
  const 圈 = q.翻频 * τ + q.相;
  const 吹 = 吹量(q, t);
  const 晃 = 2 * Math.PI * (q.频 * τ + q.相);
  const 档 = 档位(q, t);
  return {
    x: q.x0 + 走(q.u, q.vx, τ) + q.吃风 * 风.速[0] * 吹 + q.摆 * Math.sin(晃),
    y: q.y0 + 走(q.w, q.vy, τ) + q.吃风 * 风.速[1] * 吹 + q.摆 * 风力(t) * Math.cos(晃),
    翻: Math.cos(2 * Math.PI * 圈),
    转: q.种 === '纸' && 档 < 变档数 - 1 ? q.转 : (q.转 + Math.floor(圈 * 4)) % 4,
    档,
  };
};

/** 这一刻看不看得见：碎纸出发以后一直看得见（窗里扔出来、或者从画面外刮进来，过分屏线就画在她那边）；
 *  花瓣在她那边，分屏线左边才看得见（合屏时分屏线推过去，现实那半后面的花瓣跟着露出来） */
export const 看得见 = (q: 纸花片, t: number): boolean => {
  if (t < q.生) return false;
  return q.种 === '纸' || 纸花在(q, t).x < 分屏线x(t);
};

/** 外框这一刻压不压着让开框 */
const 压着让开 = (q: 纸花片, t: number) => {
  const { x, y } = 纸花在(q, t);
  const k = 片框(q);
  return x + k.宽 > 让开.左 && x < 让开.右 && y + k.高 > 让开.上 && y < 让开.下;
};

/** 让开框那几拍有没有挡着她（每半帧查一次） */
export const 挡她 = (q: 纸花片): boolean => {
  for (let t = Math.max(让开.起, q.生); t < 让开.止; t += 1 / 48) if (看得见(q, t) && 压着让开(q, t)) return true;
  return false;
};

/** 花瓣合屏起以前在画面里从分屏线后面钻出来（现实那半后面的花瓣被风吹过线）：会看着像碎纸一下子变了花瓣，不要 */
const 线后钻出 = (q: 纸花片): boolean => {
  let 线后 = false;
  let 线前 = false;
  for (let t = q.生; t < 混起; t += 1 / 48) {
    const { x, y } = 纸花在(q, t);
    if (y + 片框(q).高 <= 0 || y >= 720) continue;
    if (x + 片框(q).宽 > 中线) 线后 = true;
    if (x < 中线) 线前 = true;
  }
  return 线后 && 线前;
};

// ---------- 造 ----------
/** 碎纸第 1、2 档的形状：瓣形摆在外框正中，碎纸多出来的格离瓣心远的先掉（同远近随机），第 1 档掉三分之一、第 2 档掉三分之二，瓣形里缺的格第 2 档补上（补的格是纸白） */
const 中间形状们 = (图: readonly string[], 瓣: number, r: () => number): string[][] => {
  const [W, H] = [图[0]!.length, 图.length];
  const ox = Math.floor((W - 3) / 2);
  const oy = Math.floor((H - 3) / 2);
  const 形 = 瓣形(瓣);
  const 在瓣 = (i: number, j: number) => 形[j - oy]?.[i - ox] === 'X';
  const 多们: { i: number; j: number; 远: number }[] = [];
  for (let j = 0; j < H; j++)
    for (let i = 0; i < W; i++)
      if (图[j]![i] !== '.' && !在瓣(i, j)) 多们.push({ i, j, 远: Math.hypot(i - ox - 1, j - oy - 1) + r() * 0.5 });
  多们.sort((a, b) => b.远 - a.远);
  const 档 = (掉: number, 补: boolean) => {
    const 掉了 = new Set(多们.slice(0, 掉).map((c) => c.j * W + c.i));
    return 图.map((行, j) =>
      [...行].map((c, i) => (掉了.has(j * W + i) ? '.' : c === '.' && 补 && 在瓣(i, j) ? 'W' : c)).join(''),
    );
  };
  return [[...图], 档(Math.ceil(多们.length / 3), false), 档(Math.ceil((多们.length * 2) / 3), true)];
};

/** r揽：迟、升 从哪个随机数里取（花瓣另用一串，起风前的花瓣还是原来那些） */
const 造一片 = (
  种: 片种,
  生: number,
  x0: number,
  y0: number,
  档: number,
  r: () => number,
  抛?: readonly [number, number],
  r揽: () => number = r,
): 纸花片 => {
  const p = 纸花参数;
  const vx = 取(p.vx, r);
  const vy = 取(p.vy, r);
  const 图 = Math.floor(r() * (种 === '纸' ? 碎图们.length : 12));
  const 瓣 = 种 === '纸' ? Math.floor(r() * 12) : 图;
  return {
    种,
    生,
    x0,
    y0,
    vx,
    vy,
    u: 抛 ? 抛[0] : vx,
    w: 抛 ? 抛[1] : vy,
    吃风: 取(风.吃, r),
    迟: 取(风.迟, r揽),
    升: 取(风.升, r揽),
    摆: 取(p.摆, r),
    频: 取(p.频, r),
    相: r(),
    翻频: 取(p.翻频, r),
    轴: r() < 0.5 ? '横' : '竖',
    图,
    瓣,
    转: 种 === '纸' ? 2 * Math.floor(r() * 2) : Math.floor(r() * 4),
    翻: r() < 0.5,
    档,
    变: [],
    格们: 种 === '纸' ? 中间形状们(碎图们[图]!, 瓣, r) : [],
  };
};

/** 碎纸一档档变的时刻：中心飘过 起x 或者飘了 纸龄 秒（先到的那个）起，一档 档秒；来不及就提前起、再不够就把一档压短（扔出来以后至少 纸秒 秒是碎纸） */
const 排变 = (q: 纸花片, r: () => number): 纸花片 => {
  const 起x = 取(变法.起x, r);
  const 龄 = 取(变法.纸龄, r);
  let d = 取(变法.档秒, r);
  const 半宽 = 片框(q).宽 / 2;
  let 过 = Infinity;
  for (let t = q.生; t < 变完秒; t += 1 / 96)
    if (纸花在(q, t).x + 半宽 <= 起x) {
      过 = t;
      break;
    }
  const n = 变档数 - 1;
  const 期 = 变完秒 - r() * 变法.期错;
  let s = Math.max(q.生 + 变法.纸秒, Math.min(过, q.生 + 龄, 期 - n * d));
  if (s + n * d > 变完秒) d = (变完秒 - s) / n;
  s = Math.min(s, 变完秒 - n * d);
  return { ...q, 变: Array.from({ length: 变档数 }, (_, k) => s + k * d) };
};

/** 合屏前的整页上，楼下取景里的点（格）在哪（页面像素）：右屏左沿在 中线 */
const 楼下投 = (() => {
  const 投 = 侧投影(楼下取景, 归隐版式.右宽, 720, 楼下顶面);
  return (x: number, z: number, y: number) => {
    const p = 投(x, z, y);
    return { x: 中线 + p.x, y: p.y };
  };
})();

/** 造一片，挡她就重来（最多 试 次；都挡就不要这一片） */
const 不挡 = (造: () => 纸花片, 试 = 12): 纸花片 | null => {
  for (let i = 0; i < 试; i++) {
    const q = 造();
    if (!挡她(q)) return q;
  }
  return null;
};

/** 窗里扔的：窗洞里随机一点出发（碎纸的中心），往外扔开，落一阵再被风越吹越往左 */
const 窗里扔的 = (r: () => number): 纸花片[] =>
  撒纸.窗把们.flatMap((把) => {
    const 窗 = 撒纸窗们[把.窗]!;
    const a = 楼下投(窗.x[0], 窗.z[1], 窗.y);
    const b = 楼下投(窗.x[1], 窗.z[0], 窗.y);
    return Array.from({ length: 把.张 }, (_, i) =>
      不挡(() => {
        const 档 = r() < 撒纸.窗远 ? 纸花参数.远档 : 纸花参数.近档;
        const 半 = (4.5 * 档) / 成片倍数 / 2;
        const cx = a.x + r() * (b.x - a.x);
        const cy = a.y + r() * (b.y - a.y);
        const q = 造一片('纸', 事.纸飘下.秒 + 把.迟 + i * 撒纸.把内隔, cx - 半, cy - 半, 档, r, [取(纸花参数.抛u, r), 取(纸花参数.抛w, r)]);
        return { ...q, 迟: q.迟 + 撒纸.抛后 };
      }),
    ).filter((q) => q !== null);
  });

/** 外来的：从右屏上沿外掉进来、右沿外飘进来 */
const 外来的 = (r: () => number): 纸花片[] => {
  const s = 撒纸.外来;
  const out: 纸花片[] = [];
  const dt = 1 / 240;
  let 攒 = 0;
  let 门 = r();
  for (let τ = s.起; τ < s.止; τ += dt) {
    攒 += s.密 * Math.min(1, (τ - s.起) / (s.满 - s.起)) * dt;
    while (攒 >= 门) {
      攒 -= 门;
      门 = 0.5 + r();
      const q = 不挡(() => {
        const 档 = r() < s.远 ? 纸花参数.远档 : 纸花参数.近档;
        if (r() < s.顶占) {
          const 高 = (5 * 档) / 成片倍数;
          return 造一片('纸', 事.纸飘下.秒 + τ, 取(s.顶x, r), -高 - 4, 档, r, [取(纸花参数.vx, r), 取(s.落w, r)]);
        }
        return 造一片('纸', 事.纸飘下.秒 + τ, 1280 + 4, 取([s.上, s.下], r), 档, r);
      });
      if (q) out.push(q);
    }
  }
  return out;
};

/** 花瓣一路生：每 1/240 秒累计一次，攒满一片生一片（每片的门槛随机，不排成一排）；挡她、从分屏线后面钻出来的不要 */
const 一路生花瓣 = (种子: number): 纸花片[] => {
  const r = rng(种子);
  const r揽 = rng(种子 + 100);
  const out: 纸花片[] = [];
  const dt = 1 / 240;
  let 攒 = 0;
  let 门 = r();
  for (let t = 生起; t < 生止; t += dt) {
    攒 += 纸花参数.瓣密 * dt;
    while (攒 >= 门) {
      攒 -= 门;
      门 = 0.5 + r();
      const q = 造一片('瓣', t, -左余 + r() * (1280 + 左余 + 右余), -出发高 - r() * 24, 纸花参数.瓣档, r, undefined, r揽);
      if (!挡她(q) && !线后钻出(q)) out.push(q);
    }
  }
  return out;
};

let 缓存: 纸花片[] | null = null;
/** 全部的碎纸和花瓣（定死的种子，算一次）。碎纸先画远的、再画近的（近的压在远的上面），花瓣最后 */
export const 纸花们 = (): readonly 纸花片[] =>
  (缓存 ??= (() => {
    const r = rng(纸花参数.种子 + 2);
    const 纸们 = [...窗里扔的(r), ...外来的(r)].map((q) => 排变(q, r)).sort((a, b) => a.档 - b.档);
    return [...纸们, ...一路生花瓣(纸花参数.种子 + 1)];
  })());
