// 第 14 句（段 2-归隐）的音效：收卷铃、撕书、撒手的纸声、荧光框取出声、挂铃的铃声、樱花风的风声。全在本段里放完（风声、铃声段尾前淡掉，2-摇铃 从安静起）。
// 纯数据（段.ts 读）。增益是 Agent 暂定（三稿「克制」：压在歌下面，听得出来就行），文件本身的数是 ffmpeg 量的（每 20 毫秒一窗的 RMS）。
import { clamp01 } from '@engine/anim/anim.ts';
import { fps, 歌曲帧, 正片事件, 段时钟 } from '../../分镜.ts';
import type { 歌上音效 } from '../../声音/跨段音效.ts';
import { 纸声们, 纸声峰值 } from './第8句参数.ts';
import { 铃声文件, 风声 } from './第15句声音.ts';

const 事 = 正片事件;
/** 段 2-归隐 的止帧（第 15 句起，2-摇铃 的第一帧） */
const 段尾 = 段时钟('2-归隐').场窗口.止帧;

/** 收卷铃：原版钟（block.bell.use.1，2.49 秒，一开头就响，最响一窗 −24.5 dB），起音落在收卷铃那一帧 */
export const 收卷铃声: 歌上音效 = {
  资产: '音效/把回忆拼好给你/block.bell.use.1',
  名: '收卷铃',
  起帧: 事.收卷铃.帧,
  时长秒: 2.49,
  增益: () => 0.6,
};

/** 纸声（原版 item.book.page_turn，第8句参数.ts 量过峰帧、峰值）：最响那一下落在 拍 那一帧，峰值配到 峰值 dBFS */
const 纸声 = (名: string, 序: number, 拍帧: number, 峰值: number): 歌上音效 => {
  const 声 = 纸声们[序]!;
  return { 资产: 声.资产, 名, 起帧: 拍帧 - 声.峰帧, 时长秒: 声.秒, 增益: () => Math.round(10 ** ((峰值 - 声.峰值) / 20) * 1e6) / 1e6 };
};
/** 撕书：page_turn.3（短、利），比第 8 句放照片响一点 */
export const 撕书声 = 纸声('撕书', 2, 事.撕书.帧, 纸声峰值 + 2);
/** 撒手：page_turn.2，一摞纸散开 */
export const 撒手纸声 = 纸声('撒手', 1, 事.撒手取照.帧, 纸声峰值);

/** 荧光框取出声（entity.glow_item_frame.remove_item.1，0.1 秒，第一窗 −40 dB、第二窗起 −10.8 dB）：落在撒手取照那一帧（照片方案：合照落进手里、那一格变暗同一帧） */
export const 取出声: 歌上音效 = {
  资产: '音效/把回忆拼好给你/entity.glow_item_frame.remove_item.1',
  名: '荧光框取出',
  起帧: 事.撒手取照.帧,
  时长秒: 0.1,
  增益: () => 0.35,
};

/** 挂铃的铃声（同第 15 句的寻风之铃）：起音落在挂铃那一帧，轻一点（挂上去碰了一下）；段尾前 淡出秒 淡掉 */
export const 挂铃声参数 = { 增益: 0.25, 淡出秒: 0.3 } as const;
const 铃起 = 事.挂铃.帧 - Math.round(铃声文件.起音秒 * fps);
export const 挂铃声: 歌上音效 = {
  资产: '音效/万法皆通/wind_seeking_bell',
  名: '挂铃',
  起帧: 铃起,
  帧数: 段尾 - 铃起,
  时长秒: 铃声文件.时长秒,
  增益: (帧) => 挂铃声参数.增益 * clamp01((段尾 - 帧) / (挂铃声参数.淡出秒 * fps)),
};

/** 樱花风的风声（同第 15 句：原版鞘翅飞行的风，增益、淡入淡出同 第15句声音.ts 的 风声）：归隐起风那一帧起，合屏后 淡出秒 淡完，正好到段尾 */
const 风起 = 事.归隐起风.帧;
const 风止 = Math.min(段尾, 歌曲帧(事.归隐合屏.秒 + 风声.淡出秒));
export const 归隐风声: 歌上音效 = {
  资产: '音效/item.elytra.flying',
  名: '樱花风',
  起帧: 风起,
  帧数: 风止 - 风起,
  时长秒: 10.22,
  增益: (帧) => {
    const 进 = clamp01((帧 - 风起 + 1) / (风声.淡入秒 * fps));
    const 出 = clamp01((风止 - 帧) / (风声.淡出秒 * fps));
    return 风声.增益 * 进 * 出;
  },
};

export const 第14句声音们: readonly 歌上音效[] = [收卷铃声, 撕书声, 撒手纸声, 取出声, 挂铃声, 归隐风声];
