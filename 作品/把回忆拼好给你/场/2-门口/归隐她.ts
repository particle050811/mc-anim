// 第 14 句（段 2-归隐）里她每一帧的样子：站哪、朝哪、头看哪、手怎么摆、手里拿什么。分寸在 归隐参数.ts。
// 照片墙前在左屏；挂铃 那一帧合屏（整屏镜头），她已经在告示牌前；她消失 以后不在了。头上不冒气泡：这一句顶上有歌词，文字一时只走一路（规矩 看得懂的速度）
// 纯模块（第14句.test.ts 也读），画法在 归隐.tsx。
import { clamp01 } from '@engine/anim/anim.ts';
import type { BonePose } from '@engine/model/基岩模型.tsx';
import type { 魔法酒狐全部表情 } from '@库/角色/魔法酒狐新动作.ts';
import { 正片事件 } from '../../分镜.ts';
import {
  主手,
  副手垂,
  副手捧花,
  她的头,
  按伸帧,
  打框收帧,
  挂铃停帧,
  挂铃放下帧,
  挂铃站位,
  挂铃朝向,
  转头帧,
  墙前站位,
  墙前朝向,
  看合照朝向,
  按站位,
  挪帧,
} from './归隐参数.ts';

const 事 = 正片事件;

type 骨表 = Record<string, BonePose>;
const 缓 = (t: number) => t * t * (3 - 2 * t);
const 插 = (a: readonly number[], b: readonly number[], t: number) => a.map((v, i) => v + (b[i]! - v) * t);
/** 两个骨骼摆法之间插（只插 rot；两边都要有同一批骨骼） */
const 插骨 = (a: 骨表, b: 骨表, t: number): 骨表 =>
  Object.fromEntries(Object.keys(b).map((k) => [k, { rot: 插(a[k]?.rot ?? [0, 0, 0], b[k]!.rot ?? [0, 0, 0], t) as [number, number, number] }]));
const 右臂静: 骨表 = 主手.静;

export type 她态 = { x: number; yaw: number; 看: [number, number]; 表情: 魔法酒狐全部表情; 骨骼: 骨表; 右手: '合照' | null; 左手: '花' | '合照' };

/** 她在 帧（歌曲帧）的样子；她消失 以后不在了 */
export const 她于 = (帧: number): 她态 | null => {
  if (帧 >= 事.她消失.帧) return null;
  if (帧 >= 事.挂铃.帧) {
    // 合屏：她在告示牌前，主手刚把铃挂上钉子，停一下再放下；副手拿着合照垂在身侧
    const t = 缓(clamp01((帧 - 事.挂铃.帧 - 挂铃停帧) / 挂铃放下帧));
    return { x: 挂铃站位, yaw: 挂铃朝向, 看: 她的头.看铃, 表情: '难过', 骨骼: { ...插骨(主手.挂铃, 右臂静, t), ...副手垂 }, 右手: null, 左手: '合照' };
  }
  let 看 = 她的头.看花;
  if (帧 >= 事.抬头看合照.帧) 看 = 插(她的头.看花, 她的头.看合照, 缓(clamp01((帧 - 事.抬头看合照.帧 + 1) / 转头帧))) as [number, number];
  if (帧 >= 事.取照.帧) 看 = 插(她的头.看合照, 她的头.看手里, 缓(clamp01((帧 - 事.取照.帧 + 1) / 转头帧))) as [number, number];
  let 臂 = 右臂静;
  const 按起 = 事.手按合照.帧 - 按伸帧;
  const 收起 = 事.打框.帧 - 打框收帧;
  if (帧 >= 事.取照.帧) 臂 = 主手.垂;
  else if (帧 > 事.打框.帧) 臂 = 插骨(主手.打, 主手.垂, (帧 - 事.打框.帧) / (事.取照.帧 - 事.打框.帧));
  else if (帧 === 事.打框.帧) 臂 = 主手.打;
  else if (帧 > 收起) 臂 = 插骨(主手.按, 主手.收, (帧 - 收起) / 打框收帧);
  else if (帧 >= 事.手按合照.帧) 臂 = 主手.按;
  else if (帧 > 按起) 臂 = 插骨(右臂静, 主手.按, 缓((帧 - 按起) / 按伸帧));
  const 取了 = 帧 >= 事.取照.帧;
  const 挪进 = 缓(clamp01((帧 - 按起) / 挪帧));
  const 挪回 = 缓(clamp01((帧 - 事.取照.帧 - 1) / 挪帧));
  // 抬头看合照那一拍身子转向照片墙，取下合照转回来朝镜头
  const 转过去 = 缓(clamp01((帧 - 事.抬头看合照.帧 + 1) / 转头帧));
  const 转回来 = 缓(clamp01((帧 - 事.取照.帧 + 1) / 转头帧));
  return {
    x: 墙前站位 + (按站位 - 墙前站位) * 挪进 * (1 - 挪回),
    yaw: 墙前朝向 + (看合照朝向 - 墙前朝向) * 转过去 * (1 - 转回来),
    看,
    表情: 取了 ? '难过' : '无',
    骨骼: { ...臂, ...副手捧花 },
    右手: 取了 ? '合照' : null,
    左手: '花',
  };
};

