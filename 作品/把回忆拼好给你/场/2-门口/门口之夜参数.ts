/** 下线：照片缩成存档图标。原版 1.20.1 存档图标（GameRenderer.takeAutoScreenshot）取画面正中的正方形、缩成 64×64，选择世界列表里画成没有边的方块；
 *  这里照它裁正中的正方形，缩的时候分辨率一起往 64 降（对数插），落定时 64×64 一个点 8 个成片像素（边 512），中心在画面 0.47 高（底边让开聊天栏暗底）；
 *  相纸边收没、饱和降到 0.25、蒙一层灰（三稿「褪色、蒙灰的方形图标」= 第 0 镜「选择世界」里那个存档的图标） */
export const 下线图标 = { 点数: 64, 边: 512, 中心高: 0.47, 缩帧: 8, 饱和: 0.25, 灰: 'rgba(150, 150, 150, 0.35)' } as const;
/** 定格以后这一帧拍立得卡片的几何（W×H 画布像素，按比例算，画布多大都行）：入 = 缩进来的进度、下 = 缩成图标的进度、s = 照片缩放，
 *  w、h 照片（不含相纸边）的宽高，边、下边 相纸边宽，cx、cy 照片中心，角 斜度（弧度），源 = 从定住的整幅世界里取哪块 [x, y, 宽, 高]（下线时收成正中的正方形），
 *  点 = 照片这一刻降到几个点见方（不降时 0） */
export const 卡片 = (帧: number, W: number, H: number) => {
  const 版 = 照片版式;
  const 入 = 1 - (1 - 夹((帧 - 定格帧) / 版.缩入帧)) ** 3;
  const 下帧 = 正片事件.第11句下线.帧;
  const 下 = 帧 >= 下帧 ? 缓((帧 - 下帧 + 1) / 下线图标.缩帧) : 0;
  const s = 插(1, 版.缩放, 入);
  const u = W / 2560;
  const 图标 = 下线图标.边 * u;
  const w = 帧 >= 下帧 ? 插(W * 版.缩放, 图标, 下) : W * s;
  const h = 帧 >= 下帧 ? 插(H * 版.缩放, 图标, 下) : H * s;
  const 边 = 版.边 * W * s * (1 - 下);
  const 下边 = 版.下边 * W * s * (1 - 下);
  const 卡心y = 版.中心高 * H - (版.下边 - 版.边) * W * 版.缩放 * 0.5;
  // 图标中心对到偶数个成片像素，64 个点的边都落在整像素上
  const 标心y = 2 * Math.round((下线图标.中心高 * 1440) / 2) * u;
  const cx = W / 2;
  const cy = 插(插(H / 2, 卡心y, 入), 标心y, 下);
  const 角 = (插(版.斜度 * 入, 0, 下) * Math.PI) / 180;
  const 源 = [插(0, (W - H) / 2, 下), 0, 插(W, H, 下), H] as const;
  const 点 = 下 > 0 ? Math.round(对数插(H, 下线图标.点数, 下)) : 0;
  return { 入, 下, s, w, h, 边, 下边, cx, cy, 角, 源, 点 };
};

