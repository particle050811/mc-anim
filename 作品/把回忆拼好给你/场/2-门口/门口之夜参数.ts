/** 跟火箭时 N 从 84 拉到 12 用掉这一段的前多少（先拉开看清是谁在放、火箭在哪，再跟着往上） */
const 拉开占 = 0.7;

/** 中心吸到偶数像素：(0.5 + x)·16N（方块边）、z·16N 都是偶数，贴图像素的边落在整像素上 */
const 吸 = (N: number, x: number, z: number): [number, number] => {
  const k = 格像素(N);
  return [(2 * Math.round(((0.5 + x) * k) / 2)) / k - 0.5, (2 * Math.round((z * k) / 2)) / k];
};
const 偶 = (N: number) => Math.max(2, 2 * Math.round(N / 2));
const 对数插 = (a: number, b: number, t: number) => Math.exp(插(Math.log(a), Math.log(b), t));

/** 火箭（没放时是放的地方，炸了是炸点）落在剖面上的哪 */
const 火箭点 = (一: 一发烟花, s: number, N: number) => {
  const p = 火箭位置(一, s) ?? (s < 一.发射秒 ? [一.位[0], 一.位[1], 0.15] : 炸点(一));
  return 上剖面(N, { x: p[0], y: p[1], z: p[2] });
};

/** 歌上这一刻的连续镜头（还没取整） */
const 连续 = (s: number): 连续镜 => {
  const 段 = 镜头段;
  const [一, 三] = [烟花们[0]!, 烟花们[1]!];
  if (s <= 段.推起) return 开场;
  if (s < 段.推到) {
    // 推：N 按对数插，牌字面在画面上离中心的偏移（成片像素）跟着同一个进度缩到 0，牌子一路走到画面中心、不来回晃
    const u = 缓((s - 段.推起) / (段.推到 - 段.推起));
    const N = 对数插(开场.N, 牌近N, u);
    const [x0, z0] = 上剖面(开场.N, 牌字面);
    const 偏 = [(x0 - 开场.中心[0]) * 开场.N * (1 - u), (z0 - 开场.中心[1]) * 开场.N * (1 - u)];
    const [x, z] = 上剖面(N, 牌字面);
    return { N, 中心: [x - 偏[0]! / N, z - 偏[1]! / N] };
  }
  if (s < 段.跟起) return { N: 牌近N, 中心: 上剖面(牌近N, 牌字面) };
  if (s < 段.跟到) {
    // 跟：先拉开，中心从牌子往火箭挪，炸开那一刻正好在炸点上
    const t = (s - 段.跟起) / (段.跟到 - 段.跟起);
    const N = 对数插(牌近N, 远N, 缓(t / 拉开占));
    const 牌 = 上剖面(N, 牌字面);
    const 箭 = 火箭点(一, s, N);
    const e = 缓(t);
    return { N, 中心: [插(牌[0], 箭[0], e), 插(牌[1], 箭[1], e)] };
  }
  const 一炸 = 火箭点(一, 段.跟到, 远N);
  const 三炸 = 火箭点(三, 炸开秒(三), 远N);
  if (s < 段.落起) {
    // 在天上：从第一发的炸点慢慢挪到第二发的炸点
    const e = 缓((s - 段.跟到) / (段.落起 - 段.跟到));
    return { N: 远N, 中心: [插(一炸[0], 三炸[0], e), 插(一炸[1], 三炸[1], e)] };
  }
  const e = 缓((s - 段.落起) / (段.落到 - 段.落起));
  return { N: 远N, 中心: [插(三炸[0], 定格中心[0], e), 插(三炸[1], 定格中心[1], e)] };
};

/** 歌上这一刻的镜头：N 取偶数，中心吸到偶数像素 */
export const 镜头 = (歌曲帧: number): 门口之夜镜头 => {
  const c = 连续(歌曲帧 / fps);
  const N = 偶(c.N);
  return { N, 顶面: 正交顶面, 中心: 吸(N, c.中心[0], c.中心[1]) };
};
/** 镜头给 三渲二画布 / 侧投影 用的取景 */
export const 镜头取景 = (j: 门口之夜镜头) => ({ 中心: j.中心, 每格: 格像素(j.N) });
/** 天（渐变、月亮）的取景：按 远N 画，中心只跟镜头挪 天视差（以定格那一镜为准）；星星按同样的挪法偏移 */
export const 天取景 = (j: 门口之夜镜头) => {
  const 定 = 吸(远N, 定格中心[0], 定格中心[1]);
  return { 中心: [插(定[0], j.中心[0], 天视差), 插(定[1], j.中心[1], 天视差)] as const, 每格: 格像素(远N) };
};

/** 牌面（整块木板）在页面上的矩形（宽×高 的页面像素）：整片后期的颗粒让开这块（用户 10-24「整片后期的颗粒别压在字上」）。牌还没插上给空 */
export const 牌面矩形 = (歌曲帧: number, 宽 = 1280, 高 = 720): 页面矩形[] => {
  if (歌曲帧 / fps < 插牌秒) return [];
  const j = 镜头(歌曲帧);
  const 每页 = (16 * j.N) / (2560 / 宽);
  const [x, z] = 上剖面(j.N, 牌字面);
  const 左 = 宽 / 2 + (x - 门口.牌面.宽 / 2 - j.中心[0]) * 每页;
  const 上 = 高 / 2 - (z + 门口.牌面.高 / 2 - j.中心[1]) * 每页;
  return [{ 左: Math.floor(左), 上: Math.floor(上), 宽: Math.ceil(门口.牌面.宽 * 每页) + 1, 高: Math.ceil(门口.牌面.高 * 每页) + 1 }];
};

