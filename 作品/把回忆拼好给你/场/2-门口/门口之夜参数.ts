const 软大 = (a: number, b: number, k = 0.5) => (a + b + Math.sqrt((a - b) ** 2 + k * k)) / 2;

/** 歌上这一刻的连续镜头（还没取整） */
const 连续 = (s: number): 连续镜 => {
  const 段 = 镜头段;
  const [一, 三] = [烟花们[0]!, 烟花们[1]!];
  if (s <= 段.让起) return 开场;
  const 让后: 连续镜 = { N: 开场.N, 中心: [开场.中心[0] - 让格, 开场.中心[1]] };
  if (s < 段.推起) {
    const e = 缓((s - 段.让起) / (段.推起 - 段.让起));
    return { N: 开场.N, 中心: [插(开场.中心[0], 让后.中心[0], e), 开场.中心[1]] };
  }
  if (s < 段.推到) {
    // 推：N 按对数插，牌字面在画面上离中心的偏移（成片像素）跟着同一个进度缩到 0，牌子一路走到画面中心、不来回晃
    const u = 缓((s - 段.推起) / (段.推到 - 段.推起));
    const N = 对数插(让后.N, 牌近N, u);
    const [x0, z0] = 上剖面(让后.N, 牌字面);
    const 偏 = [(x0 - 让后.中心[0]) * 让后.N * (1 - u), (z0 - 让后.中心[1]) * 让后.N * (1 - u)];
    const [x, z] = 上剖面(N, 牌字面);
    return { N, 中心: [x - 偏[0]! / N, z - 偏[1]! / N] };
  }
  if (s < 段.跟起) return { N: 牌近N, 中心: 上剖面(牌近N, 牌字面) };
  if (s < 段.跟到) {
    // 跟：先拉开，中心从牌子往火箭挪，炸开那一刻正好在炸点上。
    // 竖着：拉开时跟拉开同一个进度从牌子抬到 地线中心z（拉到 N 12 时地面停在画面底边上面 0.75 格，不露出一大片地底下的剖面），
    // 拉开以后从那里平平地升到炸点：火箭从画面下半升上来、炸在画面中间（不死跟火箭，它越飞越快，死跟最后几帧镜头一下蹿上去）
    const t = (s - 段.跟起) / (段.跟到 - 段.跟起);
    const 拉 = 缓(t / 拉开占);
    const N = 对数插(牌近N, 远N, 拉);
    const 牌 = 上剖面(N, 牌字面);
    const x = 插(牌[0], 火箭点(一, s, N)[0], 缓(t));
    const 低 = (秒: number, n: number) => 软大(火箭点(一, 秒, n)[1], 地线中心z(n));
    const 拉完 = 段.跟起 + 拉开占 * (段.跟到 - 段.跟起);
    const z = t < 拉开占 ? 插(牌[1], 低(s, N), 拉) : 插(低(拉完, 远N), 火箭点(一, 段.跟到, 远N)[1], 缓((t - 拉开占) / (1 - 拉开占)));
    return { N, 中心: [x, z] };
  }
  const 一炸 = 火箭点(一, 段.跟到, 远N);
  const 三炸 = 火箭点(三, 炸开秒(三), 远N);
  if (s < 段.落起) {
    // 在天上：从第一发的炸点慢慢挪到第二发的炸点
    const e = 缓((s - 段.跟到) / (段.落起 - 段.跟到));
    return { N: 远N, 中心: [插(一炸[0], 三炸[0], e), 插(一炸[1], 三炸[1], e)] };
  }
  const e = 缓((s - 段.落起) / (段.落到 - 段.落起));
  return { N: 远N, 中心: [插(三炸[0], 定格中心[0], e), 插(三炸[1], 定格中心[1], e)] };
};

/** 歌上这一刻的镜头：N 取偶数，中心吸到偶数像素 */
export const 镜头 = (歌曲帧: number): 门口之夜镜头 => {
  const c = 连续(歌曲帧 / fps);
  const N = 偶(c.N);
  return { N, 顶面: 正交顶面, 中心: 吸(N, c.中心[0], c.中心[1]) };
};
/** 镜头给 三渲二画布 / 侧投影 / 屋后远景 用的取景 */
export const 镜头取景 = (j: 门口之夜镜头) => ({ 中心: j.中心, 每格: 格像素(j.N) });
/** 天（渐变、月亮、星星）的取景：一直按开场的 N 16 画（推近牌子时天不跟着放大，像推轨不像变焦），
 *  中心从开场那一镜按 天视差 跟镜头挪，吸到 N 16 的偶数像素 */
export const 天取景 = (j: 门口之夜镜头) => {
  const [x0, z0] = 开场.中心;
  const 高差 = j.中心[1] - z0;
  const { 竖下, 竖上, 软宽 } = 天视差;
  const z = z0 + 竖下 * 高差 + (竖上 - 竖下) * (软大(高差, 0, 软宽) - 软宽 / 2);
  return { 中心: 吸(开场.N, 插(x0, j.中心[0], 天视差.横), z), 每格: 格像素(开场.N) };
};

/** 牌面（整块木板）在页面上的矩形（宽×高 的页面像素）：整片后期的颗粒让开这块（用户 10-24「整片后期的颗粒别压在字上」） */
export const 牌面矩形 = (歌曲帧: number, 宽 = 1280, 高 = 720): 页面矩形[] => {
  const j = 镜头(歌曲帧);
  const 每页 = (16 * j.N) / (2560 / 宽);
  const [x, z] = 上剖面(j.N, 牌字面);
  const 左 = 宽 / 2 + (x - 门口.牌面.宽 / 2 - j.中心[0]) * 每页;
  const 上 = 高 / 2 - (z + 门口.牌面.高 / 2 - j.中心[1]) * 每页;
  return [{ 左: Math.floor(左), 上: Math.floor(上), 宽: Math.ceil(门口.牌面.宽 * 每页) + 1, 高: Math.ceil(门口.牌面.高 * 每页) + 1 }];
};

