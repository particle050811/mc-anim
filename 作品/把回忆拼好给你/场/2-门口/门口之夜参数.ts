/** 中心吸到偶数像素：(0.5 + x)·16N（方块边）、z·16N 都是偶数，贴图像素的边落在整像素上 */
const 吸 = (N: number, x: number, z: number): [number, number] => {
  const k = 格像素(N);
  return [(2 * Math.round(((0.5 + x) * k) / 2)) / k - 0.5, (2 * Math.round((z * k) / 2)) / k];
};
const 偶 = (N: number) => Math.max(2, 2 * Math.round(N / 2));
const 对数插 = (a: number, b: number, t: number) => Math.exp(插(Math.log(a), Math.log(b), t));

