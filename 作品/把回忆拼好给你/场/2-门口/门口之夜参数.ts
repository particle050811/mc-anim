/** 这一刻的亮档和照亮它的那发（同时有两发亮着取后炸的） */
export const 亮档 = (s: number): { 档: 0 | 1 | 2; 发: 一发烟花 | null } => {
  let r: { 档: 0 | 1 | 2; 发: 一发烟花 | null } = { 档: 0, 发: null };
  for (const 一 of 烟花们) {
    const 过 = s - 炸开秒(一);
    if (过 < 0) continue;
    const 时 = 亮档时长[一.形];
    const 档 = 过 < 时.二 ? 2 : 过 < 时.一 ? 1 : 0;
    if (档 > 0) r = { 档, 发: 一 };
  }
  return r;
};

// ---------- 镜头 ----------
export type 门口之夜镜头 = { N: number; 顶面: number; 中心: readonly [number, number] };
/** 推近要看清的：告示牌字面中心（地点/告示牌.tsx：牌底面 [-3, 1.5, 0] + 字面中心 [0, −1/24 − 1/512, 20/24]） */
export const 牌字面 = { x: -3, y: 1.5 - 1 / 24 - 1 / 512, z: 20 / 24 };
/** 推近：一帧一档的像素密度（都是偶数，几何地加快），到 N = 72 停住：一屏 2.2 × 1.25 格，牌面占四成宽，一个字 96 像素高（手机竖屏上 15 像素）。
 *  拉回倒着走一遍。俯角保持整屏镜头的 顶面 ÷ N = 0.2（取最近的偶数） */
export const 推近档 = [12, 16, 22, 32, 44, 58, 72] as const;
const 宽N = 整屏镜头N;
const 宽中心 = 整屏镜头.取景.中心;
const 顶面比 = 0.2;
const 顶面档 = (N: number) => Math.min(N, 2 * Math.round((顶面比 * N) / 2 + 1e-9) || 2);

/** 中心吸到偶数像素：(0.5 + x)·16N（方块边）、z·16N 都是偶数，预览级里贴图像素的边也落在整像素上 */
const 吸 = (N: number, x: number, z: number): [number, number] => {
  const k = 格像素(N);
  return [(2 * Math.round(((0.5 + x) * k) / 2)) / k - 0.5, (2 * Math.round((z * k) / 2)) / k];
};

/** 歌上这一刻的镜头：整屏 → 第9句推近 起一帧一档推到牌子上 → 第9句拉回 起一帧一档拉回整屏 */
export const 镜头 = (歌曲帧: number): 门口之夜镜头 => {
  const 推 = 正片事件.第9句推近.帧;
  const 拉 = 正片事件.第9句拉回.帧;
  let i: number; // 推近档里第几档；−1 = 整屏
  if (歌曲帧 < 推) i = -1;
  else if (歌曲帧 < 拉) i = Math.min(推近档.length - 1, 歌曲帧 - 推);
  else i = 推近档.length - 2 - (歌曲帧 - 拉);
  if (i < 0) return { N: 宽N, 顶面: 顶面档(宽N), 中心: 宽中心 };
  const N = 推近档[i]!;
  const 顶面 = 顶面档(N);
  // 牌字面在画面上离中心的偏移按 1/N 从整屏的位置缩到 0（推的时候牌子一路往画面中心走）
  const 近z = 牌字面.z + (顶面 / N) * 牌字面.y;
  const 宽z = 牌字面.z + (顶面档(宽N) / 宽N) * 牌字面.y;
  const s = (1 / 宽N - 1 / N) / (1 / 宽N - 1 / 推近档[推近档.length - 1]!);
  const 偏x = (牌字面.x - 宽中心[0]) * 宽N * (1 - s);
  const 偏z = (宽z - 宽中心[1]) * 宽N * (1 - s);
  return { N, 顶面, 中心: 吸(N, 牌字面.x - 偏x / N, 近z - 偏z / N) };
};
/** 镜头给 三渲二画布 / 侧投影 用的取景 */
export const 镜头取景 = (j: 门口之夜镜头) => ({ 中心: j.中心, 每格: 格像素(j.N) });

