// 第 8 句门口头顶那层云（地点/原版云.ts 的 小木屋上空云，屋后远景.tsx 画）每一帧的样子：往西飘、云洞接着第 7 句末开大、每格散了多少。
// 按歌曲帧算（和第 7 句同一套飘法，接得上）；段 2-收集快乐 和 核对-门口哈气 都用。纯模块（测试直接引）。
import { clamp01 } from '@engine/anim/anim.ts';
import { fps, 段窗口, 正片事件 } from '../../分镜.ts';
import { 小木屋上空云, 散起半径, type 云格子 } from '../../地点/原版云.ts';
import type { 远景云 } from '../../地点/屋后远景.tsx';
import { 云洞, 云色 } from './第8句参数.ts';

/** 第 7 句末那一帧（洞半径 = 云洞.首）、第8句晴定 那一帧（洞半径停在 云洞.末） */
const 接帧 = 段窗口('2-收集快乐').起帧 - 1;
const 停帧 = 正片事件.第8句晴定.帧;

/** 云往东挪了多少（格）：原版每刻往西 0.03 格，按歌上的刻算 */
export const 云飘 = (帧: number) => -(帧 / fps) * 20 * 小木屋上空云.每刻飘;

/** 云洞半径（格）：接着第 7 句末的速度缓出，第8句晴定 那一帧停住 */
export const 洞半径 = (帧: number) => {
  const t = clamp01((帧 - 接帧) / (停帧 - 接帧));
  return 云洞.首 + (云洞.末 - 云洞.首) * (1 - (1 - t) ** 2);
};

/** 这一格云还剩多少（0～1）：第 7 句末已经散了的（那一帧散起半径不到 首）没了；之后洞半径头一回够到它的那一帧起，散帧 帧里淡掉。
 *  云一直在飘，散起半径每帧都变：按头一回够到的那一帧算，散了的不会因为飘远了又回来 */
export const 云剩 = (c: 云格子, 帧: number) => {
  const 心 = 小木屋上空云.洞心;
  if (散起半径(c, 心, 云飘(接帧)) <= 云洞.首) return 0;
  for (let 起 = 接帧 + 1; 起 <= 帧; 起++)
    if (散起半径(c, 心, 云飘(起)) <= 洞半径(起)) return 1 - clamp01((帧 - 起 + 1) / 小木屋上空云.散帧);
  return 1;
};

/** 给 门口画布 的 远景.云 */
export const 第8句云 = (帧: number): 远景云 => ({ 飘: 云飘(帧), 剩: (c) => 云剩(c, 帧), 色: 云色 });
