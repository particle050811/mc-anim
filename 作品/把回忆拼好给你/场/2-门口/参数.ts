/** 一格在 2560×1440 上占几个像素：176，即一个贴图像素 11 像素。
 *  取舍：要放下门两边各 7 格（左边离墙 3 格的树和它的树冠、右边整间屋连东墙），竖着要放下地面一格和 7 格高的樱花树（比屋顶 6 格高）。
 *  176 时画面 14.5 × 8.2 格：史蒂夫 1.875 格高 = 330 像素（画面高的 22.9%），酒狐量到头发顶 1.52 格 = 267 像素（18.5%，连帽子约 22%）。
 *  再大（192，12 像素）画面只剩 13.3 × 7.5 格，树顶和左边树冠出画；再小（160）人物掉到 21% 以下，手机上表情看不清 */
export const 每格 = 176;

/** 地面线（草方块顶面、人脚底）离画面下边几像素（2560×1440）：一格，正好露出一层草方块侧面 */
export const 地面线离底 = 176;

/** 整屏取景：门那一格的中心在画面正中；中心 z 让地面线落在离底 地面线离底 像素 */
export const 取景 = { 中心: [0, (1440 / 2 - 地面线离底) / 每格] as const, 每格 };

/** 半屏取景（第 13、14 句分屏右边）：画布宽 宽像素（2560×1440 里的像素，比如 1280），门中心落在从左数 门在 × 宽 的地方。
 *  (门在 − 0.5) × 宽 要是整数，像素才对得齐 */
export const 半屏取景 = (宽像素: number, 门在: number) => {
  const 偏 = (门在 - 0.5) * 宽像素;
  if (Math.abs(偏 - Math.round(偏)) > 1e-6) throw new Error(`门在 ${门在}、宽 ${宽像素}：门中心落不到整像素上`);
  return { 中心: [-偏 / 每格, 取景.中心[1]] as const, 每格 };
};

