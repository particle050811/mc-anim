// 第 13 句「我们的爱总有时差」分屏的一帧（1280×720 整页）：左屏现实的课桌，右屏门这个机位的半屏，中间一条分屏线，外面盖整片后期。
// 两屏同一种画法（用户 10-24 看了矢量现实的静帧说「画风太不一致了吧 太出戏了」）：左屏也是 MC 方块和像素物件、三渲二平涂描边，像素一样大，网格连着。
// 按歌曲帧画（分屏参数.ts 的 分屏态）：左边先看墙上课表亮两格、再沉到桌面，撕页、笔筒跟着翻页，史蒂夫的手捏着页角；右边樱花树一页长一截、她一页换一个姿势，天上太阳月亮快转。
// 调色两边各用色板里自己的那套（左 现实、右 褪色：三稿「现实冷，你下线后她那边褪色」）；颗粒、暗角整页只盖一层，两屏的接缝藏在这层里（05-画风 原则 1、4）。
// 用法：段里 <时差分屏 帧={歌曲帧} />；核对时 描边、后期 可以关掉比。
import type React from 'react';
import type { V3 } from '@engine/model/parts.tsx';
import { 描边 as 描边组 } from '@engine/三渲二/描边.tsx';
import { 贴图像素对齐 } from '@engine/三渲二/对齐.tsx';
import { 整片后期 } from '@engine/三渲二/整片后期.tsx';
import { 插调子, type 调色 } from '@engine/三渲二/调子.ts';
import { standPose } from '@库/角色/骨架.tsx';
import { MagicalWineFoxEx } from '@库/角色/魔法酒狐新动作组件.tsx';
import type { 魔法酒狐新姿势 } from '@库/角色/魔法酒狐新动作.ts';
import { fps, 画幅 } from '../../分镜.ts';
import { 门口 } from '../../地点/门口小木屋.tsx';
import { 告示牌像素字 } from '../../地点/告示牌字.tsx';
import { 月铃兰 } from '../../物品/月铃兰.tsx';
import { 现实画布 } from '../../现实/画布.tsx';
import { 现实课桌 } from '../../现实/课桌.tsx';
import { 像素空间 } from '../../现实/像素块.tsx';
import { 撕页手 } from '../../现实/撕页手.tsx';
import { 描边 as 描边默认 } from '../../画风.ts';
import { 色板 } from '../../色板.ts';
import { 告示牌行们 } from './参数.ts';
import { 分屏态, 分屏版式, 右取景, 天体残影, 左镜, 手到于, 手摆, 明暗幅度 } from './分屏参数.ts';
import { 门口画布 } from './门口.tsx';

/** 她这一页的样子：x 是脚底（人那排 y = 门口.站排y），朝 是身子朝哪（正交只能取正方向，贴图像素才是整数），看 同 MagicalWineFoxEx */
export type 她这一页 = { 姿势: 魔法酒狐新姿势; x: number; 朝: '东' | '西' | '南'; 看?: [number, number] };

const 朝yaw = { 东: -90, 西: 90, 南: 180 } as const;
/** 花的正面朝镜头（镜头在南边）：偏 = 从她正前方往她左边转几度 */
const 朝花偏 = { 东: -90, 西: 90, 南: 0 } as const;

/** 每落一页换一个姿势（三稿：坐在门口望着路 → 站起来张望 → 蹲在树苗旁 → 抱膝坐在树下 → 站在告示牌旁）；100 落下之前同第一个。
 *  Agent 暂定。蹲（31 那页）是定稿静帧，蹲在树干前面（树干暗，衬得出她），朝东看着门；其余四页只出过自检帧 */
export const 她的姿势们: readonly 她这一页[] = [
  { 姿势: '坐', x: 门口.站位.门外一步, 朝: '西' },
  { 姿势: '张望', x: 门口.站位.牌门之间, 朝: '西', 看: [8, 0] },
  { 姿势: '蹲', x: 门口.树苗[0], 朝: '东' },
  { 姿势: '抱膝坐', x: 门口.站位.牌树之间, 朝: '南' },
  { 姿势: '站', x: 门口.站位.牌门之间, 朝: '南' },
];

const 中性: 调色 = { 饱和: 1, 对比: 1, 乘: '#ffffff', 抬: '#000000', 暗角: 0, 颗粒: 0 };
const 只调色 = (t: 调色): 调色 => ({ ...t, 暗角: 0, 颗粒: 0 });
/** 整页那层质感：两边的暗角、颗粒取平均 */
const 质感: 调色 = {
  ...中性,
  暗角: (色板.现实.调色.暗角 + 色板.褪色.调色.暗角) / 2,
  颗粒: (色板.现实.调色.颗粒 + 色板.褪色.调色.颗粒) / 2,
};

export type 时差分屏属性 = {
  /** 歌曲帧（分镜.ts 的时间轴） */
  帧: number;
  /** 描边开关（默认照 画风.ts） */
  描边?: boolean;
  /** 整片后期开关（默认开） */
  后期?: boolean;
};

export const 时差分屏: React.FC<时差分屏属性> = ({ 帧, 描边 = 描边默认.开, 后期 = true }) => {
  const 态 = 分屏态(帧);
  const { 左宽, 右宽, 线宽, 线色 } = 分屏版式;
  const 高 = 画幅.高;
  const 她 = 她的姿势们[Math.max(0, 态.落了几页 - 1)]!;
  const 位: V3 = [她.x, 门口.站排y, 0];
  const 酒狐 = (
    <贴图像素对齐 锚={位}>
      <MagicalWineFoxEx
        pose={{ ...standPose(位), yaw: 朝yaw[她.朝] }}
        姿势={她.姿势}
        看={她.看}
        眨眼={0}
        秒={帧 / fps}
        右手={{ 物品: <月铃兰 />, 朝向: { 偏: 朝花偏[她.朝] } }}
      />
    </贴图像素对齐>
  );
  const 右调子 = 插调子(插调子(色板.夏日白天, 色板.褪色, 态.褪色), 色板.夜, 态.夜);
  const 套 = (t: 调色, 内容: React.ReactNode) => (后期 ? <整片后期 调色={只调色(t)}>{内容}</整片后期> : 内容);
  const 页 = (
    <div style={{ position: 'absolute', inset: 0, background: '#000' }}>
      <div style={{ position: 'absolute', left: 0, top: 0, width: 左宽, height: 高, overflow: 'hidden' }}>
        {套(
          色板.现实.调色,
          <现实画布 宽={左宽} 高={高} 取景={{ 中心: [左镜.x, 态.左z], 每格: 右取景.每格 }} 描边={描边}>
            <现实课桌 翻页={态.翻页} 亮格={态.亮格} />
            <像素空间 位={[0, 0, 0]}>
              <描边组 开={描边}>
                <撕页手 到={手到于(态.翻页)} 摆={手摆} />
              </描边组>
            </像素空间>
          </现实画布>,
        )}
      </div>
      <div style={{ position: 'absolute', left: 左宽, top: 0, width: 右宽, height: 高, overflow: 'hidden' }}>
        {套(
          右调子.调色,
          <门口画布
            宽={右宽}
            高={高}
            取景={右取景}
            树进度={态.树进度}
            告示牌
            告示牌字={<告示牌像素字 行们={告示牌行们} />}
            刻={态.刻}
            明暗幅度={明暗幅度}
            残影={天体残影}
            调子={右调子}
          >
            {描边 ? <描边组>{酒狐}</描边组> : 酒狐}
          </门口画布>,
        )}
      </div>
      <div style={{ position: 'absolute', left: 左宽 - 线宽, top: 0, width: 线宽, height: 高, background: 线色 }} />
    </div>
  );
  return 后期 ? <整片后期 调色={质感}>{页}</整片后期> : 页;
};
