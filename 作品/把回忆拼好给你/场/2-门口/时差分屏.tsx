/** 她这一页的样子：x 是脚底（人那排 y = 门口.站排y）；yaw 是身子朝哪（度，同 FigurePose：90 朝西、180 朝镜头、−90 朝东）；看 同 MagicalWineFoxEx；
 *  骨骼 盖在姿势表上（按骨骼整条替换），给拿花的胳膊另摆 */
export type 她这一页 = {
  姿势: 魔法酒狐新姿势;
  x: number;
  yaw: number;
  看?: [number, number];
  骨骼?: Record<string, BonePose>;
  /** 手里的花在「正面朝镜头、立着」上再转（度）：偏 180 = 翻到背面（贴图左右镜像），倾 = 从镜头看逆时针歪 */
  花?: { 偏?: number; 倾?: number };
};

/** 花的正面朝镜头（镜头在南边）：手持物 朝向 的 偏 = 从她正前方往她左边转几度 */
const 朝镜头偏 = (yaw: number) => ((((180 - yaw) % 360) + 540) % 360) - 180;

/** 蹲着把花往前下伸（右手，侧身朝东时是离镜头近的那只）：上臂往前抬 82°、往外撇 25°，前臂再抬 10°。手在胸口前下方、帽檐底下，
 *  花伸出她的轮廓、压在暗的树干上（主会话 10-24 美术定稿「花举到剪影外」，手机上要认得出月铃兰）。
 *  试过往上举（上臂 100°～130°）：她蹲着时手就在脸边，花挡住脸、和帽檐粘成一团。Agent 暂定 */
export const 蹲举花: Record<string, BonePose> = { RightArm: { rot: [-82, -25, 0] }, RightForeArm: { rot: [-10, 0, 0] } };

/** 每落一页换一个姿势（三稿：坐在门口望着路 → 站起来张望 → 蹲在树苗旁 → 抱膝坐在树下 → 站在告示牌旁）；100 落下之前同第一个。Agent 暂定。
 *  蹲（31 那页，定稿静帧）：身子正侧面朝门（yaw −90，美术定稿「侧身朝门」，身上的贴图像素是正的），脚底在树干左边一格（身子不压在暗树干上）；
 *  头往镜头转 40°、抬 5°（正侧面时脸被头发挡住，五家看图评审都读成背对镜头的一团粉）；花翻到背面，贴图里在左边的那串白铃铛朝门、衬在暗的树干上，再歪 10°（和胳膊的角度一起试出来的）。
 *  望路、张望朝西再往镜头转 30°（yaw 120），脸和花露出来：试过正侧面（yaw 90）加转头，脸露得少，头转到 45° 帽檐里面会翻出来。
 *  这两处不取 90° 整数倍是照主会话 10-24「角色朝向尽量取 90° 的整数倍，和手机上看清表情、动作冲突时看清优先」，Agent 提议、等主会话定。
 *  抱膝坐、站朝镜头。其余四页只出自检帧 */
export const 她的姿势们: readonly 她这一页[] = [
  { 姿势: '坐', x: 门口.站位.门外一步, yaw: 120 },
  { 姿势: '张望', x: 门口.站位.牌门之间, yaw: 120, 看: [8, 0] },
  { 姿势: '蹲', x: 门口.树苗[0] - 1, yaw: -90, 看: [5, -40], 骨骼: 蹲举花, 花: { 偏: 180, 倾: 10 } },
  { 姿势: '抱膝坐', x: 门口.站位.牌树之间, yaw: 180 },
  { 姿势: '站', x: 门口.站位.牌门之间, yaw: 180 },
];

/** 斜投影里往里一个贴图像素画面上升几个贴图像素（手到于 按这个反算） */
const 斜 = 正交顶面 / 分屏N;

/** 树苗那一格（树干那排，j = 1） */
const 树根 = [门口.树苗[0], 1, 0] as const;

const 中性: 调色 = { 饱和: 1, 对比: 1, 乘: '#ffffff', 抬: '#000000', 暗角: 0, 颗粒: 0 };
const 只调色 = (t: 调色): 调色 => ({ ...t, 暗角: 0, 颗粒: 0 });

export type 时差分屏属性 = {
  /** 歌曲帧（分镜.ts 的时间轴） */
  帧: number;
  /** 描边开关（默认照 画风.ts），两屏一起管 */
  描边?: boolean;
  /** 整片后期开关（默认开） */
  后期?: boolean;
  /** 核对的对照帧用：盖在她这一页的样子上（只给的字段换掉） */
  她?: Partial<她这一页>;
};

export const 时差分屏: React.FC<时差分屏属性> = ({ 帧, 描边 = 描边默认.开, 后期 = true, 她: 盖 }) => {
  const 态 = 分屏态(帧);
  const { 服务器宽, 现实宽, 线宽, 线色 } = 分屏版式;
  const 高 = 画幅.高;
  const 她 = { ...她的姿势们[Math.max(0, 态.落了几页 - 1)]!, ...盖 };
  const 位: V3 = [她.x, 门口.站排y, 0];
  const 原显示 = DISPLAY.generated.thirdperson_righthand;
  const 花 = {
    物品: <月铃兰 />,
    朝向: { 偏: 朝镜头偏(她.yaw) + (她.花?.偏 ?? 0), 倾: 她.花?.倾 ?? 0 },
    显示: { ...原显示, scale: (原显示.scale ?? [1, 1, 1]).map((v) => v * 花倍) },
  };
  const 树 = useMemo(() => 分屏树方块(态.树进度, 树根), [态.树进度]);
  // 放大 她倍 倍（绕脚底）；贴图像素对齐 只吸附脚底
  const 酒狐 = (
    <贴图像素对齐 锚={位}>
      <group position={位} scale={她倍}>
        <group position={[-位[0], -位[1], -位[2]]}>
          <MagicalWineFoxEx
            pose={{ ...standPose(位), yaw: 她.yaw }}
            姿势={她.姿势}
            看={她.看}
            眨眼={0}
            秒={帧 / fps}
            右手={花}
            骨骼={她.骨骼}
          />
        </group>
      </group>
    </贴图像素对齐>
  );
  const 服务器调子 = 插调子(插调子(色板.夏日白天, 色板.褪色, 态.褪色), 色板.夜, 态.夜);
  // 整页那层质感：两屏的暗角、颗粒取平均
  const 质感: 调色 = {
    ...中性,
    暗角: (色板.现实.调色.暗角 + 服务器调子.调色.暗角) / 2,
    颗粒: (色板.现实.调色.颗粒 + 服务器调子.调色.颗粒) / 2,
  };
  const 套 = (t: 调色, 内容: React.ReactNode) => (后期 ? <整片后期 调色={只调色(t)}>{内容}</整片后期> : 内容);
  const 页 = (
    <div style={{ position: 'absolute', inset: 0, background: '#000' }}>
      <div style={{ position: 'absolute', left: 0, top: 0, width: 服务器宽, height: 高, overflow: 'hidden' }}>
        {套(
          服务器调子.调色,
          <门口画布
            宽={服务器宽}
            高={高}
            取景={服务器取景}
            描边宽={分屏N}
            告示牌
            告示牌字={<告示牌像素字 行们={告示牌行们} />}
            刻={态.刻}
            明暗幅度={明暗幅度}
            弧={分屏天弧}
            残影={天体残影}
            调子={服务器调子}
          >
            <方块拼搭 方块们={树} 原点={格原点} 群系={群系} 正面花草 />
            {描边 ? <描边组>{酒狐}</描边组> : 酒狐}
          </门口画布>,
        )}
      </div>
      <div style={{ position: 'absolute', left: 服务器宽, top: 0, width: 现实宽, height: 高, overflow: 'hidden' }}>
        {套(
          色板.现实.调色,
          <现实画布 宽={现实宽} 高={高} 取景={{ 中心: 态.现实镜, 每格: 16 * 分屏N }} 描边={描边} 描边宽={分屏N}>
            <现实课桌 翻页={态.翻页} 亮格={态.亮格} 课表z={分屏课表z} />
            <像素空间 位={[0, 0, 0]}>
              <描边组 开={描边}>
                <撕页手 到={手到于(态.翻页, 分屏手偏, 斜)} 摆={分屏手摆} />
              </描边组>
            </像素空间>
          </现实画布>,
        )}
      </div>
      <div style={{ position: 'absolute', left: 服务器宽, top: 0, width: 线宽, height: 高, background: 线色 }} />
    </div>
  );
  return 后期 ? <整片后期 调色={质感}>{页}</整片后期> : 页;
};
