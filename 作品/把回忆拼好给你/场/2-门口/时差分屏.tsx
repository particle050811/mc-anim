// 第 13 句「我们的爱总有时差」分屏的一帧（1280×720 整页）：左屏服务器（门这个机位的半屏），右屏现实的课桌（用户 10-24「主角的画面放在右边更合适」），
// 中间一条分屏线，外面盖整片后期。两屏同一种画法（MC 方块和像素物件、三渲二平涂描边），像素一样大（分屏参数.ts 的 分屏N），网格连着。
// 按歌曲帧画（分屏参数.ts 的 分屏态）：右边先看墙上课表亮两格、再沉到桌面，撕页、笔筒跟着翻页，史蒂夫的手捏着页角；
// 左边樱花树一页长一截、她一页换一个姿势，天上太阳月亮快转。
// 调色两屏各用自己的（右 现实 冷；左 夏日白天，只往 褪色 插一点：主会话 10-24 美术定稿「现实冷，服务器保持夏天的暖」）；颗粒、暗角整页只盖一层，接缝藏在这层里（05-画风 原则 1、4）。
// 用法：段里 <时差分屏 帧={歌曲帧} />；核对时 描边、后期 可以关掉比。
