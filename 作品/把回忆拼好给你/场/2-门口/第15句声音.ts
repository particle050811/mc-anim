// 第 15 句摇铃起的两个声音：寻风之铃的铃声、樱花风的风声。都从门口那段放起、拖过转场进隐世之境那段（声音/跨段音效.ts 切成每段一截）。
// 纯数据（段.ts 读）。增益是 Agent 暂定（三稿「克制」：压在歌下面，听得出来就行），文件本身的数是 ffmpeg 解码量的。
import { clamp01 } from '@engine/anim/anim.ts';
import { fps, 歌曲帧, 正片事件 } from '../../分镜.ts';
import type { 歌上音效 } from '../../声音/跨段音效.ts';

/** 寻风之铃（音效/万法皆通/wind_seeking_bell）：文件 2.07 秒，开头 0.04 秒近乎静音，铃一响就到 −13 dBFS 上下、0.5 秒最响（−6）、两秒里慢慢收 */
export const 铃声文件 = { 起音秒: 0.04, 时长秒: 2.069 } as const;
/** 铃声增益：一个数，整声都一样 */
export const 铃声增益 = 0.35;

/** 风声借原版鞘翅飞行的风（音效/item.elytra.flying，10.2 秒的循环，平均 −27.5 dB）：摇铃起 0.25 秒淡进来，盖满（转场）后 0.35 秒淡掉 */
export const 风声 = { 增益: 0.6, 淡入秒: 0.25, 淡出秒: 0.35 } as const;

/** 铃声：起音落在摇铃那一帧 */
export const 铃声: 歌上音效 = {
  资产: '音效/万法皆通/wind_seeking_bell',
  名: '寻风之铃',
  起帧: 正片事件.摇铃.帧 - Math.round(铃声文件.起音秒 * fps),
  时长秒: 铃声文件.时长秒,
  增益: () => 铃声增益,
};

const 风起 = 正片事件.摇铃.帧;
const 风止 = 歌曲帧(正片事件.风散开.秒 + 风声.淡出秒);

/** 风声：摇铃那一帧起，转场后淡完 */
export const 风: 歌上音效 = {
  资产: '音效/item.elytra.flying',
  名: '樱花风',
  起帧: 风起,
  帧数: 风止 - 风起,
  时长秒: 10.22,
  增益: (帧) => {
    const 进 = clamp01((帧 - 风起 + 1) / (风声.淡入秒 * fps));
    const 出 = clamp01((风止 - 帧) / (风声.淡出秒 * fps));
    return 风声.增益 * 进 * 出;
  },
};
