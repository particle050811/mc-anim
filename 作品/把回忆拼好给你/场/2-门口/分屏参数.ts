// 第 13 句「我们的爱总有时差」分屏（三稿逐句表）：左屏现实，高三教室的课桌（2D 扁平矢量，现实/ 的零件）；右屏是门这个机位的半屏（门口画布）。
// 纯模块（段.ts 也能读）：版式、左屏镜头、两边跟着歌走的状态。时刻都从 分镜.ts 的 正片事件 来，这里不写秒数。
// 全是 Agent 暂定的数（用户 10-24 把制作交给主会话），用户没看过；改了只改这里。
import { 网格 } from '../../配乐/网格.ts';
import { fps, 正片事件 } from '../../分镜.ts';
import { 樱花树阶段数 } from '../../地点/樱花树.ts';
import { 天亮 } from '../../地点/天体.ts';
import { 翻页值 } from '../../现实/撕页.ts';

/** 版式（页面像素）：左右各半屏，两边同时发生、一样分量（时差是比出来的）；右屏 640 宽正好是 场/2-门口 的 半屏取景（门在 分屏门在）。
 *  分屏线一个贴图像素宽（3 页面像素 = 6 成片像素，和描边一样粗），整条压在左屏最右边：右屏的贴图像素格从画布左边起，不切出半格 */
export const 分屏版式 = { 左宽: 640, 右宽: 640, 线宽: 3, 线色: '#16181d' } as const;

/** 左屏的镜头：41.87、42.29 两拍看墙上的课表，之后沉到桌面（这一下在 42.29～42.72 之间推完，第 13 句「镜头往下沉」的余势）。
 *  景高 = 左屏这一整块布景按原大（现实课桌的设计宽 640）有多高：比一屏 720 高，墙更高、课表上下留白更多，镜头才沉得下去；
 *  推 = 放大几倍（现实课桌按 宽 640·推、高 景高·推 画），移x = 放大后的画往左挪几页面像素（取 0.5 的整数倍，现实/像素.ts 吸好的边才对得上）。
 *  竖直方向不另给：桌子前沿对齐右屏的地面线（时差分屏.tsx 现算），两屏共用一条横线，并排时像一个画面切成两半。
 *  1.2 倍时撕页本 204 宽（左屏三分之一）；心愿卡（含「____」）、笔筒都整个在画里，墙上只露课表最底下一截 */
export const 桌面镜 = { 景高: 900, 推: 1.2, 移x: 9 } as const;

/** 撕页的手（现实/撕页手.tsx）：手背宽 = 撕页本宽的几成，指尖从正上方往左转几度。两页之间手就捏在最上面那页的右下角，等下一拍撕 */
export const 手宽比 = 0.4;
export const 手转 = 38;
/** 捏住的页角往前翻起多大（撕页本宽的几成） */
export const 翻角比 = 0.06;

/** 撕一页用几帧：五页每页隔 10～11 帧，撕 5 帧（约 0.2 秒，一下就没了）；撕 6 帧以上，分屏静帧（43.80）那一帧 31 已经开始飞了 */
export const 撕帧数 = 5;

const 落事件 = [正片事件.撕页100, 正片事件.撕页62, 正片事件.撕页31, 正片事件.撕页7, 正片事件.撕页1] as const;
/** 撕页本上五页（100、62、31、7、1）各自完全露出来的歌曲帧 */
export const 落帧们: readonly number[] = 落事件.map((e) => e.帧);

/** 到这一帧落了几页（0 = 100 还没落，5 = 落到 1）。每落一页，树长一截、她换一个姿势（三稿） */
export const 落了几页 = (帧: number) => 落帧们.filter((f) => f <= 帧).length;

/** 太阳、月亮转多快：每拍两天（三稿：一节课 40 分钟 = MC 两天，课表一拍亮一节）。撕页加速以后也不再快：
 *  这样一帧已经转 70°，再快就看成乱跳；快慢差交给左屏的撕页 */
export const 每拍天数 = 2;
/** 分屏起（41.58）那一刻的游戏刻：0 = 日出，接第 12 句末「天一亮」 */
export const 起刻 = 0;
/** 一帧转多少刻 */
export const 每帧刻 = (每拍天数 * 24000) / (网格.拍长 * fps);

/** 右屏的调子从 夏日白天 往 褪色 插多少（色板.ts；三稿「你下线后她那边褪色」）：一页比一页褪得多，第一页 0.3、落到 1 是 0.7（31 那页 0.5）。
 *  不到整套 褪色：整套把她和樱花的粉也洗成了灰，她在半屏里本来就小，就认不出来了 */
export const 褪色程度 = (落了几页: number) => 0.3 + 0.1 * Math.min(4, Math.max(0, 落了几页 - 1));

/** 天随昼夜变暗的程度（门口画布的 明暗幅度，3D 调子也按它往夜里插）。一秒四五个昼夜，按 WCAG 2.3.1 闪烁要压到亮度起伏不到 10%（三稿：不超过每秒 3 次闪烁） */
export const 明暗幅度 = 0.1;

/** 太阳月亮的残影（地点/天空.tsx）：身后再画 10 个刚转过的位置（每个早 250 刻，约 3.5°），越远越淡，一级一级的像素拖尾；
 *  片子里一帧跳 70° 的太阳看着是在转，静帧里也看得出快。挨得再密（150 刻）太阳的白方块叠成一整条，认不出是太阳；
 *  这么隔，月牙那几天的拖尾是一串分开的小月牙（自检帧 第 1 页） */
export const 天体残影 = { 张: 10, 刻差: 250, 首透: 0.5 } as const;

export type 分屏态 = {
  /** 撕页.ts 的翻页值 */
  翻页: number;
  落了几页: number;
  /** 门口小木屋 的 树进度：落几页长几截 */
  树进度: number;
  /** 游戏刻（门口画布的 刻） */
  刻: number;
  /** 往夜里插多少（0～明暗幅度），给 3D 调子 */
  夜: number;
  /** 右屏从 夏日白天 往 褪色 插多少 */
  褪色: number;
};

/** 第 13 句分屏在歌曲帧 帧 的状态 */
export const 分屏态 = (帧: number): 分屏态 => {
  const 落 = 落了几页(帧);
  const 刻 = 起刻 + (帧 - 正片事件.分屏起.帧) * 每帧刻;
  return {
    翻页: 翻页值(帧, 落帧们, 撕帧数),
    落了几页: 落,
    树进度: Math.min(落, 樱花树阶段数) / 樱花树阶段数,
    刻,
    夜: 明暗幅度 * (1 - 天亮(刻)),
    褪色: 褪色程度(落),
  };
};
