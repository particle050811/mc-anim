/** 现实那半在歌曲帧 帧 的取景中心 [x, z]（格）：课表 → 桌面，smoothstep 缓进缓出，每帧吸到整贴图像素 */
export const 现实镜于 = (帧: number): readonly [number, number] => {
  const t = Math.min(1, Math.max(0, (帧 - 现实镜.沉起) / (现实镜.沉止 - 现实镜.沉起)));
  const s = t * t * (3 - 2 * t);
  const [a, b] = [现实镜.课表, 现实镜.桌面];
  return [吸到贴图像素(a[0] + (b[0] - a[0]) * s), 吸到贴图像素(a[1] + (b[1] - a[1]) * s)];
};

