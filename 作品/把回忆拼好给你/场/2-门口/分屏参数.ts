/** 翻页值 翻页 时手那头顶在哪（贴图像素，场景坐标）：最上面那页的右下角加 偏；撕的时候跟着往右上带一下（6、4 个贴图像素）。
 *  斜 = 斜投影里往里一个贴图像素画面上升几个（正交顶面 / N），用来把 偏 的 屏z 反算成 z */
export const 手到于 = (翻页: number, 偏: { x: number; 屏z: number; y: number }, 斜: number): readonly [number, number, number] => {
  const 角 = 撕页本角(算撕页态(翻页).顶);
  const 带 = Math.sin(Math.PI * (翻页 - Math.floor(翻页)));
  const b = 摆放.撕页本;
  const 角屏z = b.z + 角[2] + 斜 * (b.y + 角[1]);
  return [b.x + 角[0] + 偏.x + Math.round(6 * 带), 偏.y, Math.round(角屏z + 偏.屏z - 斜 * 偏.y) + Math.round(4 * 带)];
};

