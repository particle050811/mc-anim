/** 第 12 句末（段 2-空床）镜头往下沉、往右横移，最后一帧还在最快的时候切过来（三稿「镜头往下沉，横移进分屏」）。
 *  分屏这边接着同一个方向走：两屏里的东西从停稳的位置往右 横、往下 竖（页面像素）处起，往左上滑、按 (1 − t)² 越滑越慢，分屏成形到位 那一帧停稳；
 *  分屏线跟着从右边滑到正中，现实那半从右边推进来，服务器那半门一直贴着分屏线。
 *  分屏起到停稳 5 帧：第一帧走 112 成片像素往左、136 往上，和 2-空床 末帧的速度（往右 117、往下 156，编排.ts 的 末帧速度）差不多。
 *  每帧吸到 4 页面像素（N = 8 的一个贴图像素），两屏的网格照样连着。Agent 暂定 */
export const 成形 = { 横: 160, 竖: 192 } as const;

/** 歌曲帧 帧 时两屏还差多少到位（页面像素，横往右、竖往下为正）；分屏成形到位 以后是 0 */
export const 成形偏于 = (帧: number): { 横: number; 竖: number } => {
  const t = Math.min(1, Math.max(0, (帧 - 正片事件.分屏起.帧) / (正片事件.分屏成形到位.帧 - 正片事件.分屏起.帧)));
  const k = (1 - t) ** 2;
  const 吸4 = (v: number) => Math.round(v / 4) * 4;
  return { 横: 吸4(成形.横 * k), 竖: 吸4(成形.竖 * k) };
};
