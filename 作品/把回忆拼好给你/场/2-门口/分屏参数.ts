/** 第 13 句分屏在歌曲帧 帧 的状态 */
export const 分屏态 = (帧: number): 分屏态 => {
  const 落 = 落了几页(帧);
  const 刻 = 起刻 + (帧 - 正片事件.分屏起.帧) * 每帧刻;
  return {
    翻页: 翻页值(帧, 落帧们, 撕帧数),
    落了几页: 落,
    树进度: Math.min(落, 樱花树阶段数) / 樱花树阶段数,
    刻,
    夜: 明暗幅度 * (1 - 天亮(刻)),
    褪色: 褪色程度(落),
    现实镜: 现实镜于(帧),
    亮格: 亮格于(帧),
  };
};

