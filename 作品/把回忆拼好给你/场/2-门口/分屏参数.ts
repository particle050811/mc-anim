/** 版式（页面像素）：左右各半屏，两边同时发生、一样分量（时差是比出来的）；右屏 640 宽正好是 场/2-门口 的 半屏取景（门在 分屏门在）。
 *  分屏线一个贴图像素宽（3 页面像素 = 6 成片像素，和描边一样粗），整条压在左屏最右边：右屏的贴图像素格从画布左边起，不切出半格 */
export const 分屏版式 = { 左宽: 640, 右宽: 640, 线宽: 3, 线色: '#16181d' } as const;

/** 一格在成片上几个像素（左右同一个 N，画风.ts） */
const 每格 = 16 * 像素N;
/** 斜投影里往里一格画面上升几格 */
const 斜 = 正交顶面 / 像素N;
const 吸到贴图像素 = (v: number) => Math.round(v * 16) / 16;

/** 右屏的取景（门口那一路给第 13、14 句留的半屏取景） */
export const 右取景 = 半屏取景(分屏版式.右宽 * 2, 分屏门在);

/** 左屏的镜头（现实画布的取景，像素和右屏一样大）：横向让分屏线那条边对着 x = 0（课桌布局.ts 的 x 从这里往左数），
 *  这时左屏的贴图像素格和右屏连成同一张网格（成片 x ≡ 2 mod 6，见 分屏.test.ts）。
 *  竖向两个停处：看课表（41.87、42.29 两拍，课表框整个在画里、居中）；看桌面（桌子前沿对到右屏的地面线，两屏共用一条横线，像一个画面切成两半）。
 *  课表亮二 之后一拍里沉下去（第 13 句「镜头往下沉」的余势），撕页100 落下时已经停在桌面上；中心吸到整贴图像素，动的时候网格也不错开 */
export const 左镜 = {
  x: -(分屏版式.左宽 * 2) / 2 / 每格,
  课表z: 吸到贴图像素((摆放.课表.z + 课表框.高 / 2) / 16 + (斜 * 摆放.课表.y) / 16),
  桌面z: 右取景.中心[1],
  沉起: 正片事件.课表亮二.帧 + 2,
  沉止: 正片事件.撕页100.帧 - 1,
} as const;

/** 左屏取景的中心 z（格）：课表 → 桌面，smoothstep 缓进缓出 */
export const 左镜z = (帧: number) => {
  const t = Math.min(1, Math.max(0, (帧 - 左镜.沉起) / (左镜.沉止 - 左镜.沉起)));
  return 吸到贴图像素(左镜.课表z + (左镜.桌面z - 左镜.课表z) * t * t * (3 - 2 * t));
};

/** 课表亮格：41.87 亮周一第 1 节、42.29 亮第 2 节（三稿：一节 40 分钟），两帧亮满，之后一直亮着 */
export const 亮格于 = (帧: number): 亮格[] => {
  const 亮 = (起: number) => Math.min(1, Math.max(0, (帧 - 起 + 1) / 2));
  return [
    { 周: '周一', 节: '第1节', 亮: 亮(正片事件.课表亮一.帧) },
    { 周: '周一', 节: '第2节', 亮: 亮(正片事件.课表亮二.帧) },
  ].filter((g) => g.亮 > 0) as 亮格[];
};

/** 撕页的手（现实/撕页手.tsx）：一个皮肤像素 6 个贴图像素（手那头 24 个贴图像素，比撕页本的角大一圈，手臂从桌沿伸到画面底边，肩那头的青袖子露出来）；
 *  从竖直往右偏 40°，往里低 20°（肩那头离镜头近），绕手臂转 25° 露出内侧 */
export const 手摆 = { 倍: 6, 斜: 40, 滚: 25, 俯: 20 } as const;
/** 手那头端面的中心对在哪（贴图像素）：手整个在桌子前沿外面（深 y，负的是桌沿往外），画面上落在页角往右 x、往上 屏z 的地方（斜投影里深一格画面高 1/3 格，按这个反算 z）。
 *  手顶着页角，不盖住「天」；放在桌沿外面，手臂不会插进桌面里 */
export const 手偏 = { x: 3, 屏z: 1, y: -9 } as const;

/** 翻页值 翻页 时手那头顶在哪（贴图像素，场景坐标）：最上面那页的右下角加 手偏；撕的时候跟着往右上带一下（6、4 个贴图像素） */
export const 手到于 = (翻页: number): readonly [number, number, number] => {
  const 角 = 撕页本角(算撕页态(翻页).顶);
  const 带 = Math.sin(Math.PI * (翻页 - Math.floor(翻页)));
  const b = 摆放.撕页本;
  const 角屏z = b.z + 角[2] + 斜 * (b.y + 角[1]);
  return [b.x + 角[0] + 手偏.x + Math.round(6 * 带), 手偏.y, Math.round(角屏z + 手偏.屏z - 斜 * 手偏.y) + Math.round(4 * 带)];
};

/** 撕一页用几帧：五页每页隔 10～11 帧，撕 5 帧（约 0.2 秒，一下就没了）；撕 6 帧以上，分屏静帧（43.80）那一帧 31 已经开始飞了 */
export const 撕帧数 = 5;

const 落事件 = [正片事件.撕页100, 正片事件.撕页62, 正片事件.撕页31, 正片事件.撕页7, 正片事件.撕页1] as const;
/** 撕页本上五页（100、62、31、7、1）各自完全露出来的歌曲帧 */
export const 落帧们: readonly number[] = 落事件.map((e) => e.帧);

/** 到这一帧落了几页（0 = 100 还没落，5 = 落到 1）。每落一页，树长一截、她换一个姿势（三稿） */
export const 落了几页 = (帧: number) => 落帧们.filter((f) => f <= 帧).length;

/** 太阳、月亮转多快：每拍两天（三稿：一节课 40 分钟 = MC 两天，课表一拍亮一节）。撕页加速以后也不再快：
 *  这样一帧已经转 70°，再快就看成乱跳；快慢差交给左屏的撕页 */
export const 每拍天数 = 2;
/** 分屏起（41.58）那一刻的游戏刻：0 = 日出，接第 12 句末「天一亮」 */
export const 起刻 = 0;
/** 一帧转多少刻 */
export const 每帧刻 = (每拍天数 * 24000) / (网格.拍长 * fps);

/** 右屏的调子从 夏日白天 往 褪色 插多少（色板.ts；三稿「你下线后她那边褪色」）：一页比一页褪得多，第一页 0.3、落到 1 是 0.7（31 那页 0.5）。
 *  不到整套 褪色：整套把她和樱花的粉也洗成了灰，她在半屏里本来就小，就认不出来了 */
export const 褪色程度 = (落了几页: number) => 0.3 + 0.1 * Math.min(4, Math.max(0, 落了几页 - 1));

/** 天随昼夜变暗的程度（门口画布的 明暗幅度，3D 调子也按它往夜里插）。一秒四五个昼夜，按 WCAG 2.3.1 闪烁要压到亮度起伏不到 10%（三稿：不超过每秒 3 次闪烁） */
export const 明暗幅度 = 0.1;

/** 太阳月亮的残影（地点/天空.tsx）：身后再画 10 个刚转过的位置（每个早 250 刻，约 3.5°），越远越淡，一级一级的像素拖尾；
 *  片子里一帧跳 70° 的太阳看着是在转，静帧里也看得出快。挨得再密（150 刻）太阳的白方块叠成一整条，认不出是太阳；
 *  这么隔，月牙那几天的拖尾是一串分开的小月牙（自检帧 第 1 页） */
export const 天体残影 = { 张: 10, 刻差: 250, 首透: 0.5 } as const;

export type 分屏态 = {
  /** 撕页.ts 的翻页值 */
  翻页: number;
  落了几页: number;
  /** 门口小木屋 的 树进度：落几页长几截 */
  树进度: number;
  /** 游戏刻（门口画布的 刻） */
  刻: number;
  /** 往夜里插多少（0～明暗幅度），给 3D 调子 */
  夜: number;
  /** 右屏从 夏日白天 往 褪色 插多少 */
  褪色: number;
  /** 左屏取景中心的 z（格） */
  左z: number;
  /** 课表亮着的格 */
  亮格: 亮格[];
};

/** 第 13 句分屏在歌曲帧 帧 的状态 */
export const 分屏态 = (帧: number): 分屏态 => {
  const 落 = 落了几页(帧);
  const 刻 = 起刻 + (帧 - 正片事件.分屏起.帧) * 每帧刻;
  return {
    翻页: 翻页值(帧, 落帧们, 撕帧数),
    落了几页: 落,
    树进度: Math.min(落, 樱花树阶段数) / 樱花树阶段数,
    刻,
    夜: 明暗幅度 * (1 - 天亮(刻)),
    褪色: 褪色程度(落),
    左z: 左镜z(帧),
    亮格: 亮格于(帧),
  };
};
