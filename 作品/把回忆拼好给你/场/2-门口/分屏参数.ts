export const 第3截形状: readonly string[] = ['....L....', '...LLL...', '...LTL...', '....T....', '....T....'];

/** 照 地点/樱花树.ts 的 樱花树方块 一样搭（前后排：左右都有叶子的叶子、树干各补一块叶子），只给第 3 截用 */
const 按形状搭 = (行们: readonly string[], 根: readonly [number, number, number]): 方块[] => {
  const [i0, j0, k0] = 根;
  const out: 方块[] = [];
  行们.forEach((行, r) => {
    const k = k0 + 行们.length - 1 - r;
    const 有叶 = (c: number) => 行[c] === 'L' || 行[c] === 'T';
    for (let c = 0; c < 行.length; c++) {
      const i = i0 + c - 4;
      if (行[c] === 'L') out.push({ 状态: 'minecraft:cherry_leaves', 位: [i, j0, k] });
      if (行[c] === 'T') out.push({ 状态: 'minecraft:cherry_log[axis=y]', 位: [i, j0, k] });
      if (有叶(c) && 有叶(c - 1) && 有叶(c + 1)) {
        out.push({ 状态: 'minecraft:cherry_leaves', 位: [i, j0 - 1, k] });
        out.push({ 状态: 'minecraft:cherry_leaves', 位: [i, j0 + 1, k] });
      }
    }
  });
  return out;
};

/** 分屏里树进度 进度 时的方块（格编号，画的时候传 原点 = 门口小木屋.tsx 的 格原点）；根 是树苗那一格 */
export const 分屏树方块 = (进度: number, 根: readonly [number, number, number]): 方块[] => {
  const 阶段 = 樱花树阶段(进度);
  return 阶段 === 3 ? 按形状搭(第3截形状, 根) : 樱花树方块(阶段, 根);
};

