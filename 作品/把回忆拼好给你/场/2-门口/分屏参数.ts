// ---------- 接进来（段 2-时差 开头） ----------
/** 第 12 句末（段 2-空床）镜头往右横移出屋、越走越快，最后一帧还在最快的时候切过来（三稿「横移进分屏」）。
 *  分屏这边接着同一个方向走：两屏从停稳的位置往右 横（页面像素）处起，往左滑、按 (1 − t)² 越滑越慢，分屏成形到位 那一帧停稳；
 *  分屏线跟着从右边滑到正中，现实那半从右边推进来，服务器那半门一直贴着分屏线。
 *  第一步走 横 × 0.36（5 帧到位），接 2-空床 末帧的速度（编排.ts 的 末帧速度：每帧 6.1 × 1.5 ÷ 9 格 × 208 = 211.5 页面像素），取 横 = 211.5 ÷ 0.36 吸到 4 的倍数。
 *  原来 2-空床 往右下沉进土里、这边从右下斜着滑进来，切的那一下从一整屏暗土跳到亮天（用户 10-24 粗剪「2-空床 → 2-时差 亮度跳」）；
 *  现在那边末帧是屋外天亮的草地和天，这边一开头是服务器那半的草地和天，地面线差不到 30 页面像素。
 *  分屏.test.ts 核这个速度。每帧吸到 4 页面像素（N = 8 的一个贴图像素），两屏的网格照样连着。Agent 暂定 */
export const 成形 = { 横: 588 } as const;

/** 歌曲帧 帧 时两屏还差多少到位（页面像素，往右为正）；分屏成形到位 以后是 0 */
export const 成形偏于 = (帧: number): number => {
  const t = Math.min(1, Math.max(0, (帧 - 正片事件.分屏起.帧) / (正片事件.分屏成形到位.帧 - 正片事件.分屏起.帧)));
  return Math.round((成形.横 * (1 - t) ** 2) / 4) * 4;
};
