/** 第 13 句分屏在歌曲帧 帧 的状态 */
export const 分屏态 = (帧: number): 分屏态 => {
  const 截 = 长了几截(帧);
  const 秒 = 帧 / fps;
  return {
    长了几截: 截,
    生长: Math.min(截, 樱花树阶段数) / 樱花树阶段数,
    姿势: 换姿帧们.filter((f) => f <= 帧).length,
    褪色: 褪色程度(截),
    日历: 日历数(秒, 日历窗),
    飞: 飞页们(秒, 日历窗, fps),
    亮格: 亮格于(帧),
  };
};

