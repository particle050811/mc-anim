// 第 9–11 句谁在哪、什么姿势、手里拿什么、牌上写到哪、气泡、亮档：按歌曲帧算，画法在 门口之夜画布.tsx。纯模块（测试读）。
// 你：种树苗（朝西）→ 转身插牌子（朝东）→ 推近时在画外写字 → 拿着烟花火箭朝西低头 → 每发右键放出、抬头跟着火箭看炸开。
// 她：第 8 句末态（闭眼歪头笑）匹配剪进来，睁眼转头看你种树、插牌子，「抬头看天」以后一直仰头看烟花，炸开那一下大笑。
// 她身子朝镜头、头转 55° 往左上看烟花（头不取 90° 的整数倍）：烟花在画面左边，身子转过去就看不见脸（静帧定稿：看清优先，记在 decisions）。
import { clamp01 } from '@engine/anim/anim.ts';
import { 加挥手, 挥手进度 } from '@库/角色/挥手.ts';
import { 火箭位置, 炸点, 炸开秒 } from '@库/特效/烟花.ts';
import { fps, 正片事件 } from '../../分镜.ts';
import { 你站, 她站, 写到, 插牌秒, 烟花们, 牌上的字, 种下秒, 站排y } from './门口之夜参数.ts';

const 秒 = (帧: number) => 帧 / fps;
const 插 = (a: number, b: number, t: number) => a + (b - a) * t;
const 事 = 正片事件;

// ---------- 你 ----------
export type 手持 = '树苗' | '告示牌' | '烟花火箭' | null;
export type 你态 = { x: number; yaw: number; 头俯仰: number; 拿: 手持; 挥: number };

/** 转身用几帧（中间那帧正对镜头） */
const 转身帧 = 2;
/** 种树苗、放烟花前低头看地面；插牌子、写字时看牌子（度，负 = 低头） */
const 低头 = -40;
const 看牌 = -15;
/** 放出前多久低头对着地面、放出后抬头跟着火箭看（看到炸完再过多久低头准备下一发） */
const 放前低头秒 = 0.25;
const 看炸完秒 = 0.4;
/** 抬头最多 50°（原版能抬到 90°；侧身仰太多头像折断了） */
const 最仰 = 50;
const 眼高 = 1.62;

/** 头对着场景里一点的俯仰（侧身站，只看 x、z） */
const 俯仰向 = (x: number, z: number) => {
  const d = Math.abs(x - 你站);
  return Math.min(最仰, (Math.atan2(z - 眼高, Math.max(0.3, d)) * 180) / Math.PI);
};

export const 你态 = (帧: number): 你态 => {
  const s = 秒(帧);
  const 转起 = 正片事件.第9句插牌子.帧 - 转身帧 - 1;
  const 换火箭 = 正片事件.写见.帧 + 4;
  const 挥 = (t: number) => 挥手进度(s - t);
  if (帧 < 转起) {
    // 朝西：头两帧手里拿着树苗，种下后手里空了
    return { x: 你站, yaw: 90, 头俯仰: 低头, 拿: s < 种下秒 ? '树苗' : null, 挥: 挥(种下秒) };
  }
  if (帧 < 转起 + 转身帧) {
    // 拿出告示牌、经正对镜头转向东
    return { x: 你站, yaw: 180, 头俯仰: 看牌, 拿: '告示牌', 挥: 0 };
  }
  if (帧 < 换火箭) {
    return { x: 你站, yaw: -90, 头俯仰: 看牌, 拿: s < 插牌秒 ? '告示牌' : null, 挥: 挥(插牌秒) };
  }
  // 写完（推近时在画外）：换上烟花火箭、转回朝西低头；之后每发放出前低头、放出时挥手、之后抬头看火箭和炸开
  let 头 = 低头;
  let 挥手 = 0;
  for (const 发 of 烟花们) {
    const 放 = 发.发射秒;
    const 炸 = 炸开秒(发);
    if (s >= 放 - 放前低头秒 && s < 放) 头 = 低头;
    else if (s >= 放 && s < 炸) {
      const p = 火箭位置(发, s);
      if (p) 头 = Math.max(低头, 俯仰向(p[0], p[2]));
    } else if (s >= 炸 && s < 炸 + 看炸完秒) {
      const [x, , z] = 炸点(发);
      头 = 俯仰向(x, z);
    }
    挥手 = Math.max(挥手, 挥(放));
  }
  // 最后一发炸完一直仰着看（定格成照片）
  const 末 = 烟花们[烟花们.length - 1]!;
  if (s >= 炸开秒(末)) {
    const [x, , z] = 炸点(末);
    头 = 俯仰向(x, z);
  }
  return { x: 你站, yaw: 90, 头俯仰: 头, 拿: '烟花火箭', 挥: 挥手 };
};

