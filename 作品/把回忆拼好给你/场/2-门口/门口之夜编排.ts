// 你：一直站在牌子和门中间、面朝西：低头种下树苗 → 换上告示牌插下 → 空手看着牌子写字 → 镜头拉开时拿上烟花火箭，每发低头右键放出、抬头跟着火箭看炸开。
// 她：第 8 句末态（闭眼歪头笑）匹配剪进来，睁眼转头看你种树、看牌子，镜头跟火箭走起抬头看天，一直仰头看烟花，炸开那一下笑开。
// 她身子朝镜头、头往左上转 30° 看烟花（头不取 90° 的整数倍）：烟花在画面左边，身子转过去就看不见脸；头转过 50° 帽檐就把脸盖住（第8句.ts 量过），
// 收到 30°、仰 20°，脸露在帽檐下面（静帧定稿：看清优先）。
import { clamp01 } from '@engine/anim/anim.ts';
import { 加挥手, 挥手进度 } from '@库/角色/挥手.ts';
import { 火箭位置, 炸点, 炸开秒 } from '@库/特效/烟花.ts';
import { fps, 正片事件 } from '../../分镜.ts';
import { 你站, 她站, 插牌秒, 烟花们, 牌字面, 牌上行们, 种下秒, 树苗x, 站排y, 镜头段 } from './门口之夜参数.ts';

const 秒 = (帧: number) => 帧 / fps;
const 插 = (a: number, b: number, t: number) => a + (b - a) * t;
const 事 = 正片事件;

// ---------- 你 ----------
export type 手持 = '树苗' | '告示牌' | '烟花火箭' | null;
export type 你态 = { x: number; yaw: number; 头俯仰: number; 拿: 手持; 挥: number };

/** 放出前多久低头对着地面、放出后抬头跟着火箭看（看到炸完再过多久低头准备下一发） */
const 放前低头秒 = 0.25;
const 看炸完秒 = 0.4;
/** 抬头最多 50°、低头最多 40°（原版能到 ±90°；侧身仰、俯太多，头像折断了） */
const 最仰 = 50;
const 最俯 = -40;
const 眼高 = 1.62;

/** 头对着场景里一点的俯仰（侧身站，只看 x、z；度，负 = 低头） */
const 俯仰向 = (x: number, z: number) => {
  const d = Math.abs(x - 你站);
  return Math.max(最俯, Math.min(最仰, (Math.atan2(z - 眼高, Math.max(0.3, d)) * 180) / Math.PI));
};
/** 低头看地上那一格的顶面中心 */
const 看地 = (x: number) => 俯仰向(x, 0);

export const 你态 = (帧: number): 你态 => {
  const s = 秒(帧);
  // 原版连着右键：前一下挥过一半，后一下重新挥（LivingEntity.swing）
  const 挥 = (t: number) => 挥手进度(s - t);
  const 第一发 = 烟花们[0]!;
  if (s < 第一发.发射秒 - 放前低头秒) {
    // 种树苗（头两帧手里拿着树苗，匹配剪进来看得到）→ 插牌子 → 写字（空手看着牌面）；镜头从牌子上拉开时换上烟花火箭（拿早了，火箭从特写的右边戳进来）
    const 种了 = s >= 种下秒;
    const 插了 = s >= 插牌秒;
    const 头 = !种了 ? 看地(树苗x) : !插了 ? 看地(牌字面.x) : 俯仰向(牌字面.x, 牌字面.z);
    const 拿: 手持 = !种了 ? '树苗' : !插了 ? '告示牌' : s >= 镜头段.跟起 ? '烟花火箭' : null;
    return { x: 你站, yaw: 90, 头俯仰: 头, 拿, 挥: 插了 ? 挥(插牌秒) : 挥(种下秒) };
  }
  // 放烟花：每发放出前低头、放出时挥手、之后抬头看火箭和炸开
  let 头 = 看地(第一发.位[0]);
  let 挥手 = 0;
  for (const 发 of 烟花们) {
    const 放 = 发.发射秒;
    const 炸 = 炸开秒(发);
    if (s >= 放 - 放前低头秒 && s < 放) 头 = 看地(发.位[0]);
    else if (s >= 放 && s < 炸) {
      const p = 火箭位置(发, s);
      if (p) 头 = Math.max(看地(发.位[0]), 俯仰向(p[0], p[2]));
    } else if (s >= 炸 && s < 炸 + 看炸完秒) {
      const [x, , z] = 炸点(发);
      头 = 俯仰向(x, z);
    }
    挥手 = Math.max(挥手, 挥(放));
  }
  // 最后一发炸完一直仰着看（定格成照片）
  const 末 = 烟花们[烟花们.length - 1]!;
  if (s >= 炸开秒(末)) {
    const [x, , z] = 炸点(末);
    头 = 俯仰向(x, z);
  }
  return { x: 你站, yaw: 90, 头俯仰: 头, 拿: s >= 镜头段.跟起 ? '烟花火箭' : null, 挥: 挥手 };
};

