/** 相纸：白边的颜色和宽（照片像素）。照 场/1-隐世之境一楼/参数.ts 的 拍立得样式（第 11 句的拍立得照它）：三边 0.03、下边 0.12 个画面宽，
 *  64 像素宽的画面上取整成三边 2、下边 8；相纸色同它 */
export const 相纸 = { 色: '#fbfaf6', 边: 2, 下边: 8 } as const;

/** 一张照片（连白边）多少照片像素 */
export const 照片尺寸 = (画: 像素画) => ({ 宽: 画.宽 + 2 * 相纸.边, 高: 画.高 + 相纸.边 + 相纸.下边 });

/** 照片连白边的 RGBA 像素（从上往下一行行排），给 照片.tsx 做贴图 */
export const 照片像素 = (画: 像素画): Uint8Array => {
  const { 宽, 高 } = 照片尺寸(画);
  const out = new Uint8Array(宽 * 高 * 4);
  const 涂 = (X: number, Y: number, c: RGB) => out.set([c[0], c[1], c[2], 255], (Y * 宽 + X) * 4);
  const 纸 = rgb(相纸.色);
  for (let y = 0; y < 高; y++) for (let x = 0; x < 宽; x++) 涂(x, y, 纸);
  const 点 = (x: number, y: number, c: string) => {
    x = Math.round(x);
    y = Math.round(y);
    if (x < 0 || y < 0 || x >= 画.宽 || y >= 画.高) return;
    if (!/^#[0-9a-f]{6}$/i.test(c)) throw new Error(`照片「${画.名}」的颜色「${c}」不是 #rrggbb`);
    涂(x + 相纸.边, y + 相纸.边, rgb(c));
  };
  const 笔: 画笔 = {
    点,
    块: (x0, y0, x1, y1, c) => {
      for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) 点(x, y, c);
    },
    椭圆: (cx, cy, rx, ry, c) => {
      for (let y = Math.floor(cy - ry); y <= Math.ceil(cy + ry); y++)
        for (let x = Math.floor(cx - rx); x <= Math.ceil(cx + rx); x++) if (((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2 <= 1) 点(x, y, c);
    },
    横带: (y0, y1, 色们) => {
      for (let y = y0; y < y1; y++) {
        const c = 色们[Math.min(色们.length - 1, Math.floor(((y - y0) * 色们.length) / (y1 - y0)))]!;
        for (let x = 0; x < 画.宽; x++) 点(x, y, c);
      }
    },
    贴: (x, y, 行们, 色, 选项 = {}) => {
      行们.forEach((行, j) =>
        [...行].forEach((字, i) => {
          if (字 === '.') return;
          const c = 色[字];
          if (!c) throw new Error(`照片「${画.名}」的小图里字符「${字}」没有颜色`);
          const ii = 选项.镜像 ? 行.length - 1 - i : i;
          点(x + ii, y + j, c);
        }),
      );
    },
    撒: (x0, y0, x1, y1, 密度, c, 种子) => {
      for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) if (哈希(x, y, 种子) < 密度) 点(x, y, c);
    },
  };
  画.画(笔);
  return out;
};
