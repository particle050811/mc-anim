type RGB = readonly [number, number, number];
const rgb = (hex: string): RGB => [parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16)];

/** 在 宽 × 高 的画面里画（x 往右、y 往下，整数像素；画出界的自动裁掉） */
export type 画笔 = {
  点: (x: number, y: number, c: string) => void;
  /** [x0, x1) × [y0, y1) */
  块: (x0: number, y0: number, x1: number, y1: number, c: string) => void;
  /** 实心椭圆：像素中心落在里面的都涂 */
  椭圆: (cx: number, cy: number, rx: number, ry: number, c: string) => void;
  /** y0～y1 按 色们 平分成几条横带（像素画的天） */
  横带: (y0: number, y1: number, 色们: readonly string[]) => void;
  /** 小图：行们从上往下，'.' 透明，别的字符查 色；镜像 = 左右翻 */
  贴: (x: number, y: number, 行们: readonly string[], 色: Readonly<Record<string, string>>, 选项?: { 镜像?: boolean }) => void;
  /** 在 [x0, x1) × [y0, y1) 里按位置哈希撒点，密度 0～1（同一张画每次一样） */
  撒: (x0: number, y0: number, x1: number, y1: number, 密度: number, c: string, 种子: number) => void;
};

export type 像素画 = { 名: string; 宽: number; 高: number; 画: (笔: 画笔) => void };

const 哈希 = (x: number, y: number, s: number) => {
  let h = (x * 374761393 + y * 668265263 + s * 2147483647) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
};

