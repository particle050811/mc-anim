import { 人色, 史蒂夫图, 她图, type 像素画 } from './照片画.ts';

const 烟花 = (笔: Parameters<像素画['画']>[0], cx: number, cy: number, r: number, 色: string, 芯: string) => {
  // 八个方向的光点，外圈一层、里圈一层，中心一个亮芯
  for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1], [0.7, 0.7], [-0.7, 0.7], [0.7, -0.7], [-0.7, -0.7]] as const) {
    笔.点(cx + dx * r, cy + dy * r, 色);
    笔.点(cx + dx * r * 0.55, cy + dy * r * 0.55, 色);
  }
  笔.点(cx, cy, 芯);
};

export const 合照: 像素画 = {
  名: '合照',
  宽: 64,
  高: 36,
  画: (笔) => {
    笔.横带(0, 29, ['#0b1440', '#101c52', '#172764', '#1f3274']);
    笔.撒(0, 0, 64, 22, 0.03, '#c9d6ff', 7);
    烟花(笔, 22, 6, 5, '#ff7ab8', '#fff2a8');
    烟花(笔, 41, 8, 6, '#ffd36a', '#ffffff');
    烟花(笔, 32, 3, 3, '#7af0ff', '#ffffff');
    笔.块(0, 29, 64, 36, '#2f4a2a');
    笔.块(0, 29, 64, 30, '#3d5e34');
    笔.撒(0, 30, 64, 36, 0.2, '#263d22', 4);
    笔.贴(22, 14, 史蒂夫图, 人色);
    笔.贴(32, 12, 她图, 人色);
  },
};
