/** 盖住 周×节 这一格的那个格（合并格返回整块） */
export const 找格 = (周: 星期, 节: 节名): 课表格 => {
  const 列 = 星期们.indexOf(周);
  const 行 = 节们.findIndex((n) => n.节 === 节);
  const 格 = 课表格们.find((g) => 行 >= g.行 && 行 < g.行 + g.跨行 && 列 >= g.列 && 列 < g.列 + g.跨列);
  if (!格) throw new Error(`课表里没有 ${周} ${节} 这一格`);
  return 格;
};
