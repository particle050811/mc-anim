// 桌上倒计时日历被风吹的进度（纯函数，段.ts、测试也能读）：用户 10-24「撕页 改成 风吹日历 掉的越来越快 撕日历还得做撕的动作 反而麻烦」。
// 起（第 100 拍）到止（第 104 拍）之间，从 100 一页页吹到 1：第 k 页在 起 + 时长 × ((k − 1) / 98)^(1 / 加速) 离开本子，头一页单独飞、往后越来越密，
// 最后一页（2）正好在 止 飞走、停在 1。飞走的纸往右上翻着飞出画面；一帧里飞走好几页时只画其中几张（按页号散列挑，每帧挑的不跳）。
import { hash2 } from '@engine/core/噪声.ts';

/** 日历的尺寸（贴图像素，日历本.tsx 按它搭）。宽 48：「距高考还有」一行 44 宽、「100天」大字 2 倍也 44 宽；页高 32；装订 6 高、8 深；纸叠 2～6 深（剩 1 页到满 100 页）。
 *  比原来的 64 宽、3 倍大字小一圈：课表要整张露在右屏里（用户 10-24「课程表怎么不展示完全」），桌上只剩日历一样东西。Agent 暂定 */
export const 日历尺寸 = { 宽: 48, 页高: 32, 装订高: 6, 装订深: 8, 纸最薄: 2, 纸最厚: 6 } as const;

/** 第一页的天数 */
export const 满页 = 100;

/** 吹日历的节奏：加速 = 离开时刻的幂（越大头几页越疏、最后越密）；飞 = 一页从离开到飞出画面几秒；每帧最多画几张新飞走的。
 *  加速 2.5：第 1 页单独飞 0.27 秒，第 2、3 页隔 2 帧，到最后一帧走 6 页。每帧最多画 1.5 张：最后 10 帧空中也只十来张，不糊成一团白。Agent 暂定 */
export const 吹法 = { 加速: 2.5, 飞: 0.42, 每帧最多: 1.5 } as const;

export type 吹窗 = { 起: number; 止: number };

/** 第 k 页（k = 1 是 100 那页，k = 满页 − 1 是 2 那页）离开本子的秒数 */
export const 离开秒 = (k: number, 窗: 吹窗) => 窗.起 + (窗.止 - 窗.起) * ((k - 1) / (满页 - 2)) ** (1 / 吹法.加速);

/** 到 秒 为止飞走了几页（离开那一刻算飞走） */
export const 飞走几页 = (秒: number, 窗: 吹窗): number => {
  if (秒 < 窗.起) return 0;
  if (秒 >= 窗.止) return 满页 - 1;
  const u = (秒 - 窗.起) / (窗.止 - 窗.起);
  // 反解 离开秒：u ≥ ((k − 1) / 98)^(1/加速) ⇔ k ≤ 1 + 98 u^加速
  return Math.min(满页 - 1, Math.floor(1 + (满页 - 2) * u ** 吹法.加速 + 1e-9));
};

/** 本子最上面那页印的天数 */
export const 日历数 = (秒: number, 窗: 吹窗) => 满页 - 飞走几页(秒, 窗);

/** 第 k 页离开时一帧走几页（离开秒 的倒数 × 帧长），用来挑画哪几张 */
const 每帧页数 = (k: number, fps: number) => {
  const u = ((k - 1) / (满页 - 2)) ** (1 / 吹法.加速);
  return u <= 0 ? 0 : ((满页 - 2) * 吹法.加速 * u ** (吹法.加速 - 1)) / fps;
};

export type 飞页 = { 数: number; 龄: number; 种: number };

/** 秒 这一刻还在空中的纸（先飞的在前）：龄 = 离开了几秒的比例（0～1），种 = 这张自己的散列（翻法、偏一点） */
export const 飞页们 = (秒: number, 窗: 吹窗, fps: number): 飞页[] => {
  const out: 飞页[] = [];
  const n = 飞走几页(秒, 窗);
  for (let k = 1; k <= n; k++) {
    const 龄 = (秒 - 离开秒(k, 窗)) / 吹法.飞;
    if (龄 >= 1) continue;
    const 种 = hash2(k, 7, 4021);
    const 密 = 每帧页数(k, fps);
    if (密 > 吹法.每帧最多 && 种 * 密 >= 吹法.每帧最多) continue;
    out.push({ 数: 满页 + 1 - k, 龄: Math.max(0, 龄), 种 });
  }
  return out;
};

/** 一张飞纸在 龄（0～1）时相对它原来位置（页面左下角）的位移和样子（贴图像素）：往右上加速飞、上下翻（高 = 页高 × |cos|，背面朝外时露纸背）。
 *  头一点往上掀（风从下面把页角掀起来），再往右上甩出去；翻两圈到两圈半，按 种 错开。Agent 暂定的轨迹 */
export const 飞姿 = (龄: number, 种: number) => {
  const 翻 = Math.PI * 龄 * (4 + 种);
  const c = Math.cos(翻);
  return {
    dx: Math.round(龄 * 8 + 龄 * 龄 * (70 + 20 * 种)),
    dz: Math.round(龄 * 24 + 龄 * 龄 * 120),
    高: Math.max(1, Math.round(日历尺寸.页高 * Math.abs(c))),
    背: c < 0,
  };
};

/** 剩 顶 页时纸叠多厚（整贴图像素）。纸叠贴着装订的后边，越吹越薄，正面往里退 */
export const 纸厚 = (顶: number) => {
  const S = 日历尺寸;
  return Math.round(S.纸最薄 + (S.纸最厚 - S.纸最薄) * Math.min(1, Math.max(0, 顶 / 满页)));
};

/** 一页上字怎么排（贴图像素，原点是页面左上角，页面 = 日历尺寸 宽 × 页高）：小字「距高考还有」一行（游戏像素字，汉字 8 高、步进 9），
 *  下面大数字放大 2 倍（原版位图数字 5×7、步进 6），「天」跟在数字右边、底对齐。数字和「天」作为一组水平居中 */
export const 页版式 = (数: number) => {
  const 宽 = 日历尺寸.宽;
  const 倍 = 2;
  const 数宽 = (String(数).length * 6 - 1) * 倍;
  const x = Math.floor((宽 - (数宽 + 2 + 8)) / 2);
  const y = 14;
  return { 小字y: 3, 大字倍: 倍, 数: { x, y, 宽: 数宽, 高: 7 * 倍 }, 天: { x: x + 数宽 + 2, y: y + 7 * 倍 - 8, 宽: 8, 高: 8 } };
};
