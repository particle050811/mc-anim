// 第 14 句楼上（46.13～48.26，分屏右半）：教学楼楼上走廊的栏杆边，史蒂夫的两只手抱着一摞书和卷子，46.98 撕开最上面那本、举到栏杆外，47.41 撒手，书和纸往下落。纯数据（测试也读）。
// 机位同门口（侧剖面朝北，顶面 2）：剖面切在走廊的栏杆（j = 0）上，人站在栏杆这边（镜头这边），两只手（撕页手，第一人称的方块手臂）从画面底下伸上来越过栏杆；
//   栏杆那边是楼外，远处是对面那栋教学楼（j = 对面楼.j）。撒出去的东西落到栏杆那边，掉到栏杆顶以下就被栏杆挡住（书是三维的，纸雨是 2D 叠层，按 栏杆顶屏 裁）。
// 坐标：格 (i, j, k) 同 门口小木屋（x 东、y 北、z 上，栏杆脚 z = 0）；书、手按贴图像素写（像素空间 原点同场景原点，一格 16 个）。全是 Agent 暂定。

/** 像素密度同左屏（归隐N = 分屏N，两屏像素一样大）；俯角同门口 */
export const 楼上N = 8;
export const 楼上顶面 = 2;

/** 取景（半屏 10 × 11.25 格）：x 0～10；竖着中心 z 4.5：栏杆脚（走廊地面）离画面底 1.1 格，栏杆顶 1.5 格，对面楼顶（斜投影里 5.5）上面露 4.6 格天，
 *  左上角歌词那一行（z 8.6～9.5）底下是天 */
export const 楼上取景 = { 中心: [5, 4.5] as const, 每格: 16 * 楼上N };

/** 栏杆：一格白色混凝土墙、上面压一层平滑石半砖（顶 z 1.5，比人腰高一点）；下面一格是走廊楼板的剖面，再往下是外墙。左右铺 [左, 右) */
export const 栏杆 = { 左: -3, 右: 13, 顶: 1.5 } as const;

/** 对面那栋教学楼：j 远处一排立面，k 底～顶（楼顶 z 2，斜投影里画面上抬 j × 顶面 ÷ N = 3.5 格），每 层高 一层：楼板线一格、窗一排两格高、窗间墙；
 *  窗每 窗距 格一扇（窗间留一格墙）。楼顶压低到栏杆上面只露一排窗：上面大半是天，手、书、纸雨衬在浅色上读得清（初稿楼顶 z 5 时立面铺满半屏，手和书糊在窗格里）。
 *  浮冰当玻璃（不透明、浅蓝，像反着天光；玻璃方块是透的，后面是天，读成破洞） */
export const 对面楼 = { j: 14, 底: -10, 顶: 2, 层高: 4, 窗距: 3, 左: -6, 右: 16, 窗: 'minecraft:packed_ice' } as const;
/** 化樱：对面楼从左（分屏线那边、风来的方向）往右一块块换成樱花树叶；每块早晚按列走、再加 抖 那么多的随机（0～1 的进度里），边不是一条直线 */
export const 化樱抖 = 0.25;

/** 天色（现实那半的阴天，sRGB）：栏杆外、对面楼顶上露出来的天，整片后期的「现实」调子还会再往冷里压 */
export const 楼上天色 = '#c3ccd3';

/** 一摞书（贴图像素）：从下往上三本、最上面那本底下夹一叠卷子，摆在右屏正中（x 80 像素 = 5 格）。x0 是左边，y0 前边（栏杆上空，栏杆 y 0～16），z0 底；宽、深、高。
 *  书宽 2.75 格（手机 390 宽上约 55 像素），比手臂（1.5 格）宽得多，读得出是「抱着一摞书」 */
export const 书们: readonly { 名: string; x0: number; 宽: number; 深: number; 高: number; 封: string; 封暗: string }[] = [
  { 名: '绿', x0: 58, 宽: 44, 深: 26, 高: 6, 封: '#4f7a45', 封暗: '#3f6337' },
  { 名: '蓝', x0: 60, 宽: 40, 深: 24, 高: 5, 封: '#3b5a8c', 封暗: '#2f4870' },
  { 名: '红', x0: 57, 宽: 44, 深: 26, 高: 7, 封: '#a8443a', 封暗: '#86362e' },
];
export const 卷子摞 = { x0: 59, 宽: 40, 深: 24, 高: 3 } as const;
/** 书摞的前边、底（贴图像素）：抱在栏杆顶上方 */
export const 书摞位 = { y0: 2, z0: 30 } as const;

/** 两只手（撕页手.tsx 的摆法，左手照右手左右镜像）：一个皮肤像素 6 个贴图像素（手臂 24 宽、72 长），
 *  从画面左下、右下两角斜着伸进来（离竖直 55°，肩那头在半屏左右边外面），手那头顶在书摞两头、书摞半高的地方，像两臂抱着一摞书 */
export const 楼上手摆 = { 倍: 6, 斜: 55, 滚: 20, 俯: 8 } as const;
/** 手那头离书摞两头往外几个像素（负 = 往里，手压住书摞的两个下角）、往前几个像素（手在书摞前面一点托着）、离书摞底多高 */
export const 托手 = { 外: -6, 前: -6, 高: 6 } as const;

/** 撕：最上面那本（红）撕成两半，撕书那一帧起 撕帧 帧往两边掰开 掰开 个像素、各往上翘 翘 个像素，撕口露出 撕口 个像素宽的白页；两只手跟着往外。
 *  撕完 举帧 帧把整摞举到栏杆外：往上 举高、往北（离镜头）举远 个像素 */
export const 撕书 = { 掰开: 6, 翘: 3, 撕口: 2, 撕帧: 2, 举帧: 4, 举高: 14, 举远: 24 } as const;

/** 撒手：两只手往外张开 张 个像素，第 收起 帧起 收帧 帧缩出画面：往外、往镜头这边（先退回栏杆这边，不穿进栏杆）、往下各 收走 个像素；
 *  书按原版掉落物的重力往下掉（0.04 格/刻² ≈ 每秒² 256 像素），掉到栏杆顶以下被挡住 */
export const 撒手 = { 张: 8, 张帧: 2, 收起: 3, 收帧: 6, 收走: [40, 40, 80], 重力: 256 } as const;

/** 贴图像素 (x, y, z) → 这一镜的「画面格」（纸雨.ts 用：x 同场景、z = 场景 z + y × 顶面 ÷ N，单位格） */
export const 画面格 = (x: number, y: number, z: number) => ({ x: x / 16, z: (z + (y * 楼上顶面) / 楼上N) / 16 });
const 书摞高 = 书们.reduce((s, b) => s + b.高, 0);
/** 卷子摞举到栏杆外以后的顶面（画面格的矩形）：撒手那一下纸从这里撒出去 */
export const 卷子顶框 = (() => {
  // 卷子夹在最上面那本（撕的那本）底下
  const y = 书摞位.y0 + 撕书.举远 + 1;
  const z = 书摞位.z0 + 撕书.举高 + 书摞高 - 书们[书们.length - 1]!.高 + 卷子摞.高;
  const 前 = 画面格(卷子摞.x0, y, z);
  const 后 = 画面格(卷子摞.x0 + 卷子摞.宽, y + 卷子摞.深, z);
  return { x0: 前.x, x1: 后.x, z0: 前.z, z1: 后.z };
})();
/** 撕口（画面格的矩形）：撕书那一下几张书页从红书（最上面那本）撕开的地方掉出来 */
export const 撕口框 = (() => {
  const 红 = 书们[书们.length - 1]!;
  const 中 = 红.x0 + 红.宽 / 2;
  const z = 书摞位.z0 + 书摞高 - 红.高 + 卷子摞.高;
  const 前 = 画面格(中 - 撕书.掰开, 书摞位.y0, z);
  const 后 = 画面格(中 + 撕书.掰开, 书摞位.y0 + 红.深, z + 红.高 + 撕书.翘);
  return { x0: 前.x, x1: 后.x, z0: 前.z, z1: 后.z };
})();


/** 楼上这一镜某一帧的样子（楼上.tsx 按它画）：撕开几成、举到栏杆外几成、撒手以后第几帧（之前是负的）和几秒、对面楼化成樱花树叶几成（0～1） */
export type 楼上态 = { 撕: number; 举: number; 撒手帧: number; 撒手秒: number; 化樱: number };

/** 歌曲帧 → 楼上态。时：撕书、撒手、化樱起止那几帧（歌曲帧，场从 分镜.ts 的正片事件取） */
export const 楼上态于 = (帧: number, 时: { 撕书: number; 撒手: number; 化起: number; 化止: number }, fps: number): 楼上态 => {
  const 举t = Math.min(1, Math.max(0, (帧 - 时.撕书) / 撕书.举帧));
  return {
    撕: Math.min(1, Math.max(0, (帧 - 时.撕书 + 1) / 撕书.撕帧)),
    举: 1 - (1 - 举t) ** 2,
    撒手帧: 帧 - 时.撒手,
    撒手秒: Math.max(0, (帧 - 时.撒手) / fps),
    化樱: Math.min(1, Math.max(0, (帧 - 时.化起) / (时.化止 - 时.化起))),
  };
};
