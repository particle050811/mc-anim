// 第 13 句左屏的现实部分：高三教室靠墙的一张课桌。上半是墙和贴在墙上的课表，下半是桌面，桌上立着撕页倒计时、透明笔筒，桌角贴着心愿卡。
// 画法：正面看墙、略俯看桌面的扁平平涂（桌面只往上收、不做近大远小），东西都是正面加一个顶面。只画物件，不画人；手以后另做。
// 整块是一张 <svg>，宽高就是分屏左半的页面像素，按 宽/640、高/720 里小的那个缩放（设计稿 640×720）。纯按 props 画，不读帧号。
import type React from 'react';
import { 现实色 } from './色板.ts';
import { 齐 } from './像素.ts';
import { 笔筒满度, 默认页们 } from './撕页.ts';
import { 撕页本 } from './撕页本.tsx';
import { 笔筒 } from './笔筒.tsx';
import { 心愿卡 } from './心愿卡.tsx';
import { 课表, 课表高, type 亮格 } from './课表.tsx';

export type { 亮格 };

/** 设计稿尺寸（分屏左半的大约大小） */
export const 设计宽 = 640;
export const 设计高 = 720;

/** 桌面的透视比：平躺在桌上的东西竖向压多少。Agent 暂定（约俯 46°） */
export const 桌面透视 = 0.72;

/** 各件东西在这块画面里的位置（页面像素，原点是这块 svg 的左上角）。镜头要推到哪一件、手要对到哪一张，用它 */
export const 课桌布局 = (宽: number, 高: number) => {
  const s = Math.min(宽 / 设计宽, 高 / 设计高);
  const 墙底 = 齐(高 * 0.58);
  const 桌前 = 齐(高 * 0.905);
  const 桌沿 = 齐(16 * s);
  const 进深 = 桌前 - 墙底;
  // 课表：墙上留出上下边，宽不超出画面两边
  const 表上 = 18 * s;
  const 表下 = 40 * s;
  const 表宽 = Math.min(宽 - 2 * 26 * s, (墙底 - 表上 - 表下) / (课表高(1)));
  const 表高 = 课表高(表宽);
  const 课表框 = { x: 齐((宽 - 表宽) / 2), y: 齐(表上 + (墙底 - 表上 - 表下 - 表高) / 2), 宽: 表宽, 高: 表高 };
  const 本宽 = 齐(170 * s);
  const 筒宽 = 齐(100 * s);
  return {
    s,
    墙底,
    桌前,
    桌沿,
    课表: 课表框,
    撕页本: { x: 齐(宽 * 0.37 - 本宽 / 2), 底: 齐(墙底 + 进深 * 0.6), 宽: 本宽 },
    笔筒: { x: 齐(宽 * 0.75 - 筒宽 / 2), 底: 齐(墙底 + 进深 * 0.7), 宽: 筒宽 },
    心愿卡: { x: 齐(宽 * 0.19), y: 齐(桌前 - 44 * s), 宽: 齐(208 * s) },
  };
};

export type 现实课桌参数 = {
  /** 这块画面的页面像素（分屏左半，约 640×720）；放到画面上的偏移取 0.5 的整数倍才对得上成片像素 */
  宽: number;
  高: number;
  /** 撕页进度（撕页.ts）：整数 k 停在 页们[k]，小数是正在撕；第 f 帧的值用 翻页值(f, 落帧们, 撕帧数) 算 */
  翻页: number;
  /** 撕页本上依次停的天数，默认 100、62、31、7、1 */
  页们?: readonly number[];
  /** 笔筒满度 0～1；不给就跟着翻页走（笔筒满度） */
  笔芯?: number;
  /** 课表哪几格亮、亮多少 */
  亮格?: readonly 亮格[];
};

export const 现实课桌: React.FC<现实课桌参数> = ({ 宽, 高, 翻页, 页们 = 默认页们, 笔芯, 亮格 }) => {
  const L = 课桌布局(宽, 高);
  const 满度 = 笔芯 ?? 笔筒满度(翻页, 页们.length);
  return (
    <svg width={宽} height={高} viewBox={`0 0 ${宽} ${高}`} style={{ display: 'block', overflow: 'hidden' }}>
      <g shapeRendering="crispEdges">
        <rect x={0} y={0} width={宽} height={L.墙底} fill={现实色.墙} />
        <rect x={0} y={L.墙底} width={宽} height={L.桌前 - L.墙底} fill={现实色.桌面} />
        <rect x={0} y={L.墙底} width={宽} height={齐(3 * L.s)} fill={现实色.墙脚} />
        <rect x={0} y={L.桌前} width={宽} height={L.桌沿} fill={现实色.桌沿} />
        <rect x={0} y={L.桌前} width={宽} height={齐(Math.max(1, 2 * L.s))} fill={现实色.桌棱} />
        <rect x={0} y={L.桌前 + L.桌沿} width={宽} height={高 - L.桌前 - L.桌沿} fill={现实色.桌下} />
      </g>
      <课表 x={L.课表.x} y={L.课表.y} 宽={L.课表.宽} 亮格={亮格} />
      <心愿卡 x={L.心愿卡.x} y={L.心愿卡.y} 宽={L.心愿卡.宽} 透视={桌面透视} />
      <笔筒 x={L.笔筒.x} 底={L.笔筒.底} 宽={L.笔筒.宽} 满度={满度} />
      <撕页本 x={L.撕页本.x} 底={L.撕页本.底} 宽={L.撕页本.宽} 翻页={翻页} 页们={页们} />
    </svg>
  );
};
