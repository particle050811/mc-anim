// 第 14 句右屏：教学楼下的空地、楼的立面、楼上挂的红横幅和你（史蒂夫）。布局、你的站位和头在 楼下布局.ts；纸是 2D 叠层（场/2-门口/纸花层.tsx）。
// 放进 现实画布（顶面 = 楼下顶面、天 = 楼下天色）。纯按 props 画，不读帧号。
import type React from 'react';
import type { V3 } from '@engine/model/parts.tsx';
import { 方块拼搭, type 方块 } from '@engine/model/方块拼搭.tsx';
import { 描边 } from '@engine/三渲二/描边.tsx';
import { 贴图像素对齐 } from '@engine/三渲二/对齐.tsx';
import { Steve, stevePose } from '@库/角色/史蒂夫.tsx';
import { 你在楼下, 横幅, 楼, 空地 } from './楼下布局.ts';
import { 新像素画, 成贴图 } from './像素图.ts';
import { 像素空间, 正面, 用贴图 } from './像素块.tsx';

const 楼下方块 = (): 方块[] => {
  const out: 方块[] = [];
  const 放 = (状态: string, i: number, j: number, k: number) => out.push({ 状态, 位: [i, j, k] });
  for (let i = 空地.左; i < 空地.右; i++)
    for (let j = 0; j < 楼.j; j++) {
      放(空地.面, i, j, -1);
      放(空地.底, i, j, -2);
    }
  for (let i = 楼.左; i < 楼.右; i++)
    for (let k = 0; k < 楼.顶; k++) {
      const 层内 = k % 楼.层高;
      const 窗 = (层内 === 1 || 层内 === 2) && ((i % 楼.窗距) + 楼.窗距) % 楼.窗距 !== 0;
      放(层内 === 0 ? 楼.楼板 : 窗 ? 楼.窗 : 楼.墙, i, 楼.j, k);
    }
  return out;
};
const 方块们 = 楼下方块();

/** 横幅上的「字」：7×7 的白块，大半填满、只漏几个红点（远看是一行白字，凑近也认不出哪个字：顶上歌词在走，横幅不能变成第二路字；
 *  核查 10-24：原来照汉字横竖画的字形，有几个像「关」「阅」，看的人会去认），一共 横幅.字数 个 */
const 字形们 = [
  ['.#####.', '##.#.##', '#######', '#.###.#', '#######', '##.#.##', '.##.##.'],
  ['###.###', '#######', '.#.#.#.', '#######', '##.#.##', '#######', '#.#.#.#'],
  ['.######', '#.#.###', '#######', '###.#.#', '#######', '.#.####', '###.##.'],
  ['##.####', '#######', '#.#.#.#', '#######', '###.###', '#.#####', '##.#.##'],
  ['#######', '#.##.##', '#######', '.#.#.#.', '#######', '##.##.#', '.#####.'],
  ['###.##.', '#######', '##.#.##', '#######', '#.#.#.#', '#######', '.##.###'],
] as const;
const 字距 = 3;

/** 横幅的贴图（贴图像素：宽 = 横幅宽 × 16，高 16）：红色羊毛的噪点、上下各一道暗边，中间一行白「字」 */
const 画横幅 = () => {
  const 宽 = (横幅.右 - 横幅.左) * 16;
  const p = 新像素画(宽, 16);
  p.噪(0, 0, 宽, 16, [横幅.红, 横幅.红暗], 1431, [5, 1]);
  p.方(0, 0, 宽, 1, 横幅.红暗);
  p.方(0, 15, 宽, 1, 横幅.红暗);
  const 字们 = 字形们.slice(0, 横幅.字数);
  const 行宽 = 字们.length * 7 + (字们.length - 1) * 字距;
  const 左 = Math.floor((宽 - 行宽) / 2);
  字们.forEach((形, n) =>
    形.forEach((行, j) =>
      [...行].forEach((c, i) => {
        if (c === '#') p.点(左 + n * (7 + 字距) + i, 4 + j, 横幅.白);
      }),
    ),
  );
  return 成贴图(p);
};

/** 横幅贴在立面正面前面一点（不和墙面打架） */
const 横幅层: React.FC = () => {
  const 图 = 用贴图(画横幅, []);
  return (
    <像素空间 位={[横幅.左, 楼.j - 0.02, 横幅.z]}>
      <正面 x={0} y={0} z={0} 宽={(横幅.右 - 横幅.左) * 16} 高={16} 图={图} />
    </像素空间>
  );
};

export const 楼下: React.FC<{ 头: readonly [number, number]; 秒: number }> = ({ 头, 秒 }) => {
  const 位: V3 = [你在楼下.x, 0.5, 0];
  const 你 = stevePose(位, 你在楼下.朝向, { sec: 秒, scale: 你在楼下.倍, headPitch: 头[0], headYaw: 头[1] });
  return (
    <>
      <方块拼搭 方块们={方块们} />
      <横幅层 />
      <描边>
        <贴图像素对齐 锚={位}>
          <Steve pose={你} />
        </贴图像素对齐>
      </描边>
    </>
  );
};
