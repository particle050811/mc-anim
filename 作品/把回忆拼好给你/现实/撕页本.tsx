// 桌上立着的撕页倒计时，按原版方块的样子搭（像素块.tsx，放在 <像素空间> 里，单位贴图像素）：顶上一条装订，下面一叠纸，正面印「距高考还有 / 大数字 天」。
// 字是本作品的游戏像素字：小字照原版大小（汉字 unihex 半个贴图像素一个点），大数字放大 3 倍（原版 /title 的大字也是整倍放大）。
// 纸叠贴着装订的后边，越撕越薄，正面往里退（斜投影里跟着往上挪 2 个成片像素一层）；顶上看得见的是装订的顶面。
// 撕页由 翻页 驱动（撕页.ts）：一次飞走的几张各画一片，从右下角被扯走、往右上甩出去。
// 翻角：捏住的那页右下角翻起一小角（狗耳朵的画法：角上露出下一页、翻过来的三角露纸背），手对在这个角上（撕页.ts 的 撕页本角）。
import type React from 'react';
import type * as THREE from 'three';
import { 像素字 } from '../界面/像素字.ts';
import { 现实色 } from './色板.ts';
import { 新像素画, 成贴图, 画布倍, type 像素画 } from './像素图.ts';
import { 正面, 像素盒 } from './像素块.tsx';
import { 撕页本尺寸, 算撕页态, 纸厚, 页版式, 默认页们, type 飞纸 } from './撕页.ts';

const S = 撕页本尺寸;
const 页高 = S.高 - S.装订高;
const 字色 = 现实色.页字;

// 一页的正面：纸、上面一行小字、大数字和「天」；翻角 > 0 时右下角画成翻起来的狗耳朵
const 画页 = (数: number, 翻角: number): 像素画 => {
  const p = 新像素画(S.宽, 页高);
  p.噪(0, 0, S.宽, 页高, 现实色.纸, 101, [5, 3, 2]);
  const 版 = 页版式(数);
  const 小 = '距高考还有';
  const 小宽 = 像素字.字宽(小) - 1;
  像素字.画(p.ctx, 小, { x: Math.round((S.宽 - 小宽) / 2) * 画布倍, y: 版.小字y * 画布倍 }, 0, 0, 字色, 画布倍);
  像素字.画(p.ctx, String(数), { x: 版.数.x * 画布倍, y: 版.数.y * 画布倍 }, 0, 0, 现实色.倒计时, 画布倍 * 版.大字倍);
  像素字.画(p.ctx, '天', { x: 版.天.x * 画布倍, y: 版.天.y * 画布倍 }, 0, 0, 字色, 画布倍);
  if (翻角 > 0) {
    // 角上（i + j < c，从右下角量）露出下一页，压在翻起来的那块的影子里；翻过来的三角（折线另一边）是纸背，亮，折线和外沿一圈暗边
    const c = 翻角;
    for (let j = 0; j <= c; j++)
      for (let i = 0; i <= c; i++) {
        const [x, y] = [S.宽 - 1 - i, 页高 - 1 - j];
        if (i + j < c) p.点(x, y, i + j >= c - 2 ? 现实色.翻角影 : 现实色.纸层[0]);
        else p.点(x, y, i === c || j === c || i + j === c ? 现实色.翻角边 : 现实色.纸背);
      }
  }
  return p;
};

const 画装订 = (宽: number, 高: number, 种: number, 下沿: boolean): 像素画 => {
  const p = 新像素画(宽, 高);
  p.噪(0, 0, 宽, 高, 现实色.装订, 种, [4, 3, 2]);
  if (下沿) p.方(0, 高 - 1, 宽, 1, 现实色.装订[1]);
  return p;
};

// 贴图按内容缓存：页上的数只有几种，不必每帧重画
const 缓存 = new Map<string, THREE.Texture>();
const 取 = (键: string, 画: () => 像素画) => {
  let t = 缓存.get(键);
  if (!t) 缓存.set(键, (t = 成贴图(画())));
  return t;
};
const 页图 = (数: number, 翻角: number) => 取(`页${数}|${翻角}`, () => 画页(数, 翻角));
const 装订前 = () => 取('装订前', () => 画装订(S.宽, S.装订高, 102, true));
const 装订顶 = () => 取('装订顶', () => 画装订(S.宽, S.装订深, 103, false));

// 飞走一张：先从右下角被扯下来（往下一点），再往右上甩出去，右边先扬起来（逆时针转）；t 0～1。Agent 暂定的轨迹（一张只飞 5 帧左右）
const 飞姿 = (t: number) => {
  const e = t * t;
  return { dx: S.宽 * (0.15 * t + 1.3 * e), dz: S.高 * (-0.08 * t + 0.6 * e), 转: -30 * t };
};

export type 撕页本参数 = {
  /** 装订正面的左下前角（贴图像素） */
  x: number;
  y: number;
  z: number;
  /** 撕页.ts 的翻页值 */
  翻页: number;
  页们?: readonly number[];
  /** 停着（没在撕）时右下角翻起多大（贴图像素）；0 = 不翻 */
  翻角?: number;
};

export const 撕页本: React.FC<撕页本参数> = ({ x, y, z, 翻页, 页们 = 默认页们, 翻角 = S.翻角 }) => {
  const 态 = 算撕页态(翻页, 页们);
  const 满 = 页们[0]!;
  const 厚 = 纸厚(态.顶, 满);
  const 纸y = y + S.装订深 - 厚;
  // 撕的时候手已经松开那一角，露出来的下一页不翻
  const 角 = 态.飞.length ? 0 : 翻角;
  return (
    <group>
      <像素盒 x={x} y={y} z={z + 页高} 宽={S.宽} 深={S.装订深} 高={S.装订高} 前={装订前()} 顶={装订顶()} />
      <正面 x={x} y={纸y} z={z} 宽={S.宽} 高={页高} 图={页图(态.顶, 角)} />
      {[...态.飞].reverse().map((纸: 飞纸, i) => {
        const 姿 = 飞姿(纸.t);
        // 绕这张纸的左上角转（扯下来时上边先离开装订）；往前挪一点，免得和下面那页贴在一起
        return (
          <group key={i} position={[x + 姿.dx, 纸y - 1 - i, z + 页高 + 姿.dz]} rotation={[0, (姿.转 * Math.PI) / 180, 0]}>
            <正面 x={0} y={0} z={-页高} 宽={S.宽} 高={页高} 图={页图(纸.数, 0)} />
          </group>
        );
      })}
    </group>
  );
};
