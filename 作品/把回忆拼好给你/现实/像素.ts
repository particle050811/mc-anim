// 现实部分的像素对齐：页面 1280×720 按 scale 2 出 2560×1440，成片的一个像素 = 0.5 页面像素。
// 矩形的边吸到 0.5 的整数倍，表格线宽取 0.5 的整数倍，配 shape-rendering="crispEdges"，线就不会糊成两个半透明像素。
// 组件整体放到画面上的偏移也要是 0.5 的整数倍，不然这里吸好的边又会错开半格。
import { 成片倍数 } from '@engine/三渲二/像素.ts';

/** 吸到成片整像素（页面像素的 1/成片倍数） */
export const 齐 = (v: number) => Math.round(v * 成片倍数) / 成片倍数;

/** 至少一个成片像素宽的线宽 */
export const 线宽 = (v: number) => Math.max(1 / 成片倍数, 齐(v));
