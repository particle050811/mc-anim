// 本作品按 60 帧编排（分镜/时间.ts 的 fps，用户 11-02 定）：段、场、界面里说的「帧」是第几个 1/60 秒，时间一律从 use当前秒() 换（决策 0015）。
// 60 帧输出时每个输出帧都正好在格上；秒 × 60 有浮点误差（31 ÷ 60 × 60 = 30.999…），贴格 贴回整数，帧号的等号判断、按帧查表照旧。
// 不在格上（以后换输出帧率）时照实给小数，不取整。
import { 贴格 } from '@engine/段/按时取值.ts';
import { use当前秒 } from '@engine/段/时间.tsx';
import { fps } from './分镜/时间.ts';

/** 当前时刻在本作品时间轴上是第几帧（1/60 秒一帧，从当前 Sequence 起算，带小数） */
export const use当前帧 = (): number => 贴格(use当前秒() * fps);
