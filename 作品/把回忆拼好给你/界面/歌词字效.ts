// 都按点算（点 = 一个字形像素，见 符文排版.ts），时刻从这个词拼齐那一帧（齐 = 词里最后一个字的最后一块落定）往后数；画法在 符文歌词.tsx。
// 这里的数都是 Agent 定的（手机 390 宽上看得出、不吵），整合时可以对着成片再调。
import { 烟花染料色 } from '@库/特效/烟花.ts';
import { 散, type 字效 } from './符文排版.ts';

export type 点 = readonly [number, number];

/**
 * 光明：拼齐那一下字变成暖光色，外面亮起几圈光（用户 10-24：不要平滑光晕，要像素的光、亮度分档）。
 * 光圈按到字的曼哈顿距离一档一档取（菱形的角，像素画里的光），每档一个透明度、档内不渐变；
 * 拼齐头 3 帧四圈、再 3 帧三圈，之后留两圈到退场。描边在的话光圈从描边外面起。
 * 亮天空上也要看得出是在发光：光色取近白的暖色、头一圈几乎不透明（Agent 定）
 */
export const 光明 = { 字色: '#ffe27a', 光色: '#fff4b8', 档们: [0.92, 0.66, 0.4, 0.2], 闪帧们: [3, 6] } as const;
export const 光明圈数 = (f: number, 齐: number) => (f < 齐 ? 0 : f - 齐 < 光明.闪帧们[0] ? 4 : f - 齐 < 光明.闪帧们[1] ? 3 : 2);

/**
 * 烟花：拼齐那一下从词的外沿炸出一圈原版烟花火花（贴图 spark_7 → spark_0，按年龄换，后半寿命淡掉，过 1/3 寿命以后一闪一闪：
 * 同 库/特效/烟花.ts 的 SparkParticle），颜色照第 10 句第三发（黄、橙，场/2-门口/门口之夜参数.ts），字自己先染上金色再回白。
 * 火花从词外框外面一圈（起圈）出发：从词中心出发的话头几帧全压在字上看不见。
 * 原版火花寿命 2.4～3 秒，这里压到 0.6～0.8 秒（下一句 0.5 秒后就进场）；摩擦照原版每刻 ×0.91 换成每帧
 */
export const 烟花 = {
  颗数: 24,
  初速: [1.6, 2.6],
  /** 每帧速度乘几（原版每刻 0.91，一帧 = 20/24 刻） */
  摩擦: 0.91 ** (20 / 24),
  /** 往下的加速度（点/帧²） */
  重力: 0.05,
  寿命: [14, 20],
  色们: [烟花染料色.黄, 烟花染料色.橙],
  字色: '#ffe9a0',
  染帧: 6,
} as const;

/** 一颗火花这一帧：x、y = 离词中心几点（贴图中心），档 = spark_几（7 最大），透 = 显现度（0～1，抖动着画） */
export type 一颗火花 = { x: number; y: number; 档: number; 色: number; 透: number };

/** 起圈 = 火花出发的椭圆半径（点）：词外框的半宽、半高再往外 1 点 */
export const 烟花火花 = (f: number, 齐: number, 种: number, 起圈: 点 = [0, 0]): 一颗火花[] => {
  const age = f - 齐;
  if (age < 0) return [];
  const out: 一颗火花[] = [];
  for (let i = 0; i < 烟花.颗数; i++) {
    const 寿 = 烟花.寿命[0] + (烟花.寿命[1] - 烟花.寿命[0]) * 散(种, i, 21);
    if (age >= 寿) continue;
    const 角 = ((i + 散(种, i, 22) * 0.6) / 烟花.颗数) * Math.PI * 2;
    const v = 烟花.初速[0] + (烟花.初速[1] - 烟花.初速[0]) * 散(种, i, 23);
    const m = 烟花.摩擦;
    // 速度每帧乘 m：走过的路 = v·(1 − m^t)/(1 − m)；重力叠在竖直上
    const 路 = (v * (1 - m ** age)) / (1 - m);
    const 年 = age / 寿;
    // 原版闪烁：过 1/3 寿命后，(年龄 + 寿命)/3 为奇数的刻不画（按刻算）
    const 刻 = Math.floor((age * 20) / 24);
    const 寿刻 = Math.floor((寿 * 20) / 24);
    if (年 > 1 / 3 && Math.floor((刻 + 寿刻) / 3) % 2 === 1) continue;
    out.push({
      x: Math.cos(角) * (起圈[0] + 路 * 1.3),
      y: Math.sin(角) * (起圈[1] + 路) + 0.5 * 烟花.重力 * age * age,
      档: Math.max(0, 7 - Math.floor(年 * 8)),
      色: 烟花.色们[i % 烟花.色们.length]!,
      透: 年 < 0.5 ? 1 : 1 - (年 - 0.5) / 0.5,
    });
  }
  return out;
};

/**
 * 刹那：拼齐那一帧冻住（字变冰色，笔画朝上的点亮一档，像原版冰块的高光），到 裂（第 11 句世界碎掉那一拍，分镜.ts 第11句碎裂）
 * 顺着拼字时的块缝裂开：各块往外让 1 点露出裂缝，停 3 帧，再一块一块往下掉（和照片后面碎成像素往下掉的世界一起）
 */
export const 刹那 = { 冰色: '#9fd2f2', 冰亮色: '#e6f7ff', 停帧: 3, 迟: 3, 重力: 0.45, 外飘: 0.25 } as const;

/** 刹那一块这一帧离原位几点；冰 = 已经冻住 */
export const 刹那块 = (f: number, 齐: number, 裂: number, 心: 点, 种: number): { dx: number; dy: number; 冰: boolean } => {
  const 冰 = f >= 齐;
  const 裂帧 = Math.max(裂, 齐 + 1);
  if (f < 裂帧) return { dx: 0, dy: 0, 冰 };
  const 向: 点 = [Math.sign(Math.round(心[0])), Math.sign(Math.round(心[1]))];
  const t = f - (裂帧 + 刹那.停帧 + 刹那.迟 * 散(种, 31));
  const 落 = t > 0 ? 0.5 * 刹那.重力 * t * t : 0;
  return { dx: 向[0] + (t > 0 ? 向[0] * 刹那.外飘 * t : 0), dy: 向[1] + 落, 冰 };
};

/**
 * 放下：拼齐后各块像纸片一样一块一块飘下去，边飘边从白转成樱花粉（纸变花，同 2-归隐 那一镜的纸雨化樱花瓣）。
 * 「下」唱到时（分镜 归隐起风）樱花风从右往左吹起来，到 归隐合屏 只有 0.4 秒、这句就退场了：所以拼齐只停 1 帧就动，落得快、被风往左带
 */
export const 放下 = { 停帧: 1, 迟: 3, 初速: 0.8, 重力: 0.22, 风: 0.6, 摆: [1, 2], 摆周期: 12, 色们: ['#ffe6ef', '#f6b8d0'], 换色帧: [2, 5] } as const;

/** 放下一块这一帧离原位几点；色 = 0 字色、1 淡粉、2 樱花粉 */
export const 放下块 = (f: number, 齐: number, 种: number): { dx: number; dy: number; 色: number } => {
  const t = f - (齐 + 放下.停帧 + 放下.迟 * 散(种, 41));
  if (t <= 0) return { dx: 0, dy: 0, 色: 0 };
  const 摆 = 放下.摆[0] + (放下.摆[1] - 放下.摆[0]) * 散(种, 42);
  const 相 = 散(种, 43) * Math.PI * 2;
  return {
    dx: -放下.风 * t + 摆 * (Math.sin((t / 放下.摆周期) * Math.PI * 2 + 相) - Math.sin(相)),
    dy: 放下.初速 * t + 0.5 * 放下.重力 * t * t,
    色: t < 放下.换色帧[0] ? 0 : t < 放下.换色帧[1] ? 1 : 2,
  };
};

/**
 * 时差：这个词的拼字（符文飞来、落定、闪）晚半拍再来一遍，画成冷色的残影，往右上错开（右半屏是现实那边，冷调）；
 * 残影自己带一圈描边（亮天空上浅蓝贴着天看不见），垫在本体底下、七成不透明。错开 5、4 点：再小就贴着字像一层投影。残影跟到退场
 */
export const 时差 = { 色: '#8fd0ff', 偏: [5, -4] as 点, 透: 0.7 } as const;

/** 这个字在不在关键词里 */
export const 在词里 = (效: 字效 | undefined, j: number) => !!效 && j >= 效.从 && j <= 效.到;
