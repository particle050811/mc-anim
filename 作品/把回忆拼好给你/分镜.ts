export const 段窗口 = (键: string): 段窗口 => {
  const w = 串们.flat().find((x) => x.键 === 键);
  if (!w) throw new Error(`分镜.ts 里没有段 ${键} 的窗口`);
  return w;
};

/** 段.ts 用：帧数、场窗口，和原声 cue 的 帧、帧数、入点秒（cue 的 资产、名、增益由段补上） */
export const 段时钟 = (键: string) => {
  const w = 段窗口(键);
  return {
    帧数: w.帧数,
    场窗口: { 起帧: w.起帧, 止帧: w.止帧 },
    原声: { 帧: 0, 帧数: w.帧数, 入点秒: w.起帧 / fps },
  };
};

/** 正片的段用：每个正片事件在这一段里的段内帧（不在这段里的也照算，会是负数或不小于帧数） */
