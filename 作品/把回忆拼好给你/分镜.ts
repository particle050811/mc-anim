export const 歌曲帧 = (秒: number) => Math.round(秒 * fps);
/** 第 n 拍的秒数 */
export const 拍 = (n: number) => 网格.首拍 + 网格.拍长 * n;
/** 第 k 小节下拍的秒数（奇数小节是乐句下拍，偶数小节是断拍回落） */
