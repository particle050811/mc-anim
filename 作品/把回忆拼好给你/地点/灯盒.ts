// 三渲二平涂的发光区（engine/三渲二/平涂.tsx 的 发光区，盒里的受光面不乘整体色调）按一盏灯收紧的盒子。纯函数。
// 灯笼、蜡烛不满一格，给整格的盒子的话，贴着的墙面、天花板、台面也落在盒子边上（边界算在盒里），跟着亮成一块不乘色调的方块。
// 挂着的灯笼身子 6 像素宽、从 1 像素高起，链子挂到顶；三根蜡烛摆在 5～11 像素里、高不过 7 像素：横向收到 ±0.25 格、往上到 0.8 格
// （同 核对-三渲二 的 灯盒；链子顶上那截照乘色调，看不出来），底边抬 1/32 格，放在台面上的蜡烛底下那块台面不跟着亮。
import type { 灯位 } from './隐世之境一楼.tsx';

/** 一盏灯的发光区 [x0, y0, z0, x1, y1, z1]（场景坐标，灯位 是方块底面中心） */
export const 灯盒 = ({ 位: [x, y, z] }: Pick<灯位, '位'>): [number, number, number, number, number, number] => [
  x - 0.25,
  y - 0.25,
  z + 1 / 32,
  x + 0.25,
  y + 0.25,
  z + 0.8,
];
