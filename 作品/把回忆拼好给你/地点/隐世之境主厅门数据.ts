export type 盒 = [number, number, number, number, number, number];
export type 平点 = [number, number];
type 点 = [number, number, number];

/** 一扇门扇：面心范围（按面心严格在盒里算这扇门的面）、转轴（网格本地 x, y）、开到底时绕 +Z 转的角（度） */
export type 扇 = { 盒: 盒; 轴: 平点; 开角: number };
/** 门洞：光照进来的那个竖直长方形，底边从 a 到 b（网格本地 x, y）、高从 底 到 顶。开着的门扇占掉的那一条不算 */
export type 门洞 = { a: 平点; b: 平点; 底: number; 顶: number };
export type 门 = { 扇们: readonly 扇[]; 洞: 门洞; /** 门洞那一格正中（地板顶面） */ 中: 点 };

