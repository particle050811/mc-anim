/** 门开到 开（0～1）时光还能穿过去的那段门洞（光的水平方向 光向 xy，从门外往屋里）：门扇没开到底时斜在门洞那一格里，
 *  挡住靠门轴那一截。按门扇底面四个角顺着光投到门洞底边上，门轴那头到投得最远的地方算挡住。开到底时就是 洞 本身；全挡住给 null */
export const 开着的门洞 = (门: 门, 开: number, 光向: readonly number[]): 门洞 | null => {
  if (开 >= 1) return 门.洞;
  const { a, b } = 门.洞;
  const [ux, uy] = [b[0] - a[0], b[1] - a[1]];
  const [dx, dy] = [光向[0]!, 光向[1]!];
  const 叉 = (px: number, py: number, qx: number, qy: number) => px * qy - py * qx;
  const 底叉 = 叉(ux, uy, dx, dy);
  // 点 p 顺着光落到门洞底边那条线上，在 a（0）到 b（1）的哪儿
  const 落 = (px: number, py: number) => 叉(px - a[0], py - a[1], dx, dy) / 底叉;
  // 盒是按面心挑面用的，四边各多了一点：取到 1/16 格就是门扇本身
  const 准 = (v: number) => Math.round(v * 16) / 16;
  let [lo, hi] = [0, 1];
  for (const { 盒, 轴, 开角 } of 门.扇们) {
    const t = (开角 * 开 * Math.PI) / 180;
    const [c, sn] = [Math.cos(t), Math.sin(t)];
    const 角们 = [
      [准(盒[0]), 准(盒[1])],
      [准(盒[3]), 准(盒[1])],
      [准(盒[3]), 准(盒[4])],
      [准(盒[0]), 准(盒[4])],
    ].map(([x, y]) => 落(轴[0] + c * (x! - 轴[0]) - sn * (y! - 轴[1]), 轴[1] + sn * (x! - 轴[0]) + c * (y! - 轴[1])));
    if (落(轴[0], 轴[1]) < 0.5) lo = Math.max(lo, ...角们);
    else hi = Math.min(hi, ...角们);
  }
  if (hi - lo < 1e-3) return null;
  const 点 = (u: number): 平点 => [a[0] + ux * u, a[1] + uy * u];
  return { ...门.洞, a: 点(lo), b: 点(hi) };
};
