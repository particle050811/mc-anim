// 时刻取歌曲帧 正片事件.哈气.帧（片子里真有的那一帧；三稿的 27.80 落在两帧之间），颗粒的种子就是它。这一拍三个角色都定住，不按时间取样。
import React from 'react';
import { useCurrentFrame } from 'remotion';
import { 整片后期 } from '@engine/三渲二/整片后期.tsx';
import { 正片事件 } from '../../分镜.ts';
import { 照片墙格们 } from '../../地点/照片墙.tsx';
import { 哈气角色, 哈气气泡 } from '../../场/2-门口/哈气.tsx';
import { 取景 as N6取景 } from '../../场/2-门口/参数.ts';
import { 门口画布 } from '../../场/2-门口/门口.tsx';
import { 第8句调子, 第8句镜头 } from '../../场/2-门口/第8句.ts';
import { 第8句天弧 } from '../../场/2-门口/第8句参数.ts';
import { 第8句照片们 } from '../../特效/照片画.ts';
import { 视图们 } from './视图.ts';

const 帧 = 正片事件.哈气.帧;
const 墙 = 照片墙格们(第8句照片们);

const 画面: React.FC = () => {
  const v = 视图们[useCurrentFrame()]!;
  // N = 6 不是 4 的倍数：地图画按 32 格画（特效/地图画.ts），天、太阳用 门口画布 的默认
  const 镜 = v.N6 ? { 取景: N6取景, 照片墙边长: 32 as const } : { ...第8句镜头, 照片墙边长: 64 as const, 弧: 第8句天弧 };
  return (
    <整片后期 调色={v.后期 ? 第8句调子.调色 : null} 种子={帧}>
      <门口画布 门开 照片墙={墙} 远景={v.远景} 调子={第8句调子} {...镜} 叠层={<哈气气泡 取景={镜.取景} />}>
        <哈气角色 你={v.你} />
      </门口画布>
    </整片后期>
  );
};

export default 画面;
