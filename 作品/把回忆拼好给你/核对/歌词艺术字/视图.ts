// 歌词艺术字核对的视图表（纯数据，段.ts 也读）：一帧一个视图，比做法 A、B、C 在三个阶段（解码前、解码中、解码完）× 三种底（亮天空、门口、夜）上的样子，
// 外加第 15 句放底部的样子和字点 8 的对照。歌词的帧是歌曲帧（段内帧 = 歌曲帧，核对不减起帧），每个视图只画一句。
// 解码前：片里每句从开口进场、头一个字跟着就解了，整句全是符文的样子片里看不到；这里把入帧提到头一个字解码前 19 帧，看整句符文（也是 00-说明 里「提前进场」的样子）。
// 解码中：取这一句里某个字解到一半的那帧（门口取 正片事件.哈气 那一帧，片里真有的）；解码完：最后一个字起唱后 6 帧（核对只画一句，不排下一句进场）。
import { 正片事件 } from '../../分镜.ts';
import type { 符文歌词做法 } from '../../界面/符文歌词.tsx';
import { 正片歌词行 } from '../../界面/符文歌词数据.ts';

export type 底 = '亮天空' | '门口' | '夜' | '对视';
export type 阶段 = '解码前' | '解码中' | '解码完';

export type 视图 = {
  名: string;
  做法: 符文歌词做法;
  底: 底;
  /** 第几句 */
  句: number;
  /** 歌词画哪一帧（歌曲帧） */
  帧: number;
  /** 盖掉这句的入帧（解码前用） */
  入?: number;
  /** 盖掉样式的字点 */
  字点?: number;
};

/** 每种底配哪一句：亮天空第 1 句（白天最亮的天，太阳在字后面），门口第 8 句（哈气那个机位），夜第 10 句（烟花那句的夜） */
const 底句: Record<Exclude<底, '对视'>, number> = { 亮天空: 1, 门口: 8, 夜: 10 };
/** 解码中取哪个字（第几个，从 0 数）解到一半：第 1 句「渺」，第 10 句「即」；第 8 句用哈气那一帧 */
const 解到一半: Record<number, number> = { 1: 4, 10: 3 };

const 阶段帧 = (句: number, 段: 阶段): { 帧: number; 入?: number } => {
  const 行 = 正片歌词行(句);
  if (段 === '解码前') {
    const 帧 = Math.floor(行.解[0]!) - 7;
    return { 帧, 入: 帧 - 12 };
  }
  if (段 === '解码完') return { 帧: Math.ceil(Math.max(...行.解)) + 6 };
  if (句 === 8) return { 帧: 正片事件.哈气.帧 };
  return { 帧: Math.round(行.解[解到一半[句]!]! - 0.5) };
};

const 做法们: readonly 符文歌词做法[] = ['A', 'B', 'C'];
const 阶段们: readonly 阶段[] = ['解码前', '解码中', '解码完'];

export const 视图们: readonly 视图[] = [
  ...做法们.flatMap((做法) =>
    (['亮天空', '门口', '夜'] as const).flatMap((底) =>
      阶段们.map((段): 视图 => ({ 名: `${做法}-${底}-${段}`, 做法, 底, 句: 底句[底], ...阶段帧(底句[底], 段) })),
    ),
  ),
  // 第 15 句放底部（对视这一帧上面是她的脸和气泡），49.96 那一帧「的」正在解
  ...做法们.map((做法): 视图 => ({ 名: `${做法}-对视-第15句底部`, 做法, 底: '对视', 句: 15, 帧: 正片事件.第15句对视.帧 })),
  // 字点 8：字大三分之一（15 个字的第 8 句宽 2160 像素，快到画面边了）
  { 名: 'A-门口-解码中-字点8', 做法: 'A', 底: '门口', 句: 8, 帧: 正片事件.哈气.帧, 字点: 8 },
];
