// 歌词艺术字核对的视图表（纯数据，段.ts 也读）：一帧一个视图。符文拼字在三个阶段（飞来中、落定闪、拼齐）× 三种底（亮天空、门口、夜）上的样子，
// 五个关键词各两三个时刻，第 15 句放底部的样子。歌词的帧是歌曲帧（段内帧 = 歌曲帧，核对不减起帧），每个视图只画一句（不排下一句进场）。
// 飞来中：句中间那个字第一块落定前 2 帧（左半句已经拼好，中间几个字的符文正在飞）；落定闪：同一个字第一块落定那一帧；拼齐：最后一个字拼齐后 6 帧。
import { 正片事件 } from '../../分镜.ts';
import { 正片歌词行 } from '../../界面/符文歌词数据.ts';
import { 符文歌词默认, 解码时段 } from '../../界面/符文排版.ts';

export type 底 = '亮天空' | '门口' | '夜' | '对视';
export type 阶段 = '飞来中' | '落定闪' | '拼齐';

export type 视图 = {
  名: string;
  底: 底;
  /** 第几句 */
  句: number;
  /** 歌词画哪一帧（歌曲帧） */
  帧: number;
};

/** 每种底配哪一句：亮天空第 1 句（白天最亮的天，太阳在字后面），门口第 8 句（哈气那个机位，15 个字断两行、错落），夜第 9 句（门口之夜，第 10 句留给烟花） */
const 底句: Record<Exclude<底, '对视'>, number> = { 亮天空: 1, 门口: 8, 夜: 9 };

const 时段 = (句: number) => 解码时段(正片歌词行(句), 符文歌词默认);

const 阶段帧 = (句: number, 段: 阶段): number => {
  const 段们 = 时段(句);
  const 中 = 段们[Math.floor(段们.length / 2)]!;
  if (段 === '飞来中') return Math.floor(中.起) - 2;
  if (段 === '落定闪') return Math.ceil(中.起);
  return Math.ceil(Math.max(...段们.map((d) => d.完))) + 6;
};

/** 关键词拼齐那一帧（词里最后一个字的最后一块落定） */
const 齐帧 = (句: number) => {
  const 效 = 正片歌词行(句).字效!;
  return Math.ceil(Math.max(...时段(句).slice(效.从, 效.到 + 1).map((d) => d.完)));
};

const 阶段们: readonly 阶段[] = ['飞来中', '落定闪', '拼齐'];

export const 视图们: readonly 视图[] = [
  ...(['亮天空', '门口', '夜'] as const).flatMap((底) => 阶段们.map((段): 视图 => ({ 名: `${底}-${段}`, 底, 句: 底句[底], 帧: 阶段帧(底句[底], 段) }))),
  // 光明（第 3 句，祭坛那句的白天）：拼齐那一帧四圈、之后留两圈
  { 名: '光明-一亮', 底: '亮天空', 句: 3, 帧: 齐帧(3) },
  { 名: '光明-留光', 底: '亮天空', 句: 3, 帧: 齐帧(3) + 6 },
  // 烟花（第 10 句）：炸开后 2 帧、7 帧
  { 名: '烟花-炸开', 底: '夜', 句: 10, 帧: 齐帧(10) + 2 },
  { 名: '烟花-散开', 底: '夜', 句: 10, 帧: 齐帧(10) + 7 },
  // 刹那（第 11 句）：冻住、裂开（第11句碎裂 那一帧）、往下掉
  { 名: '刹那-冻住', 底: '夜', 句: 11, 帧: 齐帧(11) + 1 },
  { 名: '刹那-裂开', 底: '夜', 句: 11, 帧: 正片事件.第11句碎裂.帧 + 1 },
  { 名: '刹那-掉落', 底: '夜', 句: 11, 帧: 正片事件.第11句碎裂.帧 + 8 },
  // 时差（第 13 句）：本体拼齐、残影还在飞；残影也落定
  { 名: '时差-残影在飞', 底: '亮天空', 句: 13, 帧: 齐帧(13) + 1 },
  { 名: '时差-残影落定', 底: '亮天空', 句: 13, 帧: 齐帧(13) + 7 },
  // 放下（第 14 句）：刚飘起来、快退场（2-归隐 里拼齐后 10 帧左右就合屏退场）
  { 名: '放下-飘落', 底: '门口', 句: 14, 帧: 齐帧(14) + 4 },
  { 名: '放下-落远', 底: '门口', 句: 14, 帧: 齐帧(14) + 9 },
  // 第 15 句放底部（对视这一帧上面是她的脸和气泡），49.96 那一帧
  { 名: '对视-第15句底部', 底: '对视', 句: 15, 帧: 正片事件.第15句对视.帧 },
];
