// 歌词艺术字核对的视图表（纯数据，段.ts 也读）：一帧一个视图。定稿（10-24 五家评审后定的做法）在三个阶段（解码前、解码中、解码完）× 三种底（亮天空、门口、夜）上的样子，
// 第 15 句放底部的样子，再加描边、整片后期开关和改前字点 6 的对照。歌词的帧是歌曲帧（段内帧 = 歌曲帧，核对不减起帧），每个视图只画一句。
// 解码前：长句从进场到头一个字开解不够把整句亮全（第 8 句提前 0.3 秒，15 个字要 10 帧才亮全），这里把入帧提到那一帧前 12 帧，看整句符文；第 1 句片里本来就亮得全。
// 解码中：挑一个字正拼到一半、前一个字刚拼完在闪亮点的那一帧（挑法见 解码中帧）；解码完：最后一个字拼完后 6 帧（核对只画一句，不排下一句进场）。
import { 正片事件 } from '../../分镜.ts';
import { 正片歌词行 } from '../../界面/符文歌词数据.ts';
import { 符文歌词默认, 解码时段 } from '../../界面/符文排版.ts';

export type 底 = '亮天空' | '门口' | '夜' | '对视';
export type 阶段 = '解码前' | '解码中' | '解码完';

export type 视图 = {
  名: string;
  底: 底;
  /** 第几句 */
  句: number;
  /** 歌词画哪一帧（歌曲帧） */
  帧: number;
  /** 盖掉这句的入帧（解码前用） */
  入?: number;
  /** 盖掉样式的字点 */
  字点?: number;
  /** false = 关掉（对照） */
  描边?: false;
  后期?: false;
};

/** 每种底配哪一句：亮天空第 1 句（白天最亮的天，太阳在字后面），门口第 8 句（哈气那个机位，15 个字拆两行），夜第 10 句（烟花那句的夜） */
const 底句: Record<Exclude<底, '对视'>, number> = { 亮天空: 1, 门口: 8, 夜: 10 };

/** 解码中：前一个字拼完后的第一帧（亮点还是十字），这一帧里正在拼的字最接近一半的那个 */
const 解码中帧 = (句: number) => {
  const 段们 = 解码时段(正片歌词行(句), 符文歌词默认);
  let 最好 = { 帧: 0, 差: Infinity };
  for (let k = 1; k < 段们.length; k++) {
    const 帧 = Math.ceil(段们[k - 1]!.完);
    const 解 = (帧 - 段们[k]!.起) / (段们[k]!.完 - 段们[k]!.起);
    if (Math.abs(解 - 0.5) < 最好.差) 最好 = { 帧, 差: Math.abs(解 - 0.5) };
  }
  return 最好.帧;
};

const 阶段帧 = (句: number, 段: 阶段): { 帧: number; 入?: number } => {
  const 行 = 正片歌词行(句);
  const 段们 = 解码时段(行, 符文歌词默认);
  if (段 === '解码前') {
    const 帧 = Math.floor(段们[0]!.起);
    return { 帧, 入: Math.min(行.入, 帧 - 12) };
  }
  if (段 === '解码完') return { 帧: Math.ceil(Math.max(...段们.map((d) => d.完))) + 6 };
  return { 帧: 解码中帧(句) };
};

const 阶段们: readonly 阶段[] = ['解码前', '解码中', '解码完'];
const 门口解码中 = 阶段帧(8, '解码中');

export const 视图们: readonly 视图[] = [
  ...(['亮天空', '门口', '夜'] as const).flatMap((底) => 阶段们.map((段): 视图 => ({ 名: `${底}-${段}`, 底, 句: 底句[底], ...阶段帧(底句[底], 段) }))),
  // 第 15 句放底部（对视这一帧上面是她的脸和气泡），49.96 那一帧
  { 名: '对视-第15句底部', 底: '对视', 句: 15, 帧: 正片事件.第15句对视.帧 },
  // 对照：同一帧门口解码中，关描边、关整片后期、改前的字点 6
  { 名: '门口-解码中-无描边', 底: '门口', 句: 8, ...门口解码中, 描边: false },
  { 名: '门口-解码中-无后期', 底: '门口', 句: 8, ...门口解码中, 后期: false },
  { 名: '门口-解码中-字点6', 底: '门口', 句: 8, ...门口解码中, 字点: 6 },
];
