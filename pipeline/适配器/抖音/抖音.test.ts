import { describe, expect, it } from 'vitest';
import { 按段统计, type 段区间 } from '../bili/时间轴.ts';
import { 对照行们, 都掉人, 都留得住 } from '../平台/对照.ts';
import type { 对上 } from '../平台/图与排名.ts';
import { 分秒, 抖音标题, 解析抖音, type 抖音原始包 } from './数据.ts';
import { 进段前后 } from './报告.ts';

const 包: 抖音原始包 = {
  版本: 1, 平台: '抖音', 取于: '2026-10-22T08:24:00Z', 错误: [], 请求数: 1, 停于风控: null,
  作品: [{
    id: '1', 标题: '[Opus 5.5]应力转动 6 出征暮色 一开始\n第二行 #AI', 时长毫秒: 9500, 发布: 1792503012,
    指标: { view_count: '100', bounce_rate_2s: '0.194006', completion_rate_5s: '0.56', cover_show: '20' },
    留存: { 本作: [{ key: '00:00', value: 1 }, { key: '00:03', value: 0.7 }, { key: '00:06', value: 0.5 }, { key: '00:09', value: 0.45 }], 同类作者: [] },
    跳出: null, 进度: { 跳过: [{ key: '6', value: 0.1 }], 回看: [] }, 来源: [{ key: 'homepage_hot', value: 0.98 }, { key: 'follow', value: 0.02 }], 搜索词: null,
  }],
};

describe('抖音解析', () => {
  it('MM:SS 换秒、指标字符串换数、标题取第一行、来源换中文名', () => {
    expect(分秒('05:51')).toBe(351);
    expect(抖音标题('应力转动 6 出征暮色 #AI')).toBe('应力转动 6 出征暮色');
    const [a] = 解析抖音(包);
    expect(a!.标题).toBe('[Opus 5.5]应力转动 6 出征暮色 一开始');
    expect(a!.时长).toBe(9.5);
    expect(a!.留存.map((p) => p.秒)).toEqual([0, 3, 6, 9]);
    expect(a!.指标.两秒跳出率).toBeCloseTo(0.194);
    expect(a!.指标.完播率).toBeNull();
    expect(a!.来源[0]).toEqual({ 名: '推荐', 占比: 0.98 });
    expect(a!.跳过).toEqual([{ 秒: 6, 值: 0.1 }]);
  });
});

const 区 = (起止: [number, number][]): 段区间[] => 起止.map(([起, 止], i) => ({ 编号: `6-0${i + 1}`, 键: `6-${i}`, 名: `段${i}`, 起, 止 }));

describe('进段前后和两平台对照', () => {
  it('段起点后 6 秒比前 6 秒掉得快 1.3 倍以上算陡降', () => {
    const 曲 = [{ 秒: 0, 留存: 1 }, { 秒: 12, 留存: 0.9 }, { 秒: 18, 留存: 0.6 }, { 秒: 30, 留存: 0.55 }];
    const 段 = 按段统计(区([[0, 12], [12, 30]]), 曲, [], { 开头: 0, 结尾: 0 });
    const [c] = 进段前后(曲, 段);
    expect(c!.段.编号).toBe('6-02');
    expect(c!.判断).toBe('进段后陡降');
  });
  it('两边都高于本平台平均的是都掉人，都低于的是都留得住', () => {
    const 段 = 区([[0, 10], [10, 20], [20, 30], [30, 40]]);
    const 上 = (曲: { 秒: number; 留存: number }[]): 对上 => ({
      稿: { 标识: 'x', 标题: 'x', 时长: 40, 发布: '', 留存: 曲, 同类留存: [], 弹幕秒: [], 弹幕: [] },
      交付名: '第6章', 窗: { 开头: 0, 结尾: 0 }, 段: 按段统计(段, 曲, [], { 开头: 0, 结尾: 0 }),
    });
    const a = 上([{ 秒: 0, 留存: 1 }, { 秒: 10, 留存: 0.5 }, { 秒: 20, 留存: 0.45 }, { 秒: 30, 留存: 0.3 }, { 秒: 40, 留存: 0.29 }]);
    const b = 上([{ 秒: 0, 留存: 1 }, { 秒: 10, 留存: 0.6 }, { 秒: 20, 留存: 0.58 }, { 秒: 30, 留存: 0.5 }, { 秒: 40, 留存: 0.3 }]);
    const 行 = 对照行们(a, b);
    expect(行.length).toBe(4);
    expect(都掉人(行).map((r) => r.段.编号)).toEqual(['6-01']);
    expect(都留得住(行).map((r) => r.段.编号)).toEqual(['6-02']);
  });
});
