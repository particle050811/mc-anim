describe('对时间轴', () => {
  it('章范围和标题数字', () => {
    expect(章范围('第6-7章')).toEqual([6, 7]);
    expect(章范围('冒烟')).toBeNull();
    expect(标题数字('应力转动（1-3）-初入世界')).toEqual([1, 3]);
    expect(标题数字('seedance2.0')).toEqual([2, 0]);
  });
  it('时长差 1.5 秒内、标题章号落在交付范围里才算对上；同时长的比对交付不选', () => {
    const 们 = [交付('重组A1-比对', 354.7, '2026-10-22'), 交付('第6-7章', 354.7, '2026-10-21'), 交付('第8章', 354.9)];
    expect(对交付({ 标题: '应力转动 6 出征暮色', 时长: 355 }, 们)?.m.名).toBe('第6-7章');
    expect(对交付({ 标题: '应力转动5-粉碎奸商', 时长: 355 }, 们)).toBeNull();
    expect(对交付({ 标题: '应力转动 6 出征暮色', 时长: 300 }, 们)).toBeNull();
  });
  it('段按帧换秒，留存插值、段内流失和弹幕落段', () => {
    const 段 = 段区间们({ ...交付('第6章', 40).m, 段: [
      { 编号: '6-01', 键: '6-进入森林', 指纹: '', 母版: '', 帧数: 240, 全片起帧: 0 },
      { 编号: '6-02', 键: '6-斩娜迦', 指纹: '', 母版: '', 帧数: 720, 全片起帧: 240 },
    ] });
    expect(段.map((s) => [s.名, s.起, s.止])).toEqual([['进入森林', 0, 10], ['斩娜迦', 10, 40]]);
    const [s] = 解析(包('2026-10-22T07:58:00Z'));
    expect(留存于(s!.留存, 10)).toBeCloseTo(0.8);
    // 曲线末档落在片子结尾（放完了）时那一档不算，这里给到 60 秒让 40 秒前都有效
    const 曲 = [...s!.留存, { 秒: 60, 留存: 0 }];
    const 统 = 按段统计(段, 曲, s!.弹幕秒, { 开头: 0, 结尾: 0 });
    expect(统[0]!.流失).toBeCloseTo(0.2);
    expect(统[0]!.弹幕).toBe(1);
    expect(统[1]!.弹幕).toBe(1);
    expect(统[1]!.每10秒相对流失).toBeCloseTo(1 - Math.pow(0.3 / 0.8, 10 / 30));
  });
  it('开头窗内的流失不记到段上：整段在窗内标窗内、不排名，跨窗的段只算窗后部分', () => {
    const 段 = 段区间们({ ...交付('第6章', 40).m, 段: [
      { 编号: '6-01', 键: '6-进入森林', 指纹: '', 母版: '', 帧数: 240, 全片起帧: 0 },
      { 编号: '6-02', 键: '6-斩娜迦', 指纹: '', 母版: '', 帧数: 720, 全片起帧: 240 },
    ] });
    const [s] = 解析(包('2026-10-22T07:58:00Z'));
    const 统 = 按段统计(段, [...s!.留存, { 秒: 60, 留存: 0 }], [], { 开头: 20, 结尾: 0 });
    expect(统[0]!.窗内).toBe(true);
    expect(统[0]!.每10秒相对流失).toBeNaN();
    expect(统[1]!.窗内).toBe(false);
    expect(统[1]!.计起).toBe(20);
    // 只算 20–40 秒：0.6 → 0.3
    expect(统[1]!.每10秒相对流失).toBeCloseTo(1 - Math.sqrt(0.5));
    expect(每10秒流失(s!.留存, 20, 40)).toBeCloseTo(1 - Math.sqrt(0.5));
    // 段内流失（占全部观众）照旧按整段算
    expect(统[1]!.流失).toBeCloseTo(0.5);
  });
  it('末档落在片子结尾、人几乎走光（放完了）时，那一档按结尾窗算，不排名', () => {
    const 段 = 段区间们({ ...交付('第6章', 40).m, 段: [
      { 编号: '6-01', 键: '6-a', 指纹: '', 母版: '', 帧数: 600, 全片起帧: 0 },
      { 编号: '6-02', 键: '6-b', 指纹: '', 母版: '', 帧数: 360, 全片起帧: 600 },
    ] });
    const [s] = 解析(包('2026-10-22T07:58:00Z'));
    const 统 = 按段统计(段, [s!.留存[0]!, s!.留存[1]!, { 秒: 40, 留存: 0.05 }], [], { 开头: 0, 结尾: 0 });
    expect(统[0]!.计止).toBe(20);
    expect(统[1]!.结尾窗内).toBe(true);
    expect(统[1]!.每10秒相对流失).toBeNaN();
  });
  it('结尾窗默认取最后一个段和 30 秒的较长者，窗内的段不排名', () => {
    const 段 = 段区间们({ ...交付('第6章', 100).m, 段: [
      { 编号: '6-01', 键: '6-a', 指纹: '', 母版: '', 帧数: 1200, 全片起帧: 0 },
      { 编号: '6-02', 键: '6-b', 指纹: '', 母版: '', 帧数: 720, 全片起帧: 1200 },
      { 编号: '6-03', 键: '6-c', 指纹: '', 母版: '', 帧数: 480, 全片起帧: 1920 },
    ] });
    expect(默认结尾窗(段)).toBe(30);
    expect(默认结尾窗(段.slice(0, 2))).toBe(30);
    const 曲 = [{ 秒: 0, 留存: 1 }, { 秒: 50, 留存: 0.5 }, { 秒: 100, 留存: 0.4 }];
    const 统 = 按段统计(段, 曲, [], { 开头: 0 });
    expect(统[1]!.计止).toBe(70);
    expect(统[2]!.结尾窗内).toBe(true);
  });
});

