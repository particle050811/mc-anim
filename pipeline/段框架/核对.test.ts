import { describe, expect, it } from 'vitest';
import { 核老段起帧 } from './核对.ts';

describe('核老段起帧', () => {
  const 清单 = ['7-甲', '7-乙', '7-丙'];
  it('首尾相接、中间跳过一截都放行', () => {
    expect(核老段起帧([{ 键: '7-甲', 起帧: 0, 帧数: 10 }, { 键: '7-乙', 起帧: 10, 帧数: 5 }, { 键: '7-丙', 起帧: 30, 帧数: 5 }], 清单)).toEqual([]);
  });
  it('重叠要报', () => {
    expect(核老段起帧([{ 键: '7-甲', 起帧: 0, 帧数: 10 }, { 键: '7-乙', 起帧: 9, 帧数: 5 }], 清单)).toEqual(['老段 7-乙 起在第 9 帧，和 7-甲（止于第 10 帧）重叠']);
  });
  it('顺序和清单不一样要报', () => {
    expect(核老段起帧([{ 键: '7-乙', 起帧: 0, 帧数: 10 }, { 键: '7-甲', 起帧: 10, 帧数: 5 }], 清单)[0]).toMatch(/顺序和清单不一样/);
  });
});
