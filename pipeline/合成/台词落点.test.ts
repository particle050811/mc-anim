// 台词落点：从段.ts 的声音 cue 算全片帧（字幕不再从各段代码里扒）。
import { describe, expect, it } from 'vitest';
import { cue增益, 定义段 } from '../../engine/段/段定义.ts';
import type { 段信息 } from '../清单/清单.ts';
import { 算台词落点 } from './台词落点.ts';
import { 设字库 } from './字幕卡.ts';

const 段 = (键: string, 秒: number, 声音: { 秒: number; 台词?: string; 接上段?: true; 资产?: string; 名?: string; 长秒?: number }[]) =>
  ({ 键, 段: { 场: '测试', 秒, 宽: 1280, 高: 720, 地形: [] , 声音 } }) as unknown as 段信息;

// 断屏只要字宽：每个字 9 个界面像素
设字库(new Proxy({}, { get: () => ({ w: 16, h: 16, scale: 0.5, adv: 9, shadow: 0.5, top: 0, rows: [] }) }) as never);

describe('台词落点', () => {
  it('cue 秒是开口：文件头 = 段起帧 +（秒 − 开口秒）× fps；位置取台词表，没写是 下', () => {
    const 截们 = [
      { 段: 段('甲', 2, [{ 秒: 0.5, 资产: '音效/钟', 名: '钟', 长秒: 1 }]), 全片起帧: 0 },
      { 段: 段('乙', 2, [{ 秒: 0.25, 台词: '6-李樱-走' }, { 秒: 1, 台词: '6-九胡-停' }]), 全片起帧: 120 },
    ];
    const 表 = [
      { id: '6-李樱-走', 角色: '李樱', 文本: '走吧。', 配音: '配音/6-李樱-走', 开口: 0.05 },
      { id: '6-九胡-停', 角色: '九胡', 文本: '等等，先别动！', 配音: '配音/6-九胡-停', 字幕位置: '思索上' as const },
    ];
    const r = 算台词落点(截们, 表, (id) => `/库/${id}`, 60);
    expect(r.map((a) => [a.id, a.段, a.段内帧, Math.round(a.文件头帧 * 1e6) / 1e6, a.文件, a.位置])).toEqual([
      ['6-李樱-走', '乙', 15, 132, '/库/配音/6-李樱-走', '下'],
      ['6-九胡-停', '乙', 60, 180, '/库/配音/6-九胡-停', '思索上'],
    ]);
    expect(r[1]!.屏们.map((p) => p.字)).toEqual(['等等，先别动！']);
  });

  it('台词不在表里、没配音都报错', () => {
    const 截们 = [{ 段: 段('甲', 1, [{ 秒: 0.1, 台词: '6-李樱-无' }]), 全片起帧: 0 }];
    expect(() => 算台词落点(截们, [], (x) => x, 60)).toThrow(/不在 <作品根>\/台词.toml/);
    expect(() => 算台词落点(截们, [{ id: '6-李樱-无', 角色: '李樱', 文本: '嗯' }], (x) => x, 60)).toThrow(/还没配音/);
  });

  it('接上段：同一段里接着放的不另记；跨段的另记一条 接上段，文件头照上一段的开口推，和开口那段换到全片是同一帧', () => {
    const 甲 = 段('甲', 2, [{ 秒: 1.75, 台词: '7-刘心忠-不可能' }, { 秒: 1.9, 台词: '7-刘心忠-不可能', 接上段: true }]);
    const 乙 = 段('乙', 1, [{ 秒: 0, 台词: '7-刘心忠-不可能', 接上段: true }]);
    const 表 = [{ id: '7-刘心忠-不可能', 角色: '刘心忠', 文本: '不可能！', 配音: '配音/x', 开口: 0.5 }];
    const 上一段 = (键: string) => (键 === '乙' ? 甲.段 : undefined);
    const r = 算台词落点([{ 段: 甲, 全片起帧: 0 }, { 段: 乙, 全片起帧: 120 }], 表, (id) => id, 60, 上一段);
    expect(r.map((a) => [a.段, a.文件头帧, a.接上段])).toEqual([
      ['甲', 75, undefined],
      ['乙', 75, true],
    ]);
    expect(() => 算台词落点([{ 段: 乙, 全片起帧: 0 }], 表, (id) => id, 60)).toThrow(/标了 接上段/);
  });
});

describe('声音 cue', () => {
  const 段 = (声音: unknown[]) => 定义段({ 场: '测试', 秒: 1, 宽: 4, 高: 4, 地形: [], 声音: 声音 as never });
  it('秒可带小数、不对齐到帧；资产 cue 要名、长秒，不过段尾；逐格增益个数和长秒对上', () => {
    expect(() => 段([{ 秒: 0.1234, 台词: '7-甲-说' }, { 秒: 0.3, 资产: '音效/钟', 名: '钟', 长秒: 0.7, 增益: 0.5, 淡出秒: 0.2 }])).not.toThrow();
    expect(() => 段([{ 秒: 0.3, 资产: '音效/钟', 长秒: 0.2 }])).toThrow(/要写 名、长秒/);
    expect(() => 段([{ 秒: 0.3, 资产: '音效/钟', 名: '钟', 长秒: 0.8 }])).toThrow(/不超过段尾/);
    expect(() => 段([{ 秒: 0.3, 资产: '音效/钟', 名: '钟', 长秒: 0.5, 增益: { 每秒: 24, 值: [1] } }])).toThrow(/逐格增益 1 个/);
    expect(() => 段([{ 秒: 0.3, 资产: '音效/钟', 名: '钟', 长秒: 0.2, 档: '很响' }])).toThrow(/档「很响」/);
  });
  it('增益：常数、逐格；常数带淡出秒时最后那截线性往下收', () => {
    const c = { 秒: 0, 资产: '音效/钟', 名: '钟', 长秒: 4, 增益: 0.8, 淡出秒: 2 };
    expect([0, 1, 2, 3].map((t) => cue增益(c, t))).toEqual([0.8, 0.8, 0.8, 0.4]);
    expect(cue增益({ ...c, 增益: { 每秒: 1, 值: [1, 0.5, 0.25, 0] }, 淡出秒: undefined }, 1.5)).toBe(0.375);
  });
});
