// anim film <范围…> [--名 <名>] [--级别 视频|预览] [--重渲过期] [--允许过期] [--不叠层] [--不叠字幕] [--分享版]
// anim film 补声音 <交付…> | --全部 [--只看]：给旧交付补 全片-未拉响度.flac（作品开了剪辑包的还有 剪辑包/画面.mp4），补完不再要母版
import type { 命令 } from '../cli/命令.ts';
import { 用法错误, 解析参数 } from '../cli/参数.ts';
import { 选段 } from '../清单/清单.ts';
import { 渲染级别取值, type 渲染级别 } from '../../engine/段/设置值.ts';
import { 合成成片 } from './成片.ts';
import { 补交付, 全部交付 } from './补交付.ts';
import { 找交付目录 } from '../适配器/剪映/剪辑包.ts';
import { 懒放行闸 } from '../闸/闸.ts';

export const 合成命令: Record<string, 命令> = {
  film: {
    用法: 'film <范围…> [--名 <名>] [--级别 视频|预览] [--重渲过期] [--允许过期] [--不叠层] [--不叠字幕] [--分享版]；film 补声音 <交付…> | --全部 [--只看]',
    说明: '按清单顺序接各段母版、叠透明层和字幕、拉响度、压成片，出到 交付/<UTC>-<名>/（带 SRT、字幕表、同步表、未拉响度的 FLAC、manifest.json）；--分享版 另压 50 MB 内的 720p；补声音 给旧交付补上不再要母版的文件',
    跑: async (args, 记录) => {
      if (args[0] === '补声音') {
        const q = 解析参数(args.slice(1), { 开关: ['--全部', '--只看'] });
        if (q.开关.has('--全部') === q.位置.length > 0) throw new 用法错误('anim film 补声音 要给交付目录（名字或路径），或 --全部，二选一');
        const dirs = q.开关.has('--全部') ? 全部交付() : q.位置.map(找交付目录);
        return 补交付(dirs, { 只看: q.开关.has('--只看'), 记录, 等放行: 懒放行闸() });
      }
      const p = 解析参数(args, { 值: ['--名', '--级别'], 开关: ['--重渲过期', '--允许过期', '--不叠层', '--不叠字幕', '--分享版'] });
      if (!p.位置.length) throw new 用法错误('要给范围（章、6-7 这样的章范围、场键或段）');
      const 级别 = (p.值['--级别'] ?? '视频') as 渲染级别;
      if (!渲染级别取值.includes(级别)) throw new 用法错误(`--级别 只能是 ${渲染级别取值.join('、')}`);
      const 名 = p.值['--名'] ?? (p.位置.join('+') + (级别 === '预览' ? '-预览' : ''));
      if (/[<>:"/\\|?*\x00-\x1f]/.test(名)) throw new 用法错误(`--名「${名}」不能当文件夹名`);
      const 段们 = await 选段(p.位置);
      await 合成成片(段们, {
        级别,
        名,
        范围: p.位置,
        允许过期: p.开关.has('--允许过期'),
        重渲过期: p.开关.has('--重渲过期'),
        不叠层: p.开关.has('--不叠层'),
        不叠字幕: p.开关.has('--不叠字幕'),
        分享版: p.开关.has('--分享版'),
        记录,
      });
    },
  },
};
