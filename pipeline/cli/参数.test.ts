import { describe, expect, it } from 'vitest';
import { 解析参数 } from './参数.ts';

describe('命令行参数', () => {
  it('位置、开关、带值（空格或等号）、多值', () => {
    const r = 解析参数(['6', '--级别', '预览', '--重渲', '--到预览=主题', '7'], { 值: ['--级别', '--到预览'], 开关: ['--重渲'] });
    expect(r.位置).toEqual(['6', '7']);
    expect(r.值).toEqual({ '--级别': '预览', '--到预览': '主题' });
    expect([...r.开关]).toEqual(['--重渲']);
  });
  it('不认识的选项、缺值、开关带值都报错', () => {
    expect(() => 解析参数(['--乱写'], {})).toThrow(/不认识的选项/);
    expect(() => 解析参数(['--级别'], { 值: ['--级别'] })).toThrow(/要带值/);
    expect(() => 解析参数(['--级别', '--重渲'], { 值: ['--级别'], 开关: ['--重渲'] })).toThrow(/要带值/);
    expect(() => 解析参数(['--重渲=1'], { 开关: ['--重渲'] })).toThrow(/不带值/);
  });
});
