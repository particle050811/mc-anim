import { describe, expect, it } from 'vitest';
import { 匹配, type 段信息 } from '../清单/清单.ts';
import { 点名不唯一 } from './认可.ts';

const 段 = (键: string, 编号: string, 场: string, 章: number) => ({ 键, 段名: 键.replace(/^\d+-/, ''), 编号, 章, 段: { 场 } }) as unknown as 段信息;
const 全 = [段('7-五万血', '7-08', '7-黑暗监守', 7), 段('7-黑暗来袭', '7-09', '7-黑暗监守', 7), 段('8-开门', '8-01', '8-门', 8)];

describe('accept 逐段点名', () => {
  it('段键、段名各点一段放过（同一段点两次也行），只对上一段的章也放过', () => {
    expect(点名不唯一(['7-五万血', '黑暗来袭', '五万血', '8'], 全, 匹配)).toEqual([]);
  });

  it('场键、章范围对上多段就挑出来，带上对上的段键', () => {
    expect(点名不唯一(['7-黑暗监守', '7', '8-开门'], 全, 匹配)).toEqual([
      { 选择器: '7-黑暗监守', 段: ['7-五万血', '7-黑暗来袭'] },
      { 选择器: '7', 段: ['7-五万血', '7-黑暗来袭'] },
    ]);
  });

  it('编号 7-08 现在被 匹配 当成章范围 7～8（清单.ts 的老问题），accept 照样拦下，不会把两章都记成看过', () => {
    expect(点名不唯一(['7-08'], 全, 匹配)).toEqual([{ 选择器: '7-08', 段: ['7-五万血', '7-黑暗来袭', '8-开门'] }]);
  });
});
