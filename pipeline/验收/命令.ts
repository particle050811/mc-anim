const 级别 = '视频' as const;

/** 每段现在的指纹和母版；缺母版时 --渲 就渲，不渲就记下 */
const 备母版 = async (段们: 段信息[], 渲: boolean, 记录: 运行记录) => {
  const 参数 = 渲染参数(级别);
  const 指纹们 = await 算全部段指纹(段们.map((s) => ({ 段: s, 渲染设置: 参数 })));
  const r = 段们.map((s, i) => ({ 段: s, 指纹: 指纹们[i]!.指纹 }));
  const 缺 = r.filter((x) => !有母版(x.段.键, x.指纹));
  if (缺.length && 渲) await 渲染母版(缺.map((x) => x.段), 级别, { 记录 });
  return r.map((x) => {
    const 原 = 原母版路径(x.段.键, x.指纹);
    const 有 = 有母版(x.段.键, x.指纹);
    if (有) 记用过(母版目录(x.段.键), x.指纹);
    // 原母版：CRF1，只有它能拿来抽像素；现有：判「同一指纹重渲过」看的那份（有 CRF12 就是它，段签记的也是它）
    return { ...x, 原母版: 原, 现有: 现母版(x.段.键, x.指纹) ?? 原, 有, 有段签: 段签齐(读段签(x.段.键, x.指纹)) };
  });
};

const 验: 命令 = {
  用法: 'verify [<选择器…>] [--渲] [--对基线] [--到预览 <主题>]；verify accept <段…> --理由 <…> [--渲]；verify 补参考 [<选择器…>]',
  说明: '指纹变了的段抽帧和认可版比（--对基线 和旧项目基线比），超过阈值就要 anim verify accept',
  跑: async (args, 记录) => {
    if (args[0] === 'accept') return 认.跑(args.slice(1), 记录);
    if (args[0] === '补参考') return 补.跑(args.slice(1), 记录);
    const p = 解析参数(args, { 值: ['--到预览'], 开关: ['--渲', '--对基线'] });
    const 对基线 = p.开关.has('--对基线');
    const 段们 = p.位置.length ? await 选段(p.位置) : await 全部段();
    const 阈 = 读阈值();
    const 备 = await 备母版(段们, p.开关.has('--渲'), 记录);
    const 预览 = { 目录: null as string | null };
    const 取预览 = () => (预览.目录 ??= 新建预览目录(p.值['--到预览'] ?? '验收不过'));
    let 不过 = 0;
    const 报 = (键: string, 比的: string, r: 扫描结果) => {
      const 帧变 = r.帧结论.filter((f) => f.结论 === '变了');
      const 容差内 = r.帧结论.filter((f) => f.结论 === '容差内').length;
      if (!变了(r)) {
        console.log(`✓ ${键}：和${比的}比在阈值内（${r.比法}${r.像素来源 ? `，像素取自${r.像素来源}` : ''}；${容差内} 帧有微小差别；声音${r.音频结论}${r.音频说明 ? `，${r.音频说明}` : ''}）`);
        return;
      }
      不过++;
      const 项 = [r.尺寸变了, ...帧变.slice(0, 8).map((f) => `第 ${f.帧} 帧：${f.说明 ?? '变了'}`), 帧变.length > 8 ? `另 ${帧变.length - 8} 帧` : undefined, r.音频结论 === '变了' ? `声音：${r.音频说明}` : undefined];
      记录.记('错误', `${键}：和${比的}比变了（${r.比法}${r.像素来源 ? `，像素取自${r.像素来源}` : ''}）\n    ${项.filter(Boolean).join('\n    ')}`);
    };
    const 等放行 = 懒放行闸();
    for (const x of 备) {
      const 键 = x.段.键;
      const 认可 = 读认可(认可文件(键));
      if (!x.有 && (对基线 || !x.有段签)) {
        不过++;
        记录.记('错误', `${键}：没有现在指纹 ${x.指纹.slice(0, 16)} 的母版${对基线 ? '' : '和段签'}（anim render ${键}，或加 --渲）`);
        continue;
      }
      if (对基线) {
        const 旧号 = 旧段号(键);
        const 目录 = 旧号 ? 基线目录(旧号) : null;
        if (!目录 || !fs.existsSync(目录)) {
          不过++;
          记录.记('错误', `${键}：没有基线（${旧号 ? `${目录} 不在` : '作品/应力转动/旧名.tsv 里没有它的旧段号'}）`);
          continue;
        }
        if (!fs.existsSync(x.原母版)) {
          不过++;
          记录.记('错误', `${键}：对基线要 CRF1 母版逐帧比（落点帧不全在抽样帧里），现在只有 CRF12：要重渲才能验收（anim render ${键} --重渲）`);
          continue;
        }
        await 等放行();
        const r = await 扫母版(x.原母版, { 参照: await 基线参照(目录), 阈值: 阈, fps: x.段.段.fps, 预览: { 目录: 取预览, 前缀: 键 } });
        报(键, `基线 ${旧号}`, r);
        continue;
      }
      if (!认可) {
        不过++;
        记录.记('错误', `${键}：还没认可过（看过母版后 anim verify accept ${键} --理由 …）`);
        continue;
      }
      const 同指纹 = 认可.指纹 === x.指纹;
      if (同指纹) {
        const 因 = 同指纹重渲过(读段签(键, x.指纹), 认可, x.现有);
        if (!因) {
          console.log(`✓ ${键}：指纹和认可版一样`);
          continue;
        }
        console.log(`· ${键}：指纹和认可版一样，但同一指纹重渲过（${因}），比一次`);
      }
      await 等放行();
      const 参考 = 参考文件(认可, 本平台());
      if (同指纹 && !fs.existsSync(参考)) await 备参考(认可, null, 本平台());
      const 选项 = { 认可, 旧母版: 同指纹 ? null : 原母版路径(键, 认可.指纹), 参考, 阈值: 阈, fps: x.段.段.fps, 预览: { 目录: 取预览, 前缀: 键 } };
      const 签 = await 取段签(键, x.指纹, 级别, { 等放行, 记录 });
      if (!签) {
        不过++;
        记录.记('错误', `${键}：段签的无损抽样帧丢了，CRF1 母版也没了（CRF12 的像素不拿来比）：要重渲才能验收（anim render ${键} --重渲）`);
        continue;
      }
      let r: 扫描结果;
      try {
        try {
          r = await 扫段签({ 签名: 签.签名, 抽样: 抽样路径(签) }, 选项);
        } catch (e) {
          // 认可记录的抽样间隔和段签不一样：要的帧段签里没有，只有 CRF1 能解（CRF12 的像素不拿来比）
          if (!(e instanceof 抽样里没有)) throw e;
          if (!fs.existsSync(x.原母版)) {
            不过++;
            记录.记('错误', `${键}：${e.message}，CRF1 母版已经没了：要重渲才能验收（anim render ${键} --重渲）`);
            continue;
          }
          r = await 扫母版(x.原母版, 选项);
        }
      } catch (e) {
        if (!(e instanceof 参考对不上)) throw e;
        不过++;
        记录.记('错误', `${键}：${e.message}`);
        continue;
      }
      报(键, `认可版（${认可.指纹.slice(0, 16)}，${认可.认可于}）`, r);
    }
    if (预览.目录) {
      记录.产物.push(预览.目录);
      console.log(`变了的帧（旧|新|差 并排）在 ${预览.目录}`);
    }
    console.log(不过 ? `\n${不过} 段没过：缺母版的先渲；变了的看过画面、确认是要的改动，再 anim verify accept <段…> --理由 …` : `\n${段们.length} 段都过了`);
    return 不过 ? 1 : 0;
  },
};

const 认: 命令 = {
  用法: 'verify accept <段…> --理由 <…> [--渲]',
  说明: '把现在的母版记成认可版（写 <作品根>/认可/<平台>/<段键>.toml）；一次可认可多段、共用一个理由，要逐段点名',
  跑: async (args, 记录) => {
    const p = 解析参数(args, { 值: ['--理由'], 开关: ['--渲'] });
    if (!p.位置.length) throw new 用法错误('要给段：anim verify accept <段…> --理由 …');
    const 理由 = p.值['--理由']?.trim();
    if (!理由) throw new 用法错误('要写 --理由（这次画面为什么变、谁看过）');
    const 段们 = await 选段(p.位置);
    const 不唯一 = 点名不唯一(p.位置, 段们, 选中);
    if (不唯一.length) {
      throw new 用法错误(`认可要逐段点名：${不唯一.map((y) => `「${y.选择器}」对上了 ${y.段.length} 段`).join('、')}；都看过的话写 anim verify accept ${[...new Set(不唯一.flatMap((y) => y.段))].join(' ')} --理由 …`);
    }
    const 备 = await 备母版(段们, p.开关.has('--渲'), 记录);
    // 先查齐再写：有一段缺母版就一段都不认可
    const 缺 = 备.filter((x) => !x.有 && !x.有段签);
    if (缺.length) throw new Error(`${缺.map((x) => `${x.段.键}（${x.指纹.slice(0, 16)}）`).join('、')} 没有现在指纹的母版和段签：先 anim render ${缺.map((x) => x.段.键).join(' ')}，或加 --渲`);
    if (备.length > 1) console.log(`== 认可 ${备.length} 段：${备.map((x) => x.段.键).join('、')}`);
    // 签名取自段签（和 扫母版 同一份；缺了从母版派生，要解码：整批过一次放行闸）
    await 过放行闸(async () => {});
    // 每段都签好了再写：中途哪段解码失败，一个认可文件都不改
    const 签们 = [];
    for (const x of 备) {
      const 签 = await 取段签(x.段.键, x.指纹, 级别, { 等放行: async () => {}, 记录 });
      if (!签) throw new Error(`${x.段.键} 段签的无损抽样帧丢了，CRF1 母版也没了（CRF12 的像素不拿来认可）：要重渲才能认可（anim render ${x.段.键} --重渲）`);
      签们.push(签);
    }
    const 签名们: 扫描结果['签名'][] = 签们.map((g) => g.签名);
    const 提交 = 提交状态();
    const 写了: string[] = [];
    for (const [i, x] of 备.entries()) {
      const file = 认可文件(x.段.键);
      const 旧 = 读认可(file);
      const 签 = 签名们[i]!;
      写认可(file, {
        段: x.段.键,
        指纹: x.指纹,
        平台: 本平台(),
        渲染级别: 级别,
        认可于: utc时间(),
        提交: 提交 ? `${提交.提交}${提交.有改动 ? '+未提交改动' : ''}` : '不在 git 里',
        理由,
        上一版指纹: 旧?.指纹 ?? null,
        ...签,
      });
      记录.产物.push(file);
      写了.push(file);
      console.log(`已认可 ${x.段.键}（${x.指纹.slice(0, 16)}，${签.帧.length} 帧签名）→ ${file}`);
    }
    // 认可文件都写完了再备认可参考（段签的抽样帧就是认可这版的，克隆一份；旧的认可参考不删）：备不上只警告，不让认可只写一半
    for (const [i, x] of 备.entries()) {
      try {
        const 认可 = 读认可(写了[i]!)!;
        const 参 = await 备参考(认可, x.原母版, 本平台());
        if (参 === '对不上' || 参 === '没有来源') 记录.记('警告', `${x.段.键} 的认可参考没备上（${参}），这版的母版删了以后 verify 只能比块均值`);
        else if (参 !== '已有') 记录.产物.push(参考文件(认可, 本平台()));
      } catch (e) {
        记录.记('警告', `${x.段.键} 已认可，认可参考没备上（${(e as Error).message.split('\n')[0]}）；之后 anim verify 补参考 ${x.段.键}`);
      }
    }
    console.log('记得把认可文件和这次的改动一起提交');
  },
};

const 补: 命令 = {
  用法: 'verify 补参考 [<选择器…>]',
  说明: '给本平台的认可记录备认可参考（认可那版的抽样帧，无损）：从它的段签克隆或从认可母版抽，逐帧核对认可记录的哈希才收；只新增文件',
  跑: async (args, 记录) => {
    const p = 解析参数(args, {});
    const 段们 = p.位置.length ? await 选段(p.位置) : await 全部段();
    const 计: Record<参考结果, string[]> = { 已有: [], 从段签: [], 从认可母版: [], 对不上: [], 没有来源: [] };
    const 等放行 = 懒放行闸();
    let 没认可 = 0;
    for (const s of 段们) {
      const 认可 = 读认可(认可文件(s.键));
      if (!认可) {
        没认可++;
        continue;
      }
      const 参考 = 参考文件(认可, 本平台());
      if (!fs.existsSync(参考)) await 等放行();
      const r = await 备参考(认可, 原母版路径(s.键, 认可.指纹), 本平台());
      计[r].push(s.键);
      if (r === '从段签' || r === '从认可母版') {
        记录.产物.push(参考);
        console.log(`✓ ${s.键}：${r}（${认可.指纹.slice(0, 16)}）`);
      }
      if (r === '对不上') 记录.记('警告', `${s.键}：认可那版的母版（${认可.指纹.slice(0, 16)}）抽出来和认可记录的哈希对不上（同一指纹重渲过？），没收`);
      if (r === '没有来源') console.log(`· ${s.键}：认可那版（${认可.指纹.slice(0, 16)}）的母版和段签都不在，补不了（verify 只能比块均值）`);
    }
    console.log(
      `\n认可参考：新备 ${计.从段签.length + 计.从认可母版.length}（从段签 ${计.从段签.length}、从认可母版 ${计.从认可母版.length}），已有 ${计.已有.length}，对不上 ${计.对不上.length}，没有来源 ${计.没有来源.length}${没认可 ? `；${没认可} 段还没认可过` : ''}`,
    );
    return 计.对不上.length ? 1 : 0;
  },
};

export const 验收命令: Record<string, 命令> = { verify: 验 };
