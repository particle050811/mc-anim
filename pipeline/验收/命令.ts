// anim verify [<选择器…>] [--渲] [--对基线] [--到预览 <主题>]：指纹和认可记录不一样的段抽帧比，超过阈值就要 accept；
//   --对基线：不看认可记录，直接和数据根 基线/<旧段号>/ 的旧项目基线比（迁移验收用，旧段号查 作品/应力转动/旧名.tsv）。
//   变了的帧出 旧|新|差 的并排图进预览（没给 --到预览 就新开一个「验收不过」）。
// anim verify accept <段…> --理由 <…> [--渲]：把现在的母版记成认可版，写 <作品根>/认可/<平台>/<段键>.toml（进 Git）；一次可认可多段、共用一个理由，
//   但要逐段点名（一个选择器对上多段就拒，见 认可.ts 的 点名不唯一）。
// anim verify 补参考 [<选择器…>]：从认可那版的段签（或它的 CRF1 母版）抽出认可参考，之后认可母版删了也能逐像素比。
// 一律按视频级比；真要抽帧解码时才过放行闸（一次命令只过一次；指纹和认可版一样的段不解码、不等闸，用户 10-30 授权），
// 缺母版加 --渲 时渲染照旧过渲染闸。指纹一样、但段签说同一指纹重渲过（签名和认可记录不一样，或母版大小改于和段签记的不一样）的照样比：
// 这时现在的母版不是认可那版，认可那版的像素只取认可参考（缺了先从 历史/ 里的段签备），不拿现在的母版冒充。
// 新这一版读段签（pipeline/段签/，缺了从 CRF1 当场派生），母版删了有段签照样验；认可那版的像素按 认可参考 → 认可那版的 CRF1 母版 → 只比块均值 取。
// CRF12 母版（用户 10-30 定，渲/转码.ts）的像素永远不拿来比：它按 1e-3 门槛比就全不过（02-实测数据.md 地形差 > 16 占 2.4e-2）。抽样帧丢了、CRF1 也没了，就报要重渲才能验收，不退回比 CRF12。
