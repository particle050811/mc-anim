/** 每段现在的指纹和母版；缺母版时 --渲 就渲，不渲就记下。要CRF1（--对基线）：只有压缩母版的也算缺，重渲并留下 CRF1 */
const 备母版 = async (段们: 段信息[], 渲: boolean, 记录: 运行记录, o: { 要CRF1?: boolean } = {}) => {
  const 参数 = 渲染参数(级别);
  const 指纹们 = await 算全部段指纹(段们.map((s) => ({ 段: s, 渲染设置: 参数 })));
  const r = 段们.map((s, i) => ({ 段: s, 指纹: 指纹们[i]!.指纹 }));
  const 缺 = r.filter((x) => (o.要CRF1 ? !fs.existsSync(原母版路径(x.段.键, x.指纹)) : !有母版(x.段.键, x.指纹)));
  if (缺.length && 渲) await 渲染母版(缺.map((x) => x.段), 级别, { 记录, ...(o.要CRF1 ? { 重渲: true, 留CRF1: true } : {}) });
  return r.map((x) => {
    const 原 = 原母版路径(x.段.键, x.指纹);
    const 有 = 有母版(x.段.键, x.指纹);
    if (有) 记用过(母版目录(x.段.键), x.指纹);
    // 原母版：CRF1（--对基线 只认它）；现有：判「同一指纹重渲过」看的那份（有压缩母版就是它，段签记的也是它）
    return { ...x, 原母版: 原, 现有: 现母版(x.段.键, x.指纹) ?? 原, 有, 有段签: 段签齐(读段签(x.段.键, x.指纹)) };
  });
};

/** 段签记的那份母版（新这一版要看像素时解它）：压缩母版对得上段签就用它，不然 CRF1 是段签转自的那份就用它；都不是 null */
const 段签的母版 = async (签: 段签, 键: string, 指纹: string): Promise<string | null> => {
  const 压 = 压缩母版路径(键, 指纹);
  if (签.母版.转码自 && fs.existsSync(压) && (await 对得上母版(签, 压))) return 压;
  const 原 = 原母版路径(键, 指纹);
  return fs.existsSync(原) && (await 对得上原母版(签, 原)) ? 原 : null;
};

