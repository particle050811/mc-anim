import { describe, expect, it } from 'vitest';
import { 基础, 跑, 造仓库 } from './测试夹具.ts';
import { 文本哈希 } from './规则/台词.ts';
import { 写句模块文本 } from '../配音/句模块.ts';
import type { 台词句 } from '../../engine/audio/台词句.ts';

const 配音sha = 'b'.repeat(64);
const 带配音 = {
  'assets/registry/配音.toml': ['[["资产"]]', 'id = "配音/7-李樱-五万血"', '"类别" = "配音"', '"来源" = "手工:TTS"', '"许可" = "MIT"', '"可见性" = "公开"'].join('\n'),
  'assets/资产锁.json': JSON.stringify({
    '贴图/甲': { sha256: 'a'.repeat(64), 后缀: '.png', 大小: 3, 库: 'store' },
    '配音/7-李樱-五万血': { sha256: 配音sha, 后缀: '.wav', 大小: 3, 库: 'store' },
  }),
  '作品/应力转动/段/7-甲/段.ts':
    "import { 定义段 } from '@engine/段/段定义.ts';\nexport default 定义段({ 场: '7-场一', 帧数: 10, fps: 24, 宽: 4, 高: 4, 地形: [], 声音: [{ 帧: 2, 台词: '7-李樱-五万血' }] });\n",
};
const 台词 = (行: string[]) => ({ '作品/应力转动/台词.toml': ['[["台词"]]', ...行].join('\n') });

describe('台词', () => {
  it('合规样例放行：cue 引的台词登记了，文本哈希、成品 sha、口型都对得上；备用的标 未用', async () => {
    const 根 = 造仓库(基础(), 带配音, {
      '作品/应力转动/台词.toml': [
        '[["台词"]]',
        'id = "7-李樱-五万血"',
        '"角色" = "李樱"',
        '"文本" = "五万血？"',
        '"配音" = "配音/7-李樱-五万血"',
        `"文本哈希" = "${文本哈希('五万血？')}"`,
        '"开口" = 0.03',
        '"字幕位置" = "思索上"',
        `"成品sha" = "${配音sha.slice(0, 12)}"`,
        `"口型" = { "成品sha" = "${配音sha.slice(0, 12)}" }`,
        '',
        '[["台词"]]',
        'id = "7-九胡-备用"',
        '"角色" = "九胡"',
        '"文本" = "嗯"',
        '"未用" = true',
      ].join('\n'),
    });
    expect((await 跑('台词', 根)).违规).toEqual([]);
  });

  it('文本改了、配音换了、口型过期、没登记、没段用、撞旧名都拦', async () => {
    const 根 = 造仓库(
      基础(),
      带配音,
      {
        '作品/应力转动/段/7-甲/段.ts':
          "import { 定义段 } from '@engine/段/段定义.ts';\nexport default 定义段({ 场: '7-场一', 帧数: 10, fps: 24, 宽: 4, 高: 4, 地形: [], 声音: [{ 帧: 2, 台词: '7-李樱-五万血' }, { 帧: 3, 台词: '7-李樱-没登记' }] });\n",
        '作品/应力转动/旧名.tsv': '类别\t旧名\t新键\t备注\n已删台词\t7-黄叛-受死\t\t\n',
      },
      台词([
        'id = "7-李樱-五万血"',
        '"角色" = "李樱"',
        '"文本" = "五万血！"',
        '"配音" = "配音/7-李樱-五万血"',
        `"文本哈希" = "${文本哈希('五万血？')}"`,
        '"成品sha" = "cccccccccccc"',
        '"口型" = { "成品sha" = "cccccccccccc" }',
        '',
        '[["台词"]]',
        'id = "7-黄叛-受死"',
        '"角色" = "黄叛"',
        '"文本" = "受死"',
      ]),
    );
    const v = (await 跑('台词', 根)).违规.join('\n');
    expect(v).toMatch(/文本哈希 .* 和现在念的字.*对不上：念的字改过，配音过期/);
    expect(v).toMatch(/成品sha cccccccccccc 和资产锁里 配音\/7-李樱-五万血 的 bbbbbbbbbbbb 对不上/);
    expect(v).toMatch(/口型 是对着成品 cccccccccccc 做的.*口型 过期/);
    expect(v).toMatch(/7-甲 第 3 帧的台词「7-李樱-没登记」不在 作品\/应力转动\/台词.toml 里/);
    expect(v).toMatch(/台词「7-黄叛-受死」没有段用到/);
    expect(v).toMatch(/台词「7-黄叛-受死」 撞了旧名表第 2 行的旧名/);
  });

  it('开口、字幕位置的格式；每句只开口一次，接上段的后半截要接在本段或清单上一段的开口后面', async () => {
    const 段 = (声音: string) => `import { 定义段 } from '@engine/段/段定义.ts';\nexport default 定义段({ 场: '7-场一', 帧数: 10, fps: 24, 宽: 4, 高: 4, 地形: [], 声音: ${声音} });\n`;
    const 句 = (id: string, 角色: string, 多: string[] = []) => [
      '[["台词"]]', `id = "${id}"`, `"角色" = "${角色}"`, '"文本" = "五万血？"', '"配音" = "配音/7-李樱-五万血"',
      `"文本哈希" = "${文本哈希('五万血？')}"`, `"成品sha" = "${配音sha.slice(0, 12)}"`, ...多, '',
    ];
    const 根 = 造仓库(基础(), 带配音, {
      '作品/应力转动/清单.ts': [
        "export const 清单 = [{ 键: '7-甲', 章: 7 }, { 键: '7-乙', 章: 7 }, { 键: '7-丙', 章: 7 }];",
        "export const 段目录 = (键: string) => `段/${键}`;",
      ].join('\n'),
      '作品/应力转动/段/7-甲/段.ts': 段("[{ 帧: 2, 台词: '7-李樱-五万血' }, { 帧: 5, 台词: '7-李樱-五万血', 接上段: true }]"),
      '作品/应力转动/段/7-乙/段.ts': 段("[{ 帧: 0, 台词: '7-李樱-五万血', 接上段: true }, { 帧: 1, 台词: '7-九胡-两次' }, { 帧: 6, 台词: '7-九胡-两次' }]"),
      '作品/应力转动/段/7-丙/段.ts': 段("[{ 帧: 0, 台词: '7-李樱-五万血', 接上段: true }, { 帧: 1, 台词: '7-刘心忠-没开口', 接上段: true }]"),
      '作品/应力转动/段/7-乙/画面.tsx': 'export default () => null;\n',
      '作品/应力转动/段/7-丙/画面.tsx': 'export default () => null;\n',
      '作品/应力转动/台词.toml': [
        ...句('7-李樱-五万血', '李樱', ['"开口" = 0.03']),
        ...句('7-九胡-两次', '九胡', ['"字幕位置" = "上"']),
        ...句('7-刘心忠-没开口', '刘心忠', ['"开口" = -1']),
      ].join('\n'),
    });
    const v = (await 跑('台词', 根)).违规.join('\n');
    expect(v).not.toMatch(/7-乙 第 0 帧/);
    expect(v).toMatch(/7-丙 第 0 帧的台词「7-李樱-五万血」标了 接上段，本段前面和清单里上一段都没有它开口/);
    expect(v).toMatch(/7-丙 第 1 帧的台词「7-刘心忠-没开口」标了 接上段/);
    expect(v).toMatch(/台词「7-九胡-两次」：字幕位置 只能是 下、思索上/);
    expect(v).toMatch(/台词「7-九胡-两次」：有配音就要写 开口/);
    expect(v).toMatch(/台词「7-九胡-两次」在 7-乙、7-乙 开口了 2 次/);
    expect(v).toMatch(/台词「7-刘心忠-没开口」：开口 是配音文件里第几秒开口/);
    expect(v).toMatch(/台词「7-刘心忠-没开口」没有段用到/);
    expect(v).not.toMatch(/^作品\/应力转动\/台词.toml 台词「7-李樱-五万血」/m);
  });
  it('文本哈希对的是念的字：只改字幕、写 念 = 原来的字的放行；加了不同的 念 就算配音过期', async () => {
    const 行 = (文本: string, 念?: string) =>
      台词([
        'id = "7-李樱-五万血"', '"角色" = "李樱"', `"文本" = "${文本}"`, ...(念 ? [`"念" = "${念}"`] : []), '"配音" = "配音/7-李樱-五万血"', '"开口" = 0.03',
        `"文本哈希" = "${文本哈希('五万血？')}"`, `"成品sha" = "${配音sha.slice(0, 12)}"`,
      ]);
    const 只改字幕 = await 跑('台词', 造仓库(基础(), 带配音, 行('五万血？！', '五万血？')));
    expect(只改字幕.违规).toEqual([]);
    const 改念法 = (await 跑('台词', 造仓库(基础(), 带配音, 行('五万血？', '五万点血？')))).违规.join('\n');
    expect(改念法).toMatch(/文本哈希 .* 和现在念的字.*对不上：念的字改过，配音过期/);
  });

  it('有 台词/ 句模块目录的：有配音的每句要有句模块、跟得上表和成品、是工具写的原样，多出来的句模块也拦', async () => {
    const 句: 台词句 = {
      id: '7-李樱-五万血', 角色: '李樱', 念: '五万血？', 配音: '配音/7-李樱-五万血', 成品sha: 配音sha.slice(0, 12),
      开口: 0.03, 有声长: 0.5, 时长: 0.68, 文件秒数: 0.68, 字: [['五', 0.03, 0.2]], 嘴: [[0, 'X'], [0.03, 'B'], [0.2, 'X']],
    };
    const 表 = (口型sha: string) => 台词([
      'id = "7-李樱-五万血"', '"角色" = "李樱"', '"文本" = "五万血？"', '"配音" = "配音/7-李樱-五万血"', '"开口" = 0.03',
      `"文本哈希" = "${文本哈希('五万血？')}"`, `"成品sha" = "${配音sha.slice(0, 12)}"`, `"口型" = { "成品sha" = "${口型sha}" }`,
    ]);
    const 好 = 造仓库(基础(), 带配音, 表(配音sha.slice(0, 12)), { '作品/应力转动/台词/7-李樱-五万血.ts': 写句模块文本(句) });
    expect((await 跑('台词', 好)).违规).toEqual([]);

    const 坏 = 造仓库(基础(), 带配音, 表('cccccccccccc'), {
      '作品/应力转动/台词/7-李樱-五万血.ts': 写句模块文本({ ...句, 开口: 0.05 }).replace('"有声长": 0.5,', '"有声长": 0.6,'),
      '作品/应力转动/台词/7-李樱-删了.ts': 写句模块文本({ ...句, id: '7-李樱-删了' }),
    });
    const v = (await 跑('台词', 坏)).违规.join('\n');
    expect(v).toMatch(/句模块被手改过/);
    expect(v).toMatch(/句模块的 开口 0.05 和 台词.toml 的 0.03 不同/);
    expect(v).toMatch(/台词\/7-李樱-删了.ts：作品\/应力转动\/台词.toml 里没有这一句/);

    const 缺 = 造仓库(基础(), 带配音, 表(配音sha.slice(0, 12)), { '作品/应力转动/台词/7-李樱-删了.ts': 写句模块文本({ ...句, id: '7-李樱-删了' }) });
    expect((await 跑('台词', 缺)).违规.join('\n')).toMatch(/台词「7-李樱-五万血」：没有句模块（anim voice lip）/);
  });
});
